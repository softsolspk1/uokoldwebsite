  <p align="justify">Dr. Abdul Waheed is an economist with expertise in quantitative development analyses and specializes in economic issues of South Asia. Dr. Waheed achieved a Ph.D. degree from the Graduate School of International Development, Nagoya University, Japan, under a Japanese Government Fellowship in March 2005. In his Ph.D. research, he constructed a financial macroeconomic model and designed an external debt reduction strategy for Pakistan.<br />
    <br />
    Dr. Waheed did post-doctorate research under the Japan Society for the Promotion of Science (JSPS) fellowship from March 2005-September 2006 in Japan and constructed a financial social accounting matrix for Pakistan. He was invited as a guest speaker by the Government of South Korea in October 2007 to make a presentation on the “Financial Social Accounting Matrix of Pakistan” which he constructed during his post-doctorate research in Japan. The Institute of Developing Economies (IDE) invited him to Tokyo-Japan, for six months, in 2009 as Visiting Research Fellow, to conduct research on “Financial Sector Reforms in Pakistan”. Recently, Rikkyo University has also invited him to Tokyo-Japan to conduct a course and a special seminar during June-July of 2023.<br />
    <br />
    Dr. Waheed has had 45 scholarly contributions in peer-reviewed academic journals, a chapter in a book, and a monograph. He presented several research papers at international conferences held in Japan, Korea, Turkey, Dubai, and Bahrain. Most of his articles are published in impact factor journals indexed in Clarivate, Scopus, and ABDC. His short articles have also appeared in Pakistan & Gulf Economist and the News International. He authored two books entitled “Quantitative Research Methods: A Practical Approach” and “Statistical Analysis in Business and Economics”.<br />
    <br />
    Dr. Waheed has been a research consultant to JCR-VIS for the Sovereign Credit rating of the Kingdom of Bahrain and a sub-sovereign credit rating for the Government of Punjab, Pakistan. He also completed research projects entitled “Energy Demand Forecasting” funded by Shell Pakistan Private Limited, “External Debt of Bahrain” funded by the Deanship of Research, University of Bahrain, “Demand and Supply of Selected Agricultural Commodities” funded by the Trading Corporation of Pakistan (Private) Limited, and “Food Insecurity and Malnutrition in rural Sindh” funded by the Sindh Higher Education Commission. Dr. Waheed compiled a comprehensive long-time series of Economic and Financial database for the National Bank of Pakistan, a large international bank with operations in Europe, Asia, and North America. Five students completed their Ph.D., and nine students completed their MPhil thesis under his supervision.<br />
    <br />
    Dr. Waheed has had the opportunity to teach various courses at the graduate and post-graduate levels in different educational institutions such as the University of Karachi (Pakistan), Nagoya University (Japan), Rikkyo University (Japan), University of Bahrain (Bahrain), Institute of Business Administration (Pakistan), Bahria University (Pakistan) and IQRA University (Pakistan). Currently, he is Professor and Chairman at the Department of Economics, University of Karachi. For more details, please visit his website <a href="http://waheedku.com/" target="_blank">waheedku.com.</a></p>

