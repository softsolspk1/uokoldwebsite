<h1>Dr. Nosheen Raza (Students’ Advisor)</h1>
<h4>&nbsp;</h4>
<p align="justify">The Office of the Students&rsquo; Advisor has the  responsibility of keeping students positively engaged in activities that would  make them responsible citizens of the country and provide them with an  environment where they can polish their co-curricular skills. In order to  achieve this goal, the Office of Students' Advisor has established seven (8)  students&rsquo; societies where students from different departments join hands to  organize various events and trainings to help fellow students learn and exhibit  their co-curricular skills. <br />
The societies include:</p>
<ul>
  <li>Arts and Culture Society </li>
  <li>Civic and Social Responsibility  Society</li>
  <li>Debate, discussion and Declamation  Society</li>
  <li>Inclusive Students Society</li>
  <li>Music Society</li>
  <li>Theatre and Drama Society</li>
  <li>Sports Society</li>
  <li>Quiz Society</li>
  <li>Kashmir Society</li>
</ul>
<p>&nbsp;</p>
<p align="justify">The Student Societies of the University of  Karachi were established to help students engage in activities that would help  them reach their full potential by active and positive social engagements.  These societies have functioned under the supervision of the Students&rsquo; Advisor  Office since their establishment. They have actively participated in regional,  national and international competitions representing University of Karachi and  have made the University of Karachi proud of their achievements<br />
  In particular, the Office of the Students&rsquo;  Advisor organizes students' week, where a whole week is available for students  to organize and participate in co-curricular activities. <br />
  Besides these activities, the Office of the  Students&rsquo; Advisor signed many MoUs (Memorandum of Understanding) with different  organizations to enhance student skills and to facilitate them to connect with  the industry. <br />
  The most important programs this office  organizes are Orientation Day, Independence Day event and medals distribution,  Youm-e-Mustafa (S.A.W.W), Youm-e-Hussain (A.S.) and many other events on  specific national and international occasions. </p>
<p>Other prime functions of the Office include:</p>
<ul>
  <li>Issuance of identity cards</li>
  <li>Addressing complaints</li>
  <li>Health care assistance in terms of  confidential counseling</li>
  <li>Consultation for change of  department</li>
  <li>Assistance in arranging  academic/fields trips</li>
  <li>Organizing and supervising  students&rsquo; week</li>
  <li>Celebrating national days and  events on specific occasions</li>
  <li>Providing a liaison between  students and administrative authorities.</li>
</ul>
