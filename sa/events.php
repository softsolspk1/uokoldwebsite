<h1>&nbsp;</h1>
<p align="justify">The Office of Students' Advisor has  established nine (9) students&rsquo; societies where students from different  departments join hands to organize various events and trainings to help fellow  students learn and exhibit their co-curricular skills.</p>
<p align="justify">The office of the Students Advisor organizes  programs on national days and other specific occasions. They include;</p>
<ul>
  <li>Students' Week</li>
  <li>Orientation Day</li>
  <li>Kashmir Day</li>
  <li>Pakistan Day</li>
  <li>Independence Day and Medals  Distribution</li>
  <li>Defence Day</li>
  <li>Cancer Awareness Day</li>
  <li>Kashmir Solidarity-Black Day</li>
  <li>Iqbal Day</li>
  <li>Youm-e-Mustafa (S.A.W.W) </li>
  <li>Youm-e-Hussain (A.S.).</li>
</ul>
