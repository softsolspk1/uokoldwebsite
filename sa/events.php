          <h3>Quiz Rules:</h3>
          <p><strong>Quiz Theme:</strong><br />
            Theme of the Quiz is <strong>Pakistan</strong>. <br />
            Sub-themes are:</p>
          <ul>
            <li>Freedom Movement (1857 – 1947)</li>
            <li>Post Independence (1947 – 1977)</li>
            <li>Geography &amp; Sports </li>
          </ul>
          <br />
          <p><strong>Quiz  Rounds:</strong></p>
          <ul>
            <li>Preliminary round will be held on 7th  August, 2017 at 10:30 am.</li>
            <li>Final round of the selected teams will be held  on 9th August, 2017 (timing will be announced later).</li>
          </ul>
          <p><strong>General  Rules:</strong></p>
          <ul>
            <li>Only team entries are eligible.</li>
            <li>A team shall consist of max. TWO students.</li>
            <li>The decision of the quiz-master will be final  and will not be subjected to any change.</li>
            <li>The participant shall not be allowed to use  mobile or other electronic device.</li>
            <li>The question shall be in the form of multiple  choice, True/False statement, specific-answer question, etc.</li>
            <li>Audience shall not give any hint or clues to the  competitors.</li>
            <li>Replacement of any participant of a team is not  allowed after registration.</li>
          </ul>
