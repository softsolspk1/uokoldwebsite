  <p>&nbsp;</p>
  <p><strong>The 22nd Annual  Convocation of the university was held on Saturday, December 17, 2011 at the  Valika Cricket Stadium, University of Karachi. It was presided over by the Sindh  senior minister for Education Pir Mazhar-ul-Haq who is also the Pro Chancellor of  the University of Karachi. The Vice Chancellor Prof. Dr. Pirzada Qasim Raza  Siddiqui, and the Pro Vice Chancellors Prof. Dr. Shahana Urooj Kazmi and Prof.  Dr. Nasir Khan were also present.</strong></p>
  <p>Degrees,  including 315 PhDs, were conferred on 9,766 graduates of University`s morning  and evening programme. However, the number of graduates who received their  degrees in person at the convocation was around 1,800. The convocation was held  for the students who passed their BA, BSc, BCom, BBA, BPA (Honours), BS, MA, MSc,  MCom, MBA, MPA and Pharm-D examinations in 2009 and 2010 and those who did  their MS/MD, MPhil and PhDs in 2010 and 2011. As many as 102 students were  awarded gold medals amid loud applause from students, their parents and faculty  members.<br />
    <br />
    In all 9,766 graduates were awarded degrees. They  were 7,320 students 3,718 of 2009 and 5,602 of 2011 of different bachelors and master  programmes, 131 MPhil 54 of 2010 and770 of 2011 and 315 PhDs – 125 of 2010 and  190 of 2011.<br />
    <br />
    A significant aspect of the convocation was the  conferment of doctorate of science (DSc) upon renowned urologist and director  of the Sindh Institute of Urology and Transplantation Prof (Dr) Adibul Hassan  Rizvi in recognition of his dedicated services in the field of urology. </p>
