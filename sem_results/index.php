  <h1>Incharge: Prof. Dr. Tanveer Abbas</h1>
  <p>&nbsp;</p>
  <p align="justify">Semester Examinations Section is catering the examination &amp; Academic matters related with semester rules for various Faculties of the University of Karachi as well as Affiliated Colleges.</p>
  <p align="justify">Semester Examinations Section, University of Karachi, was established in 1974 on the initiative of the then Dean, Faculty of Science; Prof. Dr. Zainul Abedin when Prof. Dr. Mehmood Hussain was the Vice-Chancellor. It passed through various phases of its evolution care-taken by various Faculty Teachers as Incharge/Advisor of this section.<br />
    The Semester Examinations Section is housed in temporary places since its inception in 1974. This section is still neglected though provided a better place than previously in 1997. The present place (at the ground floor of Computer Science Department), was one of the hostel building earlier. However, the Semester Examinations Counter for students' dealing was placed at the Administration Building to keep the students away from the confidential section. </p>
  <p align="justify">Before 1997, semester examination results were not announced comprehensively with the statements of failure and remarks of objections, if any. This deficiency had resulted in many anomalies in connection with results and promotions to higher class. Therefore, the result announcement procedure was changed and all information regarding student's particulars and his/her academic status along-with objections, if any, are being printed in result announcement sheet. This procedure has reduced the number of queries as well as anomalies in promotion to next higher class.</p>
  <p align="justify">During 1998-2006 this section has developed annual cycle for all the activities that depends on the input from various Departments and Affiliated Colleges.</p>
  <p align="justify">The year 1998 was associated with grass root organization of procedures involved in daily Daak result receiving, admit card issuance, result tabulations remuneration bills and result announcement etc.</p>
  <p align="justify">Later, in 1999 &amp; 2000, Semester rules were revised and updated with the approval of Academic Council. Consequently, a booklet was published for circulation. In this period, Semester Examinations Section has uplifted the technical and structural aspects by the induction of new computers, peripherals and standard quality furniture.</p>
  <p align="justify">In 2001 &amp; 2002 Central Air Conditioning was carried out with the induction of software for the calculation of grades from numerical marks and their conversion into fractional grading for B.S., B.Pharm. &amp; B.B.A. In this year Semester rules were also updated alongwith color printing facility &amp; the Publication of 1st Annual Report.</p>
  <p align="justify">The year 2003 &amp; 2004, were prominent due to the development of a software for Marks Proforma preparation. In addition, G-1 form was also inducted to facilitate clean application system for University students. In this year a separate unit was also established for the work load related with Affiliated Colleges.</p>
