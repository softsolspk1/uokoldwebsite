<p>Below are the few important semester rules taken from the Semester Rules Book-2002 for the convenience of the students in order to remove their difficulties which they face very soon after getting admission:</p>
  <p align="center"><strong><u>Rules for BS Program</u></strong></p>
  <p><strong><u>Subsidiary Subjects</u></strong><br />
    (i)         A student will choose two subjects as Subsidiary Subjects out of the approved list of combination of such subjects, in addition to a Major subject.<br />
    (ii)        The allocation of subsidiary subjects will be decided by the Dean in consultation with the Chairperson of the Department.</p>
  <p><strong><u>Course Requirement</u></strong></p>
  <p>Humanities will be offered to only those students who do not have Urdu as their Mother tongue. Science Students are ineligible to take Natural Science. Arts students who have passed science subject at Intermediate or A/O levels are also not eligible to take Natural Science.</p>
