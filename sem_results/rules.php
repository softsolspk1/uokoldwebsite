  <p><strong>Formula</strong><br />
    Grade points in a course= (Credit hours of the course)x (Grade point equivalent to the score given in the grade point)<br />
    <br />
    CGPR = (Total Grade Points in all the courses)/(Total number of Cr. Hrs.)</p>
  <p>* For the award of BS or BE degree  a student will have to obtain a minimum of 2.2 CGPR or 2.45 CGPR respectively.  A student who will be declared short of CGPR shall improve it in the next available single chance by appearing in two courses having less than 61 marks, i.e. C-, D+ or D Grade.</p>
  <p>Appearance in the mid-term exam is compulsory for each student, otherwise he/ she would be declared fail in that paper.  Such candidates have to appear in the mid-term test in the next year.<br />
  </p>
  <p><strong><u>CHANGE OF SUBJECTS</u></strong></p>
  <ol>
    <ol>
      <li>Student can change the major subject in the second year if they obtain A-grade in both the semesters in their minor subject, which they want to offer as their major subject, provided that they have passed all the courses of first year and secured total aggregate of 60% provided further that the Chairpersons have no object to this change subject to the availability of subsidiary combination.</li>
      <li> Students seeking change in any of the minor subject can apply for change within 30 days of the start of the semester of 1st year as well as 2nd year. All such permissions would be granted by the Dean on the recommendation of the Chairperson, provided there is a provision of such combination in the statutes.</li>
    </ol>
  </ol>
  <p><strong><u>Assessment</u></strong></p>
  <p> (a)       A minimum of 50% marks are required to pass. Both theory and practical exams are separate passing heads.</p>
  <p align="center"><strong><u>Rules for M.Sc. Program</u></strong></p>
  <p align="left"><strong><u>Conditions for Thesis/ Projects</u></strong></p>
  <ol>
    <li>M.A./M.Sc./M.Com./BS Final year students who have passed all the earlier courses and secured an average of minimum of 65% marks in 500 level courses, may be allowed to offer a thesis equivalent to 6 credit hours in lieu of two courses.</li>
    <li>Students of M.A./M.Sc./M.Com./BS Final may be permitted to offer one project or research report in lieu of one course of 3 credit hours, provided he/she secures minimum of 605 marks in 500 level courses, whereas in Sociology and Social Work it will be in lieu of 2 courses (called to be thesis) and in Library and Information Science it will be in lieu of one special course of 4 credit hours during the final year of their studies.</li>
    <li>Students will not be allowed to write thesis and work on projects at the same time.</li>
  </ol>
  <p>*Thesis/Project should be submitted on the last date of 2nd Semester Examination. However, a grace period of 40 days may be given by the Chairperson of the Department.</p>
  <p><strong><u>Assessment</u></strong></p>
  <ol>
    <li>A minimum of 40% marks are required to pass. Both theory and practical exams are separate passing heads.</li>
    <li>For M.B.A. 2.2 CGPR and where Grade Point System adopted before 2006, a minimum of 2.45 CGPR is required to obtain Master Degree.</li>
  </ol>
  <p align="center"><strong><u>General Rules</u></strong></p>
  <p><strong><u>PROMOTION RULES</u></strong></p>
  <ol>
    <li>Students shall not be promoted to the next higher class if he/she fails to clear 80% of courses.</li>
    <li>A student repeating a course shall not be given a rank in order of merit.</li>
  </ol>
  <p><strong><u>ASSESSMENT</u></strong></p>
  <p>The assessment of student’s performance will be made out of 100 marks fixed for a course in general.</p>
  <p><strong><u>FAILURES / REPETITION</u></strong></p>
  <ol>
    <li>If a student is unable to complete the attendance requirement in any course, he/she shall be required to attend the entire course whenever it is offered again. He/She will become eligible for taking the examination in the particular course only after he/she has completed its attendance requirement. Such a student shall pay a prescribed fee for attending the classes as Casual Student.</li>
    <li>If a student, after completing the attendance requirement, does not appear or fails in the terminal examination of a course, he/she will be allowed to re-appear not more than twice in the terminal examination when it is offered in the next session after the payment of prescribed examination fee as Repeater Student.</li>
    <li>A repeater student who fails to clear a course / courses in three regular, available chances will not be eligible to re-appear. He/She may be allowed as a last chance to attend the classes of the course/courses he/she failed to clear. Permission to appear in the examination will be subject to completing attendance requirements.</li>
    <li>If a student has failed in only one paper of a degree program and he/she declared to attend fresh classes as 3rd time failure shall be allowed to take condense classes to complete his degree program and to appear in the examination, provided he/she is losing one year if asked to attend fresh classes in regular semester.</li>
  </ol>
  <p><strong><u>CANCELLATION OF ADMISSION / RE-ADMISSION</u></strong></p>
  <p>      If a student admitted in BS 1st year or Masters (Prev.) or Pharm-D 1st Year class for the first time fails to attend the class for the 15 days, his/her admission shall stand cancelled. A student who has failed more than 50% courses in a year, his/her admission shall be cancelled. Cancelled admission of those students who fails in &gt;50% of courses in their first academic year will be restored by Dean with Chairperson’s recommendation.</p>
