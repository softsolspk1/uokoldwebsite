<h2>Director: Prof. Dr. Muhammad Naeem Khan</h2>
<p>&nbsp;</p>
<div align="justify">
  <p align="justify">The university aims to empower the Office of Research, Innovation, and Commercialization (ORIC) to provide centralized support to researchers, such as help with grant writing, publication, and intellectual property which will help in enhancing the internationalization and visibility of research by engaging in global networks, partnerships, collaborations, exchanges, and mobility programs with other reputed institutes. Moreover, ORIC is evolving into a commercial organ of varsities across the globe. It is aiming to embark upon Quad-Helix-Model and then to Pent-Helix-Model to serve the
    global community with shared vision. The universities should establish a maximum number of technology parks under the ownership of ORIC to boost commercialization of research. The aim is to begin with Eco-Center for Commercialization and KU Spark Valley.</p>
  
  <p align="justify">ORIC is encouraging entrepreneurship and innovation culture among the students and faculty by providing training, funding, incubation, or acceleration services.</p>
  <p></p>
  <p align="justify">The is being done at the university of Karachi in the following ways:<br/>
  <ul>
  <li>Integrating entrepreneurship education into the curriculum, teaching students the concepts, skills, and attitudes of entrepreneurship.</li>
  <li>Organizing entrepreneurship events and competitions, exposing students to real-world scenarios and challenges of entrepreneurship.</li>
  <li>Establishing entrepreneurship clubs and networks, connecting students with peers, mentors, experts, and investors who can support their entrepreneurial journey.</li>
  <li>Providing entrepreneurship resources and facilities, such as incubators, accelerators, co-working spaces, and funding schemes that can help students launch and grow their businesses.</li></ul>
  
