  <h3 align="center">Institutional Biorisk Management Committee</h3>
  <p>&nbsp;</p>
  <p align="justify">This is with aim to maintain the high standard set by the institute in the research and development for 
    publication and quality of research projects, an “Institutional Biorisk Management Committee (IBRMC)” is
    constituted to support the biorisk management system at the University of Karachi.<br/>
    The committee is comprising of following faculty members/ directors to streamline the research projects in
    accordance with the institutional biosafety policies and codes of practice along with reviewing research
    protocols involving infectious agents, animal use, recombinant DNA and genetically modified materials and
    synthetic biology aspects of the projects.</p>
 
