<h4>&nbsp;</h4>
<p><strong><u>Conference Objectives:</u></strong></p>
<ul>
  <li>Provide a platform for knowledge transfer and idea exchange. </li>
  <li>Foster research collaborations. </li>
  <li>Identify knowledge gaps and prioritize research areas. </li>
  <li>Train young scientists and environmental practitioner. </li>
  <li>Solicit experts&rsquo; advices on practical issues related to local  Marine Biodiversity Conservation, Fisheries Management, Blue Economy Marine  Renewable Energy &amp; Marine  &amp; Coastal Socio-Environmental Aspects.</li>
  <li>Identify and provide efforts for gaining all possible outcomes of  UN&rsquo;s Program <strong>&ldquo;</strong><strong>United  Nations Decade of Ocean Science for Sustainable Development</strong><strong>&nbsp;(2021-2030)&rdquo;</strong>, with the  following aims: </li>
  <li><strong>A Clean Ocean, </strong>where sources of pollution  are identified and reduced or removed.</li>
  <li><strong>A Healthy and Resilient  Ocean, </strong>where  marine ecosystems are understood, protected, restored and managed.</li>
  <li><strong>A Productive Ocean, </strong>supporting sustainable food  supply and a sustainable ocean economy.</li>
  <li><strong>A Predicted Ocean, </strong>where society understands  and can respond to changing ocean conditions.</li>
  <li><strong>A Safe Ocean, </strong>where life and livelihoods  are protected from ocean-related hazards.</li>
  <li><strong>An Accessible Ocean, </strong>with open and equitable  access to data, information and technology and innovation.</li>
  <li><strong>An Inspiring and Engaging  Ocean, </strong>where  society understands and values the ocean in relation to human wellbeing and  sustainable development.</li>
</ul>
