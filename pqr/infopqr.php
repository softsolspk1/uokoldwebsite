    The Higher Education Commission has adopted subject list of  joint Academic classifications of subjects (JACS) developed by Higher Education  Statistics Agency (HESA) with certain amendments to match with the national  context. It enlists the major disciplines, sub-fields, and helps in  standardization of the subject nomenclature along with categorizing each  subject into its relevant major discipline.</p>
