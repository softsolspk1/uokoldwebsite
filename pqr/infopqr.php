  <p align="justify">The  following information is publicly available on the Register:<br />
    <br />
    Name &amp;  Title of Qualification<br />
    The Register contains the Name &amp; Title of Qualification  which is consistent with the criteria for the use of Title and Nomenclature. It  will help in reducing the confusion by the use of different nomenclature for  similar degrees and use of similar nomenclature for degrees that are actually  quite different in duration and scope.<br />
    Qualification Levels and Program Titles<br />
    The Register has eight levels are based on the Generic  nomenclature used for the qualification in the country. A qualification must be  assigned to one of the eight levels. The Framework does not describe  qualifications at the same level as being equal and qualifications at the same  level are not interchangeable, however, they are at a comparable level in terms  of knowledge, skills or competence required.<br />
    Learning Outcomes<br />
    Each qualification level contains an Outcomes statement that  brings clarity and emphasize on the development of qualification. The  development of outcomes for a qualification guide for the development of course  content, and processes for teaching, learning and assessment. A qualification  outcome statement will inform the students and employers that what the  qualification holder will have achieved by the end of the qualification. It  will also make the purposes and objectives of learning clear to the learner and  also convey information to every employer about what job applicant knows.</p>
  <p>Credit Hours</p>
  <ul>
    <li><span dir="ltr"> </span>Credit hour  means teaching a theory course for 50 minutes each week throughout the  Semester.</li>
    <li><span dir="ltr"> </span>One credit hour  in laboratory or practical work / project would require lab contact of two hour  per week throughout the semester.</li>
    <li><span dir="ltr"> </span>The credit hours  are denoted by two digits within brackets with a hyphen in between. The first  digit represents the theory part while the second (right side) digit represents  the practical.</li>
    <li><span dir="ltr"> </span>Thus 3(3-0)  means three credit hours of theory, while 4(3-1) means a total of four credit  hours, of which three are of theory while one credit hour is for laboratory</li>
    <li><span dir="ltr"> </span>The weekly  contact hours of a 3(3-0) course will be three, the contact hours of a 4(3-1)  course will be six.</li>
    <li><span dir="ltr"> </span>The contact  hours during each week of the Summer Session will be doubled to ensure that the  course is completely taught in a semester with half the duration compared with  a regular (Fall/Spring) semester.</li>
  </ul>
