  <p align="justify"><strong><u>Quality  Assurance Mechanism</u></strong><br />
    There are two types of accreditations carried out in most  parts of the world i.e., Institutional and Program accreditation. Institutional  Accreditation looks at the whole Institution, whereas, the program  accreditation emphases on individual and professional programs. In Pakistan  Institutional accreditation is carried out by the Higher Education Commission  (HEC) while, program accreditation is carried out by the Accreditation  Councils.<br />
