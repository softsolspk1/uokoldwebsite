<div align="justify">
  <p>The Pakistan Qualification Register (PQR) is part of the  Pakistan Qualification Framework (PQF). PQR provide information about the  qualifications that the Higher Education Commission has recognized/accredited.  Higher Education Commission does not accept qualifications that are not  mentioned on the PQR. The Pakistan Qualification Register (PQR) University of  Karachi is responsible to uploading Institutional Data of University of Karachi  on Higher Education Commission&rsquo;s Pakistan Qualification Register (PQR) Portal.<br />
    <br />
    The Pakistan Qualification Register is a list of all  qualifications, as well as the providers/Higher Education Institutions that  have been recognized/accredited to deliver and issue them. Only Quality Assured  Qualifications and Higher Education Institutions accredited by the Higher  Education Commission of Pakistan are included in the register.<br />
  </p>
  <ul>
    <li>PQR assists in  making quality-assured and accredited/recognized qualifications/programs  available to all stakeholders.</li>
    <li>PQR aids in the  acknowledgment of qualifications on a global scale.</li>
    <li>PQR enables  learners&rsquo; and graduates&rsquo; cross-national mobility.</li>
    <li>PQR aids in the  identification of the credit transfer procedure.</li>
