  <div align="center"><h3>Scholarship Opportunities at the University of Karachi</h3></div>
  <p align="justify">Explore various scholarship options available for students at the University of Karachi, designed to support their educational journey and promote academic excellence.</p>
    <p>&nbsp;</p>
    <h4>Mitsubishi UFJ Foundation Scholarship</h4>
    <p align="justify">The Mitsubishi UFJ Foundation offers merit-based educational support to undergraduate students in their third and final years of the morning program. The foundation is dedicated to enhancing academic pursuits and promoting educational excellence.</p>
    <p>&nbsp;</p>
    <h4>Balochistan Endowment Fund (BEEF)</h4>
    <p><strong>Eligibility:</strong>
    <li>Local students from Balochistan enrolled at the University of Karachi</li>
    <li>Minimum of 60% marks</li>
    <li>Not receiving any other scholarships</li></p>
    
    <p><strong>Focus Academic Areas:</strong>
    <li>Energy</li>
    <li>Agriculture</li>
    <li>Health</li></p>
    
    <p>BEEF invites scholarship applications to support local students pursuing these vital fields of study.</p></p>
  
   <h4>Sindh HEC Indigenous Scholarship for MS and M.Phil</h4>
      <p align="justify">This scholarship aims to provide equal opportunities for MS/M.Phil. and Ph.D. students at the University of Karachi.
    <p><strong>Eligibility Requirements:</strong>
    <li>Must be a Pakistani national</li>
    <li>CGPA of 3.0 or above</li>
    <li>Full time researcher</li>
    </p></p>
   <h4>Bismillah Bibi & Mrs. TalatJamil Scholarship</h4>
   <p align="justify">Offered by the Trust for Science &amp;amp; Technology, this scholarship provides merit-based awards for students in the science and pharmacy departments at the University of Karachi.</p>
  <p>&nbsp;</p>
  <h4>Sindh Education Endowment Fund (SEEF)</h4>
  <p align="justify">The Government of Sindh is offering more than 300 scholarships for students from low-income groups to pursue higher education at University of Karachi.
    <p><strong>Support Provided:</strong>
    <li>Covers one year&amp;#39;s tuition fees</li>
    <li>Renewable for subsequent years subject to satisfactory academic performance.</li>
   <p>&nbsp;</p> 
  <h4>HEC Needs-Based Scholarship</h4>
  <p align="justify">This program covers two semester fee in addition to monthly stipend disbursed on bi-annual/annual basis subject to continued allocation and availability of funds at the University.
    <p><strong>Eligibility Requirements:</strong>
    <li>Family income must not exceed Rs. 45,000</li>
    </p></p></p></p>
   
  <h4>Need-Cum-Merit Based Scholarship by Zakat and Ushr Department</h4>
  <p align="justify">The Government of Sindh’s department of Zakat &amp;amp; Ushr offers scholarships to deserving students in the morning program.
    </p>
    <p>&nbsp;</p> 
  <h4>Ihsan Trust</h4>
  <p align="justify">Ihsan Trust provides interest-free loans (Qarz-e-Hasna) to needy students in both morning and evening programs at the University of Karachi.<br />
    <p><strong>Loan Details:</strong>
    <li>Zero percent interest</li>
    <li>Repayment starts a month after the loan is granted</li>
    </p></p>
    <p>&nbsp;</p> 
  <h4>Al-Rehman Welfare Trust</h4>
   <p align="justify">Al-Rehman Welfare Trust offers need based scholarship for selected academic departments. Award Money per student is Rs. 50,000/-</p>
    <p>&nbsp;</p> 
    
  <h4>University of Karachi Alumni Association (UKAA)</h4>
  <p align="justify">UKAA provides merit-cum-need scholarships to support students&amp;#39; educational pursuits at the University of Karachi.</p>
    <p>&nbsp;</p> 
    
  <h4>University of Karachi Alumni Association Houston (UKAHA)</h4>
  <p align="justify">UKAHA provides a limited number of scholarship which covers annual semester fee to support students' educational pursuits at the University of Karachi. This scholarship may be renewed subject to satisfactory academic performance and confirmation from donor agency.</p>
    <p>&nbsp;</p> 
