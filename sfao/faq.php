  <div align="center"><h3>Frequently Asked Questions (FAQs) for University Scholarships</h3></div>
  <p><strong>Q: How many scholarship slots are available, and what is the award  amount for Sindh HEC indigenous?</strong><br />
    A: 63 scholarship slots are provided in 2023-24. Each successful  candidate is rewarded Rs. 230,000.</p>
  <p><strong>Q: How long is the HEC need-based scholarship duration, and what  is the award amount?</strong><br />
    A: As per HEC policy subject to allocation and release of funds  for this purpose.</p>
  <p><strong>Q: Which departments/faculties are eligible for the Bismillah Bibi  &amp; Mrs. Talat Jamil Scholarship?</strong><br />
    A: Merit-based scholarships for students in departments under the  faculties of Science &amp; Pharmacy. Morning Program students are eligible.</p>
  <p><strong>Q: Where can I find details about the scholarship interview,  including time and venue?</strong><br />
    A: All the information will be available on the Karachi University <strong>website</strong>. <a href="https://uok.edu.pk/sfao/scholarships.php">https://uok.edu.pk/sfao/scholarships.php</a>&nbsp;</p>
<hr size="1" width="100%" align="center" /><br/>
<h3>1. What are  the official platforms for scholarship information?</h3>
<p><strong>A:</strong>&nbsp; <a href="https://uok.edu.pk/sfao/scholarships.php#y2023" target="_blank"><strong>Official  Scholarship Page</strong></a><strong>:</strong> <a href="https://www.uok.edu.pk/sfao/scholarships.php"><strong>https://www.uok.edu.pk/sfao/scholarships.php</strong></a><strong> </strong><br />
  <strong>A:</strong>&nbsp; <strong>KU</strong> <strong>Official Facebook Platform: </strong> <strong>KU Times</strong> <a href="https://www.facebook.com/kutimes?mibextid=ZbWKwL"><strong>https://www.facebook.com/kutimes?mibextid=ZbWKwL</strong></a> <br />
  <strong>A:</strong>  <strong>KU</strong> <strong>Official WhatsApp Channel:</strong> <strong>KU Times</strong> (WhatsApp Link: <a href="https://whatsapp.com/channel/0029Vap9QMDAO7RIzFDvuu2B">https://whatsapp.com/channel/0029Vap9QMDAO7RIzFDvuu2B</a> )<br />
  <strong>A:</strong> <strong>Official E-mail  address of SFAO:</strong> <strong>sfao@uok.edu.pk</strong></p>
<p>&nbsp; </p>
<hr size="1" width="100%" align="center" /><br/>
<h3>2. Are  there extensions for the submission of scholarship forms?</h3>
<p><strong>A:</strong>&nbsp;Extensions for  the submission of scholarship forms are rare. For more details, please refer to  the&nbsp;<a href="https://uok.edu.pk/sfao/scholarships.php#y2023" target="_blank">official scholarship page</a>.</p>
<hr size="1" width="100%" align="center" /><br/>
<h3>3. What is  the deadline for submitting scholarship forms?</h3>
<p><strong>A:</strong>&nbsp;Every  scholarship has different date of advertisement and deadlines. Therefore students  are advised to carefully <u>READ &amp; UNDERSTAND</u> the scholarship advertisement  uploaded on <a href="mailto:Official%20Scholarship%20Page">Official Scholarship  Page</a> where all such information is carefully mentioned by SFAO. For further  inquiries, contact&nbsp;<a href="mailto:sfao@uok.edu.pk" target="_blank"><strong>sfao@uok.edu.pk</strong></a>.</p>
<hr size="1" width="100%" align="center" /><br/>
<h3>4. How can  I obtain information about scholarships at KU?</h3>
<p><strong>A:</strong>&nbsp;By visiting  any of the official platforms listed at para-1.</p>
<hr size="1" width="100%" align="center" /><br/>
<h3>&nbsp;</h3>
<h3>5. Are  students enrolled in both the morning and evening programs eligible for  scholarships?</h3>
<p><strong>A:</strong>&nbsp;Only morning  program students are eligible for scholarships unless specified in scholarship  advertisement.</p>
<hr size="1" width="100%" align="center" /><br/>
<h3>6. What  financial assistance options are available for Evening Program students at the  University of Karachi?</h3>
<p><strong>A:</strong>&nbsp;Evening  Program students at the University can apply for Ihsan Trust Interest Free Loan  Scheme on a prescribed form available at official scholarship page.  Applications for this facility are open throughout the year. </p>
<hr size="1" width="100%" align="center" /><br/>
<h3>5. Who is  eligible to apply for the HEC Need-Based scholarship at the University of  Karachi?</h3>
<p><strong>A:</strong>&nbsp;Morning  program on campus regular students whose family income is within Rs. 45,000/- are  eligible and they can apply for HEC-Needs Based Scholarship upon advertisement  by SFAO.</p>
<hr size="1" width="100%" align="center" /><br/>
<h3>6. Can I  apply for financial aid during the semester or year?</h3>
<p><strong>A:</strong>&nbsp;Yes, you can  apply for the Ihsan Trust Interest Free Loan Scheme at any time of the year.</p>
<hr size="1" width="100%" align="center" /><br/>
<h3>7. To whom  will these scholarships be awarded?</h3>
<p><strong>A:</strong>&nbsp;Students are  encouraged to carefully read and understand the eligibility criteria for the  specific scholarship program they intend to apply for.</p>
<hr size="1" width="100%" align="center" /><br/>
<h3>8. Can I  submit manual applications to the financial aid office?</h3>
<p><strong>A:</strong>&nbsp;No,  applications must be submitted as per procedure laid down in the scholarship  advertisement. Generally the process involves two steps:</p>
<ul>
  <li>Download scholarship application form       from official scholarship page and take a Printout.</li>
  <li>Fill-in the required details on the Printed       form and provide online data on the given link mention on the form. Once       online data is provided applicants are required to submit the complete       application with required documents (hardcopy) to SFAO by the given       deadline. </li>
</ul>
<hr size="1" width="100%" align="center" /><br/>
<h3>9. Can I  apply for a scholarship before being admitted to KU?</h3>
<p><strong>A:</strong>&nbsp;No, you must  first gain admission to apply for scholarships. However if you are facing  financial difficulty you may apply for Ihsan Trust Interest Free Loan facility  after submitting admission form. </p>
<hr size="1" width="100%" align="center" /><br/>
<h3>10. What  documents are required with a scholarship application at Karachi University?</h3>
<p><strong>A:</strong>&nbsp;A list of  required documents is mentioned on the application form. Students should  carefully <u>READ and UNDERSTAND</u> the particular scholarship form.</p>
<hr size="1" width="100%" align="center" /><br/>
<h3>11. Is it  possible to change the online application after submission?</h3>
<p><strong>A:</strong>&nbsp;Yes, if  corrections are needed, the applicant can visit the SFAO office to make the  necessary adjustments alongwith a written request for correction of particulars  in online data.</p>
<hr size="1" width="100%" align="center" /><br/>
<h3>12. What  happens if a student fails an examination and requests the continuation of  their scholarship?</h3>
<p><strong>A:</strong>&nbsp;Renewal of  Scholarship for subsequent years is subject to satisfactory academic  performance. Students who are failed in course (s) may not be awarded  subsequent installments. However, only exceptional cases which are beyond  control may be considered by SFAO subject to approval of the competent  authority. </p>
<hr size="1" width="100%" align="center" /><br/>
<h3>13. How are  students informed about their financial aid status at KU?</h3>
<p><strong>A:</strong>&nbsp;SFAO notifies  every piece of information on official scholarship page and social media  platforms. Students are advised to keep themselves updated and visit the  official scholarship website on  a weekly  basis for updates on their status.</p>
<hr size="1" width="100%" align="center" /><br/>
<h3>14. Are  there scholarships available for graduate programs?</h3>
<p><strong>A:</strong>&nbsp;Yes, there are  scholarships available for graduate programs.</p>
<hr size="1" width="100%" align="center" /><br/>
<h3>15. Can I  receive multiple scholarships?</h3>
<p><strong>A:</strong>&nbsp;No, you cannot  avail multiple scholarships simultaneously.</p>
<hr size="1" width="100%" align="center" /><br/>
<h3>16. Is a  merit scholarship available at KU?</h3>
<p><strong>A:</strong>&nbsp;Yes, the  Mitsubishi UFJ Foundation provides merit-based scholarships.</p>
<hr size="1" width="100%" align="center" /><br/>
<h3>17. Can I  submit documents online after submitting my financial aid application?</h3>
<p><strong>A:</strong>&nbsp;No, in-person submission  of documents in hard copy is mandatory.</p>
<hr size="1" width="100%" align="center" /><br/>
<h3>18. Can I  apply for multiple scholarships?</h3>
<p><strong>A:</strong>&nbsp;Yes, you can  apply for multiple scholarships; however, once awarded, a scholarship will  continue for the entire year or as per criteria and duration of respective  scholarship.</p>
<hr size="1" width="100%" align="center" /><br/>
<h3>19. What  should I do if I don&rsquo;t have the required documents?</h3>
<p><strong>A:</strong>&nbsp;If you lack  certain documents, include a written application explaining the situation along  with your other documents. This does not constitute exemption from required  documents, in any case, however SFAO may assess the situation keeping in view  your written application.  </p>
<hr size="1" width="100%" align="center" /><br/>
<h3>20. What if  I don&rsquo;t have income proof (income certificate/pay slip)?</h3>
<p><strong>A:</strong>&nbsp;Here are some  alternatives:</p>
<ul type="disc">
  <li><strong>Bank Statement:</strong>&nbsp;If your       family receives financial support from abroad, provide a bank statement       for the last six months showing the credited funds.</li>
  <li><strong>Utility Bills:</strong>&nbsp;If your       family&rsquo;s income comes from a privately owned business, attach an       application detailing the source of income and include a utility bill from       the business.</li>
  <li><strong>Affidavit:</strong></li>
  <ul type="circle">
    <li><strong>For Drivers:</strong>&nbsp;Submit a        written application and an affidavit on stamp paper detailing the source        of income and monthly salary.</li>
    <li><strong>For Agriculture:</strong>&nbsp;Provide        an affidavit on stamp paper if the income is from agriculture.</li>
  </ul>
</ul>
<p><strong>Applications:</strong>&nbsp;If the  employee does not receive a salary, submit an application clarifying the situation  clearly stating employer legal status.</p>
