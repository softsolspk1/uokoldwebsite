  <h2>&nbsp;</h2>
<p>At the time of creation of Pakistan as a sovereign state in  1947, means for higher education and research were negligible. Responding to  the impending requirement of higher learning, Pakistan started establishing  relevant educational institutions of higher learning and research and thus underwent  rapid modernization. The University of Karachi was established by an act of  Pakistan parliament in June, 1951. The present campus, to which the University  shifted in 1959, is spread over 1279 acres of land, situated 12 Km away from  the city center. <br />
</p>
<p>Today the University is recognized as a premier center of  learning and research in the Subcontinent and in the Third World. A number of  scientists and scholars affiliated with the University are working in important  positions both within and outside Pakistan and have won recognition and  acclaim. One of the institutes of the University has got the distinction of  being made the Centre of the Third World Academy of Sciences. Students from  several foreign countries are also pursuing for the Masters and Doctorate  degrees. Because of high academic and research standards of the University a  large number of students from Karachi and other parts of the country apply for  admission here. Keeping in view a very high number of applicants, the  University has started evening classes in several departments at BS and Masters  Levels and a Directorate of Evening Program was established to control and run  Evening Program. <br />
  </p>
<p>At present teaching at the University campus is conducted  under six faculties: Faculty of Arts, Faculty of Science, Faculty of Islamic  Studies, Faculty of Management &amp; Administrative Sciences, Faculty of  Engineering and Faculty of Pharmacy. There are over 52 departments and 19  research institutes/ centers, which are imparting education to more than 24,000  students including students from foreign countries. The faculty comprises of  more than 700 highly qualified and experienced teachers; many of them have  obtained higher degrees from abroad and enjoy a high repute internationally.  The non-teaching staff comprises more than 1700 people to help with  administrative and other matters.
  </p>
<p>The University of Karachi is also an affiliating  and examining body and at present, 145 colleges and institutions are affiliated  to the University. The courses of studies for these institutions are approved  by the University and examinations are also conducted under its auspices. The  University conducts examinations of about 150,000 students studying in these  colleges/institutes, prepare their results and award degrees. </p>    
