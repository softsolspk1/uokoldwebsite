<h3 align="center">UPDATED ADMISSION POLICY  DOCUMENT FOR FOREIGN  STUDENTS</h3>
 <p align="center"><strong>Categories of Foreign  Students: </strong><br />
  Foreign students fall into two categories: one category consists of those  having a foreign nationality and applying from the country of their origin  while the other category consists of  those foreign students who are already in Pakistan for study purpose and have a study visa. For each category, there is  a separate admission procedure:</p>

<h4>a. &nbsp; Admission  Policy for students with foreign nationality applying from the country  of their origin:</h4>
<ul>

<li>All foreign candidates who wish to take admission in  the University of Karachi on  scholarship are required to apply for admission through Pakistan High Commission in their home country or through the Ministry of  Economic Affairs, Islamabad.</li>

<li>Once the Embassy/High Commission issues the <em>No Objection Certificate</em> (NOC), the candidate desirous of seeking  admission on scholarship has to send all the previous educational documents to Higher Education Commission (HEC) and  the Ministry of Education, Islamabad. </li>

<li>Those applying on self-finance basis have to request  their country&rsquo;s embassy or High commission in Pakistan to send their request  along with a copy of their previous educational documents and NOC to the  Registrar, University of Karachi either through email or courier. </li>

<li>After the verification of the documents from the  Higher Education Commission and Ministry of Education,  in case of those applying on scholarship, a clearance letter is sent to the  university carrying the list of nominated candidates. The nominated candidates are issued the  provisional admission  letter, which is sent to HEC or the Ministry of Economic Affairs, Islamabad,  depending on the nature of the scholarship. However, the provisional admission  letter of those who apply on self-finance basis is sent to their embassy.  </li>

<li>The provisional admission letter does not, however,  imply conformation of admission.  The provisional letter is issued to facilitate students so that they can apply for student visa and are able  to join the university when the academic session begins. Once the students join the  university, they must apply for enrolment. It is only when they are issued the  enrolment card that their admission is confirmed. </li>

<li>In order to apply for the student visa, students  are required to send all the educational         documents along with the visa application  form, a copy of the passport, photographs, and a copy of the  provisional admission letter through Pakistan  Embassy/High Commission in their home country to Assistant Director (Academics), Academics Division, Higher  Education Commission, Sector H- 9, Islamabad. It is pertinent to mention that  students can now apply for visa online by visiting the official website of the  Government of Pakistan for visa application.</li>

<li>Once the student visa is issued and the students  reach Pakistan, they have to report their arrival at both the Local  Police Station and the Office of the Foreign  Students&rsquo; Advisor, University of Karachi where they will be required to submit  the following documents:</li>
  <ul>
    <ul>
      <li>One original &amp; four copies of the No Objection  Certificate (NOC) issued by the  Embassy of the applicants&rsquo; country of origin.</li>
      <li>N.O.C or Admission letter from the Ministry of Foreign Affairs (In case, they are nominated for  any scholarship)</li>
      <li>Five copies of Passport &amp; valid Student  Visa.</li>
      <li>Five copies  of all the previous educational documents.</li>
      <li>Twelve photos (Size 1x 1 1/2)</li>
      <li>Equivalence Certificate issued by Inter Board  Committee of Chairmen (IBCC), Islamabad or Karachi (for admission in BS or  equivalent programme)</li>
  </ul>
  </ul>
</ul>
<p>&nbsp;</p>

<h4>b. &nbsp; Admission  Policy for foreign students who are already in  Pakistan for study purpose and have a valid  study &nbsp; &nbsp; &nbsp; &nbsp; visa:</h4>
<p align="justify">In order  to apply for admission to the  University of Karachi,  such foreign students have to submit the  following documents:</p>
<ul>
  <li>One original &amp; four copies of the N.O.C issued by  the Embassy of the applicants&rsquo; country  of origin.</li>
  <li>N.O.C or Admission letter from the Ministry of Foreign Affairs.</li>
  <li>Five copies of Passport &amp; valid Student  Visa.</li>
  <li>Five copies  of all the previous educational documents.</li>
  <li>Twelve photos  (Size 1x 1 1/2)</li>
  <li>Equivalence Certificate issued by Inter Board Committee of Chairmen (IBCC), Islamabad or Karachi (for admission in BS or equivalent programme). Students can now apply online  for IBCC equivalence. </li>
</ul>
<p>&nbsp;</p>
<h3>Additional  Documents Required for Change or Transfer from  the Current Department:</h3>
<ul><ul>
    <li>Four copies of the previous admission cancellation  letter of Deputy Registrar Academic  (DRA), University of Karachi.</li>
    <li>N.O.C from the Ministry of Foreign Affairs (only for  students who have already availed  themselves of Pakistan Technical Assistance Programme (PTAP) scholarship).</li>
</ul>
</ul>
<ul>
  <li><strong>Other  Requirements:</strong> All foreign students  who intend to apply for admission at the University of Karachi must check the minimum eligibility criteria given on the official  website of the University of Karachi before applying  for admission. </li>
</ul>
<ul>
  <li>The foreign candidates must take<strong> IELTS test</strong> and submit their test score. Candidates  with less than 5.0 bands in IELTS will be required to get themselves registered  in the <em>Remedial English Language  Certificate Course </em>which  is organized for the newly admitted foreign students by the Office  of the Foreign Students&rsquo; Advisor, University of Karachi every year. </li>
</ul>

<ul>
  <li>All the foreign students are also required to  get enrolled in the <em>Urdu Certificate  Course</em> once they join the university, as it is a necessary requirement.</li>
</ul>

<p>&nbsp;</p>
<p>&nbsp;</p>
<p align="justify"><strong><u>Important Note:</u></strong><br/>As per the decision  taken in the Academic Council meeting held in 2021, admissions are no more  offered in masters and honours programme in any department. From 2022 onwards,  admissions are offered in BS First year and BS third year.<br/>
As far as the  admissions in M.Phil. and Ph.D. programmes are concerned, they are processed  through the Office of the Advanced Studies and Research Board (ASRB),  University of Karachi. The Office of the Foreign Students&rsquo; Advisor does not  deal with admissions in M.Phil. and Ph.D. programmes.</p>
