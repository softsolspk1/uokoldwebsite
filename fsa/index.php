<h1>Dr. Shumaila Shafket Ali (Foreign Students’ Advisor)</h1>
<h4>&nbsp;</h4>
<p>The diversity of degrees offered in various disciplines  along with an affordable fee structure at the University of Karachi attracts  foreign students from both developing and developed countries every year. The  office of the Foreign Students&rsquo; Advisor has been established to guide foreign  students about the admission process and to facilitate them when they get  enrolled in the degree programmes and certificate/ diploma courses offered in  different departments at the University of Karachi. Since studying in another  country is more challenging, foreign students not only require help in the  admission process but also need academic advice to succeed in completing their  studies. In the past Students&rsquo; Advisor Office used to deal with the issues  related to both local and foreign students but later on a separate office was  established to deal exclusively with the foreign students&rsquo; matters.</p>
