  <h2>Expression of Interest  (EOI)</h2>
    
    <p> For Commercial Utilization of University of Karachi Estate  under Public-Private Partnership (PPP) Model</p>
    <p align="justify">The University of Karachi, a premier educational  institution of Pakistan, invites Expressions of Interest (EOI) from reputable  local and international firms,  consortia, and individuals for the commercial utilization of its available  estate under a Public-Private Partnership (PPP) model.</p>
     <p align="justify">The University possesses significant land  parcels and existing infrastructure with the potential for various commercial ventures, including but not limited to:</p>
      <ul>
        <li><span dir="ltr"> </span><strong>Educational  Facilities: </strong>Development of specialized academic blocks, research  centers, vocational training  institutes, or modern hostels. </li>
        <li><span dir="ltr"> </span><strong>Healthcare Facilities: </strong>Establishment of clinics, diagnostic centers, or specialized  hospitals. </li>
        <li><span dir="ltr"> </span><strong>Commercial/Retail: </strong>Development of shopping arcades,  food courts, convenience stores, or service centers. </li>
        <li><span dir="ltr"> </span><strong>Recreational Facilities: </strong>Creation of sports complexes, auditoriums, convention  centers, or green spaces. </li>
        <li><span dir="ltr"> </span><strong>Hospitality: </strong>Construction of guesthouses or limited-service  hotels. </li>
        <li><span dir="ltr"> </span><strong>Technology/Innovation Hubs: </strong>Development of incubators,  co-working spaces, or research parks. </li>
        <li><span dir="ltr"> </span><strong>Residential (Limited  Scope): </strong>Development of faculty/staff  housing or student accommodation. </li>
      </ul>
      <h3>Objective:</h3>
      
      <p align="justify">The primary objective of this EOI is to solicit  innovative and 
        non-binding proposals from interested parties on how they  envision 
      commercially utilizing the University's  estate to generate sustainable revenue, enhance facilities, and contribute to the overall  development and betterment of the University community, all under a PPP framework.</p>
      
      
        <h3>Submission  of Proposals:</h3>
        <p align="justify">Interested parties are requested to submit their  non-binding proposals,  outlining their initial  ideas, concepts, and potential commercial models. The proposals should broadly cover:</p>
        <ul>
          <li><strong>Proposed Use/Concept: </strong>A clear description of the proposed commercial venture. </li>
          <li><strong>Location  Preference (if any): </strong>Indicative areas within the University  estate that might be suitable for the proposed project (a general  understanding of the University's layout  is helpful, but detailed site plans are not required  at this stage).</li>
          <li><strong>Preliminary PPP Model: </strong>A brief  outline of how the proposed project could be structured  under a PPP arrangement (e.g., Build-Operate-Transfer, Build-Own-Operate, Design-Build-Finance-Operate-Maintain, etc.).</li>
          <li><strong>Anticipated  Benefits for the University: </strong>How the proposed  project will benefit the University financially, academically, or in  terms of infrastructure and services.4 </li>
          <li><strong>Resources required</strong>: What is the expected resources  required from the University for this proposal </li>
          <li><strong>Experience and Capability: </strong>A brief overview of the bidder's relevant experience and financial  capacity to undertake  such projects. </li>
          </ul>
        
        <h3>Important Notes:</h3>
        <ul>
          <ul>
            <li>This EOI is a  preliminary step and does <strong>NOT </strong>constitute  an invitation to tender or a binding commitment from the University. </li>
            <li>The proposals  received will be used by the University to assess market interest, explore viable  options, and refine  its strategy for commercial utilization of its estate. </li>
          <li>Based on the  evaluation of these non-binding proposals, the University of Karachi will  subsequently float specific, detailed project proposals (Request for Proposals  - RFPs) in the newspaper, inviting all interested parties  to submit formal bids for viable projects under the PPP model. </li>
          <li>The University reserves the right to accept or reject any or all  proposals without assigning any reason thereof. </li>
          <li>All costs  incurred by the applicants in preparing and submitting  their EOI will be borne by the applicants. </li>
        </ul>
      </ul>
      <p>&nbsp;</p>
      <h3>Submission Deadline:</h3>
