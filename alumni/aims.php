  <h3>&nbsp;</h3>
  <h3>OBJECTIVES</h3>
  <p>The University  of Karachi Alumni is established with the following aims and objectives, </p>
  <ul>
    <li>To  promote communication between old students and the University. </li>
    <li>To  support the University’s mission of imparting quality education to the youth of  Pakistan through its alumni.</li>
    <li>To  encourage the Alumni to take an active and abiding interest in the work and  progress of the University so as to contribute towards enhancement of the  social utility of their Alma Mater. </li>
    <li>To  generate a Brain Bank of professionals from amongst the alumni and provide  services for the benefit of University and its students in general. </li>
    <li>To  organize and establish scholarship funds to help needy and deserving students. </li>
  </ul>
