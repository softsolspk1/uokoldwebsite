<p align="justify">The University of Karachi   launched its first official alumni body on 11th March, 2013 to give support  to the revenue-starved institution. Aiming to unite former  students at the platform of their alma mater, the University of Karachi Alumni  will make efforts to utilize the resources of the alumni for the prosperity of  its existing students, said the vice-chancellor Prof. Dr Muhammad Qaiser during  a ceremony organized at the university&rsquo;s arts auditorium. He vowed to hold a  grand alumni convention of former students in the coming months.</p>
<p align="justify"> &ldquo;All across the world, old students significantly contribute to  the development of their universities but we have come alive only now,&rdquo; noted a  university syndicate member, Sardar Yasin Malik. Malik recalled that the first  time he was persuaded to organize the alumni to lend support to the university  was by former vice-chancellor Prof. Dr Pirzada Qasim Raza Siddiqui when the HEC  slashed recurring budgets of the public universities.  Dr Qasim, who was also present at  the ceremony, accepted in his speech that the university officials never paid  attention towards the important practice of keeping the record and contacts of  its graduating students until 2010 when the idea of forming the university&rsquo;s  official alumni association was conceived. &ldquo;The fees acquired through the  students hardly makes up for four percent of the university&rsquo;s budget, which  even if doubled would still fail to provide sustainability.&rdquo;  Being an alumnus of the university, former social welfare  minister Khanum Gohar Aijaz said that it was almost unthinkable that the  university could give anything more to its alumni as it had already given them  what they would never be able to payback. &ldquo;After receiving the best education  at KU almost for free, we have become billionaires and still expect the KU to  give us more,&rdquo; said Aijaz. &ldquo;It is time for payback.&rdquo;</p>
