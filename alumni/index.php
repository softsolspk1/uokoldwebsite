  <p align="justify">The  first official Alumni body of University of Karachi aims to help you stay in  touch with your University, college and other UoK alumni, no matter wherever  you are in the world.</p>
<p align="justify">    The  University of Karachi Alumni (UKA) - with graduates from all academic  programmes at UoK and its affiliated colleges including Bachelors, Masters,  MS/M.Phil and PhD form an integral part of the University. This ever-growing  body represents a rich resource base for the University with its huge reservoir  of diverse talents and expertise spanning over areas like Social and Biological  Sciences, Management and Administrative Sciences, Pharmacy, Islamic Studies,  Law, Medicine, Engineering and Education. The bond that our students form with  their alma mater will strengthen even further once they become alumni. </p>
  <p align="justify">Through  this alumni body, the University will ensure that good communication link is  established amongst the alumni as well as between the alumni and the University.  To achieve this it has established an office in the Public Relations Office,  where administrative facilities are provided to its alumni for the completion  of their membership. Not only this, the office will be responsible to build a  cohesive network of UoK Alumni. It will ensure unhindered communication throughout  the year that includes timely announcement of University events as well. The  office aims to organize different alumni based activities that will help  connecting the alumni around the globe. </p>
  <p align="justify">These  measures will keep our alumni informed about the whereabouts and achievements  of fellow alumni, as well as important developments at the University. To  provide a more efficient communication link, a website will soon be developed to  provide up to date information regarding alumni events. Also, the latest  developments at the University will be announced through this website. An  electronic version of the University Magazine will also be available on the  website.</p>
