   <h3>5th National Conference on Space Science & Technology</h3>
   <p><span class="date_news">09 October 2017</span></p>
   <p align="justify">The Institute of Space & Planetary Astrophysics (ISPA), University of Karachi is organizing “5th NATIONAL CONFERENCE ON SPACE SCIENCE & TECHNOLOGY” on October 9-10, 2017 for celebrating World Space Week 2017. The theme of the Conference is “Exploring New Worlds in Space”. However, a wide range of topics of Space Science & technology will be covered in the Conference. Space scientists all over Pakistan will attend this conference. Inaugural Ceremony will be held at the Arts Auditorium  on 9th October 2017 at 9:30 am. Vice Chancellor Prof. Dr. Muhammad Ajmal Khan will preside the inaugural ceremony while Dr. Hafeez Hoorani, Director General of National Center for Physics will be the chief guest. The closing ceremony will be held on October 10th 2017 at 4:45 pm at Arts Auditorium  and the Dean, faculty of Science  Prof. Dr. Tasneem Adam Ali will preside the closing ceremony.</p>
