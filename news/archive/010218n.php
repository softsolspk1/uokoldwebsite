   <h3>Plantation Pivotal for Controlling the Heat Waves</h3>
   <p><span class="date_news">28 February 2018</span></p>
   <p align="justify">Vice Chancellor Prof. Dr. Muhammad Ajmal Khan said the global warming and increased frequency of heat waves have threatened the natural balance of environment. The natural calamities tropical cyclones, tornadoes, floods and droughts combining with global warming have become a serious threat for the south Asian countries. The trees play an important role to reduce the impact of these calamities. Plantation is the only way to save our world from the danger of global warming. We must promote the culture of plantation since it plays a major role in controlling the heat waves. He was expressing his views while inaugurating the plantation campaign at University of Karachi. Deans, Registrar Dr. Munawar Rasheed, Students Advisor Dr. Syed Asim Ali, Controller of Examinations and a large number of faculty and students were present on the occasion. The Vice Chancellor and deans planted different plants to inaugurate the campaign in which more than 2,500 plants will be planted. Dr. Ajmal Khan also inaugurated cleanliness campaign at the varsity and visited departments. </p>
