   <h3>UoK observed Plantation Day accompanied by a fire fighting drill</h3>
   <p><span class="date_news">22 Mar 2013</span></p>
   <p align="justify">&quot;Urbanization, farming, overgrazing, global warming, and tourism development has resulted in a significant decrease in forest round the globe. Especially in Pakistan where the total forest area coverage has shrunk to 3%.  This deforestation results in modification of climate of an area mostly leading to desertification and aridity that eventually leads towards economic failure in different respects,&quot; these views were expressed by the Vice Chancellor – Prof. Dr. Muhammad Qaiser during his address to the Plantation Day organized by the Department of Public Administration here on Thursday. The Plantation Day was organized to mark the International Forest Day.  Chairman – Department of Public Administration – Prof. Dr. Khalid Iraqi informed that approximately 2000 saplings have been planted by the students of DPA which will add in the beautification of campus by making it greener. The &quot;go green&quot; campaign of DPA students was accompanied by an awareness walk in which the volunteers provided easy tips for keeping the University clean and green. Keeping in view the need of the day, the department also organized a fire fighting drill in order to cope with any unlikely incident.</p>
