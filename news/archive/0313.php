   <h3><strong>Talk on </strong><strong>&ldquo;<em>Italy-Pakistan Relations</em>&rdquo;</strong><strong> </strong>at <strong>Area Study Centre for Europe UoK</strong></h3>
   <p><span class="date_news">8 Mar  2013</span></p>
   <p align="justify">A lecture was held on the topic of Italy-Pakistan Relations on 7th March 2013 at the Area Study Center for Europe (ASCE), University of Karachi. H.E Mr. Adriano Chiodi Cianfarani, Italian Ambassador to Pakistan, graciously expressed his views on long lasting cooperation between Italy and Pakistan. The program started with recitation of holy Quran followed by the welcome note of Dr. Uzma Shujaat, Incharge ASCE. Dr. Shujaat highlighted the major areas of cooperation between Italy and Pakistan and praised Italy&rsquo;s support to Pakistan in trade, agriculture disaster management etc. &ldquo;Italy is the third largest trade partner among EU state members and 10th largest overall&rdquo;, said Dr. Shujaat. She further expressed that Italy has always supported Pakistan in European Union. It is also the home of culture, arts and roman history, she added. While delivering his lecture, H.E. Mr. Cianfarani praised the current agreement on Strategic Engagement Plan&rdquo; signed by the foreign ministers of Italy and Pakistan on 5th February 2013.  &ldquo;It is a great achievement and we hope that Pakistan can be benefited with Italy&rsquo;s expertise in defense, security and counter terrorism&rdquo; he expressed. He furthermore said that Pakistan has a great trade potential and Italian investors are willing to invest in different fields in Pakistan. He referred to the current investment of Fiat in the agricultural sector. H. E. Mr. Cianfarani threw light on Italy and Pakistan trade, which has reached to 1.5 billion US dollars and hope that it will increase in the near future as many Italian companies are willing to initiate joint ventures with Pakistan businessman. He further informed the audience that Italy is supporting Pakistan in energy and disaster management. He mentioned that Italian government has participated in rehabilitation work after the earthquake of 2005 and flood of 2010. &ldquo;57.75 million euros were provided by Italy for people affected by natural disasters in Pakistan and 40 million euros were given for employment and livelihood projects, he added. He further discussed the Italy-Pakistan cooperation in the United Nations and on different international forums. &ldquo;Italy attached great importance to building ties with Pakistan&rdquo; he added. The program ended with question answer session.  </p>
