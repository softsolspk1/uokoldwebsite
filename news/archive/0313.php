   <h3>UoK organizes seminar on the future of Democracy</h3>
   <p><span class="date_news">21 Mar 2013</span></p>
   <p align="justify">&ldquo;Judiciary and media are two most important fractions of  democracy and both are performing well in their own capacities. In this  relation, a media commission has been formed to analyze the relation between  media and democracy during elections. As per the set-up, 43000 observers will  monitor every region of Pakistan during elections. The upcoming elections will  prove to be better in the respect that it will have a strong monitoring  setup.&rdquo;, these views were expressed by the Vice Chancellor Prof. Dr. Muhammad  Qaiser, former senator Javed Jabbar and others during their address to the  seminar titled &ldquo;The future of democracy in Pakistan – A crisis and a question&rdquo;  here on Wednesday. While talking about Democratic institutions and future of  democracy in Pakistan, Javed Jabbar highlighted that the process of improving  the democratic setup always begins from the grass route level. Education at the  primary level is the best way to promote democracy because individual integrity  and identity at this level will lead to an improved and far better form of  democracy. He was of the view that successful countries never hesitate in  developing intellectual and scientific fields. The process of improvement in  the democracy and Pakistani society should begin from the grass route level  because education at the primary level is the best way to promote democracy. At  this level, promotion of individual integrity and identity will give a boost to  a strong democratic setup. Well known Journalist Shahnawaz Farooqi said that  education is imperative for smooth democracy. Not a single country in the world  can survive without democracy because democracy itself is divided into several  forms and shapes that facilitate life at different levels. Dr. Riyaz Ahmed  Sheikh expressed that corruption is the root cause of every failure; we must  try to get rid of it first.&nbsp;While concluding, Dr. Tahir Masood –  Chairperson Department of Mass Communication remarked that the system can be  improved only when an individual be given attention.</p>
