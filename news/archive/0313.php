   <h3>UoK inaugurates the Flower Show 2013</h3>
   <p><span class="date_news">26 Mar 2013</span></p>
   <p align="justify"><em>&ldquo;It  is a well-known fact, that worldwide thousands of plant species are endangered  and facing extinction with the current trend of their exploitation and  destruction. In such a scenario it is imperative that awareness may be spread  among common people and this is&nbsp; the  aim of setting up a botanical garden at University of Karachi which works to  conserve and rehabilitate rare and endemic species which are fast vanishing on  account of environmental degradation. Currently a considerable number of such  plant species were being conserved through tissue culture at the university&rsquo;s  plant conservation center&rdquo;,&nbsp;</em>these views  were expressed by the Vice Chancellor – Prof. Dr. Muhammad Qaiser&nbsp;while  addressing the inaugural ceremony of KU-CPC Flower Show 2013.&nbsp;</p>
   <p align="justify">This event also intends to showcase the&nbsp;mission of the Centre which revolves around conserving and  restoring the rare endemic plants of Southern regions of Pakistan through  tissue culture.&nbsp;Explaining the flower show&rsquo;s unique features, KU botanical  garden head Dr Anjum Parveen said that almost 3000 species of plants including  endemic and endangered species as well as those indigenously used for medicinal  purposes are on display in order to create awareness about them.&ldquo; <em>These  species include Cadabaheterotricha, Abutilon pakistana, Asparagus dumosus,  Commiphorastockiana that are native to Sindh. We have been able to conserve  these species through tissue culture at the university</em>,&rdquo; she said.  Ornamental species such as Fuchsia magellanica, native to southern areas of  South America, and orchids along with plants found favorable to produce  bio-diesel fuel, for instance, jatropha and cassava, were also on display at  the show, added Dr. Anjum. While sharing information about the Botanical Garden  situated inside the University, Dr. Qaiser said that&nbsp; the garden has many sections  comprising a wide, diverse range of plants and trees, which are all watered  with the help of an energy-efficient waste water treatment plant. The whole  garden is connected through a 2.75km-long walkway and can be accessed by  wheelchair. An amphitheater has also been constructed for educational  activities. </p>
