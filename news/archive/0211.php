        <p align="justify">SAARC has a long way to travel. Concerted efforts on the part of member countries can turn a weak organization into a strong one. The intelligentsia has a big role to play.&rdquo; These views were expressed by Professor Dr. Qasim Raza Siddiqui, Vice Chancellor, University of Karachi. He was speaking at the inaugural session of a three day &ldquo;Third SAARC Simulation Exercise&rdquo; organized by the Department of International Relations, University of Karachi in collaboration with Hanns Siedel Foundation, Islamabad.
          Former Foreign Secretary Mr. Shamshad Ahmed Khan delivered the key note address. He said that SAARC has unfortunately not remained immune to hegemonic tendencies. A culture of equality is needed in SAARC. Apart from it theSAARC countries should now start discussing political and security issues so that its practical usefulness can be enhanced.
          Mr. Martin Axman-Resident Representative, Hanns Siedel Foundation, Islamabad-presented his welcome address and appreciated the efforts made by the several universities particularly University of Karachi for making SAARC Simulation Exercise a reality.</p>
