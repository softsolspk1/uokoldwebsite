   <h3>UoK distributes EMEA Scholarships</h3>
   <p><span class="date_news">4 Jun 2013</span></p>
   <p align="justify">&ldquo;Due to the fact that University of Karachi is one of  the premier institutions of higher learning and research, it has been enlisted  among the top universities of world. The pace of development will be continued  with great vigor and motivation&rdquo;, expressed the Vice-Chancellor, University of  Karachi, Prof. Dr. Muhammad Qaiser, during the Erasmus Mundus Europe Asia  Scholarships distribution Ceremony here&nbsp;<span data-term="goog_2104712343" tabindex="0">on Tuesday</span>.&nbsp; Prof. Dr. Shahana  Urooj Kazmi, the Coordinator of -Erasmus Mundus Scholarship Programme informed  that the EMEA Scholarship is a fully funded by European Union. She added that  the students, teachers, researchers and University staff (academic or  administrative positions) are selected in the project. University of Karachi is  one of the Asian Partner Universities of Erasmus Mundus Europe Asia (EMEA)  program and being a partner university, our candidates&rsquo; applications are  considered under Target Group 01 Budget Group A.&nbsp; The scholarships are  fully funded and span from one month administrative training to 34 months  research in European universities for BS, MS, M.Phil, Ph.D. research work.  While addressing the ceremony Dr. Qaiser said those who have attained the  scholarship would act as ambassadors of Pakistan at their respective foreign  universities, and are a testament to the fact that the University's education  standards are at par with the academic quality of international institutions.  </p>
