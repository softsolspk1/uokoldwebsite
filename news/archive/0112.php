   <h3>Arfa Karim Memorial Lecture held at Department of Computer Science</h3>
   <p><span class="date_news">31 January 2012</span></p>
   <p align="justify">A lecture in the memory of  the once youngest Microsoft certified professional, Pakistani&nbsp;student and computer&nbsp;prodigy,  Arfa Karim was held at the Department of Computer Science, University of  Karachi. The lecture will be held yearly in the month of January to pay tribute  to the youngest Microsoft certified professional from Pakistan. Arfa Karim  recently died on January 14th after being in a coma for about a  month.    </p>
   <p align="justify">The lecture was attended by a  large number of students of computer science and information technology.  Meritorious Professor Dr. S.M. Aqil Burney and Professor Dr. Kamal Jaffery who  is from MIT delivered lectures on latest trends in Computer and Information  Technology research and persuaded the youth to get inspiration from Arfa Karim  and try to do their best in whatever field they are in and bring laurels to  their family and country. Mr. Jibran Jamshed, form Microsoft Innovation Center  was also present.        </p>
   <p align="justify">Dr. Burney's talk was built  around the concept of how to channelize the power of mind at a young age so  that the country can benefit from it. He said that the youth in Pakistan has  tremendous potential and it is the need of the hour that this potential is  channelized for the benefit of the nation. He said that given a proper chance  and guidance, the youth of Pakistan can achieve any milestone in the world and  children like Arfa Karim have proved it many a times. He said that geniuses are a rare breed and are born in centuries, but we as  a country are very lucky to have this breed in abundance. He said that Arfa  Karim Randhawa was an IT genius. She created a significant place for herself in  the IT World at the age of nine, and was declared as the youngest Microsoft  Certified Professional (MCP) by Microsoft&nbsp;Corporation&nbsp;USA. He said that the government of Pakistan must take tangible measures to fulfill&nbsp;the dreams&nbsp;of Arfa by giving&nbsp;concrete&nbsp;shape to the&nbsp;projects&nbsp;she had planned to implement during  her lifetime. In her death, Pakistan has indeed lost a genius. Dr. Burney said that this Arfa Karim memorial lecture will be  an annual event at the Department of Computer Science, University of Karachi  and will keep inspiring the students to be like Arfa Karim and motivating them  to do their best for their country.
   </p>
   <p align="justify">Mr. Jibran Jamshed talked about the Microsoft's commitment to  Pakistan and its youth. He said that youth like Arfa Karim are a beacon of hope  and intelligence for others. He motivated the other students to opt for  Microsoft certification programs and make a name for themselves and their  country.</p>
   <p>     Professor Dr. Kamal Jaffery who is from MIT, talked about his  latest research in the field of bio-informatics and computer science at MIT. He  said that Pakistan as a nation is blessed with talent and it is imperative that  this youth is guided in the right direction.</p>
