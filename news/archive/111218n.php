   <h3>V.C Visits Various Installs at IDEAS 2018</h3>
      <p><span class="date_news">29 November 2018</span></p>
   <p align="justify">Vice Chancellor Karachi University Professor Dr. Muhammad Ajmal Khan visited IDEAS 2018 and showed gratitude towards armed forces. On this occasion, he said that Pak Army is our nation’s pride and they are ready to deal with all internal and external threats.

He expressed that Pakistan’s defense is getting stronger day by day. The military weapons and instruments being made in Pakistan at local level is being the great source of attention for delegations of different countries and representatives of their armed forces.

Like past years, Pakistan Armed Forces are receiving multiple contracts of war equipment which is highlighting Pakistan’s name internationally and increasing the foreign exchange of Pakistan.  With the passage of time, Pakistan’s ability to manufacturing war weapons has turned autarky and Pakistan is not only producing modern technology based weapons but also exporting the same throughout the world.

“The whole world recognizes the efficiency of Pakistan army”, He added. He visited the stalls of different countries and expressed solidarity to the Pakistani soldiers and armed forces. He was heartening to observe the foreign stalls and said that the drone named Burraq introduced by Pakistan Army is great and will bring good name to Pakistan.

</p>
