   <h3>Admission Test for M.Phil., PhD, MS and MD Admissions 2017</h3>
   <p><span class="date_news">12 May 2017</span></p>
   <p align="justify">Board of Advanced Studies and Research (BASR) Convener  Admissions Prof. Dr. Muhammad Ahmed Qadri has notified that the Admission Test  for M.Phil., PhD, MS and MD Admissions 2017 will be held on Sunday 14th&nbsp;May  2017 at 10:00 am. 2942 students were declared eligible to appear in the  admission test 2513 students in M.Phil. 328 in PhD, 44 in M.D while 63 students  submitted forms in M.S program.&nbsp;According to Dr. Qadri, 1165 students  applied in faculty of science, 764 in social sciences, 190 in pharmacy, 273 in  management and administrative sciences, 105 in education, 292 in Islamic  studies while 52 students applied for admissions in faculty of law. <br />
     All the candidates are instructed to reach the admission test  venue half an hour before the time of the test with original CNIC and Admit  card. The list of successful candidates in the admission test will be announced  on the official website of UoK on 19th&nbsp;May 2017. All those  students who have their degrees from HEC recognized private academic  institutions or foreign university must get their Equivalency Certificate from  the Deputy Registrar(Academics) UoK before provisional admission. </p>
