   <h3>Meeting of the Academic Council</h3>
   <p><span class="date_news">22 March 2012</span></p>
   <p align="justify">"University of Karachi will allow all the existing students of BS 1st, 2nd and 3rd year to switch their program from BS to Bachelors (Honors). Semester rules 2002 will be applied on them. However, in order to bring uniformity in the examination and evaluation procedures, passing percentage for both, BS and Bachelors (Honors) Program, will be 45%," this decision has been made in a recent meeting of Academic Council which was chaired by the Vice Chancellor - Prof. Dr. Muhammad Qaisar. In the beginning of the meeting, minutes of 5 previous meeting of the Academic Council were approved. Moreover, minutes of 8 meetings of the Board of Advanced Studies and Research had also been approved. Members of the Academic Council collectively gave approval for the five year BA, LLB Honors Program. In the recent meeting of the Academic Council, an approval was given for the affiliation of 23 institutions. Moreover, the Vice Chancellor, while considering the efficiency of teaching and research in the University, suggested that the examinations of BA, B.Sc and B.Com may be conducted in the respective colleges. The decision was highly appreciated by the faculty members. In relation, it was decided that a proper strategy will be devised in a meeting with the college principals.</p>  
