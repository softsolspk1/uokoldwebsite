   <h3>University signs consortium with Idaho University, USA, to enhance its scientific research</h3>
   <p><span class="date_news">16 March 2012</span></p>
   <p align="justify">"Since globalization brings with it significant challenges, it also provides an opportunity for unifying research practices across international boundaries. International research collaboration among Universities has intensified and  is frequently regarded as an indicator of quality and a way in which to develop and disseminate scientific knowledge to newly developing countries. It is indeed prestigious for University of Karachi that it is a part of a number of international consortiums that are leading to more productive research outcomes," these views were expressed by the Vice Chancellor, Prof. Dr. Muhammad Qaisar during his addressed to the signing ceremony of Memorandum of Understanding between University of Karachi and University of Idaho, USA. The MoU is designed to foster a friendly relationship through mutual cooperation in the sphere of teaching and scientific research between both the Universities.  Dr. Shahana Urooj Kazmi, Pro-Vice Chancellor informed that specific areas have been highlighted in the MoU for potential future collaboration, these include Aquaculture, Animal and veterinary sciences, Agriculture and Water resource management.The agreement was signed by Prof. Dr. Muhammad Qaiser Vice Chancellor University of Karachi ; Prof Dr AbDul Hameed Bajoi Vice Chancellor, LUAWMS; Prof. Dr Talat Naseer Pasha Vice Chancellor , UVAS ; Dr Robert J Harder , Interim Director, Intl. Program office, University of Idaho and Dr Barbara A. Rasco for Dr. Da  niel J. Bernardo. Moreover, University of Karachi along with 10 other following institutions in Pakistan and the United States has established a consortium for using their collective expertise to evaluate, develop, and implement practical solutions to enhance aquaculture and fisheries productivity in Pakistan. the members of consortium will work jointly and through partnerships between the individual members to achieve its stated purpose.The  other Universities are Lasbela University of Agriculture, water and Marine Sciences (LUAWMS), Lasbela ; University of Agriculture Faisalabad (UAF) ; Government College University, Faisalabad (GCUF) ; Bahria University National Center for Maritime Policy  Research (NCMPR) , Karachi ; Sindh Agriculture University (SAU), Tandojam ; University of Veterinary &Animal Sciences(UVAS), Lahore; University of Idaho, (Uldaho), Moscow,ID, USA ;and Washington State University, College of Agriculture, Human, and Natural Resource Sciences (CAHNRS), Pullman, Washington, USA.</p>  
