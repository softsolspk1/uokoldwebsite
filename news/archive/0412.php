   <h3>Media, Academia and Policy Makers: A Strategic Triangle</h3>
   <p><span class="date_news">27 April 2012</span></p>
   <p align="justify">“Media is a vehicle to project the product that the academia produces. Media, Academic and Policy makers constitutes a strategic triangle, the outcome of which is a balanced and well-built country with a knowledge based society. History media and policy makers can form a strategic triangle that can provide better solutions to the challenges that Pakistan is facing currently," these views were expressed by the Vice Chancellor, Prof. Dr. Muhammad Qaisar and others during their address at the panel discussion organized by the Department of General History. The panel discussion titled Academia, Media, Policy Makers: A Strategic Triangle is part of a project named as History Media Policy Project (HMP) that has been initiated by the General History Department and Public Policy Forum (PPF). While talking about the objectives of the forum, Dr. Taha - Project Director- informed that beside a few exceptions, the quality of argument discussion of our legislators and policy makers on talk shows, in seminars, workshops, conferences and even in the courtroom is not up to the mark that is why we initiated the project that aims at establishing links among historical data, media and policy makers. It would facilitate amjor stakeholders to bridge up the gap among factual data and other respective entities, expressed Dr. Taha.</p>
