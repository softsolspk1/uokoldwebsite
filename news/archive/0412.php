   <h3> Seminar on Impact of Advertising</h3>
   <p><span class="date_news">13 April 2012</span></p>
   <p align="justify"> &ldquo;Advertising is a technique that can be very effective in mass marketing of any product. However, advertises focus more on the benefits, which consumer will get from that product, rather than the product itself. It is the most active medium with which products can be known to public easily. As a result, the public can decide which product they need and why,&rdquo; these view were expressed by Tahir A. Khan, Arsalan Hashmi, Farhan Jamalwi, Irfan Siani, Ali Rizvi and Dr. Tahir Masood while addressing to a seminar organized by the Department of Mass Communication titled <strong><em>Impact of Advertising on Society&rdquo;. </em></strong>Chairperson, Department of Mass Communication – Prof. Dr. Rafia Taj said that advertising has numerous impacts on society, both, good and bad. A well-formed advertisement can market a bad product quite well and sometimes a good product&rsquo;s market is hampered just because of a badly designed advertisement. </p>
