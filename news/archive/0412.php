   <h3>Talk by the Russian Consul General on Russia's role in the emerging world order
</h3>
   <p><span class="date_news">13 April 2012</span></p>
   <p align="justify"> &ldquo;Terrorism, arms race and drug trafficking are some of the areas which can be a strong point of convergence between Russian Federation and Pakistan&rdquo;. These ideas were expressed by <strong>Mr. Andrey V. Demidov</strong>, Consul General of Russian Federation, Karachi ,at a seminar on <strong><em>&ldquo;Russian Foreign Policy in the Emerging Global Order&rdquo;</em></strong>. The seminar was organized by the Area Study Centre for Europe, University of Karachi, on April 12, 2012. Prof. Dr. Moonis Ahmar, Director, Area Study Centre for Europe presented his inaugural address in which he threw light  upon the dynamics of global politics and transformation. He said that the world order is still in transition. He said that Russia has its huge advantages as well as challenges. Internally, Russia needs to democratize more and externally the policy of mutual recognition and accommodation can yield great results. He stressed upon the need for greater Pakistan-Russia cooperation in various fields.</p>
