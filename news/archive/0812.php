   <h3><a name="ind" id="ind"></a>University celebrates the Independence Day</h3>
   <p><span class="date_news">15 Aug 2012</span></p>
   <p align="justify">"The day of Independence of Pakistan reminds us that we are a united nation who struggled hard to attain its freedom under the guidance and leadership of Quaid-e-Azam. We celebrate this day to rejuvenate the promises with our beloved homeland. He insisted that while celebrating the 65th birth anniversary of Pakistan, we should not forget the problems that our nation is facing these days," these views were expressed by the Vice Chancellor, Prof. Dr. Muhammad Qaiser while celebrating the Independence Day in the lawn of the new administration Block. The Vice Chancellor added that this auspicious day, when Muslims achieved Independence, should be celebrated despite the timely hardships that we face as a nation. According to Dr. Qaiser, we are fortunate to celebrate this promising day during the holy month of Ramzan; this gives us an opportunity to pray for our country's prosperous future. The Vice Chancellor advised that during our celebrations, it is pertinent to maintain the sanctity of Ramzan. The ceremony was attended by the Registrar, Deans of all the faculties, and a large number of faculty members and employees. </p>  
