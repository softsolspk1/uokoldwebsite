   <h3>Sindh at the Crossroad of Success Through CPEC</h3>
   <p><span class="date_news">03 Apr 2017</span></p>
   <p align="justify">seminar entitled "Sindh at the Crossroad of success through CPEC" organized by Institute of Sustainable Halophyte Utilization, University of Karachi will be held on Thursday 6th April 2017 at 9:30 am at Arts Auditorium KU. Vice Chancellor KU Professor Dr. Muhammad Ajmal Khan will preside the occasion while Mr. Naveed Ahmed Shaikh, Secretary to Chief Minister, Universities and Boards will be the guest of honor. Director General, Sindh Board of Investment Dr. Tanveer Ahmed Qureshi, political analyst and lawyer Javed Qazi and retired federal secretary, government of Pakistan Fazalullah Qureshi will also speak on the occasion. The purpose of the seminar is to create awareness about the socioeconomic impacts of CPEC particularly for Sindh. The seminar will highlight the importance of CPEC in alleviating poverty, ways of achieving revenue generation and environmental improvement with special emphasis to Sindh.</p>
