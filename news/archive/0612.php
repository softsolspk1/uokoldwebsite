   <h3><a name="n050612" id="n050612"></a>University witnesses the rarest astronomical event involving Venus, Earth and Sun</h3>
   <p><span class="date_news">6 June 2012</span></p>
   <p align="justify">"It's the last opportunity of the century to witness the rare astronomical when Venus will come in between Sun and Earth. Transits of Venus occur eight years a part, with more than a century between cycles. Planet Venus began its journey at 6:00am and disappeared from the surface of sun at 9:50am here on June 6th 2012", informed the in-charge Institute of Space and Planetary Astrophysics (ISPA). He was addressing his students and other visitors who were keen in witnessing the rarest astronomical event at the KU Observatory on Wednesday morning. Venus appeared on Sun as a dark small spot that drifted slowly from one side of the sun to the other and then disappeared. While talking about the idiosyncrasies of Venus, astronomical experts informed that Transits of Venus are very rare; only eight transits have been witnessed since the invention of the telescope in 1608. The atmosphere of this planet is 100 times denser than that of the Earth. The atmosphere is filled with carbon dioxide and a greenhouse gas that keeps its temperature consistent around 482 Degree Celsius. Venus is surrounded by the clouds of Sulfuric Acid. In order to make possible the observation of this rare incident, special arrangement were made which included telescopes, solar filters and glasses. Many senior astronomers were also present to coordinate the event and update the viewers with latest information. A large number of citizens along with KU students and faculty members were present to witness the rarest event. Special arrangements were also made to assist vast media coverage of the event :: <a href="/news/2012/venus.jpg" target="_blank">View Image</a></p>
