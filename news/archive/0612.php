   <h3>University identifies major causes of depletion of fisheries in Pakistan</h3>
   <p><span class="date_news">1 June 2012</span></p>
   <p align="justify">Approximately 1 lac coastal inhabitants are involved in fishery in the coastal areas of Pakistan, spread over an area of 990 kilometer. Fishery is an important social and economic activity in this region, however, depletion of under water resources and hazards to the biodiversity would lead the entire nation towards a declining economy and acute financial and social crises.  It is, therefore, imperative that for any effective measure or plan for fisheries in Pakistan scientific data on fish taxonomy, biology, life cycle be conducted by the research institutions. A data base for fish description and fisheries needs to be developed on urgent basis," these views were expressed by the Vice Chancellor, Prof. Dr. Muhammad Qaiser, Director- Centre of Excellence for Marine Biology – Prof. Dr. Pirzada Jamal, Professor of Ichthyology, University of Miyazaki – Mr. Yukio Iwatsuki and other while addressing the inaugural ceremony of a seminar titled Fish and Fisheries organized by the Centre of Excellence for Marine Science to celebrate the International Biodiversity Day here on Wednesday. </p>
