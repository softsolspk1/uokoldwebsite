   <h3>University  invites its alumni to register for the first ever official alumni body</h3>
   <p><span class="date_news">18 Feb 2013</span>   </p>
   <p align="justify">University of Karachi is launching its first ever alumni body titled University of Karachi Alumni on February 20th 2013 at 2:00pm in the Arts Auditorium. Through this alumni body, the University will ensure that good communication link is established amongst the alumni as well as between the alumni and the University. To achieve this it has established an office in the Public Relations Office, where administrative facilities are provided to its alumni for the completion of their membership. Not only this, the office will be responsible to build a cohesive network of UoK Alumni. It will ensure unhindered communication throughout the year that includes timely announcement of University events as well. The office aims to organize different alumni based activities that will help connecting the alumni around the globe. It is pertinent to note that graduates from the colleges and institutes affiliated to KU are also eligible to attain the membership. These measures will keep the alumni informed about the whereabouts and achievements of fellow alumni, as well as important developments at the University. To provide a more efficient communication link, a website will soon be developed to provide up to date information regarding alumni events. Also, the latest developments at the University will be announced through this website. An electronic version of the University Magazine will also be available on the website. For more details, email can sent to alumni@uok.edu.pk. <strong>Forms are available <a href="/alumni/membership.php" target="_blank">here</a></strong>.</p>
