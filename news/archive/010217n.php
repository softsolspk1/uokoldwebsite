   <h3>ISHU UoK Celebrated 11th Foundation Day</h3>
   <p><span class="date_news">23 Jan 2017</span></p>
   <p align="justify">ISHU-The Institute of Sustainable Halophyte Utilization, University of Karachi celebrated its 11th Foundation Day on Friday January 20th, 2017. On this occasion, Quran khawani was held at the Institute. Distinguished National Professor, Dr. Muhammad Ajmal Khan (Pride of Performance and Sitara-e-Imtiaz), the founding Director of ISHU celebrated the day with students and faculty by cutting a cake and prayed for its continued success in future. Prof. Ajmal Khan lauded the efforts of the ISHU team in publishing more than 100 peer reviewed research articles, 5 books by international publishers and producing 12 PhD scholars since 2007. He further urged them to continue working hard for the betterment of Karachi University and Pakistan in the scientific arena. Collectively, over 350 publications by Prof. Ajmal Khan and his ISHU team has significantly added to the collective wealth of information on local salt tolerant plants of Pakistan, which are useful as food, fodder, medicine and biofuel. The Director ISHU and faculty members thanked Dr. Ajmal Khan for his efforts in establishing the institute and providing a platform for carrying out high quality research</p>
