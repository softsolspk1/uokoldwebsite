   <h3>PCMD Students Wins First Prize</h3>
   <p><span class="date_news">03 Jan 2017</span></p>
   <p align="justify">The students of Dr. Panjwani Center for Molecular Medicine and Drug Research (PCMD), University of Karachi (UoK), received first prize for their innovative project in the national event held in Islamabad, Dr. Iqbal Choudhary informed the participants.<br />
It is pertinent to mention here that the National University of Science and Technology (NUST) organised the national event, entitled "DICE (Distinguished Innovations, Collaboration and Entrepreneurship) Mega Innovation and Entrepreneurship event 2016" on December 21 and 22, 2016, in which around 300 students from different universities across the country participated. The PCMD students won the 1st the prize in the category of biological sciences, medical sciences and veterinary sciences. They presented the project of heart attack detection device. The device presented there was a prototype model. The project was evaluated by different panel of judges. At the closing ceremony,   the awards according to categories were distributed. Dr. Panjwani Center received the first prize for aforementioned project. All the participant teams were awarded certificates. Vice Chancellor University of Karachi Prof. Dr. Muhammad Qaiser, Patron-in-Chief ICCBS Prof. Dr. Atta-ur-Rahman and Director ICCBS-UoK Prof. Dr. M. Iqbal Choudhary have congratulated the students on their achievement.</p>
