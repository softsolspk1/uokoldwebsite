   <h3>UoK Students Elected on Key Posts of IQRA Youth Parliament</h3>
      <p><span class="date_news">10 October 2018</span></p>
   <p align="justify">Students of Karachi University got elected on various leading positions of IQRA Youth Parliament. Syeda Ayesha Zeeshan from Criminology department got elected on the post of Speaker while Muhammad Ammar Abbasi was elected the Leader of the House of IQRA Youth Parliament. Vice Chancellor KU Prof. Dr. Muhammad Ajmal Khan and Students Advisor KU Dr. Syed Asim Ali congratulated the students. According to details, IQRA Youth Parliament’s first session was held at Iqra University, President Azad Jammu Kashmir Sardar Masood Khan administered the oath from the members of the Youth Parliament while Mayor Karachi administered the oath of Speaker from KU’s student Syeda Ayesha Zeeshan in the next session. Concluding session was chaired by Governor Sindh and Patron in Chief of IQRA Youth Parliament Imran Ismail. Speaker, Leader of the House and others presented the resolutions passed during the first session to the Governor Sindh. VC KU Dr. Ajmal Khan congratulated Syeda Ayesha Zeeshan and Muhammad Ammar Abbasi for getting elected on key posts and termed their success as a major success of KU students. He also congratulated Founding Chancellor IU Hunaid Lakhani and Vice Chancellor Prof. Dr. Wasim Qazi for successful event of IQRA Youth Parliament.</p>
