   <h3>Independence Day Celebrations</h3>
   <p><span class="date_news">14 August 2017</span></p>
   <p align="justify">Dr. Munawwer Rasheed has notified that Independence Day Celebrations Program will be held on Monday 14th August 2017 at the ground floor of the New Administration Building. The proceedings of the program will commence from 7:30 am while VC Prof. Dr. Muhammad Ajmal Khan will hoist the national flag at 8:00 am. He will also address the faculty members, employees and students of KU. Special prayer for the wellbeing of the nation and the country will also be made at the end. After this ceremony, another ceremony organized by Students Advisor Office KU will be held. Chinese teachers at KU will present national songs. All those students who have represented and won laurels for the varsity in different co-curricular competitions nationally and internationally will be awarded with medals/awards. Vice Chancellor Professor Dr. Muhammad Ajmal Khan and Students Advisor Syed Asim Ali will also speak on the occasion. </p>
