   <p><span class="date_news">07 August 2017</span></p>
   <p align="justify">Poster competition organized by Department of Social Work and Center of Excellence for Women Studies, University of  Karachi under supervision of Prof. Dr. Nasreen Aslam Shah will be held on Thursday 10th August 2017 at department of social work at 10:00 am. In the competition, the national flag of Pakistan will be featured using different methods. A pamphlet having messages to the students on 70th anniversary of Pakistan will also be issued on the occasion. This exhibition will continue till 14th August 2017.</p>
