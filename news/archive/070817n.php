   <h3>All Karachi Inter-Varsity Competition</h3>
   <p><span class="date_news">03 August 2017</span></p>
   <p align="justify">University of Karachi is organizing All Karachi Inter-varsity Competition to mark the Independence Day Celebrations. Debate/Speech Competition (Urdu and English), Quiz Competition and National Song Competition will be held on 7th, 8th and 9th August 2017 at HEJ Auditorium, University of Karachi. The initial rounds of competitions will be held on 7th and 8th August while the final round will be held on 9th August 2017. Concluding and Prize distribution ceremony will be held on Wednesday 9th August at 11:45 am. Vice Chancellor KU Prof. Dr. Muhammad Ajmal Khan will preside while DG Rangers Sindh Major General Muhammad Saeed will be the chief guest.</p>
