   <h3><a name="hack" id="hack"></a>Hacking attempt on UoK website could not hit the website data source</h3>
   <p><span class="date_news">30 Aug 2013</span></p>
   <p align="justify"></a>A hacking attempt was made on the official  website of University of Karachi early Friday morning from International DNS  Server by hackers claiming to be Indian. Fortunately, the attack could not harm  the website source and the entire data is safe but the DNS Server was affected.  In order to maintain the integrity of the online documents the website was put to offline mode and a  complete scan of the web host was carried out to identify and address any  possible security glitches. The fact needs to be accentuated that the official  website of UoK is one of the most accessible University websites of the region.  It receives about 2 million hits every week. During year 2012 it received over  90 million hits from all over the world. Some of these hits include different  hacking attempts made on the web server to harm the documents and online  information system. Most of these phishing, defacing and denial of service  attempts on daily basis are tackled and the website is kept up and runs  successfully.</p>
