   <h3>Sustainable Development: Halophytes for Green Revolution Conference</h3>
   <p><span class="date_news">13 April 2018</span></p>
   <p align="justify">The inaugural ceremony  of 4 days International Conference &ldquo;Sustainable Development: Halophytes for  Green Revolution&rdquo; organized by Institute of Sustainable Halophyte Utilization  (ISHU), University of Karachi will be held on Monday, 16th&nbsp;April,  2018 at 6:30 pm at ISHU. <br />
     According to Director  ISHU, Dr. Bilquees Gul this conference aims to bring together leading academic  scientists/researchers, UN organizations, public and private national and  international organization, industries and policy makers to discuss in general  the sustainable use of halophytes (i.e. naturally salinity tolerant plants of  saline areas) and facilitate research to determine the efficacy of the ideas  for halophytic green revolution to turn saline wastelands into a resource. The  ultimate goal is to transform currently barren arid/saline lands into  productive croplands, so that food security can be achieved in future. This  kind of research will greatly benefit the poor farmers of the Pakistan and  other countries, which suffer from land salinization and drought. Institute of  Sustainable Halophyte Utilization (ISHU), University of Karachi is one of the  leading institutes of the world for research on halophytes and saline  agriculture.&nbsp;In recognition of achievements of ISHU in very short period  of time (since its establishment in 2006), UNESCO established first ever &lsquo;Chair  in Sustainable Halophyte Utilization&rsquo; at ISHU in 2009 under UNITWIN Programme  of UNESCO. Despite small size and scarce funding, ISHU is trying its level best  to play a pivotal role in sustainable utilization of halophytes and saline  lands. This conference is also a contribution towards sustainable halophyte  utilization for green revolution in the arid regions.&nbsp; <br />
     Beside national  participants, a number of renowned scientists from Germany, Thailand, Ethiopia  and Tunisia will participate. </p>
