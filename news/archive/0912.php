   <h3>Four-Day workshop on Bio statistical Methods in Genomics & Bioinformatics</h3>
   <p><span class="date_news">25 Sep 2012</span></p>
   <p align="justify">"Statistical Advisory Board - to be established at University of Karachi", agreed upon by the Prof. Muhammad Qaiser, Vice Chancellor, University of Karachi, upon the recommendation of Dr. Manzoor H. Soomro, Chairman, Pakistan Science Foundation. Dr. Soomro was addressing the concluding ceremony of Four-Day workshop on "Biostatistical Methods in Genomics & Bioinformatics," held during September 19-22, 2012 at Dr. A. Q. Khan Institute of Biotechnology & Genetic Engineering (KIBGE), University of Karachi, as the Chief Guest. Dr. Soomro emphasized the need and importance of statistical tools and techniques, utilized in almost all kinds of research projects right from the designing phase till the end of the research. These methods are equally necessary for biological, physical as well as social science researchers. Prof. Muhammad Qaiser, in his presidential address, highlighted the significance of Biostatistics as a fundamental feature of designing, analyzing, and accomplishment of any research project. He also commended the hard work that was put up by the resource persons as well as the organizing committee, KIBGE in conducting such event to facilitate the young researchers. The Vice Chancellor appreciated the efforts of Director General, Faculty and Staff the institute for recurrently organizing such workshops and conferences to enhance the skills of young researchers. While presenting the vote of thanks, the Director General of the institute, Prof. Abid Azhar thanked the resource persons and the participants to be a part of an interactive, mutually benefited activity.</p>  
