   <h3>Ambassador of Pakistan delivers talk on Peace and Security in the Region</h3>
   <p><span class="date_news">5 Sep 2012</span></p>
   <p align="justify">"Regional alliance is imperative in order to maintain collective peace and security in various parts of the world," expressed the Ambassador of Pakistan to United Arab Emirates, Mr. Jamil Ahmed Khan during his hour-long lecture that drew a large number of participants including university students, academics and guests from other walks of life, in a seminar titled Regional and Trans-regional approach to peace and security organized by the Department of Political Science, University of Karachi. During his presidential address, Prof. Dr. Muhammad Qaiser – Vice Chancellor, University of Karachi, emphasized that a combination of Peace, Security and Education results in a triangle that guarantees absolute success of a nation. He was of the opinion that fruitful discussions on alive and contemporary issues can open up the youth's minds and inculcate a sense of tolerance in them. During the course of his talk, the Ambassador Jamil Ahmed Khan, underscored the importance of regional alliances and walked the audience through the complex set of institutional mechanisms and how these frameworks resolved conflicts by drawing on his experiences of working with the United Nations and other multilateral bodies. He emphasized the importance of peaceful coexistence against the backdrop of various conflicts with potential to endanger the world peace and security. </p>
