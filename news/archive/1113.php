   <h3>POSCO Asia Fellowship Award Ceremony 2013</h3>
   <p><span class="date_news">20 Dec 2013</span></p>
   <p> "As per UNESCO statistics, the average enrolment in the tertiary level of education is increasing every year. One of the reasons behind this improvement is the increased exposure provided to our youth for which organizations like POSCO TJ Park Foundation are playing a significant role. The POSCO TJ Park Foundation has been focusing on developing international scholarship programs in Asia, especially Pakistan;which helps in providing a worldwide recognition to its huge pool of intellectual manpower. I strongly believe that if appropriate exposure is provided to these minds of intellect, then Pakistan will be able to meet the challenges of this ever expanding horizon of innovation and technology," these views were expressed by the Vice Chancellor – Prof. Dr. Muhammad Qaiser and Consul General of the Republic of Korea Lee, Chang-Heeduring their address to the POSCO Asia Fellowship Award Ceremony 2013 in the Vice Chancellor's Secretariat, University of Karachi here on Friday. The POSCO Asia Fellowship is a scholarship program designed to invite promising Asian graduate students to the Master's and Ph.D. Program at the Graduate School of International Studies, Seoul National University (SNU-GSIS), supporting their studies at one of the most prestigious institutions of higher learning in Korea.</p>
