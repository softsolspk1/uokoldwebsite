   <h3>Lecturer of UoK Wins Best Research Paper Award in USA</h3>
   <p><span class="date_news">22 Aug 2016</span></p>
   <p align="justify">Karachi University Economics Dept. Lecturer Rabia Shakir got best research paper award at the 8th Annual International Conference "Research for Change" organized by World Business Institute, Australia at New York USA. She was the only Pakistani participant to be awarded the best paper award among the distinguished research scholars from all over the world. Her paper on Pakistan's Monetary Policy will be published in the Journal of Accounting, Finance and Economics, World Business Institute Australia. For this achievement, she was also awarded the fellowship in the World Business Institute Australia.</p>
