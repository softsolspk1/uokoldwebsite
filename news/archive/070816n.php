   <h3>UoK Disowns Karachi University Model United Nations II Conference</h3>
   <p><span class="date_news">23 Aug 2016</span></p>
   <p align="justify">University of Karachi has notified that a conference entitled "Karachi University Model United Nations II" is being held at Regent Plaza Hotel from 26th to 28th August 2016 misusing the name of University of Karachi as there is no permission/clearance taken from the university for organizing this conference. Therefore, Karachi University categorically disowns and denies any affiliation with "Karachi University Model United Nations II". University of Karachi will not be responsible for any financial or any sort of irregularity or mismanagement. Furthermore, KU's students' society "Karachi University Model United Nations Society" also has no affiliation whatsoever with this conference.</p>
