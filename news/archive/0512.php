   <p><span class="date_news">24 May 2012</span></p>
   <p align="justify">"In order to standardize the catalogue and archive genetic associated data and to make it easily accessible to the scientific community, a genetic associated database or genomic library has recently been developed for indigenous entompoathogenic nematodes (EPN) and root-knot nematodes (|RKN) species at NNRC. The fact is satisfactory that more than 100 isolates of EPN and more than 75 of RKN have so far been sequenced in a Gene Bank", these views were expressed by the Vice Chancellor – Prof. Dr. Muhammad Qaiser, Dr. Manzoor Soomro – President Pakistan Science Foundation, Prof. Dr. Shaheena Fayyaz – Director National Nematological Research Centre, University of Karachi and other while addressing the inaugural session of an international workshop at NNRC titled Root-knot Nematodes in Vegetables using EPN here on Thursday. The workshop, mutually funded by University of Karachi and Pakistan Science Foundation, was organized in connection to the Pak-China 17th Protocol on S & T Cooperation. Under this agreement a four member Chinese delegation headed by Prof. Dr. Richou Han, Director, Guangdong Entomological Institute, China visited Pakistan. </p>
