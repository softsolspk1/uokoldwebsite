   <h3>University to release bio-pesticides for local farmers for the first time in Pakistan</h3>
   <p><span class="date_news">27 May 2012</span></p>
   <p align="justify">"For the first time in Pakistan, National Nematological Research Centre (NNRC), University of Karachi will release nematode samples to local growers and farmers which will replace pesticides. Nematodes are small parasitic animals that can kill bacteria without leaving any harmful impact on crops", this has been announced in the concluding ceremony of the three day workshop titled Biological Control of Root-knot Nematode in Vegetables using EPN organized by the National Nematological Research Centre, University of Karachi. The workshop, inaugurated by Prof. Dr. Muhammad Qaiser – Vice Chancellor, KU, concluded on the note that excessive use of pesticides in crops leave harmful impacts. There impacts are harmful for human health and lead to severe human diseases and illness. In order to deal with this situation, use of nematodes can be extremely fruitful. The aim of this workshop was to stimulate awareness, upgrade knowledge and improve skills of participating farmers, extension workers and students on EPN technologies developed by the NNRC for the biological control of RKN in vegetables. </p>
