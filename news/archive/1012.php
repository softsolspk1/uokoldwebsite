   <h3><strong>A Rising China and Contemporary Europe: Situating South Asia - Seminar at ASCE</strong></h3>
   <p><span class="date_news">17 Oct 2012</span></p>
   <p align="justify">Area Study Center for Europe, University of  Karachi organized a seminar on the topic &quot;A Rising China and Contemporary  Europe: Situating South Asia&quot; on October 16th&nbsp;2012 at ASCE,  University of Karachi. A six member delegation of&nbsp;&nbsp;&nbsp;Chittagong  University, Bangladesh presented their research project funded by the  University Grants Commission of Bangladesh. The main purpose of this research  project is to improve research capabilities of the political science department  of the Chittagong University. These views were expressed by Prof. Dr. Bhuian M.  Monoar Kabir, the director of the project. &quot;We are here to get the Pakistani  view about the rise of China and its impact on South Asia&rdquo; he said. Prof. Dr.  Kabir emphasized the point that India and Pakistan should keep aside the  disputed issues and learn from China&rsquo;s strategy of non-intervention and  peaceful relations with its neighbor &quot;</p>
   <p align="justify">Ms. Munazza Kazmi, Senior Research Fellow,  Area Study Center For Europe (ASCE) described the Sino-Europe relations and how  China is helping Europe for coping with this current Euro crisis. She said that  &quot;Chinese are now taking advantage in identifying investment opportunities in  Europe&quot;. Mr. Sajjad Ahmad, Senior Research Fellow, ASCE, threw light on the  historic Sino-Pak relations and how this relationship developed after the  deterioration of Sino-Indian relationship. </p>
   <p align="justify">Prof. Dr. Anwara Begum, lead researcher of the  project, delivered well-articulated and interactive presentation. While  describing state of Sino-Europe relations, she mentioned that &quot;China has always  been interested in Europe. It has more research centers to study Europe than  USA&quot;. She further said that, &quot;Europe is knowledge based economy and China is  trying to become one that&rsquo;s why China wants to have good relations with  Europe. The Chinese scholars are in favor of helping European economy as it  is a big market for Chinese goods. And if the purchasing power of EU citizens  fall down it will affect Chinese economy as well&quot;. </p>
   <p align="justify">Director of ASCE, Prof. Dr. Moonis Ahmar  appreciated the ideas illustrated by the presenters and emphasized that there  are several myths about the rise of China and China becoming Super power.  &quot;China has a long way to go to match the level of development like US and  Europe have done. Super Power is not only about having billions of dollars of  foreign exchange reserves, its means also quality of life of common people and  human development&quot;, he said. Prof. Ahmar also mentioned that &quot;China has many  challenges in terms of innovation, rural-urban gap and class difference, which  it needs to address on immediate basis&quot;. </p>
