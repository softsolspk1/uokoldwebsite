   <h3>Seminar on &quot;Halal: Symbol of Intolerance in the Hygiene, Safety and Quality&quot;</h3>
   <p><span class="date_news">6 Oct 2012</span></p>
   <p align="justify">A seminar on "Halal: Symbol of Intolerance in the Hygiene, Safety and Quality" was organized by the Department of Agriculture & Agribusiness Management. Vice-Chancellor Prof. Dr. Muhammad Qaiser, who presided over the seminar appreciated the efforts of the department for organizing a seminar on such an important topic. He said that the Halal certification is accepted as a symbol of quality and hygiene not only by the Muslims but non-Muslims as well and there is large market available for Halal products that needs to be explored. Prof. Dr. Saleem Shahzad, Chairman of the Department highlighted the importance of the seminar and said that this will provide very important knowledge to the participants specially the students of the department who can utilize it in their professional life. Mufti Ehsan Ahmed Waqar of Halal Foundation and Mufti Saad Shamim of Halal Industry Research Center emphasized the importance of Halal products in the light of Sharia and explained the Sharia way of slaughter. Mr. Muhammad Akram Khan and Mr Raheel Iqbal of Hailal Industry Research Center, Mr. Umar Mukhtar Tarar of PCSIR, Mr. Khuwaja Ghulam Moinuddin of PSQC Association, Ms. Zehra Shakir Khan or RINA / RI&CA, Mr. Shaharyar Ahmed Khan of SGS, Pakistan and Dr. Abdul Rab Farooqui, Pharmaceutical Consultant also made deliberations about Halal certification.
The speakers said that only knowing about the Halal and Haram things is not enough. We should know everything about the product and its ingredients. Each and every component of the food and the way of its preparation and every step of the supply chain has to be certified as Halal by a competent authority. Even a minute amount of component, the way of its storage or supply that is not Halal can make the food Haram. It was emphasized that it is the right of the consumers to ask the retailers about Halal certified products in order to take care of their health.  Halal standards should be followed not only for food but for garments, cosmetics and medicines as well. </p>
