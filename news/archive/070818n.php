   <h3>Awareness Seminar on Safe Handling and Disposal of Dyes</h3>
   <p><span class="date_news">13 August 2018</span></p>
   <p align="justify">An awareness seminar on Safe Handling and Disposal of Dyes organized by Department of Chemistry, University of Karachi (KU) in collaboration with ORIC, KU will be held on 15th August, 2018 at 9:00 am at Arts Auditorium, University of Karachi. Registrar and Director ORIC KU Prof. Dr. Majid Mumtaz will deliver the welcome address while Nazish Shekha, Sustainability Consultant, Dr. Sitara Rashid, Textile Consultant, Dr. Farhana Abdul Rauf, WHO Consultant, Dr. Qaisra Mansoor, Consultant Dermatologist, Dr. Iffat Zehra from Archroma will address. The major purpose of the seminar is to raise awareness about the environmental and health impacts of using dyes and chemicals without knowing the source of inquiring about their authenticity.</p>
