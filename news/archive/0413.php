   <h3>Training Workshop on Research Methodology Organized by the IR Department</h3>
   <p><span class="date_news">4 Apr 2013</span></p>
   <p align="justify">"Research is the intellectual  backbone of a society; it has the potential to bring about a qualitative change  in the political, social and economic milieu of a society. These views were  expressed by Prof. Dr. Moonis Ahmar in his concluding address in a two-day  workshop on "Research Methodology". The Workshop was organized by the  Department of International Relations, University of Karachi on 2-3 April,  2013. He further added that the purpose of holding such a workshop is to  enhance the capacity of students to develop substantial expertise and skills in  different areas of research. 
Prof.  Dr. Shaista Tabassum, Chairperson, Department of International Relations, said  in her address that without research there cannot be any genuine process of  intellectual and technological growth.
Prof.  Malahat Kaleem Sherwani, Dean Faculty of Arts, said in her concluding address  that no society has ever progressed without having a vibrant culture of  research. There is an urgent need to facilitate the culture of research at all  levels particularly in higher education. 
Dr.  Anila Amber Malik, Associate Professor, Department of Psychology and the main  resource person of the workshop said in her concluding address that the culture  of research is of immense significance for a nation to steer successfully in  today's world.<br />
