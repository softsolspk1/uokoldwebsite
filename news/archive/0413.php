   <h3>Seminar at department of International Relations</h3>
   <p><span class="date_news">23 Apr 2013</span></p>
   <p align="justify"></p>
   <p align="justify">&ldquo;The real difference between the West and Islam is epistemological not political; both have mutually incompatible epistemological planes, yet thorough introspection can unleash possibilities of fruitful contact&rdquo; .These views were expressed by eminent journalist and scholar Shahnawaz Farooqi at a seminar on &ldquo;Islam and the West: prospects and challenges&rdquo; at the Department of International Relations, University of Karachi, on April 22, 2013. He spoke extensively on the nature of truth as perceived by the West and Islam. He outlined five essential areas which should be taken into account while drawing any meaning comparisons and possibilities of dialogue between the West and Islam; ontology, epistemology, concept of man, Concept of self, and concept of universe. He was of the view that the West has an overwhelmingly materialist perspective regarding the nature of life and universe. The west is almost oblivious to an ulterior and superior hand involved in the creation of the universe. The modern western epistemological tradition, beginning mainly from René Descartes, believes in rationalist paradigm. It considers man to be the center of universe and human reason to be the sole source of knowledge, emancipation and even salvation. Professor Dr. Shaista Tabassum –Chairperson department of International Relations-said in her concluding  remarks that human existence in this world inherently carries a discoverable theme behind it .Human intellect should mainly focus on  making sense of that colossal meaning in order to lead life in a humane manner.   </p>
