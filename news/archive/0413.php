   <h3>UoK hosts Chinese Cultural Photo Exhibition </h3>
   <p align="justify"><span class="date_news">23 Apr 2013</span></p>
   <p align="justify">&ldquo;Among its neighboring countries, Pakistan enjoys the most active bilateral relations with China. It is pertinent that efforts be made to strengthen these friendly ties by sharing knowledge and expertise. Confucius Institute of Chinese Language at University of Karachi will play a significant role in bridging the gap among scholars of both the countries&rdquo;, these views were expressed by the Vice Chancellor – Prof. Dr. Muhammad Qaiser and Acting Consul General of China – Pan Qinjiang while addressing the inaugural ceremony of the <strong><em>Chinese Cultural Photo Exhibition</em></strong> in Gymnasium Hall of University of Karachi. The exhibition contained a large number of photographs and images depicting the cultural impulse of China. It provided students, the updated knowledge of Chinese traditional values and social &amp; historical outlook of a country that embraced itself out of the dungeons of poverty and illiteracy. During his address, the Vice Chancellor gave a brief account of Pak-China relations and insisted upon initiating collaborative research projects and students' exchange programs between the two countries in future because according to him, <em>past interactions have proved to be fruitful in every respect. </em>The Chinese delegate later visited the Department of Public Administration where Chinese Consul General delivered a lecture to the students of Public Administration. He informed the audience that the University of Karachi will set up Chinese language institute and students of this institute will be able to study free advance course at Sichuan Normal University, China.</p>
