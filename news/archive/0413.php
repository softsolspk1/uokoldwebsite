   <h3>UoK lauds efforts of  participants of the IBA Convention and Cricket Tournament in Sri Lanka</h3>
   <p align="justify"><span class="date_news">24 Apr 2013</span>   </p>
   <p align="justify">&ldquo;Time management and prompt response were the two key factors that accelerated our victory&rdquo;, expressed one of the delighted students of the Department of Public Administration who represented University of Karachi in IBA Media Accession &amp; Reinforcement Convention (IMARC) and competed other Universities of Karachi including NED, CBM, Aga Khan University. The Vice Chancellor – Prof. Dr. Muhammad Qaiser in his address appreciated the students&rsquo; efforts and said &ldquo;<em>Students, Teachers and Administration together makes a triangle of ultimate success. Together they are able to manage even the most critical challenges of time. It is noteworthy that the University is imparting quality education which is evident from the success of our students at different platforms&rdquo;. </em>He was speaking to a ceremony organized to appreciate the efforts of the students who won the IMARC Convention and of the students who won the runner&rsquo;s up trophy in the inter University cricket tournament that took place in Sri Lanka. It is pertinent to note that in order to reach the final match, our students also defeated the team from India. Chairperson Department of Public Administration – Prof. Dr. Khalid Iraqi informed the audience that this was the first time when students represented University of Karachi in a social media forum like IMARC. It is indeed a pleasurable moment for us that our students have brought a good name to the University. Prof. Dr. Abuzar Wajidi – Dean Faculty of Management and Administrative Sciences expressed that healthy competition results in encouragement. Such activities prepare our youth to face the challenges of this modern and ever changing world. On this occasion, a large number of faculty members and students were also present.  </p>
