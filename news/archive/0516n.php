   <h3>Seminar on World Youth Day</h3>
   <p><span class="date_news">17 Aug 2015</span></p>
   <p align="justify">Youth are an asset to  any nation and they have a pivotal role in the success of the nations. Educated  youth class of any nation provides an excellent opportunity of sustainable  development. Civilized nations of the world provide great opportunities to the  youth for displaying their talent and abilities for the nation's welfare and  progress. Health, education, science and technology, politics, industry and in  every sector of state, youth must be provided a greater role in order to  achieve sustainable development. Prof. Dr. Tariq Masood Ali Khan Director  Institute of Environmental Sciences at a Seminar expressed these views on  World Youth Day at a seminar jointly organized by Institute of Environmental  Sciences KU and Pakistan Red Crescent Society. Registrar, Prof. Dr.  Moazzam Ali Khan commended the Prime Minister Youth Program and termed it very  vital for resolving the issues of the youth and providing them financial  assistance for getting quality education. He added that the youth should be  provided a role in the policymaking of the country, as it will bring positive  and fruitful results. Youth Parliament is an ideal forum of framing national  policies but it needs to be further revitalized. This forum must be connected  to the national decision making to include the youth in national and regional  issues. He lauded the efforts of PRCS and Volunteer Cell in organizing this  event.</p>
