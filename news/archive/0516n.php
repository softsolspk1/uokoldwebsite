   <h3>EU-UoK  Horizon  2020 (<a href="https://drive.google.com/a/uok.edu.pk/folderview?id=0B3niqFRaEVPPfkcxVVRVbnVBelI4cGRlOVhjeDlGSXVZeDhYalRyZjFYQUdUeFVhWllwWGc&amp;usp=sharing_eid" target="_blank">Attachments</a>)</h3>
   <p><span class="date_news">20 Aug 2015</span></p>
   <p align="justify">European  Union is a strong and diversified political institution. Science and technology  have no borders. Europe has the most powerful system of integration. Horizon  2020 will provide the funds of around 300-400 million Euros to Pakistani  researchers for assistance in their respective research. Research and scholarly  work in University of Karachi is commendable and indeed Pakistan is producing  internationally acclaimed researchers. Pakistan is a rapidly growing nation and  we want to make it much more vibrant in the field of science and research.  These views were expressed by His Excellency Steafano Gatto, Acting Head of  Delegation of European Union in Pakistan at an Awareness Seminar on Horizon  2020 jointly organized by European Union Delegation to Pakistan, Pakistan  Science Foundation and University of Karachi .On the occasion notable  dignitaries and faculty members were also present, notable were VC Prof. Dr.  Muhammad Qaiser, Chairman Pakistan Science Foundation Prof. Dr. M. Ashraf,  Registrar Prof. Dr. Moazzam Ali Khan, Syed Lal Shah, Dr. Mirza Habib, Irfan  Ahmed, President KUTS Prof. Dr. Jamil Hasan Kazmi, Dr. Haris Shoaib and Prof.  Dr. Abid Hasnain. 
     He  further congratulated Pakistan Science Foundation for organizing this seminar  while thanked University of Karachi for hosting this program. These programs  would also be organized in different other cities of the country as they are  very vital in guiding the researchers and providing them new horizons, he  added. </p>
   <p align="justify"> VC Prof. Dr. M. Qaiser welcomed His Excellency Steafano Gatto, Acting Head of  Delegation of European Union in Pakistan, Chairman Pakistan Science Foundation  Prof. Dr. M. Ashraf and other distinguished dignitaries on the occasion. It's a  commendable step of organizing these sorts of awareness programs, research is  the future of mankind and solutions of all the societal problems are hidden in  research and scholarly work. This research grant from European Union would  assist the researchers and it would provide uncounted opportunities of  sustainable development in the field of science and technology in Pakistan, he  added. 
     Prof.  Dr. M. Ashraf said that Pakistan Science Foundation was founded in 1973  according to&nbsp;Pakistani parliament act and providing funding to research  institutions of Pakistan. The basic aim of PSF is to promote and popularize  science. Science and technology is the key to development in every walk of  life. This grant of Horizon 2020 is highly competitive and open for all. </p>
   <p align="justify">     Mr.  Denis Dambois European Union Counselor, Scientific Affairs based at New Delhi  office India while addressing through video link emphasized on the dire need of  innovative research for the developing nations. Europe is a highly diversified  region and has the largest number of researchers in the world. 1/3 of the  production of Science and technology is produced by Europe alone. This 7 years  program of Horizon 2020 is open for all individual researchers from all  countries. European Union is working in collaboration with Pakistan in this  regard and 402 Pakistani students, 10 scholars have gotten grants from the  European Union which is highly appreciable and commendable he noted. </p>
