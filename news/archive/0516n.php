   <h3>VC  inaugurates Exibition on Pakistan Movement at Dr. Mahmood Hussain Library</h3>
   <p><span class="date_news">11 Aug 2015</span></p>
   <p align="justify">Pakistan has been founded after significant sacrifices of our  forefathers. God provided the Quaid-i-Azam&nbsp;Muhammad Ali&nbsp;Jinnah the  opportunity to convert the idea of Pakistan into a reality. The movement  progressed alongside with the&nbsp;Indian independence movement&nbsp;which had the similar views and motives,  but the Pakistan Movement sought to establish a nation-state that protected the  religious identity and political interests of Muslims in South Asia.&nbsp;Muhammad Ali Jinnah&nbsp;also acclaimed the Pakistan movement&nbsp;to have started when the first Muslim  put a foot in the Gateway of Islam. The cause of Pakistan Movement became an  inspiration in different countries of the world. Protection of one's beliefs,  equal rights, and liberty were incorporated in the state's constitution. These  views are expressed by the Vice Chancellor Prof. Dr. Muhammad Qaiser while addressing  in the inauguration ceremony of Exhibition on Independence Movement of Pakistan  organized by Prof. Malahat Kaleem Incharge Dr. Mahmood Hussain Library on  Tuesday 11th&nbsp;August, 2015. Prof. Malahat Kaleem, Incharge  Library presented the welcome address.  </p>
