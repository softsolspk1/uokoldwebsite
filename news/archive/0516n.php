   <h3>Intl. Conference on Contemporary Social Sciences 2015  would take place from 5-6 December.</h3>
   <p><span class="date_news">11 Aug 2015</span></p>
   <p align="justify">Faculty of Social Sciences University of Karachi has announced  the holding of fifth International Conference entitled as International  Conference on Contemporary Social Sciences 2015 (ICCSS). The conference would  take place in Arts Auditorium, Faculty of Social Sciences, from&nbsp;5-6  December, 2015.  Dean Faculty of Social Sciences Prof. Dr. Moonis Ahmar told that  this conference is one of the new activities being launched by the faculty as  part of the strategic objective for the advancement of the frontiers of the  production and dissemination of knowledge. It would permit the faculty members  of the Social Sciences to reflect on their experiences and exchange views on  common challenges and produce viable solutions to them. 
     Interested students/faculty members may submit their abstracts  till August 20 while the notification of the acceptance of the abstracts would  be issued on 30th&nbsp;August, 2015. Date of submission of final  paper is September 25th while the registration deadline is&nbsp;October  31, 2015. Conference Secretariat i.e. Dean Office, Faculty of Social Sciences,  University of Karachi could be contacted for further information. </p>
