        <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">The Higher Education Commission has taken a number of initiatives for broadening the reach of information technology to meet the IT challenges of the country, especially for the education sector. The Higher Education Commission has recently signed a MoU with PTCL for the provisioning of Broadband DSL connections to students, faculty members and administrative staff at substantially subsidized rates at their residence. The DSL facility/service under this MoU offer Broadband connection at 256 kbps, 512 kbps and 1 Mbps with 30% discount on prevailing PTCL commercial rates against each capacity. </font></p>
