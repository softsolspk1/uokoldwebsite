        <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Be it known to all concerned that the Annual  Convocation for the regular students (under semester system) of the University  of Karachi is expected to be held shortly, to confer degrees to the desiring  candidates who have passed Bachelors (Honours), B.S., B.Pharmacy, Masters and  M.Pharm in 2007. Those who obtained their M.S./ M.D./ M.Phil/ Ph.D./ D.Litt./  D.Sc. in 2007 - 2008 will also be conferred the degrees. Medals and Merit  Certificates shall also be awarded to the position holders of various  Departments (where available) in the University Examinations mentioned above.</font></p>
        <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">The desirous candidates of degree (who have not yet  received their degrees) are advised to apply for registration to the Annual  Convocation on prescribed application form. The forms can be downloaded <a href="#frm">here</a> and  also available from the Convocation Camp Office, Silver Jubilee Gate No.1, Main  University Road, University of Karachi <strong><u>from 26th March, 2008.</u></strong> Duly filled in forms (with required documents) shall be received only in the  Convocation Camp office along with prescribed Registration and Degree forms  with fees to be deposited at the banks  branch at Silver Jubilee Gate after endorsement by the Camp Office during  10:00 a.m. to 01:00 p.m. and on Friday 10:00 to 12:00 Noon till <strong><u>10th April, 2008</u></strong>.</font> ( <span class="style4"><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Extended till Saturday 03, May 2008 </font></span>) </p>
        <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">No candidate will be allowed  to enter in the convocation pindal without wearing prescribed Academic  Costume/Robe. </font></p>
        <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif"><strong>(
