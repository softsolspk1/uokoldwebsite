        <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Be it
          known to all concerned that the Annual Convocation of the regular
          students (Morning and Evening Programmes) of the University of Karachi
          is expected to be held shortly at the
          University Campus, Karachi to confer degrees to the desiring candidates
          who have passed Bachelors (Honours), B.S., B.Pharmacy, Masters and
          M.Pharm in 2006 under Morning Programme and 2006 under the Evening
            Programme. Those who obtained their M.S./M.D./M.Phil/Ph.D./D.Litt./D.Sc.
            in 2006-07 and onward will also be conferred the degrees. Medals
            and Merit Certificates shall also be awarded to the position holders
            of various Departments in the University Examinations mentioned above.</font></p>
        <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Those
            intending recipients of degrees who have not received their degrees
            are advised to apply for registration to the Annual Convocation on
            prescribed application form which can be downloaded from <a href="#frm">here</a>. They
            are  also available from the Convocation Camp Office, Silver Jubilee
            Gate No.1, Main University Road, University of Karachi from 5th March,
            2007. Duly filled in forms (with required documents) shall be received
            only in the Convocation Camp office alongwith prescribed Registration
            and Degree forms with fees to be deposited at the banks branch at
            Silver Jubilee Gate after endorsement by the Camp Office during 10:00
            a.m. to 01:00 p.m. and on Friday 10:00 to 12:00 Noon till 17th March,
            2007.</font></p>
        <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">The already
            registered candidates who have not been awarded degrees / Gold Medal
            / Merit certificate in the year 2006 due to the postponement of
            the convocation - 2006, will also be awarded the same on the Convocation
            2006-07. They would be issued new convocation invitation cards on
            surrendering the old convocation invitation cards on a date announced
            later. They need not to apply a fresh.</font></p>
        <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">It is
            notified that no candidate will be allowed to enter in the convocation
          pindal without wearing the prescribed  Academic costume/robe. </font></p>
