<p align="left"> <font size="2" face="Verdana, Arial, Helvetica, sans-serif"><a href="#shots">Shots</a> | <a href="#gov">Urdu Version</a></font></p>
      <p align="justify">&nbsp;</p>
      <p align="justify"><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Governor Sindh, Dr Ishratul Ebad Khan,  on Saturday inaugurated the  newly-constructed buildings of  the    National     Centre     for  Proteomics and the Department  of Food Science and Technology,  University of Karachi. </font></p>
      <p align="justify"><font size="2" face="Verdana, Arial, Helvetica, sans-serif"> Talking to the media after the  inaugural ceremony, Dr Ebad,  who is also the chancellor of all  public sector universities in the  province, said that the allocation  for higher education in the country had been enhanced from 0.2  to two per cent of the GDP. </font></p>
      <p align="justify"><font size="2" face="Verdana, Arial, Helvetica, sans-serif"> The governor said that the  University of Karachi had now  joined the league of 500 big universities around the globe. He     said that there had been a pleasant change in the overall academic atmosphere at the varsity  over the past few years. He  was of the view that  the main objective of a seat of  higher learning was to carry out  research work. </font></p>
      <p align="justify"><font size="2" face="Verdana, Arial, Helvetica, sans-serif"> Speaking about the possibility  of a change in the academic calendar, the Sindh governor said  that a decision in this regard  would be taken keeping in view  the weather conditions and the  aspirations of the stakeholders i.e.  the students and the faculty  members. </font></p>
      <p align="justify"><font size="2" face="Verdana, Arial, Helvetica, sans-serif"> The foundation stone of the  Administration Block- II was also  laid on the occasion</font>. <font size="2" face="Verdana, Arial, Helvetica, sans-serif">The new building of the Administration Block will consist two floors and will be completed at  a cost of Rs. 34.28 million. The covered area of the building will be 16284 sq. feet. </font></p>
      <p align="justify"><font size="2" face="Verdana, Arial, Helvetica, sans-serif">The inaugurated building of Department of Food Science and Technology has been completed at a cost of Rs. 33.41 million and has a covered area of 47421 sq. feet. </font></p>
      <p align="justify"><font size="2" face="Verdana, Arial, Helvetica, sans-serif">The inauguration ceremony was attended by the Vice Chancellor Prof. Dr. Pirzada Qasim Raza Siddiqui, Chairman Search committee Dr. S. M. A. Qureshi, Pro-Vice Chancellor Prof. Dr. Akhlaq Ahmed, Registrar Prof. M. Rais Alvi, Prof. Dr. Abuzar Wajidi, Prof. Dr. Shakeel Farooqui, Prof. Dr. Abid Hasnain, Prof. Dr. Aqil Burney, Prof. Dr. Khalid Iraqi and many other faculty members and staff. </font></p>
