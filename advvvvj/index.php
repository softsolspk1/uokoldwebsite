  <p><strong>Job Title: Bursar </strong><br />
    <strong>Location:</strong> University of Karachi, University  Road<br />
    <strong>Department:</strong> Finance Department<br />
    <strong>Reports to:</strong> Director of Finance<br />
    <strong>Job Summary:</strong></p>
  <p align="justify">The Bursar is responsible for  overseeing and optimizing the university&rsquo;s revenue streams. This includes  managing tuition, fees, grants, donations, other income sources and other tasks  assigned by the supervisor. The Revenue Manager will work closely with various  departments to ensure financial strategies align with the university's goals,  enhance financial sustainability, and support the institution's mission.  Additionally, the Revenue Manager will lead efforts to digitize financial  processes, leveraging ICT systems to improve efficiency and accuracy.</p>
  <p><strong>Key Responsibilities:</strong></p>
  <ul>
    <li><strong>Revenue Optimization:</strong></li>
    <ul>
      <li>Develop and implement strategies to  maximize the university&rsquo;s revenue from all sources. </li>
      <li>Monitor and analyze revenue  performance, identifying trends and areas for improvement. </li>
      <li>Collaborate with enrollment  management to optimize tuition pricing and scholarship allocation. </li>
    </ul>
    <br />
    <li><strong>Financial Analysis:</strong></li>
    <ul>
      <li>Conduct financial analysis and  modeling to support decision-making. </li>
      <li>Prepare detailed revenue reports and  forecasts. </li>
      <li>Analyze the impact of proposed  changes to pricing, fees, and funding structures. </li>
    </ul>
    <br />
    <li><strong>Budget Management:</strong></li>
    <ul>
      <li>Assist in the preparation and  management of the university's budget, focusing on revenue projections. </li>
      <li>Monitor actual revenue against  budgeted figures and report variances. </li>
    </ul>
    <br />
    <li><strong>Policy Development:</strong></li>
    <ul>
      <li>Develop and implement  revenue-related policies and procedures. </li>
      <li>Ensure compliance with relevant  regulations and university policies. </li>
    </ul>
    <br />
    <li><strong>Collaboration and Communication:</strong></li>
    <ul>
      <li>Work with academic and  administrative departments to understand revenue-related needs and  opportunities. </li>
      <li>Communicate revenue strategies and  performance to senior leadership and stakeholders. </li>
      <li>Provide training and support to  staff on revenue management best practices. </li>
    </ul>
    <br />
    <li><strong>Grant and Donation Management:</strong></li>
    <ul>
      <li>Oversee the administration of grants  and donations, ensuring funds are utilized effectively and in compliance with  donor stipulations. </li>
      <li>Work with the advancement office to  identify and pursue new funding opportunities. </li>
    </ul>
    <br />
    <li><strong>System and Process Improvement:</strong></li>
    <ul>
      <li>Enhance revenue management systems  and processes to improve efficiency and accuracy. </li>
      <li>Lead efforts to digitize financial  processes through the implementation and management of ICT systems particularly  in fee collection processes. </li>
      <li>Stay updated with industry best  practices and technology advancements in revenue management and ICT. </li>
    </ul>
    <br />
    <li><strong>ICT and Digital Transformation:</strong></li>
    <ul>
      <li>Collaborate with the IT team to  implement and maintain systems that support financial operations. </li>
      <li>Identify opportunities for  automation and digital transformation to streamline revenue-related processes. </li>
      <li>Ensure data integrity and security  within digital financial systems. </li>
    </ul>
    <br />
    <li><strong>Qualifications:</strong></li>
  <ul>
    <li>Bachelor&rsquo;s degree in finance,  accounting, business administration, information technology, or a related  field. Master&rsquo;s degree preferred. </li>
    <li>Professional certification (e.g.,  ACMA, CA, ACCA) is a plus. </li>
    <li>Minimum of 5 years of experience in  revenue management, financial analysis, or a digital transformation. </li>
    <li>Strong analytical and  problem-solving skills. </li>
    <li>Excellent communication and  interpersonal skills. </li>
    <li>Proficiency in financial management  software, ICT systems, and Microsoft Office Suite. </li>
    <li>Experience with digital  transformation and ICT systems in a financial context. </li>
    <li>Knowledge of higher education financial  management is preferred. </li>
    <li>Government working Experience is not  mandatory. </li>
  </ul>
  <br />
  <li><strong>Working Conditions:</strong></li>
