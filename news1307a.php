   <h3>2 days Orientation Workshop jointly organized by HEC and KU</h3>
   <p align="justify"><span class="date_news">12 Jun 2015</span></p>
   <div align="justify">In the present era, technology has brought revolutionary changes in every walk of life which is very beneficial for everyone. In this regard if the Uniform Semester Examination System is enforced in every university it would provide the students great and prospective facilities of national and international level of advance studies. These views were expressed by Prof. Dr. Anila Ambar Malik, Prof. Dr. Maqsood Ali Ansari and Prof. Muhammad Ali at two days orientation workshop on HEC Policy Guidelines for the Implementation of Uniform Semester Examination System jointly organized by HEC Pakistan and University of Karachi
     Prof. Dr. Anila Ambar Malik, Prof. Dr. Maqsood Ali Ansari and Prof. Muhammad Ali briefed the participants about the policies regarding Uniform Semester Examination System. Prof. Dr. Anila further added that if the proposals proposed in the workshops  regarding the enforcement of Uniform Semester Examination System are implemented then the problems faced by the students on the international level would be resolved. In concluding session Registrar KU Prof. Dr. Moazzam Ali Khan thanked all the guests and said that the holding of this workshop with collaboration with HEC is a highly commendable and I hope that this would be continued in future. Dean Faculty of Science KU Prof. Dr. Viqar Hussain distributed the certificates to the participants. </div>
