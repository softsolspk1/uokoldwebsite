   <h3>KU Signs MoU with CIMA</h3>
   <p align="justify"><span class="date_news">12 Jun 2015</span></p>
   <div align="justify">The University of Karachi signed a Memorandum of Understanding with the Chartered Institute of Management Accountants (CIMA) based in London, UK on Friday, June 12. The MoU was signed between Karachi University Business School and CIMA. Mr. Bradley Emerson, Regional Director CIMA (for Middle East, South Asia & North America) and Dr. Danish Siddiqui, Chairman KUBS signed on behalf of their respective institutions. The ceremony was held at the office of Dean, Faculty of Management & Administrative Sciences, University of Karachi. On this occasion the Dean, Prof. Dr. Khalid Iraqi said the agreement will offer a faster track for the KU graduates to acquire CIMA professional qualification and support them in successfully meeting the challenges of the business profession. Appreciating the supportive role of Vice Chancellor, Dr. Muhammad Qaiser in this agreement he added that university-corporate industry relations and collaborations has acquire increased significance in present times. Mr. Emerson said that this memo will promote collaboration between the KU and the accounting professional bodies like CIMA while the CIMA would offer gold medal awards, fee exemptions and some scholarships annually to the KUBS students.</div>
