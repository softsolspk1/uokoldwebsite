<h3 align="justify">Affiliation of Educational Institutions to the University:</h3>
<p align="justify">&nbsp;</p>
<ul>
  <li>
    <p>An educational institution applying for affiliation to the University shall make an application to the University and shall satisfy it:
    </p>
    <ul>
      <li>
        <p>that the educational institution is under the management of the Government or of a regularly constituted governing body;</p>
      </li>
      <li>
        <p>that the financial resources of the educational institution are sufficient to enable it to make due provision for its continued maintenance and efficient working;</p>
      </li>
      <li>
        <p>that the strength and qualifications of the teaching and other staff, and the terms and conditions of their services, are adequate to make due provision for the courses of instruction, teaching or training to be undertaken by the educational institution;</p>
      </li>
      <li>
        <p>that the educational institution has framed proper rules regarding the efficiency and discipline of its staff and other employees;</p>
      </li>
      <li>
        <p>that the building in which the educational institution is to be located is suitable, and that provision will be made in conformity with the Statutes and Regulations for the residence of students, not residing with their parents or guardians, in the hostels established and maintained b y the educational institution or in hostels or lodgings approved by it, and the supervision and physical and general welfare of students;</p>
      </li>
      <li>
        <p>that provision has been made for Library and adequate library services;</p>
      </li>
      <li>
        <p>that where affiliation is sought in any branch of experimental sciences, due arrangements have been made for imparting instruction in that branch of science in a properly equipped laboratory, museum and other places of practical work;</p>
      </li>
      <li>
        <p>that due provision will, so far as circumstances may permit, be made for the residence of Principal and members of the teaching staff in or near the college or the place provided for the residence of students; and</p>
      </li>
      <li>
        <p>that the affiliation of the educational institution, having regard to the provision which may have been made for students by another educational institution in its neighbourhood, will not be injurious to the interests of education or discipline.</p>
      </li>
      </ul>
  </li>
  <li>
    <p>The application shall further contain undertaking that after the educational institution is affiliated any transference of, and changes in the management and in teaching staff shall be forthwith reported to the University, and that the teaching staff shall possess such qualifications as are or may be prescribed.</p>
  </li>
  <li>
    <p>The procedure to be followed in disposing of an application for the affiliation of an educational institution shall be such as may be prescribed.</p>
  </li>
  <li>
    <p>The Syndicate may, on the recommendation of the Affiliation Committee, grant or refuse affiliation to an educational institution.</p>
  </li>
</ul>
