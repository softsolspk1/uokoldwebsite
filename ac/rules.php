<ul>
  <li>Registration Certificate from Education and Literacy Department, Government of Sindh.</li>
  <li>List of members of the Governing Body along with its rules and regulations regarding its formation its functions and powers.</li>
  <li>Names of the members of the Board of Governors of your Institute along with profile of the Board members. </li>
  <li>  A copy of course outline &amp; syllabus. </li>
  <li> One nominee of the Intermediate Board and one nominee of the University of Karachi to be taken on the Governing Body of your College/Institution. (in case of BBA/BCS nomination to be as per syndicate rules). </li>
  <li> List of members of the Selection Board, rules &amp; regulations regarding its formation, functions and powers. Concerned Chairman or their nominees of our University Departments (in case of professional colleges, the Deans or their nominees) to be taken on the Selection Board of your College/Institution at the time of recruitment/appointment of new teachers. (in case of BBA/BCS nomination to be as per syndicate rules). </li>
  <li> Copy of the Society’s Registration Certificate together with byelaws of the Society, and profile of the society members. </li>
  <li> Subject-wise list of books with accession nos. indicating title of each book, name of author, name of publisher, year of publication and number of volumes pertaining to the course/classes applied for presently available in the library or to be procured for this purpose. </li>
  <li> Details of the building of the Institute. Whether it is owned by the Society or it is on rental basis. If on lease/rent, then provide us tenancy agreement for at least ten years. Map/site plan of the Institute’s building may also be provided (Land area must be 2000 square yards). </li>
  <li>List of faculty members along with their qualifications, division, year of passing experience: also indicating their service rules and pay scales, cadre-wise presently available or further to be engaged/appointed for the opening of the said course/degree program applied for. </li>
  <li> Workload of the college teachers i.e. their periods of Intermediate and the proposed degree program (time-table). </li>
  <li>Financial resources; last three years bank statement with a reserve fund of Rs.5,00,000/- (Rs. Five lacs only) for running expenditure of the college/institution. Yearly allocation of budget for the said degree program and also a bank certificate showing/indicating the exact amount available in the college account. </li>
  <li>Position of the college building with respect to classrooms, furniture, space etc. </li>
  <li>Undertaking that the college teachers shall be paid at least grade-17 salary with all permissible allowances and annual increment as per salary structure of the Directorate of College Education, Karachi (or Govt. rules/salary structure) That salary to the college teachers shall be paid through crossed cheque under intimation to this office every monthly. </li>
  <li>Undertaking to be produced to this office, that the disciplinary action i.e. suspension and termination of services of the non-teaching and teaching staff shall be finalized/decided under permission of the University. </li>
  <li>Registration of the Society, the certificate of registration will have to be produced to the University, rules and regulations of the Society about its functions and powers etc. </li>
  <li>N.O.C. from P.M.D.C., Islamabad and Govt. of Sindh, Health Department (<em>in case of Medical and Dental Colleges</em>). </li>
  <li>Position of laboratory facilities with stock nos. i.e. laboratory equipment, instruments, chemicals, laboratory furniture / fixtures etc. for the course/degree program, applied for available in the college/institution. </li>
  <li>Proposed number of students to be admitted in the said course/degree program, applied for. </li>
  <li>Proposed fee structure i.e. admission fee, tuition fee, and caution money, if any, for the said degree/Postgraduate program applied for affiliation. </li>
