  <h3 align="center"><strong>ADMISSION  OF INTERNATIONAL STUDENTS TO UNIVERSITY OF KARACHI</strong> </h3>
  <h4><br />
    <strong>Application</strong><strong> </strong></h4>
  <p><br />
    You are applying for admission at the University of  Karachi, Pakistan through a three-step on-line admission process as under:</p>
  <ul>
    <li>Registration  of your application </li>
    <li>Uploading  of documents </li>
    <li>Closing the  application </li>
  </ul>
<p>You will get to the online application links:</p>
  <p>    Before you register your application you need to decide  the fields of study you are going to select.  You will also have to prepare all documents  you need to upload. Once you have started your application you must complete it since it's impossible to save  incomplete data. In case of incomplete data your application will not be  considered for processing.</p>
  <p> Please carefully read all information  and instructions on this website for International students before starting the registration phase. You  may also download the <strong>Prospectus/Guidelines</strong> below.</p>
  <h4><strong>Application step-by-step</strong></h4>
  <p>    You have applied for the admission at  the University of Karachi, Pakistan through an online application system (which is available only for  the international students).</p>
  <p> Please note that applications are allowed on 'ONE  APPLICATION PER PERSON' basis. Persons who register multiple applications their application  will not be considered.</p>
  <p><strong>1.     Read all  info on the webpage.   </strong>Identify which departments you may  apply for. You can 
    choose at least three  relevant departments.  Selection for  provisional admission in a particular 
    department will be decided  on the basis of your merit and eligibility.</p>
  <p><strong>2.    Prepare the    relevant documentation.   </strong>Go through   the    list   of   required    documents.   Uploaded 
    documents must have a maximum file size of 3 MB. Please upload files in PDF,  JPG or PNG format only. No Word  documents may be uploaded. </p>
  <p> <strong>3.   Start your  application process:</strong></p>
  <ul>
    <li>enter all the required personal data. </li>
    <li> enter details of last academic data . </li>
    <li>Specify the program in which you are applying for.</li>
    <li>specify the relevant Departments you  want to take the admission in (options of 3 departments) </li>
  </ul>
  <p><strong>4.   Submit   the    application.   </strong>Once    you   have   submitted    your   application,   it    will   not   be    possible   to 
    change it. Only submitted  applications will be considered for the selection process.</p>
  <p><strong>You will receive a confirmation email</strong> after you have submitted your  application. There will be also a notice on your screen after you have submitted your application. In  case of non-receipt of confirmation, please contact +<strong>921-  99261376.</strong></p>
  <p><strong>Register an account on the application  website</strong>. After you  have registered or submitted yourapplication,  you will receive a User-ID through email.</p>
  <h4><strong>Documents to upload</strong></h4>
  <ul>
    <li>    Make sure to scan documents  with sufficient resolution. <br />
      </li>
    <li>All supporting documents  must be in English.</li>
  </ul>
<h4> <strong>Definitions</strong></h4>
  <ul>
    <li>Course record: The official stamped  and signed document showing the courses and results (grades) of your previous studies.</li>
    <li>      Official Transcript of Diploma or  Degree: Certified proof of each (Certificate/Diploma/Degree) from the educational institution. If no degree  has been issued, please submit a certified document showing your eligibility for the program applied  for.</li>
    <li>      Proof of registration: Official stamped  and signed document proving your previous registration at your home university for degree/ diploma  (admission letter).</li>
    <li> Documentary evidence of completion of studies abroad  (Scanned Copies of pages from passport showing bio-data, entry, exit and visa of the country concerned).</li>
    <li> Copy of Computerized National Identity Card and B. Form.</li>
</ul>
  <h4> <strong>Selection Process</strong></h4>
  <p>    As soon as the  application closes, the selection process will start and advance as follows:</p>
  <ul>
    <li>    The  University of Karachi assesses the incoming applications according to  pre-defined criteria.<br />
      </li>
    <li> Based on assessments made by the  University of Karachi, the Director, Admissions Committee takes the decision for the selection of  candidates according to the policies. The selection observes the overall eligibility and equivalency criteria.<br />
      </li>
    <li> All candidates are informed about  the result of their applications via email from the coordinating office. Note that you may be contacted by the  University before you get the results of your application for admission. You may be contacted in case of previous  application for admission. However, such contact will not be considered a guarantee for a provisional admission. Only an  official email from the coordinating office  should be considered the definite result of your application concerning the  Provisional Admission.</li>
    </ul>
 
  <h4><strong>When  you are selected</strong></h4>
  <p>    The result of the  application will be announced within a month of uploading the application.  All notifications are sent by email at the email address  registered in your application.</p>
  <h3> <strong>SUCCESSFUL CANDIDATES</strong><strong> </strong></h3>
  <ul>
    <li>Successful candidates  are required to submit the  prescribed  forms. See Annex I, II and III for the Provisional admission in different  degree programs. </li>
    <li> University will send a copy of provisional admission letter to the Higher  Education Commission (HEC).<br />
      </li>
    <li> The HEC shall confirm and endorse admission to the  Ministry of Interior, Government of Pakistan.</li>
  </ul>
