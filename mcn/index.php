<h1>In-charge: Nadeem Ahmed</h1>
<h4>&nbsp;</h4>
<h4><a href="/downloads/mcn.pdf" target="_blank">Download MCN Brochure  <strong>2006-2010</strong> (PDF: 5MB)</a></h4>
 <p>&nbsp;</p>
 <p align="justify">The Main Communication Network (MCN) at the University of Karachi (UoK) has entered another year, and we are grateful for the improved global connectivity it has brought. Thanks to round-the-clock internet access and the University's website, we can now instantly share news, information, and results like never before. The MCN team remains dedicated and forward-thinking in their efforts to provide these services.</p>
 <p align="justify">In response to the ever-increasing internet consumption by university users, the initially allocated internet bandwidth has been upgraded from 128Mbps to 360Mbps. This significant increase has resulted in a 100% availability of internet bandwidth through MCN-UoK, facilitating the research and development activities of faculty members, researchers, and students. This seamless service acts as a catalyst for enhancing the academic excellence of our university.</p>
 <p align="justify">With currently over 10,000 active nodes in the university (increasing to over 12,000 with visitors), the number of internet connections continues to rise. We are proud to report that the response time, which measures the server's reaction time to a given input, is exceptional, averaging around 3.0ms. Furthermore, this response time is steadily decreasing, reflecting the continuous improvement in network services provided by MCN. Our Technical Support team works tirelessly to ensure the university's internet functions properly and provides assistance to all users.</p>
 <p align="justify">In line with our ongoing efforts, we have designed a new web architecture and developed a new website in 2008/2009. Moreover, we are currently working on a new web architecture in 2023. This updated website serves as a comprehensive resource, offering information about departments, degree programs, admissions, institutes, and administration at the University of Karachi. With over a thousand documents and a vast collection of pictures capturing important events (also available on our Facebook page), the website provides easy access to information about admissions, faculties, departments, research institutes, events, meetings, and more.</p>
 <p align="justify">Research collaboration is a vital aspect of any university, and UoK places great importance on this. Through successful educational collaborations with leading universities worldwide, UoK has demonstrated its value in the research field. The establishment of the Video Broadcasting and Conferencing Center within the Department of Computer Science (UBIT) has played a significant role in achieving this milestone. This state-of-the-art center, sponsored by the Federal Higher Education Commission (HEC) in 2009, can accommodate over fifty research scholars simultaneously, opening doors for new international and national research endeavors.</p>
 <p align="justify">We take pride in the progress we have made and the continuous efforts to improve MCN services at UoK. We remain committed to providing an exceptional communication network that supports the academic endeavors of our university community.</p>
