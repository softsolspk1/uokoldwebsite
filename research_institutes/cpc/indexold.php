  <h2>Director:  Dr. Roohi Bano (In-Charge)</h2>
  <h3>Objectives</h3>
  <ul>
    <li>    To maintain a substantial and diverse ex-situ collection of rare and threatened plants, including cultivars</li>
    <li>To establish a Centre for plants Conservation with specialization in the floristic studies and conservation of flora of Pakistan</li>
    <li>To develop a Germ plasm/seeds bank of indigenous as well as cultivars.</li>
    <li>To conserve and restore the rare native and endemic plants of Pakistan via  ex-situ conservation and re-habitation of fast depleting biodiversity </li>
    <li>To facilitate human resource development in the field of plant Conservation</li>
  </ul>
<h3>Vision</h3>
  <p>    Centre for Plant Conservation will be the hub of Academic and research activities. It will provide opportunities for collaborative research with related departments/Institutes on one hand and on the other it will also enhance the knowledge of plant conservation and sustainable utilization of plant biodiversity of rare and endemic plants of Pakistan.</p>
  <h3>Mission</h3>
  <ul>
    <li>    To provide and promote facilities for advanced study and research in various aspects of plant conservation, plant systematic and ethno botany </li>
    <li>To promote and arrange extension lectures, national and international seminars, conferences, courses of further study and in-service training for those already engaged in on various aspects of the discipline and also for the common public. </li>
    <li>      To provide services and consultation to the relevant departments of public and private institutions </li>
    <li>      To collaborate with other academic centres and institutes and to equip and enable the Centre for carrying out the functions set out herein.</li>
    <li>      To developed the Centre for Plant Conservation as an internationally recognized organization.</li>
    <li> Centre for Plant Conservation, University of Karachi is working to save the country’s rare plant species, which are on the brink of extinction &amp; could soon disappear from the planet. In this Centre In-situ as well as ex-situ flora Conservation is taking place.      <br />
    </li>
  </ul>
