  <h2>&nbsp;</h2>
  <p>A modern and fully equipped Centre for Plant Conservation was established at the University of Karachi. This centre is divided into two major sections. (i) Botanic garden and (ii) the herbarium. In the Botanic garden conservation of many threatened plant species further several interesting flowering, wild and fruit plants are being cultivated. </p>
  <p> The Botanical Garden of the University of Karachi was inaugurated by the Governor Sindh the Chancellor of the University of Karachi, Dr. Ishratul Ebad Khan on 12 September, 2007. Spread over an area of 35 acres more than two thousand species of plants are growing at the garden. The entire garden has been developed with the treated water supplied from the Sewerage Treatment Plant, specially set up within the Campus.  The objective of the Centre of Plant Conservation which includes Karachi University Botanic Garden and Karachi University Herbarium is to improve the environment, creating awareness and for the promotion of conservation of natural resources. Centre is actively engaged in various research activities including tissue culture of endemic and rare plants. </p>
