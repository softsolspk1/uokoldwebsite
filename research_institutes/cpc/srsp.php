<h3 align="center">Contribution to Red data book of Pakistan: Evaluation of Conservation Status of Some Endemic Taxa of Sindh-Pakistan</h3>


<p align="justiy">The Office of Research, Innovation and Commercialization (ORIC), University of Karachi, proudly congratulates 
Dr. Roohi Bano, Associate Professor, Centre for plant Conservation, University of Karachi, on being awarded a research project 
under the SRSP Projects Award.<br/>
Project Title: Contribution to Red data book of Pakistan: Evaluation of Conservation Status of Some Endemic Taxa of Sindh-Pakistan.
Principal Investigator: Dr. Roohi Bano, Centre for Plant Conservation, University of Karachi.<br/>
This SRSP Project Award recognizes the scientific merit and national importance of documenting and evaluating threatened endemic plant 
species of Sindh for the Red Data Book of Pakistan.<br/>
ORIC will extend complete administrative and technical support throughout the project lifecycle to ensure successful execution and translation.<br/>
We wish Dr. Roohi Bano great success in this important work.</p>
