  <h2>&nbsp;</h2>
  <p>The herbarium is a place where a collection of dried plant specimens are kept for scientific studies. These specimens are arranged according to a particular system of classification. Nowadays a modern herbarium is a sort of research laboratory, training and reference centre and a permanent data store house of all the plants of an area. Herbarium is a fundamental source of identification of plants and a permanent reference centre. It serves basic need of identification for basic and applied research in botany, biology, agriculture, pharmacy, genetics pharmaceutical chemistry, aerobiology and biotechnology. Karachi University Herbarium has more than 150,000 plants species (mostly flowering plants), including those which are several decades old. A collection of taxonomic literature mainly dealing with flowering plants is also present in the herbarium. The types of new taxa (new species, sub-species, varieties) are properly preserved and kept here for future use. It also acts as a data store house and provides a major source of information on habitat, ecology, distribution of rare and endangered species. Herbarium also acts as a source of library and laboratory for the systematic research. The herbarium Staff provides significant service to the public by identifying unknown plants and by answering a number of questions about the plants, their distribution patterns, ecology and usefulness. A rich collection of specimens provides a sound foundation for training in plant biodiversity also in order to draw relationship of wild and cultivated plants, their affinities and correct identification (which is the key for the utilization of a particular species, unknown species hardly get any attention), the name of a plant is the key to its literature. One has to take information from other branches of science such as pollen morphology, chemistry, ecology, genetics etc. The data is therefore collected from these branches of science which not only helps in identification but also the better understanding of biodiversity and different environmental problems.</p>
