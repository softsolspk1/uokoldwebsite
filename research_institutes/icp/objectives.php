<h3>Director's Message</h3>
<p align="justify">The field of Clinical Psychology is a broad branch of psychology that focuses on diagnosing and treating mental, emotional, and behavioral problems in general. The aim of Institute of Clinical Psychology, university of Karachi is to provide professional education and training in clinical psychology and to produce competent clinical psychologists in the country. Considering the global scenario, people are facing different challenges in the sphere of mental health, and with the increased awareness regarding mental health problems; people are concerned   regarding   the   quality   of treatment. Institute of Clinical Psychology since its establishment has been working in different domains such as academic, clinical and research and always tries to meet International Standards. 
In the recent years ICP has attained the status of the pioneer Institute of University of Karachi in the field of Clinical Psychology, which had produced approximately, one hundred, M.Phil (s) and Ph.D (s) in the field of Clinical Psychology. Our Alumni are working in variety of discipline in multiple organizations and Universities of Pakistan. They are also being hired in different hospitals which have psychiatric setups as well as in other departments where clinical psychologists provide their services. The scope has also been extended to different schools including special schools, as school counselors and rehabilitation psychologists.
Institute of Clinical Psychology has a competent faculty and supporting staff equipped with knowledge and professional skills. Most of our faculty members have been trained in specialized fields from abroad. They have expertise along with passion and enthusiasm to work for human being's to bring positive change in the society. Students are also encouraged to grow ethically and professionally, and for this purpose individualized supervised programs are being offered in clinical and research domain.
They are also being provided with professional training courses and workshops by National as well as International trainers.
I welcome you all to join Institute of Clinical Psychology, to learn and become the part of our mission.</p>

