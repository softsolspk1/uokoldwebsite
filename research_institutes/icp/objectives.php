<h3>Founder's Message</h3>
<p align="justify">I am immensely pleased that the Institute of Clinical Psychology, University of Karachi is continuously striving and improving the standards of education as well as professional training in the field of Clinical Psychology.
With the advent of new scientific knowledge of science and technology and growing awareness among the general public, it is obvious that we, in the Institute of Clinical Psychology, University of Karachi    should     also    develop    the    same    latest advancement   in   the   course   of   studies   being taught   in   the   Institute   of   Clinical  Psychology, University of Karachi so that students with advance studies/training should tackle challenges of Clinical Psychology in their respective Institutions/organizations where they utilize their education/training as a profession.
We are more than confident with our faculty, clinicians as well as other professional staff that in future they will too work hard with the same zeal and motivation they are doing right now for a better scenario in the Institute of Clinical Psychology, University of Karachi in future.
