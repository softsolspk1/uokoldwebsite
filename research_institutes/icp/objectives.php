  <h2>&nbsp;</h2>
  <h3>Mission Statement</h3>
  <p>To develop an optimum standard of clinical practice, research and professional training in clinical psychology and broadening its scope by grafting its application in other related disciplines.</p>
  <p>&nbsp;</p>
  <h3>Objectives</h3>
  <p>The Institute of Clinical Psychology is already being recognized as one of the premier institutions in Pakistan, where Professional training and services of international standard in the field of clinical psychology are offered. The Institute of Clinical Psychology, University of Karachi aims to achieve the following objectives:</p>
  <ul>
    <li>To expand the growth and strengthen the status of Clinical Psychology as a profession in Pakistan and to impart specialized training in this field.</li>
    <li>To promote research suited to our own social cultural milieu in psychotherapy, psychological assessment, diagnostic testing, speech therapy, occupational therapy, rehabilitation and other related areas.</li>
    <li> To bridge the highly disproportionate gap between &quot;demand&quot; (needs of psychologically treatable patients) and &quot;supply&quot; (availability of qualified clinical psychologists).</li>
    <li>To help patients who are mentally disturbed or have behavior problems to function at higher levels, live fuller and richer lives and be able to give more of themselves to their society.</li>
    <li>To stop the draining out of talent; it is expected that students aspiring to be clinical psychologists will avail these training facilities provided within the country in an environment which teaches them to do clinical practice in a culturally appropriate way. <br />
    </li>
  </ul>
<p>&nbsp;</p>
<h3>Message from the Vice Chancellor</h3>

  <p align="justify">Institute of Clinical Psychology, University of Karachi is contributing a great deal towards advancement of postmaster professional education in clinical psychology in Pakistan. The Institute has developed a system of gradual, consistent and effective improvement of training at postmasters level and is continuously striving to improve its academic standards, training and evaluation system to achieve the international status. The faculty of the Institute consists of distinguished professionals from different fields.</p>
  <p align="justify">Institute facilitates research in multiple disciplines and has been successful in conducting researches of international standards. In order to expand the horizon of learning, it has also been establishing academic affiliations with leading institutions of the region and developed world. 
    The institute regularly organizes a series of workshops and short courses for the continued professional growth of mental health professionals. Experienced mental health educationists from within country and abroad are invited to conduct these courses and training programmes.</p>
  <p align="justify">ICP is proud to provide the bulk of clinical psychologists and teachers in the country who are performing with a spirit to bring out the best in prevention and treatment of psychological disorder and clinical research.</p>
