  <h2>Prof. Dr. Sobia Aftab (Director)</h2>
  <p>&nbsp;</p>
  
  <p align="justify">Institute of Clinical Psychology is a reputable institute and has a distinguished status in the field of clinical psychology and research since it has been established. The Institute’s high quality training, research and congenial environment ensures its position as the institute of choice for Pakistan’s high-caliber postmasters students. The students of ICP are highly competitive and are working effectively in wide-ranging fields of employment. It is this reason that students of ICP are in high demand in various organizations. This has been made possible due to:</p>
  <h4 align="justify">Educational Excellence</h4>
  <p align="justify">The Institute has a dexterous faculty working to maintain a standard in academics, research and clinical practices. Regular class schedule in morning session and supervised clinical practice in evening session makes a comprehensive training schedule to gain knowledge in the field of Clinical Psychology.</p>
  <h4 align="justify">Intensive Clinical Supervision</h4>
  <p align="justify">Interns have to under go a rigorous training for clinical internship, including training in conducting psychotherapy, individually supervised therapy sessions and learning standardized patterns of administration, scoring, interpretation of psychological assessment tools and report writing. Further interns are also trained regarding diagnostic issues. The major aim is to make interns meet international standards required for working as a Clinical Psychologist. Moreover, there are weekly case conferences in which interns are encouraged to present their cases before the panel of clinical experts in order to receive guidance and exchange ideas amongst themselves.  </p>
  <h4 align="justify">Multidisciplinary Approach</h4>
  <p align="justify">The Institute focuses on a multidisciplinary approach in clinical practice. The interns are trained for conducting psychotherapeutic sessions using different approaches like Psychoanalysis, CBT, REBT, Multimodal Approach, etc. However depending on the needs of the patient, occupational Therapy, Speech Therapy, and Rehabilitation Services are also available within the premises of the Institute for the convenience of the patients. A Medical Officer is also available in order to examine the progress of the patients who are on medication.<br />
    During their extensive internship the interns are also required to assess and diagnose the patients by administering standardized psychoneurological, intelligence, achievement, aptitude, objective and projective personality tests.  </p>
  <h4 align="justify">Research and Development of Psychological Instruments</h4>
  <p align="justify">Institute facilitates research in multiple disciplines that includes clinical psychology, child and educational psychology, social psychology, consumer behavior and marketing research. In its vision to promote research, the institute facilitates its faculty to participate in research projects, and interns to conduct supervised researches. The Institute has been successful in conducting researches of international standards, and funds are raised every year to purchase psychological test material from international sources. There is also focus on translation of tests/scales in local language and then conducting normative studies in order to have statistics of psychological problems prevalent in Pakistan.  </p>
  <h4 align="justify">Cost Effective</h4>
  <p align="justify">ICP charges very reasonable fee for all available courses of Clinical Psychology to provide an equal opportunity for all deserving candidates. </p>
