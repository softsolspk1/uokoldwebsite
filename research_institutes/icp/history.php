  <h2>&nbsp;</h2>
  <p align="justify">The Institute of Clinical Psychology was created under a directive of General Muhammad Zia-ul-Haq, President, Islamic Republic of Pakistan. Prof. Dr. Farrukh Z. Ahmad, who originally conceptualized the idea of establishing an Institute, was appointed as its first director. The Institute has its own Board of Governors, a Selection Board, and an Academic Committee in accordance with its Statues which have been passed by the Senate of the University of Karachi and the Governor of Sindh in his capacity as the Chancellor of the University.<br />
  </p>
  <p align="justify">The Institute of Clinical Psychology, University of Karachi was established in response to the dire need for mental health professional and the acute dearth of professional psychological services in Pakistan. Till 1983, when the Institute came into being, no professional training facilities existed for Clinical Psychologists in Pakistan. Courses in Clinical Psychology offered at the Master's level by the department of Psychology of various universities were merely aimed at familiarizing students with the subject matter, scope and some methods used in this area, without providing them opportunities to develop skills necessary to the practice of and research in clinical psychology. Students desirous of becoming clinical psychologists have been going abroad for the necessary specialized training, and rarely, if ever, return to Pakistan, thereby adding to the problem of &quot;brain drain&quot;. Moreover, with the increasing incidence of mental health problems, psychologically disturbed persons are grossly under served in terms of professional help, which can only be given by qualified clinical psychologists. The above-mentioned factors, as well as the fact that indigenously trained professionals would be better able to deal with problems specific to our own culture made the creation of an institution devoted to the education and training of qualified clinical psychologists an absolute necessity and of vital importance to our social and national development.</p>
  <p align="justify">The Institute of Clinical Psychology, University of Karachi has a total land endowment of 25.5 acres out of which 3 acres have been donated by the Government of Sindh in the heart of the city of Karachi and a plot measuring 22.5 acres of land has been allocated by the University of Karachi in its own campus.</p>
  <p align="justify">A Psychological Clinic, a Library and some of the academic and administration facilities of the Institute of Clinical Psychology, University of Karachi have been built on the 3-acre plot of land. The address of its site is: 118, Block 20, Abul-Asar Hafeez Jalindhri Road, Gulistan-e-Jauhar, Karachi-75290, Pakistan. The proximity of this plot to the city centre and its consequent accessibility for the patients to Psychological Clinic of the Institute of Clinical Psychology was the prime reason why a location was selected outside the campus of the University of Karachi which is inaccessible to the majority of patients and technically unsuitable for the profession of Clinical Psychology.</p>
