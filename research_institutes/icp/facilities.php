  <h2>&nbsp;</h2>
  <p>In the planning of the Institute of Clinical Psychology, University of Karachi, following facilities has been included in order to make it exclusive for the training of Clinical Psychologists in Pakistan:</p>
  <ul>
    <li>The Institute is defined as the academic and research facility of the Institute of Clinical Psychology. Only a part of this facility has been completed in the first phase of the Building Complex of the Institute of Clinical Psychology, in which practicum, seminars and tutorials in addition to lectures are conducted.</li>
    <li>The Rehabilitation center of the Institute is now under process of construction as a part of accomplishment of the second phase of the Building Complex.</li>
    <li>The research wing is equipped with computers, video recorders, biofeedback instruments, Psychological tests/scales and other technical equipment the use of which is imperative for high quality research in the field of Clinical Psychology. Small research cubicles are also be provided in order to facilitate uninterrupted and undisturbed work by researchers.</li>
    <li>The classrooms are fully equipped with latest teaching equipments.</li>
    <li>Students are provided with computers and Internet facility, a fully equipped computer lab is under construction.</li>
    <li>Photocopying and Printing facilities are also provided on discretionary rates for students.</li>
    <li>A well comprehensive Library comprising of 50,000 volumes is available for the students. Students can also use main library of the University of Karachi.</li>
    <li>Student Advisor is a unique facility for students having problems related to academic or non-academic issues. They can approach and discuss their problems with complete assurance of confidentiality.</li>
    <li>Hostel facility is available for female students in main campus of University of Karachi.<br />
    </li>
  </ul>
<p>&nbsp;</p>
  <h3>Psychological Clinic</h3>
  <p>&nbsp;</p>
  <p>The Psychological Clinic is defined as the facility where the internship requirements of the students enrolled in the Institute of Clinical Psychology, University of Karachi are catered for. As part of their training, clinical psychologist conduct psychological assessments, counseling, psychotherapy, marital, family and vocational guidance on patients and clients of diverse ages and socioeconomic backgrounds with a wide variety of psychological, interpersonal and emotional problems. The Psychological Clinic has psycho-diagnostic and psychotherapy cubicles, reception and waiting areas for patients. Emergency alarms and other modern facilities are also provided in the Building Complex.  </p>
  <ul>
    <li>At present the Psychological Clinic also offers the following outpatient services to the general public:</li>
    <li>Psycho-diagnosis and Psychological Testing</li>
    <li>Psychotherapy</li>
    <li>Behavior Training for Mentally Retarded / Developmentally Deficient Clients and the Emotionaly handicapped</li>
    <li>Family and Marital Counseling</li>
    <li>Speech &amp; Language Therapy</li>
    <li>Student Counseling and Guidance</li>
    <li>Personnel Selection</li>
</ul>
<p>&nbsp;</p>
<h3>Library</h3>
<p>The building of the library has been completed in the first phase of the Building Complex. It is going to be equipped with most modern facilities for the establishment of a highly sophisticated library.</p>
<p>The library will have reading and reference sections as well as lending facilities. In addition to place for the shelving and storage of up to 50,000 books and periodicals it is also planned to have seating arrangements for up to 100 persons. The library will also have facilities for cataloguing, photocopying, binding and microfilming.</p>
<p>In addition to this, the student of the Institute of Clinical Psychology can also utilize the facilities of the main Library of University of Karachi.</p>
<p>&nbsp;</p>
<h3>Rehabilitation Centre</h3>
<p>Temporary arrangements for rehabilitation facilities has already been made on the existing available land of the Institute of clinical Psychology. However, the permanent unit of the rehabilitation centre is now under construction. This centre will have house facilities for the rehabilitation, vocational training and recreation of patients and clients who will be referred from the Psychological Clinic. Skills, including carpet weaving, carpentry, electrical work, music and art, will be encouraged and taught in separate workshop under the guidance of trained professionals who will be supervised by trained and qualified Clinical Psychologists to promote therapeutic and rehabilitation goals. Care is being taken to provide different and physically separate facilities for both sexes.</p>
<p>&nbsp;</p>
<h3>Day Care Centre</h3>
<p>A temporary day care centre for the education, training, and treatment of emotionally handicapped children is shortly going to be established. The permanent center which will be constructed as a part of the second phase of the Institute's Building Complex is planned to be a childrens' and adolescents' day treatment and rehabilitation centre. Its services will cater to the following 3 categories: (i) the emotionally disturbed, (ii) the neurologically handicapped, and (iii) the mentally retarded. Individual / group treatment, and rehabilitation programs will be conducted separately for each of these categories. Arrangements are also being made for separate facilities for both sexes.</p>
<p>Service elements and methods for these programs will include: small classroom for re-educational programs, pre-vocational training, job counseling, group therapy, Occupational therapy, speech therapy and art therapy.</p>
<p>The key objectives of the day treatment programs are:</p>
<p>a. To improve client's ability to function within the community.<br />
b. To improve the family's ability to effectively manage these youngsters.<br />
c. To keep youngsters out of the legal system.<br />
d. To reduce the number of admissions to hospitals.<br />
e. To return youngsters to the school setting.</p>
<p>&nbsp;</p>
<h3>Rehabilitation Farming</h3>
<p>Since Pakistan is basically an agricultural country a large plot of land will also be provided with farming facilities for the treatment and rehabilitation of patients upon the recommendation of the experts of the Institute. These patients will be sent to the farming facility provided on five acres of land located on the Institute of Clinical Psychology's 22.5 acre plot of land in the University of Karachi campus.</p>
<p>&nbsp;</p>
<h3>Gymnasium</h3>
<p>A gymnasium will be constructed in the second phase of the Building Complex in order to supplement the day care centre and rehabilitation centre by fulfilling clients' recreational needs as well as for the remediation of children's motor skills deficits.</p>
<p>&nbsp;</p>
<h3>Auditorium-Cum-Cafeteria</h3>
<p>The auditorium which will be built in the subsequent phase, will have seating capacity for 225 persons. Film projection facilities will also be available. It is planned to conduct National and International seminars and conferences here. A cafeteria attached to the auditorium with seating for 50 persons will serve the dietary needs of the Institute of Clinical Psychology's staff, students and patients.<br />
</p>
