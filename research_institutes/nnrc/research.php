    <li>
      <p align="justify">Since its inception, it has produced 18 Ph. Ds and 3 M.Phils. Some of these showed excellent performance during their academic tenure and received several awards.</p></li>
    
    <li>
      <p align="justify">At present 12 post-graduate students are doing research work for their M.Phil. / Ph.D.</p>
    </li>
    <li>
      <p align="justify">Research is the main role played by NNRC, besides the research work produces by the students numerous research projects allocated by different national and international working bodies are carried out by the center. The major funding and project allocation bodies associated with NNRC are, HEC and PSF.</p></li>
     
    <li>
      <p align="justify">The NNRC collaborates with the government, international research bodies, research centers and non-governmental organizations to create awareness on vital issues of nematode problems and provides forum for all the Nematologists, researchers, agriculturists, extension workers and students of the country to exchange information about nematode diseases by organizing nationaland international conferences, seminars and workshops regularly</p>
    </li>
  </ul>
