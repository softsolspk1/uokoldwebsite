  <h2>Director:   <strong>Dr. Saboohi Raza</strong></h2>
  
  <p align="justify">National Nematological Research Centre (NNRC) is a leading  research and educational institute dedicated to the generation, acquisition of  knowledge about Nematology in Pakistan. NNRC was established in 1974 and now  has come to symbolize as an efficient, dynamic and forward looking research  centre in Pakistan. Nematology is a highly specialized field of biological  sciences including agriculture and provides services of specialists dealing  with nematodes. NNRC is the only research as well as academic centre, which is  solely associated with the study and research of Nematology in the country. The  main objective of NNRC is to promote the subject of Nematology so as to generate  highly trained manpower through M. Phil / Ph. D. degree program.<br />NNRC has now get ISO Certification 9001-2015 for the compliance of its Diagnostic services and Educational program.</p>
  <p align="justify">Ph.D programme  in Nematology is aimed at imparting a full range of knowledge, awareness and  expertise in Nematology to meet the challenges of the new millennium.  International and national scientific conferences, seminars and training  workshops also organized as a part of the routine work/study. NNRC has  regularly published bi-annual scientific journal,&nbsp;<em>Pakistan Journal of  Nematology&nbsp;</em>(PJN) since 1983 and PSN Newsletter since 2002, covering the  significant research in fundamental and applied Nematology within and outside  the country, besides several books, booklets, manual, proceedings and many  national and international patents. The centre also has collaborations in  research with many international and national agricultural research  institutions and universities including other departments of the University of  Karachi. The website of PJN:&nbsp;<a href="http://www.pjn.com.pk/">www.pjn.com.pk</a><u> </u></p>
  <p><strong><u>Vision</u></strong>:  The main vision of the NNRC is to grow more food  and healthy agricultural crops that are free from the attack of nematode pests. <br />
    <p><strong><u>Mission</u></strong>:  Eradication  of nematodes from our agricultural crops is the mission of the centre, besides  to promote the subject of Nematology and produce highly trained manpower  through M. Phil and Ph. D degree programs.</p>
