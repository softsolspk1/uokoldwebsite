  <p>&nbsp;</p>
  <p align="justify">Centre for Molecular Genetics is currently a research facilitation centre.  The centre has regularly trained postgraduate researchers and awarded PhD and  MPhil, degrees in Genetics and Microbiology. Possibilities for those students  who want to work at the centre but obtain degree in a discipline other than  Genetics exist, but this can only be managed through prior  arrangements/collaborations.</p>
<p align="justify">Subject to policies of the university, candidates enroll initially  in MS programme under supervision or co-supervision of the director of the  Centre for Molecular Genetics. Candidates must pass both a written entrance  test and an interview by the departmental research committee of the department  of the discipline in which the candidate is seeking admission to qualify for  admission. Successful candidates must take courses worth 18 credit hours in  genetics or allied subjects during the first year. Depending on the Grade Point  Average score achieved (in accordance with requirement of the university, the  students may be allowed to proceed with research work. An MS degree may be  awarded after at least one year of research work followed by positive  evaluation by Advanced Studies and Research Board (ASRB). Alternatively, the  student may opt further his/her research towards a PhD degree provided ASRB  reviews the student's progress and allows him or her work towards a PhD degree.  A PhD degree may then be awarded after successful defense of thesis examination  conducted by the BASR's examination board.</p>
<p align="justify">Candidates holding MS or MPhil degree in genetics or allied  subjects may directly apply in the Ph.D. programme and enroll under  supervision/co-supervision of the director of the Centre for Molecular  Genetics, subject to policies of the University of Karachi. Candidates must  pass both a written entrance test and an interview by the departmental research  committee of the department of the discipline in which the candidate is seeking  admission to qualify for admission. Successful candidates must take courses  worth 18 credit hours in genetics or allied subjects during the first year  followed by bench work. Subject to successful defense of the thesis examination  conducted by the BASR's examination board, a Ph.D. degree may then award.</p>
<p align="justify">Researchers seeking the degree of MSc in Genetics and working under  supervision or co-supervision of the director of the Centre for Molecular  Genetics have regularly been supported for lab facilities and technical and  academic supervision.</p>

