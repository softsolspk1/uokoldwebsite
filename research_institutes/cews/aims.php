<p>Some of  the aims of the Centre are to:<br />
  </p>
<ul>
  <li>
    <p>Enhance  the participation of women in mainstream national development through an  effective and judicious use of information technology;<br />
    </p>
  </li>
  <li>
    <p>Create  a better understanding of the scope and concepts of Women’s Studies in the  context of Pakistan;        <br />
    </p>
  </li>
  <li>
    <p>Critically  analyze the status and role of women, both historically and contemporaneously;<br />
    </p>
  </li>
  <li>
    <p>Stimulate  a dialogue on the status of women in Muslim societies, particularly in  Pakistan, to help develop a better comprehension of faith, belief, traditions,  and myths;<br />
    </p>
  </li>
  <li>
    <p>Critically evaluate development approaches  and strategies as they affect women in particular and the society in general;<br />
    </p>
  </li>
  <li>
    <p>Help  develop sustainable strategies for combating health, poverty, and environmental  hazards; Enable students step into the practical life with trust in their  potential as change makers.</p>
  </li>
