  <h2>Director:  Prof. Dr. Asma Manzoor.</h2>
  <p>&nbsp;</p>
<p>The  centre was established as a project in 1989 by the Ministry of Women  Development, Government of Pakistan. For the last 21 years CEWS has had a  special appeal for students from all over the country. The first M.A in Women’s  Studies in Pakistan began in 1996 at the University of Karachi. In 2002 Centre initiated M.Phil / Ph.D  program. From 2004 the discipline of Women’s Studies was introduced as a subsidiary  course at First Year (Hons.) level. From January 2007 BS (Hons.) 4 years  program was launched and from January 2010 M.A (Evening) program has  also started. Innovative courses and seminars offered at the Centre, and  research conducted here, aims at generating a functional knowledge base with  the purpose of identifying hitherto under-used and neglected human resources  for national growth.</p>
<p>&nbsp;</p>
<h3>Career  Opportunities</h3>
<p>Majority  of CEWS graduates are now placed at various administrative positions in NGOs,  International Welfare Organizations, Research Organizations, Planning and Development,  Government, Semi-Government, Private Organizations and Teaching both at the  local and national level. CEWS give priority to its students and employ as  cooperative teachers and research associates. Along with this, Graduates of the  Centre are working in different International, National and other organizations  such as Ministry of Women and Development (MoWD) Islamabad, Women and  Development Department (WDD) Sindh, Sindh University (Jamshoro), Karrakurum  University, Social Policy Development Centre (SPDC), Aga Khan Rural Support  Program (AKRSP), World Wild Life Fund (WWF). They are also working in NGOs like  Aurat Foundation, Shirkat Gah, War Against Rape (WAR), Health Oriented  Preventive Education (HOPE), Madadgar, Pakistan Institution of Labour Education  and Research (PILER), Labour Education Foundation (LEF), Society for the  Protection of the Rights of the Child (SPARC), Society for the Advancement of  Community Health, Education and Training (SACHET), Inter Press Communication  (IPC), Rozan, etc.</p>
