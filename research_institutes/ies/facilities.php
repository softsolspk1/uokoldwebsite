  <p>Environmental  Biochemistry and Chemistry Laboratory, Environmental Microbiology Laboratory,  Pesticide Detection Laboratory, Bio-analytical Laboratory, Instruments Room,  Seminar Library, Experimental Field. The laboratories are equipped with latest  and sophisticated equipment.  </p>
  <p>&nbsp;</p>
  <h3 align="justify">Laboratories</h3>
  <h4>Environmental Biochemistry and Chemistry Laboratory</h4>
  <p>Physical and chemical parameters related to water, wastewater, soil, food and air are analyzed in this laboratory.</p>
  <h4><strong>Environmental Microbiology Laboratory</strong></h4>
  <p>All the microbiological work pertaining to environmental samples is done here. In addition, there is another laboratory fitted with Laminar Flow hood where highly sophisticated work in germ free environment could be carried out. Sterile conditions are maintained here strictly.</p>
    <h4>Pesticide Detection Laboratory</h4>
  <p>Environmental and biological samples for pesticide detection are processed and determined in this laboratory using High Performance Liquid Chromatography.</p>
   <h4><strong>Bioanalytical Laboratory</strong></h4>
  <p>Samples for environmental toxicological studies and for bioassays are done here.</p>
  <h4>Instruments Room</h4>
  <p>All sophisticated equipment of the Institute is placed in this room where environmental samples after processing in the respective labs are further analyzed using appropriate equipment.  </p>
  <h3 align="justify">Seminar Library</h3>
<p align="justify">The seminar library is highly equipped with books and journals on environment. All the latest leading text and reference books are available. In addition, a large number of research reports, references and other reading materials are constantly received from different organizations especially from WHO, United Nations Environment Programme, US. Environmental Protection Agency, International Development Research Centre, Canada, etc. About 5000 references are available.</p>
  <h3 align="justify">Experimental Field </h3>
  <p align="justify">For research and training in wastewater treatment an experimental Waste Stabilization Ponds have been developed in Karachi University on an area of 10 acres. These experimental ponds are capable of treating 80,000 gallons of wastewater daily. The treated effluent is recycled for irrigation purposes to experimentally demonstrate the fact that wastewater is not an economic liability but in fact it is an asset. The treated wastewater is being used in irrigating the Botanical Garden near Silver Jubilee gate.</p>
