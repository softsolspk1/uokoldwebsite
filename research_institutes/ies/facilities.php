  <h3 align="justify">Analytical Capability</h3>
  <p align="justify">The following parameters of water, wastewater, foods and soil are done in the various labs of the Institute.</p>
  <h3 align="justify">Physical Parameters</h3>
  <p align="justify">pH, Colour, Turbidity, Total solids, Dissolved solids, Suspended solids, Grain size analysis, Porosity, Density, Viscosity, Refractive index etc.</p>
  <h3 align="justify">Chemical Parameters</h3>
  <p align="justify">Volatile solids,  Chemical oxygen demand (COD), Biochemical oxygen demand (BOD5), Total Kjeldahl Nitrogen (TKN), Ammonia nitrogen, Nitrate and nitrite nitrogen, Total phosphates, Chlorides, Sulphates, Alkalinity,  Carbonates and bicarbonates, Hardness, Heavy and trace metals, Proteins, Carbohydrates, Fats, Phenols, Detergents, Methylene blue active substance, Hydrogen sulphide, Fluorine,  Pesticides, Insecticides etc.</p>
