    <li><strong>Workshop on Biosafety, Health and Environment</strong> was held on 5TH June, 2007 in collaboration with Higher Education Commission on    the occasion of World Environment Day.   The objective of the workshop is to familiarize the trainees with the principles of biosafety, health and environment and to communicate the recent development in biosafety and related fields. The present socioeconomic environment with associated development of health care system prompted to disseminate the knowledge to participants with the special interest to safeguard the life of workers without compromising the loss to the employers.</li>
    <li><strong>Euro – Asian Research &amp; Training in Climate Change Management</strong> (a  project of European Commission) was organized from April 23rd - May 5th 2007. It was jointly organized by Area Study Center for Europe, Centre of Excellence in Marine Biology and Institute of Environmental Studies, University of Karachi. The theme of the training was Sustainable Integrated Coastal Zone Management and Climate Change including Modeling Risk Assessment for Climate Change. In particular issues and laws related to coastal zone management, marine biodiversity losses, socioeconomic problems and marine pollution pertaining to climate change were discussed.  It was an international event in which five countries Pakistan, China, Italy, France and Netherlands participated.</li>
    <li><strong>Training Programme for Laboratory Staff</strong> December 19-21, 2006 jointly organized by Institute of Environmental Studies and Office of Dean Faculty of Science, University of Karachi. This training helped in improving the skills and knowledge of laboratory staff and in creating awareness pertaining to health and safety issues in laboratories. The program was meant to develop methods for the disposal of laboratory wastes and to formulate a strategy for the establishing model laboratories in the university. </li>
    <li><strong>Workshop on Fisheries products of Pakistan:Challenges of changing International regime  August 28- 30, 2006</strong> jointly organized by Institute of Environmental Studies, Marine Reference and Resource Collection Centre, University of Karachi and PCSIR Laboratories Complex, Karachi. The objective of the workshop was to evaluate the sources of pollution and how they are affecting the quality of fishery products and what measures should be taken to prevent contamination and hazards associated with this industry as it contributes significantly Pakistan’s export.</li>
    <li><strong>Workshop on Statistical Methods In Environmental Science,March 6-9, 2006</strong>   jointly organized by Department of Statistics and the Institute of Environmental Studies, University of Karachi. The importance of environmental problems is increasing in the society worldwide. The statistical methods in this context are very useful tools for data analysis, evaluation of impact on the environment and decision making. This workshop organized the teaching methodology, in which theory and practice has been integrated, was presented. The development of environmental statistics which is also known as Envirometrics , is quite recent, growing interest in environmental change is being demonstrated by the  society worldwide.</li>
