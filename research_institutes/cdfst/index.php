  <h2>Director: Dr. Nadeem Mahmood.</h2>
  <p>&nbsp;</p>
   <p align="justify">For the first  time in Pakistan University of Karachi is offering the Digital Forensic  education at the undergraduate / graduate / post graduate/ MS &amp; Ph.D.  level. Centre for  Digital Forensic Science &amp; Technology will keep functioning for the  betterment law enforcement agencies, specially judiciary for its quick justice  for public interest and economic viability for public at large.
   <p align="justify">CDFST will play  an integral role in the criminal justice system. This Centre will support law  enforcement agencies (Police, Rangers, NAB, FIA, CPLC and etc.) in meeting the  expectations of Government and community. The Centre will strive connecting the  crime scene and judicial system through the development and delivery of  impartial expert scientific opinion evidence. This Centre will educate  resolving complex criminal cases and will be a bridge in providing easy access  to criminal justice system with its advanced curriculum. This Advanced Digital  Evidence Educational System will be a value added to the conventional evidence  system of Pakistan. This Centre will impart digital forensic education to the  new generation of students who have the aptitude and desirous of joining this  exciting and newly emerging subject in Pakistan.</p>
   <p align="justify">This Centre is  committed to provide qualitative digital forensic education with state of the  art facilities and will play its crucial role in economic strengthening of  Pakistan. This Centre will create new job opportunities and provide a clear  career path towards specialization to the students undertaking such programs.  Inter-alia qualified manpower will be available to the public and private  sector in various fields as applications of digital forensic science are not  limited to criminal law, and can include civil law, product liability, medical  integrity, highway safety, environmental protection, consumer protection and  national security.</p>
   <p align="justify">Presently, many  universities are providing courses/programs ranging from BSc. (Hons), Masters,  M.Phil and Ph.D in various subjects like Bio-chemistry, Bio-informatics, Physics  and chemistry etc related to forensic science in one context or another.  Availability of digital forensic studies program at a suitable level can  provide a clear platform for dedicated digital forensic science studies for a  career start. Similarly, the police forces and law enforcement agencies will  have a growing demand in future for inducting digital forensic analysts/experts  to make their investigations more effective, objective and scientific in nature  rather than to rely on the existing obsolete methodology and technology. </p>
   <p align="justify">    This Centre will  range all laws e.g. Prevention of Electronic Crime Evidence Ordinance 2007,  Investigation for Fair Trial Act, 2012, Law in process on Cyber Crime and will  adopt any future legislation as well.</p>
