  <h3>Chancellor's Speech</h3>
    Assalam-o-Alaikum Ladies & Gentlemen<br />
  <p align="justify">I from the bottom of my heart really appreciate all  distinguished guests for your valuable presence in this historic inauguration  ceremony of Centre for Digital Forensic Science &amp; Technology University of  Karachi.<br />
    I must congratulate Prof. Dr. Qaisar, Vice Chancellor,  Karachi University and his team on stepping towards the world of achievements  especially in the field of Digital Forensic Science &amp; Technology despite of  all the difficulties. I foresee that the substantiating advancement will  rejuvenate the supremacy of this nation on the globe. However, this Centre will  definitely be playing its role as one of paving components of Rule of Law. As  we all know that &ldquo;The rule of law requires balance between rights and  responsibilities, where no one is above the law — including the government. The  Constitution guarantees fundamental rights and everyone is supposed to have access to justice,  including the accused and I hope this blended education will serve the purpose  in letter and spirit. This omnipotent Centre for Digital Forensic Science &amp;  Technology will go long way to success of this university. <br />
    I am very pleased, honoured &amp; satisfied indeed to  be with you as an ICON of this tremendous inaugural ceremony of this Centre for  Digital Forensic Science &amp; Technology, University of Karachi<br />
    University of Karachi has been contributing to society  through the pursuit of education, learning, and research since June 1951. I  hope this Centre for Digital Forensic Science &amp; Technology will foster and  produce students of the highest intellectual potential, irrespective of social,  racial, religious and financial considerations, and then support them through  their intellectual journey. <br />
    The dedicated, highly qualified professional  faculty members, and digital forensic experts will play their due role for this  paradigm shift and will bring about turn-around in all aspects. <br />
    I  hope this Centre will provide unique, creative, progressive and inspiring  environment to our researchers, faculty members, students and staff. Despite  tumultuous circumstances University of Karachi keeps combating the challenges  and always in preparation for upcoming challenges.<br />
  On  this occasion I must say that all august members of Senate, Syndicate, Academic  Council, Finance and Planning Committee always play their vital role in devising  / formulation long term strategies in line with missions and core values set  forth to path on dream come true of University of Karachi<br />
    I pay tribute to the hard work, creativity and determination of  colleagues across the University and I want to close by thanking them for all  that they will do to promote and deliver the highest standards of education and  research excellence at this Centre for Digital Forensic Science &amp;  Technology. </p>
