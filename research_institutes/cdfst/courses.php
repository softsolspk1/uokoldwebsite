<h3 align="center">Audio / Visual Analysis</h3>
<p align="justify">Audio / Visual Analysis Unit will deal with  the scientific examination, comparison and/or evaluation of audio and video  evidence in legal matters. The Audio Visual Analysis Department will be  equipped with latest forensic tools for audio and video analysis which are used  all over the world in Forensic Community. This will also cover the following:</p>
 <ul>
   <li>Clarification  of Audio evidence using different noise reduction and other algorithms.</li>
   <li>Clarification  of Video evidence for identification and association of different events  happened by video surveillance systems.</li>
 </ul>
 <p>Analysis  of images extracted from video evidence using forensic enhancement and  clarification tools.</p>
 <p align="justify"><strong>Video forensics </strong>is  the scientific examination, comparison and/or evaluation of video in legal<strong> </strong>matters.  Video forensics reliably digitizes video tape footage onto a computer system,  be able to de-multiplex or separate camera views from multiplexed <a href="http://en.wikipedia.org/wiki/Closed-circuit_television"> CCTV</a> footage, convert  digital video from DVR (Digital Video Recorder) devices into digital video  formats usable for forensic analysis. Video forensics also performs  clarification techniques such as <a href="http://en.wikipedia.org/w/index.php?title=Frame_averaging&amp;action=edit&amp;redlink=1"> fram</a>e <a href="http://en.wikipedia.org/w/index.php?title=Frame_averaging&amp;action=edit&amp;redlink=1"> averaging,</a> highlight  someone or something of interest in the video, enlarge portions of the video  for areas of interest, measure heights of individuals or distances between  points seen in the video.</p>
<h3 align="center">GPS FORENSICS</h3>
<p align="justify">Modern Global Positioning Systems (GPS) devices are capable of storing vast amounts of navigational data in the form of maps, track lines, waypoints, routes, and more. Some of this data is captured and stored automatically by the device whenever it is in use. Other data is manually entered by the GPS user. In the hands of a law enforcement investigator, the data can be used as devastating evidence in a courtroom setting. GPS Forensics provide law enforcement officers with a foundation for recovering evidence from GPS devices and preparing it for courtroom presentation.</p>
<h3 align="center">GEO FENCING</h3>
<p align="justify">A Geo-Fence is a virtual perimeter for a real-world geographic area. A Geo-Fence could be dynamically generated—as in a radius around a store or point location, or a Geo-Fence can be a predefined set of boundaries, like school attendance zones or neighborhood boundaries.<br />
The use of a geo-fence is called geo-fencing, and one example of usage involves a location-aware device of a location-based service (LBS) user entering or exiting a geo-fence. This activity could trigger an alert to the device's user as well as messaging to the geo-fence operator. This info, which could contain the location of the device, could be sent to a mobile telephone or an email account.</p>

