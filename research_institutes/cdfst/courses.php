<h3 align="center">Computer Forensic</h3>
  <p align="justify"> Computer forensics is a branch of <a href="http://en.wikipedia.org/wiki/Digital_forensics"> digital  forensic science</a> pertaining to legal evidence found in computers and digital storage media. The  goal of computer forensics is to examine digital media in a forensically sound  manner with the aim of identifying, preserving, recovering, analyzing and  presenting facts and opinions about the information.<br />
    Computer forensics will be an important and  integral part of CDFST pertaining to legal evidence found in computer systems  and digital storage medium. It is to perform forensic investigation on digital  evidence while maintaining the documented chain of custody so that it can be  presented as evidence in the court of law.</p>
  <p><strong><u>Scope of Computer Forensics</u></strong></p>
  <ul>
    <li>Scientific examination and analysis of  Digital Storage Media for example hard drives, Flash Memory, Floppy Disks,  CD/DVD etc.</li>
    <li>Forensic Analysis of Mobile phones and  Personal Digital Assistants (PDAs).</li>
    <li>Forensic Examination of standalone/ networked  computers after a break-in, for example, to determine how the attacker gained  access and what the attacker did.</li>
    <li>Retrieve/acquire evidence from digital media.</li>
    <li>Recovery of deleted digital data in case of  damaged hardware that may have evidentiary value.</li>
    <li>Recovery of deleted digital data in case of  software failure that may have evidentiary value.</li>
    <li>Forensic Analysis of retrieved and/or submitted  media.</li>
    <li>To provide expert testimony on resultant  analysis on Agency cases in the Court.</li>
  </ul>
  <h3 align="center">MOBILE FORENSICS</h3>
<p align="justify"> Mobile device forensics	is a branch of	digital forensics relating to recovery of digital evidence or data from a  mobile device under  forensically sound conditions. The phrase mobile device usually refers to  mobile phones; however, it can also relate to any digital device that has both internal memory and  communication ability, including  PDA devices,  GPS devices and  tablet computers.</p>
  <h3 align="center">NETWORK FORENSICS</h3>
  <p align="justify">Network forensics is a sub-branch of digital forensics relating to the monitoring and analysis of computer network traffic for the purposes of information gathering, legal evidence, or intrusion detection. Unlike other areas of digital forensics, network investigations deal with volatile and dynamic information. Network traffic is transmitted and then lost, so network forensics is often a pro-active investigation.</p>
    <h3 align="center">DATABASE FORENSICS</h3>
    <p align="justify">Database forensics is a branch of digital forensic science relating to the forensic study of databases and their related metadata. The discipline is similar to computer forensics, following the normal forensic process and applying investigative techniques to database contents and metadata.

Today almost all applications use high performance databases to deal with data. So the database security community is coming up with a number of different techniques and approaches to assure data confidentiality, integrity, and availability. But it is observed that digital attacks are targeting the databases ensuing database security breaches and threats. The outcome is that the existing laws / regulations are specifying investigations and response to security breaches or policy violations. This gives rise to the need for database forensics which satisfies this demand. Organizations must, therefore, consider their incidence response policies carefully, which are part of their overall security policies. </p>

