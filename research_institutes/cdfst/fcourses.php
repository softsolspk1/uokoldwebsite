  <h3 align="center">Latent Finger Prints</h3>
    <strong><u>Introduction:</u></strong>
<p align="justify">Thousands of years ago, Chinese used  thumbprints on legal documents and on criminal confessions. It is perhaps the  first sign of recognition that a person&rsquo;s fingerprints are unique.<br />
    The use of fingerprints in the identification  of criminals is the most frequently applied technique in forensic science.  Fingerprints offer a powerful means of personal identification and still remain  the most commonly used forensic evidence worldwide. No two individuals possess  the same fingerprints. Because of this, fingerprints are an excellent means of  identification. Moreover, while other visible human characteristics change –  fingerprints do not change.<br />
    The Latent Fingerprint Department will be  fully equipped Labs and high-quality scientific services are provided. It will ensure  that all examinations and documentations will be done in compliance with  guidelines as provided by any regulatory authority.</p>
