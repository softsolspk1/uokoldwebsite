  <h3 align="center">Trace Evidence</h3>
  <p align="justify"><strong><u>Trace Chemistry</u></strong><u> </u><br />
    The Trace Chemistry unit  will analyze a wide variety of evidence types. Debris from an explosion or a  fragment of an explosive device can be used to identify which type of explosive  might have been used. Paint and glass from a hit-and-run accident or a burglary  can be compared to see if evidence left at the scene can be tied to a suspect.<br />
    Numerous other types of evidence, such as  hair and fiber can be analyzed by the Trace Chemistry section. Quite often a  comparison is performed between an unknown and a known substance to determine  if they could have shared a common origin. Several analytical tools are  utilized by the trace chemist. The stereo microscope is used for close visual  examinations and for preliminary chemical spot testing.<br />
    Analytical instruments are  used to make comparisons and identifications. Some of the instrumentation used  in the Trace Chemistry section includes gas chromatography, infrared  spectroscopy, mass, spectroscopy, x-ray diffraction, scanning electron microscopy  and energy dispersive x-ray microanalysis.</p>
  
  <h3 align="center">Polygraph</h3>
  <p align="justify">A polygraph (popularly referred to as a lie  detector) is an instrument that measures and records several physiological  responses such as blood pressure, pulse, respiration and skin conductivity while  the subject is asked and answers a series of questions, on the theory that  false answers will produce distinctive measurements. The polygraph measures  physiological changes caused by the sympathetic nervous system during  questioning. Several other technologies are also used in the field of lie  detection, but the polygraph is the most famous. An example of a different  method which is commonly used is a device which monitors the response of the  individual&rsquo;s eye. If the iris contracts suddenly, this could indicate that the  person is lying.</p>
