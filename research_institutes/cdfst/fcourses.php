  <h3 align="center">Deoxyribonucleic Acid (DNA)</h3>
  
  <p align="justify">DNA (Deoxyribonucleic Acid) can be obtained  from biological specimens left at crime scenes such as murder, aggravated  battery, sexual assault, hit and run, burglary, etc. The biological specimens  most often encountered include blood evidence, seminal fluid, or saliva. In  serology, these body fluids are identified and, if needed, the biological  material is then further tested utilizing DNA analysis (STR or short tandem  repeat analysis). In additional to blood evidence, the crime laboratory will  conduct serological examinations on other body fluids. The examination most  frequently requested is for the identification of semen in connection with  sexual assault cases. The third body fluid that is tested for is saliva.  Certain items of evidence may contain saliva (Bacall cells). These exhibits may  be used for DNA analysis and include such items as cigarette butts, drinking  straws, soda/beer cans, masks, bottles, etc.<br />
    Determination of the type  and characteristics of blood, blood testing, bloodstain examination, and  preparation of testimony or presentations at trial are the main job functions  of a forensic serologist, who also analyzes semen, saliva, other body fluids  and may or may not be involved with DNA typing. It must be recognized, however,  that in many crime labs, there may be no clear distinction between job title and  job function.</p>
  <p>There&rsquo;s no substitute for Forensic Serology,  whether for medical or forensic purposes. Blood&rsquo;s presence always links suspect  and victim to one another and the scene of violence. Bloodstain patterns tell a  lot about position and movement during the crime, who struck whom first, in  what manner, and how many times.<br />
    The Crime Laboratory Analysts will identify  biological materials and determine species of origin. The Crime Laboratory  Scientists will receive, secure, handle, inventory, return and preserve  physical evidence collected in criminal investigations and submitted to the  crime laboratory for examination or analysis. The basic principle of Forensic  Serology in the modern forensic lab is to locate, identify the body fluid  stains (such as blood, semen, saliva, vaginal secretions etc.) and save for the  purpose of DNA analysis. There is no crime in the world which can be committed  without leaving any trace behind. On the basis of this principle, forensic  serologist&rsquo;s job is to find, locate and identify the body fluids and other  traces. &ldquo;Failure of not finding the physical evidence at the crime scene does  not mean that it is not present, physical evidence is always present when  humans are not. Physical evidence cannot lie and purge itself when human are.  Physical evidence is factual and can never be absent from the crime scene.  (Prof. Locards)&rdquo; Failure of not finding the physical evidence due to the lack  of training can diminish its value. That is why the state of the art training  is very important and integral part of this project.</p>
