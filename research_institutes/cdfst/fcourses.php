  <h3 align="center">Pathology</h3>
<p align="justify">Forensic pathology is a  branch of Pathology concerned with determining the cause of death by  examination of a dead body. The autopsy is performed by the pathologist at the  request of the medico-legal authorities usually during the investigation of  criminal law cases and civil law cases. Forensic pathologists are also  frequently asked to confirm the identity of a cadaver (dead body or a corpse).<br />
    The forensic pathologist is  a medical doctor who has completed training in anatomical pathology and who has  subsequently sub-specialized in forensic pathology. He performs autopsies/post  mortem examinations to determine the cause of death. The autopsy report  contains an opinion about : The pathologic process, injury, or disease that  directly results in or initiates a series of events which lead to a person&rsquo;s  death (also called mechanism of death), such as a bullet wound to the head,  exsanguinations due to a stab wound, manual or ligature strangulation,  myocardial infarction due to coronary artery disease, etc.), and the &lsquo;manner of  death&rsquo;, the circumstances surrounding the cause of death, which includes:</p>
  <ul>
    <li>Homicide</li>
    <li>Accidental</li>
    <li>Natural</li>
    <li>Suicide</li>
  </ul>
  <p align="justify">Examines and document wounds and injuries,  both at autopsy and occasionally in a clinical setting.&nbsp;Collects and  examines tissue specimens under the microscope (histology) in order to identify  the presence or absence of natural disease and other microscopic findings such  as asbestos bodies in the lungs or gunpowder particles around a gunshot wound.<br />
    Collects and interprets toxicological  analyses on bodily tissues and fluids to determine the chemical cause of  accidental overdoses or deliberate poisonings. Forensic pathologists also work  closely with the Toxicologist, medico-legal authorities for the investigation  of sudden and unexpected deaths.</p>
  <h3 align="center">Questioned Document</h3>
<p align="justify">Questioned document examination  is the forensic science discipline pertaining to documents that are (or may be)  in dispute in a court of law. The primary purpose of questioned/forensic  document examination is to answer questions about a disputed document using a  variety of scientific processes and methods. Many examinations involve a  comparison of the questioned document, or components of the document, to a set  of known standards. The most common type of examination involves handwriting  wherein the examiner tries to address concerns about potential authorship.<br />
  A document examiner is often  asked to determine if a questioned item originated from the same source as the  known item(s), and then present their opinion on the matter in court as an  expert witness. Other common tasks include determining what has happened to a  document, determining when a document was produced, or deciphering information  on the document that has been obscured, obliterated or erased. Questioned  document examination is also concerned with reconstruction of burnt or torn  documents that might be considered important in a civil or criminal  investigation.</p>
