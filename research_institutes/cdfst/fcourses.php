  <h3 align="center">Toxicology</h3>

<p align="justify">Forensic toxicology is the medico- legal  investigation of death, poisoning, and drug use. Postmortem Forensic toxicology  determines the absence or presence of drugs and their metabolites, chemicals  such as ethanol and other volatile substances, carbon monoxide and other gases,  metals, and other toxic chemicals in human fluids and tissues, and evaluates  their role as a determinant or contributory factor in the cause and manner of  death.<br />
  <em>The mission of Forensic  Toxicolog</em>y  unit is adherence to international standard operating procedures, provision of  professional and un-biased scientific services to the community in the field of  forensic analysis of toxic substances. Aim is the use of latest techniques and  technologies to obtain accurate and reliable results and their interpretation.</p>
