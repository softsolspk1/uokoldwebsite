  <h2>Director General : Prof. Dr. Khalid Mahmood Iraqi (Acting) </h2>
 
  <p align="justify">Dr. A. Q. Khan Institute of Biotechnology and Genetic Engineering (KIBGE) is a research
institute with state-of-the-art facilities to conduct research on modern biological sciences
and to impart higher education at the University of Karachi. The institute was established
with an aim to foster research-based knowledge relevant to the developing world in the
scientific domain of biotechnology and genetic engineering. There are four
interdisciplinary key areas of research at KIBGE that include agriculture biotechnology,
environmental biotechnology, industrial biotechnology and medical biotechnology.:</p>
  
    <p align="justify"><strong><u>Agriculture Biotechnology</u></strong><br/>focuses research on food safety and security issues such as
antimicrobial resistance, pesticides and heavy metal contamination in food chain and
sustainable crop production using proteomic and genomic approaches.</p>
    <p align="justify"><strong><u>Environmental  Biotechnology</u></strong><br/>focuses research on developing biopolymeric nanofibers,
nano-composites, nanohybrid systems using sustainable approaches for controlling
environmental pollutants widespread in the environment.</p>
    <p align="justify"><strong><u>Industrial  Biotechnology</u></strong><br/>focuses research on production and structural elucidation of
various industrial metabolites that include enzymes, antimicrobial peptides, biopolymers
and nanomaterials that are synthesized under in-vivo / in-vitro conditions using microbial
or synthetic biology approaches./p>
  <p align="justify"><strong><u>Medical Biotechnology</u></strong><br/>focuses research on hereditary and acquired disorders prevalent
in the community, cancer genomics, cardiovascular complications, metabolic and
inflammatory disorders for disease biomarker discovery and validation.
KIBGE has established a sound scientific research environment that promotes quality
research in aforementioned scientific fields.</p>




  
