  <p align="justify">Confucius Institute at  University of Karachi (CIUK) is a non-profit institution sponsored by the Chinese  International Education Foundation. On 22nd May, 2013, the signing ceremony  was held in the President House, Islamabad for the establishment of CIUK between  Sichuan Normal University and University of Karachi.</p><br />
  <p align="justify">The <strong><u>Mission</u></strong> of CIUK is to facilitate the teaching of the Chinese  language to people who want to learn Chinese and looking for carrier  opportunities in Chinese companies in Pakistan and other parts of the world.</p><br />
  <p align="justify">The<strong><u>Vision</u></strong> of CIUK is to be the leading Chinese language center and  pursue excellence in education and people-to-people contact.</p><br />
   <p align="justify">The <strong><u>Objective</u></strong> of CIUK is to provide the best Chinese courses and  cultural activities and to help students increase their opportunities for  further education and career development.</p><br />
<p align="justify">Since its inception in 2013, CIUK has developed  from a small institute into the largest Chinese language center in Pakistan in  terms of the number of teachers, students, and teaching sites. More than 30  Chinese language teachers (local and native) provide courses including HSK1-6,  BCT1-4, YCT1-2, and calligraphy, tea culture, dance, Chinese martial arts,  Chinese culture lectures, Taiji, and paper-cutting.</p><br />
