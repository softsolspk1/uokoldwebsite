<p><strong><u>Programme Mission (Graduate Programme in Space Science and Technology)</u></strong></p>





  <p align="justify">The Institute also offers  admission in the M.Phil. and Ph.D. programmes. They aim at producing research  expertise which can help to solve indigenous problems related to Space Science  and Technology.</p>
