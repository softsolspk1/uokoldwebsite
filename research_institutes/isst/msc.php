  <h2 align="center">BS Program in Space Science and Technology</h2>
   <p align="justify">Our BS degree program aims to provide education in Astrophysics, Atmospheric Physics, 
Remote Sensing and GIS, Satellite Orbits and Communication, and Aerospace Studies for 
developing indigenous research and R&D capability. This undergraduate program will 
produce human resources to cater to the needs related to the field of Space Science and 
Technology via teaching and research.<br />
  </p>
  <p align="justify">The objective of undergraduate programs is to produce under-graduates with<br />
  
  (i)&nbsp; A broad understanding of fundamental courses of Space Science (Astronomy, Astrophysics,    Aerospace Science, Remote Sensing &amp; GIS, Satellite Communication, Computer   Programming, Machine Learning) <br />
    (ii)  Knowledge of Space Technology (Aviation Technology, Drone Technology, Aerial    Mapping) </p>
  
  <p><strong><u>Duration of Program:</u></strong><br />
  The BS degree in Space Science &amp; Technology would be minimum 4-year program spread over 8 semesters. </p>
  <p><strong><u>Eligibility for Admission to BS in Space Science and Technology:</u></strong></p>
  <ul>
   <li>Intermediate Science with Physics and Mathematics or equivalent</li>
   <li>D.A.E. (Electronics, Mechanical, Electrical, Radio, TV, Telecommunication, Computer Science, IT)</li>
  </ul>
