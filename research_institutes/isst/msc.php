<h2 align="center">BS in Aviation  Technology And  Management</h2>
<p align="justify"><strong>Program Objectives:</strong><br/>
The  international aviation industry is growing rapidly; there is an increasing  demand for qualified skilled professionals who can manage and maintain aircraft  as well as aviation operations. Therefore, the  Institute of Space Science &amp; Technology (ISST),  University of Karachi  has designed the curriculum  of new degree program: <strong>BS in Aviation  Technology &amp; Management</strong>. This undergraduate program is designed for students who intend  to pursue a career in aviation technology, unmanned aerial systems, and airport  management. Students will learn the discipline&rsquo;s latest technology and hands-on  and research-based courses. During 4-year  study, students will focus on deeper topics in the emphasis  area and prepare for careers with courses in aerospace science, aviation  technology, telecommunication, global navigation satellite  system (GNSS), airline  management and more. Hence, the curriculum of this  program is designed to meet the indigenous requirements of <strong>Space Science  program of Pakistan</strong>. T<strong>he curriculum of this  program blends aviation technology courses with management studies ensuring  graduates are well-prepared to serve aviation and airline industry. Moreover,  this undergraduate program aims to produce qualified professionals for SUPARCO,  National Aerospace Science and Technology Park (NASTP), Airlines (including  PIA, Serene Air, etc.), Pakistan Civil Aviation Authority, Aviation Industry and Drone Industry,</strong></p>
<p><strong>&nbsp;</strong></p>
<p><strong>Duration of Program:</strong><br />
  The BS degree in Aviation  Technology and Management would be minimum 4-year program spread over 8  semesters.</p>
<p><strong>Eligibility for Admission  to BS in Aviation Technology and Management:</strong></p>
<ul>
  <li>Intermediate Science with Physics  and Mathematics or equivalent</li>
  <li>D.A.E. (Electronics, Mechanical, Electrical, Radio, TV, Telecommunication, Computer Science, IT)</li>
</ul>

