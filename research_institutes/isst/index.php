  <h2>Director: Dr. Syed Tanweer Iqbal. (Assoc. Prof.)</h2>
  <p>&nbsp;</p>
  <p align="justify">The University of Karachi is the pioneer university in Pakistan that realized the importance of Space Science and started a subject of Astronomy in 1952 at the Department of Mathematics. The Institute of Space Science and Technology (ISST) came into existence as an autonomous Research Institute of the University of Karachi in 1994.  After one year, the institute had introduced M.Phil. / Ph.D. research program first time in Pakistan. ISST has already produced quality research work in areas such as Computational Astronomy, Cosmology, Space Weathers, Star Formation, Galactic Physics, Climate Change, Food Risk Assessment etc.</p>
  <p align="justify">The institute offers admission to BS in Space Science and Technology. During 4-year study, students learn the following courses: Astronomy, Cosmology, Remote Sensing & GIS, Analog & Digital Electronics, Satellite Communication and Aerospace Science, Computer Programming, Machine Learning, etc. The curriculum of this program is designed in compliance with international standards, emerging technologies, and to meet the indigenous requirements of Space Science program of Pakistan. In addition, the proposed curriculum ensures the quality, trends and the development of dynamic professional human resources.</p>
  <p align="justify">The international aviation industry is growing rapidly; there is an increasing demand for qualified skilled professionals who can manage and maintain aircraft as well as aviation operations. Therefore, the Institute of Space Science & Technology (ISST), University of Karachi has designed the curriculum of new degree program: BS in Aviation Technology & Management. This undergraduate program is designed for students who intend to pursue a career in aviation technology, unmanned aerial systems, and airport management. Students will learn the discipline’s latest technology and hands-on and research-based courses. During 4-year study, students will focus on deeper topics in the emphasis area and prepare for careers with courses in aerospace science, aviation technology, telecommunication, global navigation satellite system (GNSS), airline management and more. Hence, the curriculum of this program is designed to meet the indigenous requirements of Space Science program of Pakistan. The curriculum of this program blends aviation technology (aerospace science, satellite communication, unmanned aerial systems) courses with management studies ensuring graduates are well-prepared to serve aviation and airline industry. Moreover, this undergraduate program aims to produce qualified professionals for SUPARCO, National Aerospace Science and Technology Park (NASTP), Airlines (including PIA, Serene Air, etc.), Pakistan Civil Aviation Authority, Aviation Industry and Drone Industry.</p>
  




