   <p align="justify" class="big">Sardar  Muhammad Yasin Malik, a distinguished industrialist and philanthropist, was  born in 1941. Through years, he has won recognition for his dynamic support for  activities vital to human development as health, education &amp; social welfare  and his initiatives continue to have a positive impact on the life of a common man.<br />
     <br />
     He is the Group Chairman of Hilton Pharma (Pvt.) Ltd., and Hinovex Pharma.<br />
     Mr.Yasin  Malik has been served as Caretaker Provincial Minister for Religious Affairs  &amp; AUKAF in March 2013. <br />
  <br />
     The President of Pakistan has conferred Presidential Award to Sardar Yasin  Malik on his social services on 6th October 2011. On 23rd  March 2010 The President of Pakistan decorated the civil award &ldquo;Hilal-i-Imtiaz&rdquo;  and on 23rd March 2006 &ldquo;Sitara-i-Imiaz&rdquo; to Yasin Malik. The Governor  of Sindh has conferred the Honorary Ph.D Degree on him. He is also the Member of  the Syndicate, University of Karachi.<br />
  <br />
     He served Pakistan State Oil (PSO) as Chairman on the Board of Management from  2004 to 2008 and as Chairman Board of Management from 2008 to 2009. He has also  been the Director on the Board of Directors of Habib Bank Limited (HBL). <br />
  <br />
     Government of Pakistan has appointed Yasin Malik as member of Pay &amp; Pension  Commission and Board of Investment. Government of Sindh nominated him as a  member of Sindh Social Welfare Council, Karachi. <br />
  <br />
     He has been Special Assistant to the Prime Minister of Pakistan with the status  of a Federal Minister. He has been democratically elected as the first Sardar  of around 3 million people of Malik Biradri. He has been elected as Chairman of  Chartered Institute of Logistics and Transport (CILT). <br />
  <br />
     He is the Chairman of Advisory Committee of College of Family Medicine  Pakistan. He is the Board Member of Iqra University, Ziauddin University, Baqai  Medical University, Dow University of Health Sciences, Hamdard University, Sir  Syed University of Engineering &amp; Technology, United Medical &amp; Dental  College, Nazeer Hussain University, Patient Behbud Society for AKUH and Board  of Trustees of Pakistan Navy Educational Trust (PNET) appointed by the Chief of  the Naval Staff. He is member on the Board of Directors of The Cancer  Foundation (TCF). <br />
  <br />
     He has supported and sponsored many activities of Sindh Madrassatul Islam, Alma  Mater of Quaid-e-Azam Muhammad Ali Jinnah and granted scholarships to deserving  students in various universities and educational institutions. <br />
  <br />
     Yasin Malik donates medicines to around 25 health centers all over Pakistan on  regular basis and has donated ambulances &amp; coffins to different  organizations.<br />
     <br />
   He is the  President of The Education Foundation, which has a networking with 425 schools  in the urban slums for system improvement of teaching and administration. Over  4000 regular teachers and 650 special teachers and more than 1100  heads/administration from these schools &amp; 35 special schools have been  trained. He is associated with various universities, educational and health  related institutions. <br />
   <br />
     He is the Vice  President of Pakistan Red Crescent Society with Governor of Sindh as the  President. Chairman Pakistan Red Crescent Society Islamabad has nominated Sardar  Yasin Malik as Chairman for Special Committee on Volunteerism, especially to  meet the natural disasters.<br />
     <br />
     He sponsored  renovation of a modern Professional Development Center for management/teaching  faculty at Karachi University. He provided two sets of complete and modern  Rescue Divers Equipment for Kanjhar Lake as there was no diving facility  available for deep diving. <br />
     <br />
     Karachi`s  first Public Toilet Scheme with around 100  toilets managed by Citizens-Police Liaison Committee (CPLC) and inaugurated by  the Governor of Sindh, is Yasin Malik`s brainchild. He sponsored substantial  expansion of accommodation, education and healthcare facilities at the Karachi  Central Jail. <br />
     <br />
     He is member of  Board of Trustees of the Fatimid Foundation and Kashif Iqbal Thalassemia Care  Center. He is the President of Nazriya-e-Pakistan Council, Karachi Chapter and  member of Friends of IBA (Institute of Business Administration) Committee. <br />
     <br />
     Government of  Sindh has awarded Yasin Malik &ldquo;Best Performance Award&rdquo; which was presented by  the then Prime Minister of Pakistan in recognition of his contribution &amp;  performance in his field. National Commission for Human Development, Government  of Pakistan has awarded &ldquo;Man of the Year 2004&rdquo; to Yasin Malik for social  services. He was the sole recipient of Rotary International`s Best Family Award  in the year 2003-04 for service above self on Pakistan and Afghanistan basis.<br />
     <br />
     Government of  Sindh has appointed Yasin Malik Justice of Peace for his social services. He is  Patron of Society for the Promotion of Arabic. Yasin Malik is Chairman of  Federation of Pakistan Chambers of Commerce  &amp; Industry`s (FPCCI) Standing Committee on Religion and Culture.<br />
     <br />
     Government of  Pakistan, Planning Commission, Planning &amp; Development Division selected  Yasin Malik as Co-Chairman of Task Force on Pharmaceutical Sector. He is Former  Chairman of Pakistan Pharmaceutical Manufacturers'` Association, as Chairman he  played a vital role in promoting the pharmaceutical industry. <br />
     <br />
     He is a member of  Ministry if Industries Sindh Advisory Council and Patron of Fire Protection  Association of Pakistan (FPAP) and Make-a-wish Foundation. Yasin Malik is a  member of various business forums, international friendship associations and  social welfare organizations.</p>
