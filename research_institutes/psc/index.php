  <p align="justify">Pakistan Study  Centre was established under an Act of the parliament passed in 1976. The  Centre began functioning in 1983 and since then it has developed into a  prestigious institute of higher learning and research. Apart from conducting  courses at Masters, M.Phil and Ph.D., levels, the Centre has excelled in  original in-house and contractual research that has received wide acclaim both  at the national and international levels. Its research journal&nbsp;<em>Pakistan Perspectives</em>&nbsp;is regarded  as one of the most prestigious journals of social sciences published in  Pakistan. The Centre has also organized numerous international and national  conferences apart from regular in-house seminars and symposia.<br />
