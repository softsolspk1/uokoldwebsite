  <h2>Director: <strong>Dr. </strong>Nuzhat Afsar (Assoc. Prof.)</h2>
  <p align="justify">&nbsp;</p>
<p align="justify">Institute of Marine Science (IMS) was established in 1981 to  acquire superior knowledge of our marine environment. Advanced knowledge of sea  and skill in various fields of marine science are required for mariculture,  seafood quality, seaweed culture, seashells/ pearl industry, oil/ gas operators  and naval warfare <em>etc.</em> The IMS  undertakes research in marine science including ecological, biological,  biochemical, chemical, geological studies on marine life of northern Arabian  Sea. Marine resources of Pakistan are still untapped, which must be given due  attention to contribute greater share in economic growth of Pakistan. Without  requisite expertise in various fields of marine science it is not possible to  exploit the immense wealth of our productive, rich coastal zones and  continental shelves.<br />
  </p>
<p align="justify">The Institute’s mission is to conduct avant-garde research, train  young scientists, provide expertise to governmental or nongovernmental agencies  and industries to accomplish optimal protection for and exploitation of our marine  resources and to promote fresh knowledge to constitute public policy and  maritime doctrine.</p>
