  <h2>&nbsp;</h2>
  <h3><strong>Cooperation  with The European Commission</strong></h3>
  <p align="justify"><strong>European  Union-sponsored M.Phil. Coursework programme</strong><br />
    In September 1999, a European Union-sponsored  programme in European Studies was launched at the ASCE for three years. It was  a comprehensive programme covering nearly all the activities of the Centre.  Under this EU-sponsored programme, the European Union rendered technical and  financial assistance to the Centre. The updated curricula of the M.Phil./Ph.D.  coursework programme (focused on European Union studies) were mostly taught in  the first two years by Visiting Professors from European Universities and a  Resident Expert from Europe.</p>
  <p align="justify">The Centre&rsquo;s Academic Staff, now trained in  European Union subjects in European Universities, have, after completion of the  programme in August 2002, taken over the responsibility of teaching these  advanced courses in the programme.</p>
  <p align="justify"><strong>The Jean  Monnet Project 2001</strong><br />
    In 2001, the ASCE was awarded the Jean Monnet Chair  of European Political Science by the European Commission&rsquo;s Directorate General  for Education and Culture (Higher Education: Socrates-Erasmus, Jean Monnet  Project) for three years. Under the contract, after three years, the project  would continue for another two years without funding.</p>
  <p align="justify">The Jean Monnet Project aims to support the setting  up of academic initiatives in European integration studies in selected  universities all over the world. It is a pilot initiative offering symbolic  support to European Integration specialists to lend greater visibility to their  work in the field.</p>
  <p align="justify">Recently, the Centre&rsquo;s Jean Monnet Project was  selected for inclusion in the compendium&nbsp;<strong><em>Jean Monnet Project:  Success Stories</em></strong>&nbsp;published by the European Commission.</p>
  <p align="justify">Under this project, besides conducting courses on  the European Union, the ASCE carried out research on European Union-related  topics and also held seminars and workshops. Eminent scholars were invited to  participate in these events.</p>
  <p align="justify"><strong>The CLIMA  Project</strong><br />
    The Area Study Centre for Europe, University of  Karachi, became a partner in the project &ldquo;CLIMA&rdquo; (Euro Asian Research and  Training in Climate Change Management) funded by the European Union. It was  launched in March 2006 and ended in February 2009. The Centre inducted experts  from two institutes of the University of Karachi – the Institute of  Environmental Studies and the Centre of Excellence for Marine Sciences in this  project to assist in its scientific aspects.</p>
  <p align="justify">CLIMA has been developed within the European  Commission&rsquo;s Asia-Link Programme, which is dedicated to networking between  European and Asian higher education institutions. Its objective is to create a  Euro-Asian network on Climate Change and Sustainable Development.</p>
  <p align="justify">Within the 3-year duration of this project, CLIMA  has trained 20 young selected researchers/faculty from the following partner  Universities/ Institutes:</p>
  <ul>
    <li>Ca&rsquo;Foscari University of Venice, Italy (2 trainees)</li>
    <li>University of Padova, Italy (2 trainees)</li>
    <li>Ecole des Hautes Etudes en Sciences Sociales,  France (2 trainees)</li>
    <li>Renmin University, People&rsquo;s Republic of China (4  trainees)</li>
    <li>Vrije University, Amsterdam, The Netherlands (2  trainees)</li>
    <li>Tsinghua University, People&rsquo;s Republic of China (4  trainees)</li>
    <li>University of Karachi, Pakistan (4 trainees)</li>
  </ul>
  <p>&nbsp;</p>
  <p align="justify">The training was done through four thematic workshop/training  sessions. Twenty Research Papers were developed/published on various aspects of  Climate Change by the trainees under the supervision of international experts.  These four training sessions have resulted in the development of course materials  for an online curriculum Master&rsquo;s Programme on Climate Change Management.</p>
<p align="justify">The Final Conference of CLIMA was held in Venice  from October 9-11, 2008. A delegation from the University of Karachi  participated in the Conference, headed by Prof. Dr. Pirzada Qasim Raza  Siddiqui, Vice Chancellor, University of Karachi.</p>
