  <h3>Seminars,  Conferences and Workshops</h3>
  <p align="justify"><strong>Seminars,  Conferences, and Workshops</strong><br />
The Area Study Centre for Europe arranges lectures, workshops, seminars and conferences  on contemporary global issues, emerging socio-political, security and  economic trends concerning Europe and its relations with Pakistan  and the rest of the world. Local and foreign scholars, faculty members  and senior students participate in these programmes.</p>
  <p align="justify">The Centre held its first international seminar in  October 1995 on <em>Post-Cold War European Order and South Asia </em>in  collaboration with the German-based  Hanns Seidel Foundation (HSF), Islamabad. The Centre has held  several international seminars and research projects in collaboration with the HSF. Eminent scholars from Europe,  Africa, Asia and Pakistan participated in these events.</p>
  <p align="justify">Under the European Union-sponsored programme, the  Centre revamped its M.Phil. coursework from 1999 to 2002 to upgrade the  Centre's standards. The Centre won the  Jean Monnet Chair in 2002, which sponsored several seminars and  workshops which has enhanced EU-Pakistan academic cooperation. Furthermore, the  ASCE became the principal Institute in conducting the EU Commission-sponsored  CLIMA international project, under which the Centre held highly reputed  international conferences and workshops in Karachi.</p>
  <p align="justify">The Centre also held<strong> </strong>various International Conferences in cooperation with the Goethe  Institut Karachi, Alliance Francaise,  Rabita Forum International and Transparency International to promote  intercultural dialogue between the West and Islam, to share intellectual study on issues of regional connectivity and to  lead academic debate on climate change awareness and climate justice.</p>
