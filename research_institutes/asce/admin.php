  <h3>Administration,  Financing and Staff</h3>
  <p align="justify">The Centre has its own administrative setup, and  the management, overall control and supervision of the affairs of the Centre  vest in the Board of Governors, headed by the Vice-Chancellor of the University  of Karachi as the Chairman, Board  of Governors. All academic and research programs of the Centre are approved by the Board of Governors. The Centre&rsquo;s academic programme is linked  with the University of Karachi, which awards the M.S., M.Phil., and Ph.D.  degrees, and languages certificates, diplomas, etc. The Federal Government  finances the Centre, on the recommendation of the Ministry of Federal Education  and the Higher Education Commission.</p>
  <p align="justify">The Centre is headed by a Director who supervises  the administrative, academic and research activities at the Centre. The ASCE  has a devoted and well-trained Research/Academic staff with expertise in the  field. </p>
  <p align="justify"><strong>Publication  Wing</strong><br />
    The Centre has its own publication wing, fully  equipped with computers and other facilities and is manned by an expert compositor.  The Centre&rsquo;s publications are composed and proofread at the Centre.</p>
  <p align="justify"><strong>Library</strong><br />
    The Centre has a modest but well-equipped  specialised library for research scholars and students. It has material on  European history, politics, foreign policy, diplomacy, economy, culture,  philosophy, law, legal institutions and contemporary developments in Europe.  Lately, the Centre has also begun acquiring books on European literature and  Fine Arts. The material is in the form of books, documents, journals, magazines,  and newspapers.</p>
  <p>The Centre&rsquo;s library facilities&nbsp;have&nbsp;been  enhanced under the European Union-sponsored European Studies Programme. It has  now acquired books on European Union-related subjects. The Library is used by  university students, scholars and faculty members.</p>
