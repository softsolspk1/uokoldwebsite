  <h2>Director: Prof. Dr. Samina Saeed (Officiating)</h2>
  <p>&nbsp;</p>
<p align="justify">The Area Study Centre for Europe was established at the University of Karachi by an Act of Parliament (ASC Act No. XLV, 1975), along with five other Area Study Centres in major state-sector universities of Pakistan. The Centre undertakes research at M.Phil., M.S., and Ph.D. levels. The research findings of the Centre’s own research staff are published in the form of books, monographs and profiles. The Centre also publishes the bi-annual research journal, Journal of European Studies, with articles on contemporary European issues and related topics. The Centre is focusing its research on the European Union, its governance and politics, law, economics and external relations. European Common Foreign and Security Policy, Europe-Pakistan relations, Europe and the Muslim World and Europe’s relations with the developing world are also amongst the subjects of research and teaching at the Centre. Since one of the aims of establishing the Area Study Centres is to provide feedback to policy makers in the country, the Centre also receives research proposals and assignments from the Foreign Office and other institutions of the Government of Pakistan. The Centre offers language courses in French, German, and English at the certificate and diploma levels.</p>
<p>&nbsp;</p>
<h3>Location and Surroundings</h3>
<p align="justify">The Centre is located a little remotely from the hustle and bustle of the faculties, near the I.B.A. Staff Town and H.E.J. Institute of Chemistry. It has its own building with a serene atmosphere, ideal for research and academic pursuits.</p>
