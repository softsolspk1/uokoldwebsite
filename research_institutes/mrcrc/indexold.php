  <h2>Incharge: Mr.  Qadeer Mohammad Ali </h2>
  <p>The Marine Reference Collection and Resource Centre is  the oldest marine biodiversity research centre in Pakistan. It was founded in 1967 as  an Invertebrate Reference  Museum by renowned marine scientist of  the country Prof. Dr. Nasima M. Tirmizi (late), who was also founder director  of the first Institute of Marine Science in Pakistan. MRC&amp;RC has been  providing excellent facilities to the marine science community of Pakistan  and regional countries. It supports marine biodiversity research through  comprehensive taxonomic data on marine fauna and flora and is in fact one of  the unique research and training facilities in the region with a mission  emphasizing taxonomic research, conservation and education. <br />
    The centre, which has only been a feature of  invertebrate taxonomic studies, has demonstrated an ability and agility in  responding to the management and conservation of marine biodiversity in a  national, regional and international context. MRC&amp;RC has a preeminent  museum dedicated to inspiring curiosity and learning about the invertebrate  fauna through its unparallel collections, exhibits and research. <br />
    So far 32 research projects have been accomplished  through national and international fundings/grants. And approximately 500  research publications are to the credit of centre including illustrated keys,  monographs, books and proceeding etc. <br />
    The centre is linked with numerous international  research organizations including: Expert-Centre for taxonomic Identification  (ETI) Amsterdam, Zoological Museum Amsterdam, Raffles Museum Singapore,  Smithsonian and British   Museum. </p>
