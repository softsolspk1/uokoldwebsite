<h3></h3>
  <h3><strong>Specific  Research Areas</strong></h3>
  <p align="justify">The Centre  supports marine biodiversity research through comprehensive taxonomic data on  marine fauna &amp; flora and thus offers research and training facilities in  the region with a mission emphasizing on conservation and education.</p>
  <ul>
    <li>Survey, monitoring and assessment of coastal habitats and  its biodiversity.</li>
    <li>Collection of fauna and flora from shores, offshore waters  and harbors.</li>
    <li>Sorting of collections, curating, preservation and storing.</li>
    <li>Identification, documentation, registration and cataloguing.</li>
    <li>Experiments on live collection in wet/aquaculture lab,  rearing of larvae etc.</li>
    <li>Publication of conclusions in the form of reports,  monographs, illustrated keys, as well as presentation of papers at the  national, international seminars/workshops, etc.</li>
    <li>Exchange of material as loan or donation.</li>
    <li>Research supervision/guidance for full/partial fulfillment  of M.Sc., M. Phil./Ph.D. degrees.</li>
    <li>Training of manager/scientists from government and  non-government organizations.</li>
    <li>Planning and undertaking research projects</li>
  </ul>
  <p></p>
  <p><strong>RESEARCH  JOURNAL</strong></p>
  <p align="justify"><strong>Pakistan  Journal of Marine Sciences (PJMS)</strong><br/>
  The Pakistan Journal of Marine  Sciences (Print ISSN 1019-8415, Online ISSN 2710-4583, CODEN PJMSE8) a  bi-annual journal is an official publication of The Marine Reference Collection  and Resource Centre, University of Karachi and is being published from the last  31 years regularly.<br />
    PJMS is dedicated to publish  original research papers in the broad field of Ocean Sciences. All the major  aspects of marine science are covered in PJMS including zoology, botany,  geology, chemistry, physiology, systematic, ecology, physical oceanography and  fisheries. The journal is abstracted and indexed by ASFA, BIOSIS, PASTIC,  Chemical Abstracts, Current Contents, Oceanic Abstracts and Zoological Records.</p>
