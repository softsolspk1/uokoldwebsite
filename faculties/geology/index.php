  <h2>Chairperson:   <strong>Prof. Dr.  Erum Bashir</strong></h2>
  <p>Thee Department of  Geology, University of Karachi is one of the oldest institutes for teaching of  geology in Pakistan which started functioning in 1954. The department has a  spacious building which contains many laboratories and classrooms. Among the  universities of Pakistan, it has one of the most impressive geology museums.  This museum houses a large collection of valuable   rocks, fossils and mineral specimen.  For students of geology these serve as  reference geological samples. The Department has produced a large number of  graduates who hold key positions in national and multinational organizations. </p>
  <p>&nbsp;</p>
  <h3>Career  Opportunities<br />
</h3>
  <p>BS  Degree holders of geology from this university can choose careers as petroleum  geologist, engineering geologist, marine geologist, geochemist geophysicist,  environmental geologist. In all national and multinational oil companies, a  large number of petroleum geologists from Karachi University are engaged in  exploration activity. Engineering geologist are required to investigate the  foundations for all large civil engineering projects such as dams, motorways,  power plants and high rise buildings. Engineering companies and government  agencies employ engineering geologist and hydrogeologists for developing  groundwater resources, resolving environmental issues and for assisting in  better planning. </p>
  <p>Courses  in oceanography and marine geology are offered to prepare our graduates to  explore ocean resources. They have a career in oceanographic institutes,  coastal development authorities and offshore oil exploration companies.</p>
Geophysics and  geochemistry are interdisciplinary sciences. Principles of physics and  chemistry are applied in understanding the constitution and the dynamics of the  earth. These subjects are for monitoring of environmental problems and  essential tools in oil and mineral exploration. </div>
