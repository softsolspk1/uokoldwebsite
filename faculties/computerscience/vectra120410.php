        <p align="center"><font face="Verdana, Arial, Helvetica, sans-serif"><strong><font size="2">Inauguration Ceremony of <br>
          &quot;Industry University Coordination Programme in ICT for sponsored Research and Development&quot;<br>
        </font></strong><font size="2"><strong>(VectraCom group and University of Karachi)</strong></font></font></p>
        <p align="center"><font size="2" face="Verdana, Arial, Helvetica, sans-serif"><em>DCS/UBIT playing a dominating role arranged a mile stone inaugural  ceremony at UBIT/DCS by making a joint venture agreement between University of  Karachi and VectraCom group on 12-Apr-2010.</em></font></p>
        <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Prof. Dr. S.M Aqil Burney in his  inaugural address highlighted the importance of research and development in ICT  and related technologies as the cornerstone in modern development and research.  He said that ICT today act as a change catalyst to transform the societies into  knowledge societies. &nbsp;He highlighted the  excessive use of cellular phones in our country which has crossed 100 million  in just 5 years. This burst of usage of technology has caused the society to  change and now it is upto the industry and academia to find new ways of using  these technologies for the betterment of the societies. Citing the examples of  many foreign universities, He emphasized that universities should be generating  revenue from industry liaisons and coordination.</font></p>
        <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif"> Mr. Emran Riaz, Chairman of the  VectraCom group&nbsp; lauded the efforts put  in by Dr. Burney and his team for making this dream a reality. He said that these  initiatives will not only help the industry but will also be crucial for the  growth and development of the students at the University of Karachi.&nbsp; He emphasized that such programs should  continue to evolve.</font></p>
        <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif"> While sharing the mutual vision,  Mr. Khurram Paradhan, Manager of the portfolio planning division for Pakistan  and Afghanistan of Nokia stated that Nokia supports such initiatives and is  always ready to co-operate with the academia. He also mentioned the &ldquo;calling  global innovators&rdquo; program launched by Nokia to gather innovative ideas from  across the world and use them to better the technology. <br>
          Dean Science, Prof. Dr. Darakhshan  J. Haleem congratulated the Department of Computer Science / UBIT on taking  such initiative. She also extended full support to the department in arranging  and organizing such events.</font></p>
        <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif"> Vice Chancellor University of  Karachi, Professor Dr. Pirzada Qasim Raza Siddiqui in his presidential address  also congratulated Dr. Burney and his team in making this coordination  possible. He also highlighted the fact that this initiative is the first of its  kind and department of Computer Science has taken the lead and other  departments should also follow. He also said that universities around the world  a source of making revenue for the purpose of research and development and that  is only possible after they engage in close coordination with the industry. </font></p>
        <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif"> A memorandum of understanding was  also signed between the University of Karachi and VectraCom group to facilitate  each other in research and development related to ICT and related areas. The ceremony was attended by pro-vice  chancellors Prof. Dr. Nasiruddin Khan and Prof. Dr. Shahana Urooj Kazmi, Dean  faculty of Arts Prof. Saleem Memon, dean faculty of Islamic studies Prof.  Ghulam Mehdi, directors and chairpersons of several institutes and departments  and a large number of teachers of University of Karachi.</font></p>
