  <p align="justify">A minimum of 50% marks are required to pass. Both theory and practical exams are separate passing heads.</p>
  <h4 align="left"><strong>Categories</strong></h4>
  <p><strong>Category K : </strong>Applicants who passed their prerequisite examination from Karachi Board. Also those who passed their prerequisite examination from the Federal Board provided that the college where studied is located in Karachi. <br />
    <strong>Category S : </strong>Applicants who passed their pre-requisite examination form any Board located in any where in the Province of Sindh excluding Karachi. <br />
    <strong>Category P : </strong>Applicants who passed their prerequisite examination from Pakistan or foreign Board/teaching Institution excluding those located in the Province of Sindh. </p>
