  <h3 align="justify">INTERNATIONAL CONFERENCE</h3>
  <p align="justify">The group presented a paper at the First International e-Health conference in Pakistan at AKU during Jan-2010. Main objective of this conference was to introduce and advocate e-Health as a viable and relevant option for improving public and private healthcare in Pakistan.</p>
  <p align="justify">&nbsp;</p>
  <h3 align="justify">SEMINAR</h3>
  <p align="justify">A seminar on &quot;HMS &amp; ICT in Developing Countries&quot; was held at DCS (UBIT), University of Karachi in coordination with Staffordshire University Health Sciences Department in Jun-2009. Staffordshire University was represented by Mr. Kamran Ahsan.</p>
  <p align="justify">The speakers emphasized on the importance of ICT especially in service sector due to the increasing cost of medical care and lack of penetration of health facilities in the remote areas of Pakistan. It was concluded the mammoth growth of communication and technology, if utilized in health sector, has the potential for delivering far reaching and cost effective health care to all citizens of the country.</p>
  <p align="justify"><br />
  </p>
  <h3 align="justify">PROJECTS</h3>
  <p align="justify">The group members have undertaken several projects. One project is based was an e-Health application for creating awareness about epidemics such as Swine flu and dengue fever. Moreover, we are specially focusing on airborne, waterborne as well as skin diseases. Another project is a dietary management application for hospitals and other health related issues. </p>
