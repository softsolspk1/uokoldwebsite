  <div align="center"><h2><font size="+1">Vision</font></h2>
  <p align="center">To become an internationally recognized Computer Science Department as Centre of Excellence in Higher Education where students receive high quality education.</p></div>
  
  <p align="left"><font size="+0.5"><strong>Introduction:</strong></font> The University of Karachi holds a unique position in the country's educational system. As a respected research and reaching institution, it is committed to intellectual leadership, and to excellence in both developing knowledge and conveying that knowledge to its students. The University of Karachi meets the commitments to preserve knowledge through its instructional and research programs for higher level education. </p>
<p>The Department of Computer Science, University of Karachi, was established by a resolution of Academic Council in its meeting, held on November 27. 1984, and it began functioning in the academic year 1985-86 by offering a Degree Program in Master of Computer Science (MCS) and become one of first institutions in Karachi imparting education in Computer Science and Technology. The Department also offers evening program leading to Post Graduate Diploma (PGD) in Computer &amp; Information Sciences. In the year 1995; Department started MCS evening program, on self-finance basis, to cater the growing demand of professionally skilled manpower in the field of Computer Science.</p>
<p>To further strengthen the discipline of Computer Science by producing high quality pro with sound fundamental knowledge. the department has started in the year 1996 and 2001 BS (Computer Science) in the morning and evening, a four year degree program leading to MS (Computer Science), a two year program after completing the BS. MS programs leads to PhD (Computer Science) program. The University of Karachi has excellent supporting faculty in the subjects of Mathematics, Statistics, Physics and other allied subjects for teaching these courses at BS (Computer Science) level. The first batch of BS (Computer Science) of the morning program passed in 1999.</p>
<p>The Department of Computer Science offers a wide range of courses at various levels. The purpose of these courses is to provide opportunities for advanced studies and research in the field of Computer Science and information Technology and related fields, and also to produce highly skilled computer personnel to cater the need of Computer professionals in the country and abroad. The Department maintains high standard of education through continuous assessment and with periodic tests, quizzes, seminars and field projects. The Department maintains close link with professional organizations at national and international levels, to enhance professional and academic standard of the faculty and as well as of the students.</p>
<p>&nbsp;</p>
<h3>Curriculum Policy</h3>
<p align="justify">The contents of courses offered are revised after every two years and books are recommended to cope with the rapid developments which are taking place in Computer Science and Information Technology. All the curricula have been designed in the light of recommendations of Task Force (on the Curriculum for Computer Science Programs for general Universities of Sindh). Thus all the curricula of Department of Computer Science are developed for CS/IT on the following policy:</p>
<p align="justify">&quot;Curriculum should be made flexible so as to be responsive to the changing g structure of the market. The curricula shall encourage thinking, creativity and project construction ability. The curricula of CS/IT shall be made comparable with international standards and matching the needs of the next century by developing libraries, laboratories, and above all teaching staff&quot;.</p>
