    <li>O&rsquo; Mally (1971).  Introduction to Digital Computer. Halt, Rinehart and Winston, New York.</li>
    <li>M.A. Harroson  (1965). Introduction to Switching and Automata Theory. McGraw Hill.</li>
    <li>G. Birkhott and  T.C. Bartee (1970). Modern Applied Algebra. McGraw Hill.</li>
