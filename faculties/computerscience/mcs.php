  <p>Sequential  circuits, Synthesis of Synchronous Sequential circuits. Transition diagram.  Finite state machines. machines. Moore &amp; Mealy machine. Capabilities &amp;  Limitation of finite state machine, state equivalence  &amp; Machine Minimization. Simplification of  Incompletely  specified machine.  Interactive networks.</p>
  <p>Fundamental  Mode Circuits. State Assignment in Asynchronous Sequential circuits. Plus Mode Circuits.</p>
  <p>State  assignment using partitioning lattice of closed partitions over &amp;  generation of closed partitions. Information flow in sequential machines.  Decomposition &amp; Synthesis.</p>
  <p>Experiments;  Homing Experiments, Distinguishing Experiments Machine. Identification  Experiment, Fault detection experiment. Design of diagnosable machine.</p>
  <p>Finite  memory machines, Definite machines, memory span   w.r.t. output sequence information less machine.</p>
  <p>Inert  Linear Machine, Insert Linear Machine &amp; rational. Transfer function,  General Model Reduction of  Linear  Machines. Identification of Linear Machine, Application of Linear Machine to  error correction.</p>
  <p>Deterministic  Recognizers, Transition Graph, Converting Non-deterministic to deterministic  graphs. Regular expression. Transition graphs, Recognizing Regular sets,  Regular sets corresponding to Transition graphs. Two way Recognizer.</p>
