<p><strong>&nbsp;</strong></p>
  <p><strong>CS-501 : <u>Fundamentals of Digital  Computers</u></strong>                                               Credit Hour (2+1)</p>
  <p>Decimal  and Binary systems, Binary addition, subtraction, multiplication and division  Octal and Hexa decimal number systems.</p>
  <p>Fundamental  concept of Boolean Algebra. Basic laws of boolean algebra. De Morgan&rsquo;s Theorem.  Sum of the Products and Product of Sums expressions. Three input variable  expression. Maps for simplifying expression.</p>
  <p>Logical  design. Binary counter. Integrated circuits. Medium and Large scale  integration.  Digital circuits. Diodes  and transistors. Diods and circuits. Resistor transistor Logic.  Diode-transistor Logic. Transistor Logic. Emitter-coupled Logic.</p>
  <p>Input  Output devices. Computer  Organization.  Addressing techniques, Index resistors. paging and indirect addressing. Single  address microprocessor, two address computers.</p>
  <p><strong><u>Recommended Books :</u></strong></p>
  <ul>
    <li>T.C. Bartee  (1977). Digital Computer Fundamentals. 4th Edition.  McGraw Hill.</li>
