      <div align="justify">
       

The Department of Computer Science from University of Karachi has been a silent contributor to the talents we see today in the tech industry. The students of this department who proudly call themselves UBITians have proven time and again the incredible talent and skills they possess. This year they bagged another win at the Microsoft Imagine Cup 2016 Nationals and also won the IBA ProBattle Trophy for the third time in a row, pulling off a rare hat trick in the process.
<br/><br/>

IBA ProBattle is an annual competition held by the Computer Science Department of one of Pakistan's most prestigious institutions IBA. Sponsored by highly reputable companies such as HBL, Microsoft, Systems Limited, Gfk Etilize and more this event with its logo of a sword was befitting for the warriors of UBIT to show just what they were made of. The competition was fierce with students form SSUET, IBA, Iqra , Isra , Szabist , FAST, Habib and DHA Suffa giving their all to win. Even so, UBITians persevered and took the trophy home.
<br/><br/>

However, it would be unfair to attribute this win to just luck as preparations for competing in this event seemed no less than preparing for war when even the faculty members held sessions to mentor the students and seniors guided their juniors about the challenges they faced in the past IBA ProBattle events. Over 120 students participated in more than 45 teams and if you asked the students what their goal was, their answer would be "To win for UBIT".
<br/><br/>

The students stood united in every front with cheers of pure joy coming from the UBITians in the audience every single time a UBITian was called on the stage to collect their award. Beyond the capacity for excellence UBITians displayed something even more valuable; their respect and love for their department and everything it stands for. 
Victorious in various categories the underdogs flaunted their aptitude in Data Analytics with Muhammad Abdul Subhan taking the winner's trophy and Kamran Tariq being the Runner UP followed by Muhammad Anas Arshad who won for Business Idea. Muhammad Abdul Subhan also took home the trophy for his one-of-a-kind creativity in Logo and Poster Design while Tabish Rafiq was the runner up. We also had Kasra Zunaiyyer as a runner up for Software Exhibition while Wasi Tariq and Huda Jawed won the prize for Pseudocode. Lastly Saad Arif Khan became the runner up for Photography competition.
<br/><br/>

Taking things beyond local competitions, UBITians have proven their worth at a national level with winning the Microsoft Imagine Cup 2016 Pakistan award by team Dextrous Infinity. Kasra Zunaiyyar, a third year student won in the games category of the competition with his adventure game iNtOiT.
<br/><br/>

iNtOiT is designed for Windows platform and supports "Oculus Rift", a technology for virtual reality. The storyline follows two brothers Kaptin and Hamm who are trapped inside a computer game and have to go through different levels in order to get back to reality. 
<br/><br/>

Imagine Cup is an international event that gives students the opportunity to bring forth that technology which brings a positive change into our lives. The competition is first held on a national level and the winners then compete with students of other countries online.  Imagine Cup 2016 Pakistan was organized by Microsoft and Higher Education Commission (HEC) with Dr. Arshad Ali, Executive Director of HEC as the chief guest.
Kasra Zunaiyyar, a third year student, won against teams from Lahore, Islamabad and Quetta and is set to compete in the international rounds soon. This win only serves as a testament to the inventiveness the students of this department retain.
<br/><br/>

UBIT has had a long history of conquests at various competitions and challenges and plan on achieving more feats in the near future. As Vince Lombardi once said:
