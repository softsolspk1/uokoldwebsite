  <h3>B.A. / B.Sc. (Computer Science) Course Outlines</h3>
<p>&nbsp;</p>
  <p><strong>Paper – I<br />
FUNDAMENTALS OF DIGITAL COMPUTERS<br />
  </strong></p>
  <p>Introduction to Computers. Early history of Computers. Types and Generations of Computers. History of Data Processing. The need for Information processing. History of recording Techniques. Concepts’ of Hardware, software, and Firmware systems. The date processing Cycle. Organization of typical, microcomputer. Devices (Input / Output) and Peripherals of Computers. The central processing unit and Memories.</p>
  <p>Number systems, Binary, Octal, Decimal and Hexadecimal number systems, and their Conversions from one to another number system, addition, Subtraction, Multiplication and Division of Binary, Octal, and Hexa decimal number systems, One’s Complement, Two’s Complement.</p>
  <p>Concepts of Binary Logic Gates, AND gate, OR gate, NOT (Inverter) gate, NAND gate, NOR gate, Exclusive OR gate, gate, Exclusive NOR gate, Concepts of Boolean Algebra, Constructing circuits from Boolean expressions, MAX term Boolean expression, MIN term Boolean expression, Simplifying Boolean Expression using KARNAUGH Map with three variables. <br />
    Code, Encoding, decoding, The 8421 BCD Code, The Excess-3 Code, The Gray Code. Flip- flop, The J-K Flip Flop.</p>
  <p>Arithmetic Circuits, Binary Adders, Adders, Half Adder, Full adder, Three Bit adder, Buttery Subtractions, Parallel Subtraction,</p>
  <p><strong>BOOKS FOR REFERENCE:</strong><br />
    1. Roger L. Tokheim : Digital Electronics (II Edition). McGRAW HILL Book Company, 1984.</p>
  <p>2. N. Subramnian : Introduction to Computers. TATA McGRAW HILL Book Company, 1988.</p>
  <p>3. T. C. Bartee : Digital Computer Fundamentals (Fourth Edition). McGRAW HILL Book Company 1984.</p>
  <p>4. A. P. Malvino : Digital Computer Electronics (Second Edition). An Introduction to Microcomputers. McGRAW HILL Book Company, 1984.</p>
  <p>5. Tremblay, Bluntum : Introduction to Computer Science. McGRAW HILL Book Company, 1984.<br />
  </p>
  <p><strong>Paper-II <br />
    ALGORITHMS AND PASCAL PROGRAMMING</strong><br />
  </p>
  <p>Introduction to Computer Applications, Introduction to Computer Programming, Problem Analysis and Algorithm Development, Introduction to Flow Charting, Flow Chart symbols, Algorithm Logic design using Flow Charts, Three Algorithm Components, Sequential Flow, Conditional Flow, Repetitive Flow.</p>
  <p>Data Typology, Types of Data, Declaration of Unstructured variables, Constants and Variables, Boolean data type, Character data type, User defined Scalar Data type, Integer data type, Real data type, BEGIN – END statements, Arithmetic operators, Logical operators, Arithmetic and Logical Expressions Input/Output statements, Flow Control Statements, FOR – DO statements, IF – THEN – ELSE Statements, Nested IF – Statements, Looping and branching, FOR – Do statements, WHILE – DO statement, and REPEAT – UNTIL Structures, Nested WHILE – DO statement, CASE – END statement, GOTO statement.</p>
  <p>Concepts of ARRAYS, Single and Multiple Dimensional arrays, Concepts of Subroutines, Functions and Procedures, Recursive Procedures, File Processing.</p>
  <p>Concepts of Top Down Structured Programming, Top Down program Logic, structured program Logic, Concepts of Modular programming.</p>
  <p><strong>BOOKS FOR REFERENCE:</strong><br />
    1. Byron S. Gottfried : Programming with PASCAL <br />
    McGRAW HILL Book Company, 1986.</p>
  <p>2. Johan Konvalina, : Programming with PASCAL <br />
    Stanley Wileman McGRAW HILL Book Company, 1987.</p>
  <p>3. George W. Cherry : PASCAL Programming Structures Reston<br />
    Publishing Company, Inc.</p>
  <p><strong><br />
    PRACTICAL – I</strong></p>
  <p>Thirteen practicals covering all features of PASCAL language with program algorithms. (20 marks)<br />
    Viva – Voce (10 marks)<br />
  </p>
  <p><strong>Paper – III<br />
    INTROUCTION TO COMPUTER SCIENCE</strong><br />
  </p>
  <p>Introduction to Computer Science, Overview of different programming languages, Principles and techniques in high level language programming, Data Storage, Main Memory, Bulk Storage, Data Manipulation, Arithmetic/Logic instructions.</p>
  <p>Concept of Operating System and Utility Software’s, Functions of Operating systems, Virtual characteristics, The Evolution of Operating systems, Operating system Architecture, Program Execution, Batch Processing Interactive Processing, multi-user System, Time sharing, Multi tasking and Multi Processing.</p>
  <p>Concepts of Software engineering, Concepts of Data Structures, Use of Arrays, Link Lists, Trees, Data Flow Diagrams, Concepts of File Structure, Sequential Files, Indexed Files, Hashed Files, Concepts of Database, Types of Databases, Relations Design and Operations, Network Design and Operations, Hierarchical Design and Operations.</p>
  <p><strong>BOOKS FOR REFERENCE:</strong><br />
    1. Gorden I. Devis : Computer Data Processing. McGraw HILL Book Company, 1987.</p>
  <p>2. A. B. Tucker : Programming Languages, McGraw HILL Book, Company, 1986.</p>
  <p>3. Madnick : Operating System. McGraw HILL Book Company, 1988.</p>
  <p>4. J. G. Brookshear : Computer Science An Overview Second Edition. The Penjamin/Comings Publishing Company.</p>
  <p>5. J. Glenn Brookshear : Computer Science, An Overview, Second Ed. The Benjamin/Cummings Publishing Co. Inc.</p>
  <p><strong>Paper – IV</strong><br />
    <strong>COMPUTING METHODS, SYSTEMS ANALYSIS AND DESIGN</strong><br />
    <br />
    SECTION A: (2 questions to be attempted)<br />
    Introduction to Numerical Computing, Concepts of estimation to errors, Relative and Absolute errors, Truncation errors, Roundoff errors, error propagation.</p>
  <p>Finite differences, Differences Operators, Interpolation, Newton. Forward and Backward Formula for interpolation, Calculation of errors in Newton Forward and Backward formula, Polynomial approximation, Lagrange’s formula of interpolation, Calculation of error in Lagrange’s formula, Divided differences, Newton’s interpolation formula for divided differences.</p>
  <p>Numerical solution of non-linear algebraic equations, Half interval method, Regula falsi (False position) method, Newton Raphson method, Secant method.</p>
  <p>SECTION B: (3 questions to be attempted)</p>
  <p>Introduction to systems analysis, Definition of systems and procedures, Definition of systems analysis, Characteristics of a system, Feasibility study, Types of feasibility study, Problem definition, The problem reporting machinery, Definition of Subject, Scope and Objectives, Outline of the systems study, Study techniques and planning, structure of the organization, Interactions between outputs, inputs and resources, Understanding the existing requirements.</p>
  <p>Define the new systems requirements, Long-range plans, Evaluation criteria for the new systems, Designing the new systems, Computerized systems design, General concepts of cost analysis, The tools of systems analysis, Flow charts, Gantt charts, Decision table, Organization chart, Work distribution chart, Data flow charts, PERT/CPM.</p>
  <p><strong>BOOKS FOR REFERENCE: </strong><br />
    1. Carl Erik Froberg : Introduction to Numerical Analysis. Second Edition Addison Wesley Publishing Co.</p>
  <p>2. Shan S. Kuo : Computer Application of Numerical Methods National Book Foundation, Islamabad.</p>
  <p>3. William S. Dorn &amp; Daniel D. McCracken<br />
    : Numerical Methods with Fortran IV Case Studies.</p>
  <p>4. Don Yates : Basic Systems Analysis ELBS, USA, 1988.</p>
  <p>5. J. Race : A Professional Guide to Systems Analysis McGraw Hill Book Company, 1988.</p>
  <p><strong>PRACTICAL – II</strong><br />
    <br />
    SECTION A : (10 marks)<br />
    Six practicals covering all the methods of Approximation and Error estimation with program algorithms using PASCAL Programming Language.</p>
  <p>SECTION B : (10 marks)<br />
    Seven practicals covering all the features of databases with program algorithms.<br />
    Viva Voce : (10 marks)</p>
