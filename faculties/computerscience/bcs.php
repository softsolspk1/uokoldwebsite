  <h3>B.C.S. (Three Year) Course Outlines</h3>
  <p>&nbsp;</p>
  <p align="left">The courses are briefly outlined here along with credit hours and pre-requisites for each course.</p>
<p>The curriculum comprising of both hard–core computer science courses and supporting courses has been designed to achieve academic excellence and in-depth knowledge in different areas of computer science.</p>
<p>The outline given under each of the courses indicates the minimum coverage of each course. Changes and advancements taking place in different areas are reflected in the course contents and individual instructors do regular additions.</p>
<p><strong>Classification of courses</strong></p>
<p>The program is divided into three types of courses provide the basis of academic and practical understanding of different areas of Computer Science.</p>
<p><strong>Essential Courses</strong></p>
<p>These are mandatory courses prescribed by the University of Karachi for all degree programs. Each of the following courses are of 3 credit hours, contributing a total of 9 credit hours.</p>
