        <p>Course Number : CSSE - 313<br/>
         Course Name : Introduction To Software Engineering<br/>
         Pre-Requisite : None<br/>
         Credit Hours : 2+1</p>
        <p align="justify">Course Content :<br/>
        Introduction: Requirement Elicitation:<strong> </strong>Complete understanding of the Problem Domain, Knowledge About  Methods and Techniques for Uncovering, Discovering, and Communicating  Functional and Non-functional Requirements and Constraints; Requirement  Analysis:<strong> </strong>Modeling of Software  Requirements in the Information, Functional and Behavioral Domains of a  Problem, Perceived Primary and Derived Requirements of a System, Various  Requirements Modeling Methods (e.g. Structured Analysis, Object-Oriented  Analysis), the Use of Prototyping to Examine and Assess Requirements, Domain  Analysis Techniques,<strong> </strong>Requirement  Specifications:<strong> </strong>Representation of  Software Requirements that Result from Requirement Elicitation and Requirements  Analysis, Specification Standards, Application of Specification Methods that  Involve Structured Natural Language, Graphical and Symbolic Notation, Design  Description Languages and Formal Specification Languages, Software  Characteristics, The Software Crisis: Problems &amp; Causes, Software  Engineering, Software Life Cycle: Overview of Software Life Cycle, Software  Engineering Paradigms, Types of Documentation, Documentation throughout the  Life Cycle, Project Initiation, System Analysis: Problem Clarification &amp;  Scope, Objective &amp; Feasibility Study Requirement Analysis: Facts Finding  Techniques, Analysis Principles, Essential &amp; Implementation View, Analysis  Modeling: Data Modeling, Behavioral Modeling System.<br>
          Case Study: A project will be assigned to students, which  will be carried out throughout the semester. They will practically apply  everything on the Project that was studied in theory.<br>
        
        Introduction to Waterfall, RAD, Spiral, Evo-Incremental  Delivery Model, Wish List, Creation and CASE Tools. An Introduction to Software  Engineering, its Requirement and Scope, Software Crises, Waterfall Model,  Spiral Model, Jackson Structured Programming Techniques, Managing Software  Development, Requirement Analysis, Introduction to Z-specifications, Overview  of VDM, An Introduction to SRS Diagrams.</p>
        <p>Suggested Book :</p>
        <ul>
          <li>Software Engineering  Analysis and Design by C. Eastral and G. Davis, Published by McGraw-Hill, 1992.</li>
          <li>Software Engineering by  Roger S. Pressman, 4th Edition, Published by McGraw-Hill, 1997.</li>
        </ul>
