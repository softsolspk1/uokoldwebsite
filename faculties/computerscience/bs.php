<h2 align="center"> B.S Program</h2>

<h3>Mission (BSCS)</h3> 
<p align="justify">To strive for Excellence in Teaching & Research of Computer Science, is the opted 
mission. Educate students with the best practices of the field foster the 
development of problem solving and communication skills & ethical values 
providing quality teaching experiences through effective teaching methodology.</p>

<p><strong>Curriculum (BSCS) Program :: </strong> <a href="docs/curbscs.pdf" target="_blank"> Click here</a> </p>
<p>&nbsp;</p>
<p>&nbsp;</p>
<h3>Mission (BSSE)</h3> 
<p align="justify">The mission of the BS Software Engineering Program is to prepare software 
engineers for professional careers, advanced study, leadership roles and 
entrepreneurial endeavors through exposure to industrial practices, modern 
teaching and experiential learning that helps them to develop problem-solving skills 
so they can fully and ethically participate in a diverse society.</p>

<p><strong>Curriculum (BSSE) Program :: </strong> <a href="docs/curbsse.pdf" target="_blank"> Click here</a> </p>
<p>&nbsp;</p>
<p>&nbsp;</p>

<h3>Mission (BSAI)</h3> 
<p align="justify">The BS (AI) program gives the students an in-depth knowledge they need to transform large   and complex scenarios into actionable decisions. The program and its curriculum focus on   how complex inputs from the universe e.g. weather, galaxies, vegetations, human senses   (vision, audio, smell, taste, touch), perceptions, actions, emotions, human biology, languages   and various such disciplines in conjunction with databases are designed, processed and used   to make logical decisions via queries, reasoning, automation and betterment of existing   systems and environment. The curriculum of the BS (AI) program includes coursework in   foundations of mathematics, linear algebra, statistics, computing, automated reasoning,   modeling, case studies, machine learning, natural language processing, artificial neural   networks, large language models using classical till contemporary generations of artificial   intelligence models e.g. deep neural networks, graph neural networks, generative artificial   intelligence. The program also encourages students to take courses in ethics and social   responsibility, with the opportunity to participate in long term projects in which artificial   intelligence can be applied to solve problems that can change the world for the better — in   areas like agriculture, defense, healthcare, governance, transportation, e-commerce, finance   and education.</p>

