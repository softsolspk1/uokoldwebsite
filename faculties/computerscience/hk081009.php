        <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">A delegation of four members  representing the Universities of Hong Kong visited, University   of Karachi and delivered knowledge  about Hong Kong universities in a seminar at UBIT,  Department of Computer Science. Meritorious Prof. Dr.  S.M. Aqil Burney, briefed the delegation about University   of Karachi and Department of  Computer Science, UBIT.</font></p>
        <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Prof. Roland T Chin, Chair  Professor of Computer Science and Vice President for Academic Affairs,  Professor Dr. Ting-Chuen Pong, Department of Computer Science and Engineering  represented the Hong Kong University of Science and Technology. Dr. C. Roland  Vogt of School of Modern  Languages and Culture. &ldquo;The University of Hong Kong&rdquo; and Chan Shiu-lun, Anthony  of UGC-Hong Kong were also presented along with Dr. Farrukh of LUMS Lahore.</font></p>
        <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Prof. Roland T Chin presented  Hong Kong Ph.D Fellow Schemes on the basis of &ldquo;best and brightest&rdquo; should be in  Hong Kong and informed 135 scholarships on Ph.D level are  available at Global level irrespective of subject / fields. Also informed about  laboratories, research trends and excellence available in the 8 universities of  Hong Kong and informed all these universities of highest  rank. Professor Pong informed about Hong Kong   University of Science &amp;  Technology way of working and invited students, researchers of University   of Karachi to apply for Ph.D  scholarships in this University of one of the highest ranking Universities in Asia  and best at global level. Dr. C. Roland Vogt informed about humanities studies  in Hong Kong and cultural diversity present in Hong   Kong. After the seminar students of Department of Computer  Science, UBIT and of other Departments of the University asked questions and  discussed related issues with the delegation, More than 100 Students, Teachers,  Researchers from Economics, Physics, Statistics, Biological &amp; Social  Sciences attended the seminar. At the end delegation visited Vice Chancellor  office and the Vice Chancellor, Prof. Dr. Pirzada Qasim Raza Siddiqui presented  shield to the members of delegation and appreciated the effort being made by  Hong Kong for quality education at Ph.D level through Ph.D Fellowship programme  at global level.</font></p>
