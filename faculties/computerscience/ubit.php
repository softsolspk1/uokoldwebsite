  <p> Academic activities have already started at the UBIT on initiative of its director, Dr. Aqil Burney. After assuming the chairmanship of the department of computer science in March 2008, Dr. Burney did his utmost in facilitating the provision of basic academic necessities at the complex. It was due to his untiring efforts that classes of undergraduate and graduate levels are being conducted here. Moreover, UBIT is being used in parallel with the existing building of the DCS the reason being the presence of a strong infrastructure of academic activities that exists at the present building of DCS. At present, the department of Computer Science offers BS (Computer Science), BS (Software Engineering), MCS and MS/PhD programs. Besides these program conducted at the UoK campus, the department also conducts the Examination and Lab of BCS program of the affiliated colleges. As a result, the shifting is being conducted gradually as the academic and research facilities present at the UBIT is being strengthened with the passage of time. </p>
