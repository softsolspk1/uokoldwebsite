              </ol>
              <p><font face="Verdana, Arial, Helvetica, sans-serif"><font size="2"><strong><u>INSTRUCTIONS FOR THE APPLICANTS OF BS PROGRAM</u></strong></font></font></p>
              <p><font face="Verdana, Arial, Helvetica, sans-serif"><font size="2">Those who  are seeking admission on the basis of O/A level or any other qualification at  par with HSC are required to submit a copy of equivalence certificate issued by  the University of Karachi or Intermediate Board Chairmen&rsquo;s Committee (IBCC)  together with the application form otherwise their application will not be  entertained.</font></font></p>
              <p><font face="Verdana, Arial, Helvetica, sans-serif"><font size="2">Applicants  for BS Program who wish to avail of marks of Hifz-e-Quran should submit a  photocopy of their Hifz-e-Quran certificate alongwith their form. They are  reminded that 20 marks will be added to their total on the basis of  Hifz-e-Quran (candidate&rsquo;s grade or division is not changed on the basis of  these marks)</font></font><font face="Verdana, Arial, Helvetica, sans-serif"><font size="2">. </font></font>              </p>
              <p><font face="Verdana, Arial, Helvetica, sans-serif"><font size="2"><strong><u>INSTRUCTIONS  FOR CANDIDATES WHOSE NAME APPEARS IN THE ADMISSION MERIT LIST</u></strong></font></font></p>
              <p><font face="Verdana, Arial, Helvetica, sans-serif"><font size="2">Candidates whose names  appear in the admission list will have to complete all formalities for  admission within the stipulated time, otherwise their admission will lapse. The  following documents are to be submitted for completion of admission:<br>
              </font></font></p>
              <ol>
                <li><font face="Verdana, Arial, Helvetica, sans-serif"><font size="2">The original marks sheets of the last examination (Non returnable).</font></font></li>
                <li><font face="Verdana, Arial, Helvetica, sans-serif"><font size="2">Character certificate from the head of the institution last attended.  For external candidates a character certificate from any gazetted officer (non  returnable).</font></font></li>
                <li><font face="Verdana, Arial, Helvetica, sans-serif"><font size="2">The National Identity Card of the Candidate, or in case candidate is  below 18 years father&rsquo;s/mother&rsquo;s identity card with &lsquo;B&rsquo; Form and their  photocopies (the original will be returned after verification).</font></font></li>
                <li><font face="Verdana, Arial, Helvetica, sans-serif"><font size="2">The original certificate of Matric/H.S.C/ A / O Level, and an attested  copy of the same. (The original documents will be returned).</font></font></li>
