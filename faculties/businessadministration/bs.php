              <p><font face="Verdana, Arial, Helvetica, sans-serif"><font size="2">According to new education policy of Higher Education  Commission (HEC) Four Years BS (Bachelor of Studies) Program is introduced  beginning January 2007 Session. This program will be applicable for the  students admitted to Four Years BS Program from January 2007 Session. </font></font></p>
              <p><font face="Verdana, Arial, Helvetica, sans-serif"><font size="2">The BBA (Honors) and MBA programs presently offered will  continue till new Four Years BS Program reaches it final stage. MBA (Direct)  admission for two years studies will continue till Four Years BS Program  completes it period.<br>
                <br>
              Four Years BS Program consists of Eight Semesters. In all  there are 45 courses of study spread over four years. Total Credit Points in BS  Program will be 45*3=135  plus 3 credit hours of Project Research Report and Supervised Internship  Program which will be of 8 weeks.</font></font></p>
              <p><font face="Verdana, Arial, Helvetica, sans-serif"><font size="2">On successful completion of four years BS studies the  student will be entitled to receive BS Degree which is considered equivalent to  Masters degree. After receiving this four years BS degree the student can apply  for any post of 17 Grade. </font></font></p>
              <p><font face="Verdana, Arial, Helvetica, sans-serif"><font size="2">In case a student does not want to continue for full four  years degree program he/she has the option to quit studies after 2 years and  will get a BS (Pass) degree. Further he/she has another option of receiving BS  (Honors) degree after successful completion of 3 years studies. <br>
              </font></font></p>
              <h3 align="left"><font face="Verdana, Arial, Helvetica, sans-serif"><font size="2">ELIGIBILITY  FOR ADMISSION TO BS (BACHELOR OF STUDIES) &ndash;&nbsp;  4 YEARS PROGRAM</font></font></h3>
              <p><font face="Verdana, Arial, Helvetica, sans-serif"><font size="2">Admissions shall be open to  those who have passed Higher Secondary (Intermediate) Examination or Equivalent  Examination in at least second division marks (50 per cent) from recognized  Board. </font></font></p>
              <p><font face="Verdana, Arial, Helvetica, sans-serif"><font size="2">However, students who are  already graduates, or are presently enrolled for any graduation program in any  department, are NOT eligible for admission to BS program as enumerated under  Admission Criteria.</font></font></p>
