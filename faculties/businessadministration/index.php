  <h2>Chairman: Dr. Sheikh Muhammad Fakhre Alam Siddiqui (In charge)</h2>
  <p>The Karachi  University Business School (KUBS) was established in the year 1999-2000 because  Institute of Business Administration (IBA a constituent of University of  Karachi) was declared autonomous degree awarding institution. </p>
  <p>KUBS  within short period of eight years has become well established institution with  good reputation and high image in the business world. MBA (Banking and Finance)  two years professional program is also run jointly with Institute of Bankers  Pakistan (IBP). The admissions of which are announced separately. </p>
  <p>The  mission of KUBS is prepare right  leaders for the right organization. KUBS is committed to impart our  students general management education focused on building a deep understanding  of business, teaching with skill and passion. We intend to imbibe a sprit of  entrepreneurship and creativity among our students and prepare them for a  global community that is increasingly reliant on technology.</p>
<p>&nbsp;</p>
<h3><strong>Students&rsquo; Attendance &amp; Discipline</strong></h3>
<p>  Almost full attendance is desirable in the interest  of students themselves. However, leaving an allowance of exigencies like  sickness, a minimum of 85% is required, according to the decision of Academic  Council. A students having more than six absences in a course will not be  allowed to take semester examination and he/she will get an &ldquo;F&rdquo; grade (failure)  in the course concerned.</p>
<p>&nbsp;</p>
<h3>Teaching &amp; Research</h3>
  <ul>
    <li>In  addition to regular faculty members, eminent faculty is also drawn from outside  business organizations to share with students their practical experience  especially in those courses which are practical oriented.</li>
    <li>Case  studies, class presentations, questions-answers session, seminars etc. are  regularly conducted.</li>
    <li>Periodical  assessment of student performance through terminal exams, and final exam is  done. Term papers and research reports are also produced in almost all courses  by the students.    </li>
  </ul>
  <p>&nbsp;</p>
  <h3>Career Opportunities</h3>
<p>Tremendous  opportunities exist in the field of Banking, Finance, and Marketing in national  and multinational organizations. Our graduates are in great demand and highly  paid jobs are offered to them.</p>
