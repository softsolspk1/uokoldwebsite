          <td height="210" valign="top"><div align="justify">
              <h3 align="left"><font face="Verdana, Arial, Helvetica, sans-serif"><font size="2">MBA  (AFTER HONORS) FOR THREE YEARS BBA (HONORS) &ndash; 1 YEAR PROGRAM</font></font></h3>
              <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">The MBA (After Honors) Program for Three Years BBA (Honors)  students will consist of two semesters in 1 year with 6 courses in each  semester. Thus, there will be 12 courses. Total credit points will be (12x3) =  36.</font></p>
              <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif"><strong><u>MBA (MORNING) &ndash; 2  YEARS PROGRAM</u></strong></font></p>
              <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">The MBA (Morning) Program for graduates will consist of four  semesters in 2 years with six courses in each semester. Thus, there will be 24  courses. Total credit points will be (24x3) = 72.</font></p>
              <h3><font size="2" face="Verdana, Arial, Helvetica, sans-serif">MBA (EVENING) &ndash; 3 YEARS PROGRAM</font></h3>
              <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">The MBA (Evening) Program for graduates will consist of six  semesters in 3 years with four courses in each semester. Thus, there will be 24  courses. Total credit points will be (24x3) = 72.</font></p>
              <h3 align="left"><font size="2" face="Verdana, Arial, Helvetica, sans-serif">ELIGIBILITY  FOR ADMISSION TO MBA (MORNING)&nbsp; &ndash; 2 YEARS  PROGRAM &amp; MBA (EVENING) &ndash; 3 YEARS PROGRAM</font></h3>
              <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Admissions shall be open to  those students who have successfully completed their graduation in any field  (Science, Arts, Commerce, Engineering, and Medicine) with at least second  division marks (50 per cent) from any recognized University. </font></p>
              <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">ADMISSION PROCEDURE</font></p>
              <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif"><strong><u>AT THE TIME OF SUBMISSION OF FORM</u></strong></font></p>
              <ol>
                <li><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Powder Photocopy of National  Identity Card.</font></li>
                <li><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Powder Photocopies of mark  sheets of graduation examinations, Intermediate Examination, and a powder copy  of Matriculation Certificate.</font></li>
                <li><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Four recent passport size  photographs.</font></li>
                <li><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Students, who have passed  their requisite examinations from Private and Foreign  Universities and Foreign Boards are  required to obtain equivalence certificate from Karachi University.</font></li>
              </ol>
              <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif"><strong><u>INSTRUCTIONS  FOR CANDIDATES WHOSE NAME APPEAR IN THE ADMISSION MERIT LIST</u></strong></font></p>
              <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Candidates whose names  appear in the admission list will have to complete all formalities for  admission within the stipulated time, otherwise their admission will lapse.</font></p>
              <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">The following documents are  to be submitted for completion of admission:</font></p>
              <ol>
                <li><font size="2" face="Verdana, Arial, Helvetica, sans-serif">The original marks sheets of the last examination (Non returnable).</font></li>
                <li><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Character certificate from the head of the institution last attended.  For external candidates a character certificate from any gazetted officer (non  returnable).</font></li>
                <li><font size="2" face="Verdana, Arial, Helvetica, sans-serif">The National Identity Card of the Candidate, or in case  candidate is below 18 years father&rsquo;s/mother&rsquo;s identity card with &lsquo;B&rsquo; Form and  their photocopies (the original will be returned after verification).</font></li>
                <li><font size="2" face="Verdana, Arial, Helvetica, sans-serif">The original certificate of Matric/H.S.C/ A / O Level, and  an attested copy of the same. (The original documents will be returned).</font></li>
                <li><font size="2" face="Verdana, Arial, Helvetica, sans-serif"> 10 recent passport size photographs. </font></li>
                <li><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Affidavit by Oath Commissioner on Judicial paper (sample is  given in this booklet). </font></li>
                <li><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Original &amp; Photocopy of Certificate of Hifz-e-Quran  (only for Honors). The original will be returned after verification.</font></li>
                <li><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Payment of prescribed fee.</font></li>
              </ol>
              <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">After completion of the  above formalities, the candidate will have to fill in an enrolment form. Under  the University rules his/her admission will not be deemed complete until he/she  receives his/her enrolment card.</font></p>
              <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif"><strong>NOTE</strong></font></p>
              <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">All admissions to BS  Program and MBA two-year course of study are provisional, and subject to  verification of documents. Admissions obtained through forged documents or  incorrect statements shall be cancelled.</font></p>
