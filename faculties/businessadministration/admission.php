              <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif"><strong>ADMISSION POLICY</strong></font></p>
              <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Admissions in Karachi University are given according to merit.  There is no Discretionary Quota for admissions. Since the numbers of applicants  is much higher than the number of available seats under the University rules  the applicants have been divided into three categories i.e. <strong>K</strong>, <strong>S</strong>,  and <strong>P</strong>.</font></p>
              <ol>
                <li><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Category &ldquo;<strong>K</strong>&rdquo;. For <strong>BS Four Years </strong>program,  preference shall be given to those applicants, who have passed Secondary School  Certificate (SSC) and Higher Secondary Certificate (HSC) or equivalent  examination from an educational institution situated in Karachi and also  recognized by the University.</font> </li>
                <li><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Whereas, for admission  in <strong>MBA (Morning) </strong>degree program, in  addition to the SSC and HSC, preference shall be given to those applicants who  have also obtained graduation degree from an academic institution affiliated to  the University of   Karachi. Five percent  (5%) seats have been reserved for applicant who have done their graduation from  a non-public sector degree awarding institute situated in Karachi  and recognized by the University   of Karachi.&nbsp;&nbsp;&nbsp;</font></li>
                <li><font size="2" face="Verdana, Arial, Helvetica, sans-serif">The condition for <strong>MBA (Evening) </strong>applicants of having  passed the pre-requisite examinations during the last five years has been  relaxed and the category (<strong>K</strong>,<strong> S</strong>, &amp;<strong> P</strong>) criteria for admission  have been waived off.</font></li>
                <li><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Category &ldquo;<strong>S</strong>&rdquo; comprises those  applicants who have passed their pre-requisite examinations from a recognized  educational institution in the Province  of Sindh (Excluding Karachi)</font></li>
                <li><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Category &ldquo;<strong>P</strong>&rdquo; comprises those  applicants who have passed their pre-requisite examinations from a recognized  educational institution outside the Province   of Sindh.</font></li>
              </ol>
              <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Preference in admissions is  given to &ldquo;<strong>K</strong>&rdquo; category candidates. In  case seats are left &ldquo;<strong>S</strong>&rdquo; category  candidates are considered. If seats are still available then consideration is  given to &ldquo;<strong>P</strong>&rdquo; category candidates.</font></p>
              <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Admissions in the University  are given strictly as per above mentioned criterion of categories.<br>
                CHANGE OF CATEGORY</font></p>
              <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Candidates who fulfill the  following conditions can apply for change of category from <strong>S</strong> or <strong>P</strong> to <strong>K</strong>.</font></p>
              <ol>
                <li><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Those students whose father or mother is domiciled in Karachi, but who  have passed the requisite examination from any registered National or  International Institution outside Pakistan or from any recognized Pakistani  Board or University which conducts examinations in Foreign Countries and they  have passed their examination from abroad, such candidates will have to produce  their father's or mother's domicile certificate with their applications.</font></li>
                <li><font size="2" face="Verdana, Arial, Helvetica, sans-serif">Students whose parents are employees of the Federal or Sindh  Governments, or of autonomous or Semi-autonomous bodies or of Government  Corporations, or of the Armed Forces, who have been posted in or transferred to  Karachi within the last two years. Such applicants will have to produce the  appointment letter or transfer letter of their father/mother together with  their application.</font></li>
                <li><font size="2" face="Verdana, Arial, Helvetica, sans-serif">3% seats in each department will be allocated for those candidates who  have passed their pre-requisite examination from a recognized educational  institution located outside Karachi but they  have their initial education including Matric/Intermediate from Karachi. Such candidates  should have Karachi P.R.C. and their parents  should have Domicile and N.I.C. of Karachi.  Candidate below the age of 18 years are required to submit photocopy of  &quot;B&quot;-Form.</font></li>
              </ol>
              <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif"><strong>APPLICATION FOR CHANGE OF CATEGORY</strong></font></p>
              <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">All such applicants who  fulfill the criteria for change to category <strong>K</strong>, should attach with their forms an application on plain paper for  change of category together with their father&rsquo;s/mother&rsquo;s domicile certificate,  NIC and appointment/transfer letter. At the time of admission will have to  produce the original and photocopies of all documents.</font></p>
              <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif"><strong>DISCIPLINE COMMITTEE</strong></font></p>
              <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">There is a discipline  committee to maintain law and order situation and to ensure a proper academic  environment. The committee takes notice of the cases of infringement of law and  order and undesirable activities at the campus, and takes disciplinary action  against the offenders. The Vice Chancellor is Chairman of this Committee while  the Advisor, Student&rsquo;s Affairs its member secretary. The committee meets  several times a year to review the prevailing law and order situation and other  related matters and takes appropriate decisions.</font></p>
              <p><font size="2" face="Verdana, Arial, Helvetica, sans-serif">If any candidate has secured  admission on the basis of misinformation and/or fake documents, his/her  admission will automatically be cancelled and suitable punitive action will be  taken against him, which can extend upto being debarred from any educational  institution for three years.&nbsp; </font></p>
