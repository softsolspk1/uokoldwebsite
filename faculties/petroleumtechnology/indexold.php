  <h2>Chairman: Mr. Nadeem Ahmed Khan (Assoc. Prof.)<strong></strong></h2>
  <p>&nbsp;</p>
  <p>In the  mid 1990’s Karachi University envisaged the need of the job oriented studies  and established Petroleum Technology Department. Its syllabi were compiled by  the joint efforts of the Oil &amp; Gas industry and the academia. The vision  was to bring forward a generation taught and developed by the Professors of the  University and the scholars of the Petroleum Industry. These students are  capable to take over needs of the industry.</p>
  <p>Petroleum  Technology program is successfully running in the Faculty of  Engineering/Science along with Petroleum Industry scholars who are  participating in the guidance towards the state of the art direction and  teaching. The M.Sc. program covers the subjects of Exploration, Drilling, Well  Completion, Production, Reservoir, Natural Gas Engineering, Refining,  Economics, Environment &amp; Safety, Logistics and Industrial Management. The  program is such designed to include all aspect of Oil &amp; Gas Industry so  that student could adjust to different aspects/places in the industry.</p>
<p>&nbsp;</p>
<h3>Teaching and Assessment</h3>
<p>It is a two-year (4-semester) program of  20 courses of 3 credit hours each. The program includes theory classes six days  a week as well as practical, seminars and a six-week internship.</p>
An intensive study of  chemistry and geology of petroleum, drilling, well logging, reservoir, environmental  issues are required by the students. This program is mainly for fresh science  and production, refining, pipeline, corrosion and engineering graduates who  plan to enter petroleum industry or have recently joined.
<p>&nbsp;</p>
<h3>Career Opportunities</h3>
<p>Petroleum Technology program of  University of Karachi was initiated in 1996 following the policy of introducing  job-oriented technology programs at the University. The program aims to meet  the future requirements of technical and professional personnel in view of  growing participation of national and multinational companies and a prospect of  enhanced petroleum exploration and refining activities in Pakistan. </p>
<p>Pakistan has an expanding oil industry  with accelerated exploration activities, refineries, petrochemical industries,  and oil and gas distribution network. There is a job market at home, in the  Middle East and in other parts of the world.</p>
