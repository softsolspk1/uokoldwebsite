      <td colspan="2"><p align="justify">The University of Karachi  has 7 medical and dental colleges affiliated with it. The only public sector  college is Karachi Medical &amp; Dental College  and the Dean, Faculty of Medicine is the senior most professor of Karachi Medical &amp; Dental College.  The colleges running both MBBS &amp; BDS programmes are Karachi  Medical &amp; Dental College, Jinnah   Medical Dental   College and Liaquat  College of Medicine and Dentistry. Those running BDS programs alone are  Altamash Institute of Dental Medicine and Fatima  Jinnah Dental  College and those having MBBS  programme alone are Liaquat   National Medical   College and Sir Syed  College of Medicine. Admissions in this college are as per PMDC regulations.</p>
        <p align="justify">Over the past  years, there have  been vast changes in the Undergraduate and Postgraduate programmes of the University  in the fields of Medicine and Dentistry. The teaching methodology and the examination  system of the University has changed from MCQ system to the internationally  acclaimed Short Essay Questions and Best Choice Questions few  years ago.&nbsp; In this regard, training workshops for all faculty  are held twice a year under the supervision of the Dean. The Board of Studies  has constituted 2 committees, a Coordination Committee and a Quality Assurance  Committee for examinations. The Semester system is being studied for possible  implementation within the next year. </p>
        <p align="justify">The Postgraduate programmes in clinical  fields are the M.S. and M.D. programmes and in Basic Sciences, the MPhil, PhD.  Details of these are available on the <a href="/admissions/msphd/msmd.php">website</a>.</p>
        <p align="justify">The MS, MD programmes has changed  from a 2 year programmes to a full 4 year, structured programme with 1 year  course work at the University and 3 years clinical work in the supervisors  department. For Admission, clearing the University of Karachi Entry    Test is mandatory. Subsequently, candidates are  chosen on the basis of merit. The &nbsp;synopsis  of each candidate is reviewed by the supervisor and the Dean  before submission to the Board of Advanced Studies &amp; Research, University of Karachi for final approval. Standardization  of the Masters examination is ensured by having external examiners only, a  change which has been implemented recently. The curriculum of each specialty is  being reviewed by a M.S, M.D Curriculum Committee headed by the Dean.&nbsp; </p>
