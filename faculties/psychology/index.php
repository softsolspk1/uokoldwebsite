  <h2>Chairperson: Prof.  Dr. Farah Iqbal</h2>
  <p>&nbsp;</p>
  <p>The  department of Psychology came into existence in 1954 under the Chairmanship of  Professor Dr. Qazi Aslam. It gradually attracted both students and teachers  with the result that teaching and research psychologists like Dr. Haseen Uddin Zuberi,  Dr. S. M. Hafeez Zaid, Dr. Farrukh Z. Ahmed, Dr. Afzal Imam and Dr. M.Wasim led  the department to its present academic heights. It has now become one of the  leading departments of the Faculty of Arts.</p>
<p>Since  1956, the teaching and practice of Clinical psychology has enjoyed popularity  both amongst teachers and students of the department. Dr. Farrukh Z. Ahmad, the  then chairperson, took active steps to establish a separate institute of  clinical Psychology.</p>
  <p>The  department’s teachers are also members of the Sindh Psychological Association  and the Pakistan Psychological Association. They further act as subject  specialists in the Provincial and Federal Public service commission for the  appointment of teachers in colleges. Seminars, lectures, mental health camps,  picnics, students’ week, welcome and farewell parties etc. are arranged for the  students so that they remain updated with current happenings and also get a  chance to take a break from study schedules.  </p>
  <p>&nbsp;</p>
  <h3>Teaching and Assessment</h3>
  <p>Teaching  is based on interactive class participation: group discussions, class  presentations by students, assignments, research work etc. to maintain interest  and make learning more effective. The use of audio visual aids brings out the  creativity of teachers and students, and helps in improving their presentation  skills. Assessment is based on class performance of students, their  punctuality, assignments and particularly the semester examination results.</p>
<p>&nbsp;</p>
<h3>Career  opportunities </h3>
<p>After  doing Masters in Psychology (Clinical/Industrial/ Educational /Investigative  Psychology), the students can pursue careers in any of the following fields:  Organization, NGOs’ clinical setup, educational institutes, law enforcement  agencies, the armed forces etc.</p>
