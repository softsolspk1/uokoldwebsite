  <h2>&nbsp;</h2>
  <h4 align="center">(Revised in RPEC Meeting on 10.10.2009)</h4>
  <p align="center">&nbsp;</p>
  <table border="1" cellspacing="0" cellpadding="0" width="95%">
    <tbody>
      <tr>
        <td valign="top"><p align="right"><strong>1.</strong></p></td>
        <td valign="top"><p>The requests made for the financial assistance from the Research Facility Centre, Faculty of Arts, will be considered by the R.P.E.C (Research Proposals Evaluation Committee). Application should be sent through proper channel and the following requirements are to be completed:-</p>
          <ol>
            <li>Application proforma duly filled having estimated budget not exceeding Rs.65,000/- with proper justification of the expenditures.</li>
            <li>Synopsis including methodology of research (qualitative, quantitative, investigative / survey based or based on literature review)</li>
            <li>Bio-Data of the researcher/s (having academic qualification at university level and research experience).</li>
          </ol></td>
      </tr>
      <tr>
        <td valign="top"><p align="right"><strong>2.</strong></p></td>
        <td valign="top"><p><strong>(a)</strong>  Ceiling for Research Grant for each research project is fixed upto Rs.65,000/-.<br />
          <strong>(b)</strong>  Research grant will be allowed for the following heads only:</p>
          <ol>
            <li>Books, Journals, monographs etc. provided these are not available in Dr. Mehmood Hussain Library, University of Karachi, Seminar Library of the Department or not available on internet.</li>
            <li>Photocopying of relevant research material.</li>
          </ol>
          <p><strong>(c) (i) </strong>Traveling one round trip airfare to any one place within the country, subject to the requirement of the study. <br />
            <strong>(ii)</strong> Daily allowance as admissible under University rules during visit. (not exceeding more than 10 days)<br />
            <strong>(iii)</strong> Traveling within Karachi (Rs.300/- per trip upto maximum Rs.5,000/-).<br />
            <strong> (iv) </strong>Traveling outside Karachi by road or by rail as per University Rules.</p>
          <ol>
            <ol>
              <li>Data processing charges not exceeding 25% of the approved grant. However, in cases where the sample of study is not enough to warrant extra expenditures, data collection charges may be extended upto 35%.</li>
              <li>Stationery (Actual expenses)</li>
              <li>Typing on current rates of RFC (Actual expenses)</li>
              <li>Assistantship where the project requires Assistant/s (at least graduate or equivalent). The assistant shall be paid @ Rs.2,000/- per month for the stipulated period of the research project subject to a maximum limit of Rs.12,000/-. The principal researcher will be allowed to engage more assistants for shorter period where the total amount does not exceed what might have been paid to one. (CV of appointed person/s should be submitted to the RFC for information)</li>
              <li>Low-priced equipment such as calculators and card cabinets etc.</li>
              <li>Miscellaneous including mailing charges etc.</li>
            </ol>
          </ol>
          <p><strong>(j)</strong> <strong>(i)</strong>   All items other than consumable items, such as books, calculators, file cabinets etc. purchased from the allocated research grant be deposited with the Research Facility Centre. The same can be given to the concerned department of the researcher.<br />
            <strong>(ii)</strong>      Photocopies of books should also be returned to the RFC in proper binded form, in case if their cost equals to or exceeds Rs.3000/-.</p></td>
      </tr>
      <tr>
        <td valign="top"><p align="right"><strong>3.</strong></p></td>
        <td valign="top"><p>Grant for following heads will not be allowed:</p>
          <ol>
            <li>Purchase of costly equipment (exceeding from Rs.5000/-) including computer, typewriter, microscope, voice recorder, still/movie camera etc.</li>
            <li>Purchase of furniture, air-conditioner, mobile phone etc.</li>
            <li>Purchase of encyclopedia and other costly reference material including manuscripts.</li>
            <li>Travel to foreign countries.</li>
            <li>Purchase &amp; installation of telephone, telefax machine or television set etc.</li>
            <li>Purchase of Photocopying or cyclostyling machines etc.</li>
          </ol></td>
      </tr>
      <tr>
        <td valign="top"><p align="right"><strong>4.</strong></p></td>
        <td valign="top"><p><strong>(a) (i) </strong>Financial Assistance can be given towards typing, photocopying and binding of M.Phil/Ph.D. thesis at the rate of Rs.40/- per page not exceeding Rs.15,000/-. Incase of typing, photocopying and binding of M.Phil. thesis, the financial assistance can also be offered not exceeding Rs.10,000/-.<br />
          <strong>(ii)</strong> Payment will be made when the thesis is ready for typing. The application for this purpose should be forwarded by the Supervisor / Chairperson of the concerned department.<br />
          <strong>(b)   </strong>The receipts of all expenses as mentioned in <strong>4(a)(i)</strong> is to be duly certified by the supervisor.<br />
        </p></td>
      </tr>
      <tr>
        <td valign="top"><p align="right"><strong>5.</strong></p></td>
        <td valign="top"><p>Grant will be released in three instalments, after consideration by the Research Proposals Evaluation Committee and approval by the Vice Chancellor as per following detail:</p>
          <ol>
            <li>First instalment equal to 25% of the total allocated research grant</li>
            <li>Second instalment equal to 25% of the total allocation on receipt of the audited accounts of 1st instalment alongwith the progress report,</li>
            <li>Third instalment (of actual expenses not exceeding 50% of the total allocation) will be reimbursed/released on completion of the said project, on receipt of the audited accounts of the total expenditures alongwith a soft copy and three hard copies (binded form) of final report of the study after consideration by the Research Proposals Evaluation Committee.</li>
          </ol></td>
      </tr>
      <tr>
        <td valign="top"><p align="right"><strong>6.</strong></p></td>
        <td valign="top"><ol>
          <li>Each grantee will submit a quarterly report of his/her work to the Research coordinator for consideration by the Research Proposals Evaluation Committee.</li>
          <li>Each grantee, on completion of project, will submit a soft copy and three hard copies of the final report with proper documentation in hard binding, which will be presented before the Research Proposals Evaluation Committee for acceptance.</li>
        </ol>
          <p> </p></td>
      </tr>
      <tr>
        <td valign="top"><p align="right"><strong>7.</strong></p></td>
        <td valign="top"><p>Retired University teachers will not be considered for research grant except as co-researchers.</p></td>
      </tr>
      <tr>
        <td valign="top"><p align="right"><strong>8.</strong></p></td>
        <td valign="top"><p>In case a grantee:</p>
          <ol>
            <li>fails to complete the study in the specified or allowed time and does not apprise the committee of the reason for it, or</li>
            <li>does not submit the report as required vide rule no.6, or</li>
            <li>does not submit the accounts, as required</li>
            <li>does not return the un-consumable items, books, photocopies of articles/books/journals or other reference material, costing more than or equal to Rs.3,000/-,</li>
          </ol>
          <p>the grant will be recovered through accounts section in:</p>
          <ol>
            <li>six equal instalments from in-service faculty members deducted from their monthly salary or</li>
            <li>ten equal instalments from retired faculty members deducted from their monthly pension</li>
          </ol></td>
      </tr>
      <tr>
        <td valign="top"><p align="right"><strong>9.</strong></p></td>
        <td valign="top"><p>No researcher will be given the grant for more than one projects at a time except in case where the applicant is working as a co-researcher in any other project.</p></td>
      </tr>
      <tr>
        <td valign="top"><p align="right"><strong>10.</strong></p></td>
        <td valign="top"><p>Whenever a researcher will need an additional grant, he will apply to the Research Proposals Evaluation Committee giving proper justification for such a request.</p></td>
      </tr>
      <tr>
        <td valign="top"><p align="right"><strong>11.</strong></p></td>
        <td valign="top"><p>With the prior permission of the Evaluation Committee, the principal researcher may reallocate money from one item to any other item provided that it does not exceed the total amount allocated.</p></td>
      </tr>
    </tbody>
