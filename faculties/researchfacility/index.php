  <h2>Research Coordinator: Dean, Faculty of Arts</h2>
  <p>&nbsp;</p>
  <p>The centre was established on the recommendations of the University of Karachi Syndicate’s meeting held in 1987.  The main objective of the center is to motivate, mobilize and facilitate the teachers of the Faculty of Arts to take interest in research and pursue their work to upgrade and equip themselves with the latest developments in their respective fields.</p>
  <h3>Facilities</h3>
  <p>The centre is equipped with a computer lab to facilitate the teachers in typing/composing (Urdu and English), and Internet browsing, and also a photocopying section to get the photocopies of their research projects / theses / papers etc on very nominal rates as decided by the Research Proposals Evaluation Committee (RPEC).</p>
  <h3>Finances</h3>
  <p>The centre receives grants from the University of Karachi for the research work. It also generates revenue from the services from photocopying, typing and composing on very nominal rates as decided by the RPEC. The financial affairs of the centre are also maintained from the research grant.</p>
  <h3>Functions of the Centre</h3>
  <p>The Research Coordinator (nominated member of the Research Proposals Evaluation Committee) is the Incharge of the centre and supervises the routine official work including correspondence and ensures implementation of the recommendations made by the committee (approved by the Vice Chancellor) under the intimation to the Dean, Faculty of Arts. </p>
