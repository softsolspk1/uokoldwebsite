  <h2>Annual  Research Talk (ART)</h2>
  <p align="justify" style="line-height:1.5">ART is an annual research showcasing event organized by Department of Physiology, University of Karachi. The event has successfully been executed since 2017 by the departmental Seminar Committee.</p>
    <p align="justify" style="line-height:1.5">The primary objective of ART is to provide a platform to the young researchers and set a stage to display their research activities at all academic levels from undergraduate to doctorate programs. The format of ART is very dynamic and encompasses various aspects of contemporary research findings too which are shared with students by eminent scholars particularly prevailed health issues in our community and their doable local solutions either preventions or precautions. The postgraduate research fellows who recently awarded M. Phil. and/or Ph.D. also present their ideas and significant findings to inspire the future scholars. Not limited to this, the students are encouraged to prepare thematic posters to enhance their reading, extracting and presenting skills along with dissemination of recent updates on a particular topic.</p>
    <p align="justify" style="line-height:1.5">The thematic and original research contributions are then gone through a blind assessment by a jury and shields & certificates are presented to three best posters under different categories of academic levels as token of appreciation.</p>
    <p align="justify" style="line-height:1.5">The event welcomes all biosciences students and usually contributions are made by scholars of other students within university or from other universities.</p>
