  <p>&nbsp;</p>
  <p>The Department of Physiology is an important segment of  the Faculty of Science, University of Karachi and occupies a very prominent  place in the modern age of Biosciences, Clinical/Biomedical Sciences and other  Applied Biological Sciences. This department, founded by Prof. Dr.  Mahmood Hussain Qazi in 1964 was the first one outside medical colleges to  introduce teaching and research programs in Basic and Experimental Physiology  at the graduate and postgraduate levels. This department is the only institute  in the country which has produced M.Phils. and Ph.Ds. in various disciplines of  Physiology over the past many years.</p>
