  <h2>Chairman:  Prof. Dr. Abdul Wahab Suri</h2>
  <p>&nbsp;</p>
  <p align="justify">The Department of Philosophy was  founded in 1952. It is the first department that came into existence in the  faculty of Arts initially (now the faculty of Arts and Social Sciences)  University of Karachi. DR. M.M. Ahmed a man of saintly wisdom and Philosophical  acumen, was the founder Chairman of the Department. From the very beginning,  the department has remained committed to fostering a wide variety of  Philosophical approaches and has gradually evolved towards developing links  between philosophy and other disciplines. The member of its teaching staff  include Professors and Lecturers. All teachers are strongly committed to  teaching and research and have contributed through their publications  significantly in the advancement of learning. Moreover, its senior faculty  members have also served on important positions of responsibilities in other  areas is the Chairman of the department.   <br />
    Philosophy Department is  committed to a variety of approaches. Researches pursued by its faculty members  and students involve living issues from History of Philosophy, Meta-logic,  Phenomenology, Existentialism, Ethics, Analytical Philosophy, Concept of self,               Postmodernist Thought, Islamic  Modernism, Philosophical Anthropology, Critical Theory, Hermeneutics,  Philosophy of Art, Philosophy of Mind,   Pragmatism etc. The  department has enough human resources to produce high quality researchers in the  field of Philosophy of Law, Postmodern Philosophy, Muslim Philosophy, Aesthetic  Bio-ethics etc.</p>
