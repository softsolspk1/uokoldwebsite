  <h2>Chairman: Mr. Syed Shamoon Haider (In charge)</h2>
  <p align="justify">The Department of Visual Studies has completed its first decade, graduating innovative and award winning designers, architects and artists, who are making their mark in the professional world. The Department of Visual Studies sees itself as a bridge between tradition and innovation. Courses are interdisciplinary and contextualized. A strong theory component alongside practical and professional courses distinguishes the curricula of the Department. A dedicated faculty supported by visiting faculty from professional fields and the university’s own pool of excellent scholars, provides training that is current and professional. Students are encouraged to widen their experience and engage with the larger issues within which they will practice.</p>
  <p>We live in a rapidly changing world that needs responsible solutions for its many unfolding challenges. With 70% of Pakistan’s population below the age of 25, the future lies in the hands of our youth. The graduates of the Department of Visual Studies have the opportunity to influence social perception, the built environment, and determine the cultural legacy of their times. History of ideas, sociology and researched dissertations are some of the ways in which students develop analytical skills, and measure their designs against their social, cultural, economic and environmental impact. Uniquely placed within Pakistan’s largest University, with 52 departments and 20 postgraduate institutes offering a wide range of studies in the sciences and humanities, the students of the Department of Visual Studies are exposed to students and faculty across all academic disciplines.</p>
  <p>Future plans include postgraduate studies, an evening programme of short courses for professionals wishing to acquire further training.</p>
  <h3>&nbsp;</h3>
  <h3><strong>Teaching and Assessment</strong></h3>
  <p>Student assessment is based on practical assignments given  throughout the term and examinations held at the end of each semester. Passing  percentage is 50% in each course, and the result is is calculated on the basis  of G.P.R. A student must have obtained a CGPR of 2.45 in order to be awarded a  degree.</p>
  <p>&nbsp;</p>
