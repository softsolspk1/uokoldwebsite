<h3>FOUNDATION STUDIES</h3>
<p align="justify">All specializations begin with a one year of foundation studies introducing students to a wide range of basic skills. Subjects introduced in the first year will be drawing, design, draughting, materials &amp; processes and contextual studies. The objective of these preparatory courses, which are compulsory, is to provide the basic skills and knowledge necessary to engage productively in the subsequent years of training in the chosen specialization.</p>
  <p align="justify">&nbsp;</p>
  <h3 align="justify">ARCHITECTURE</h3>
  <p align="justify">The Architecture programme seeks to produce Architects capable of design solution in the context of social and technical research and innovation. The course consists of Architectural Theory and History, Building related Technologies, Service and Materials, Communication Skills and the application of these in Studio Practice. The Program acknowledges the digital revolution, introducing computer-aided design in the secondary year of the course.<br />
  </p>
  <p align="justify">Practical on-site experience and visits to relevant locations, along with their documentation and analysis, are undertaken to help the student relate the issues of the built environment issues.<br />
    A four-month internship program allows the students to gain valuable practical experience leading to a graduating degree project.</p>
  <h3 align="justify">FINE ART</h3>
  <p align="justify">Fine Art course is an integrated programme that emphasizes concept development and encourages the student to explore creative expression within the contemporary cultural and intellectual discourse.<br />
</p>
  <p align="justify">Students are encouraged to use a wide range of media, materials and processes. Drawing is a key discipline. Art history and art theory will supplement concept development.<br />
    Traditional disciplines of painting, miniature, sculpture and printmaking are offered along with photography and AV media studies.<br />
  </p>
  <p align="justify">Critical analysis and awareness of one&rsquo;s place within regional and international developments prepares students to engage with current art concerns.<br />
    Students are expected to present a self-directed body of work that can be interdisciplinary or in one medium their choice.</p>
  <h3 align="justify">ISLAMIC ARTS</h3>
  <p align="justify">Islamic Arts has a practical curriculum with a theoretical base exploring surviving Arts and Crafts practices throughout the Islamic World.<br />
</p>
  <p align="justify">The underlying philosophy of this programme acknowledges the Islamic Arts as a vibrant subject of great relevance to the Muslim world.These arts need to be revived at a practical level to supplement the theoretical treatises and the cataloguing and documentation by Muslim and Western scholars.</p>
  <p align="justify">Local and world wide masters of Muslim arts &amp; crafts will be invited to teach the main modes of expression such as Architectural detailing, Textiles, Carpet Weaving, Ceramics, Silver/Gold-smiting, Metalwork and Jewellery, and the &lsquo;Arts of the Book&lsquo; including binding, illumination, gilding and miniature painting.</p>
  <h3 align="justify">ART HISTORY</h3>
  <p align="justify">The Art History programme encourages the students to look critically at the History of Art and Ideas. Contemporary South Asian art, global art practices, and historical accounts of the developments in art as presented in the Euro-American &ldquo;Grand Narratives&rdquo; of art history are studied in depth, but also re-examined through the post-colonial perspective of cultural studies.<br />
</p>
  <p align="justify">Research is an important component of this course and students are expected to present a substantial research paper at the end of the course. History and criticism of art &amp; design and tutorials on related areas of philosophy, literature and the performing arts are incorporated. This is a theory course; however, students supplement their studies with a studio course of their choice.</p>
  <h3 align="justify">INDUSTRIAL DESIGN</h3>
<p align="justify">Industrial Design is an inter-disciplinary profession that interfaces between art and technology to conceive design and develop products for the home, the work place and public amenities.</p>
  <p align="justify">The Industrial Design programme facilitates a wide range of learning experiences including imaginative speculation on design solutions; hands-on practical fabrication of drawings, 3D models and computer representation of design ideas; and the articulation of theoretical frameworks for understanding design ideas within a historical and cultural context.</p>
  <p align="justify">Emphasis is placed on social responsibility and the environmental impact of designed products, use of materials and waste management. Evaluating and contemporizing traditional crafted products is an important part of improving standards of living. Individual guidance gives students the flexibility to produce designer for industry as well as small workshop practice.</p>
  <h3 align="justify">TEXTILE DESIGN</h3>
<p align="justify">The Textile Design programme aims to prepare design students for a role in the textile industry, both for clothing and furnishing textiles, accessories and for adding value to traditional crafts.</p>
  <p align="justify">Professionals, technical and design skills are encouraged for a range of printed, woven, knitted and embroidered textile products, and their application for clothing and furnishing. Block and screen-printing, transfer processes, dyeing, experiences of fabric and weaving on looms are more of the skills taught.</p>
  <p align="justify">Internship and workshop are arranged as an essential part of the curriculum. Students are required to engage in detailed research of traditional and modern textile processes, including visits to craft communities.</p>
  <h3 align="justify">DESIGN &amp; MEDIA ARTS</h3>
<p align="justify">Design &amp; Media Arts acknowledges the wider application of Graphic Design, Electronic Media and Advertising practice.</p>
  <p align="justify">Areas of study are divided into two option: Print Design or  Media Arts. Design includes advertising, information graphics, typography, packaging, printmaking, printing-press technology, photography, illustration, computer graphics, editorial design. Media Arts include camera, pre/post production, animation, photography, illustration and marketing.<br />
    Both disciplines take into consideration the multi-cultural and economically polemic markets, critiquing the place of design and media practice in culturally complex societies. Seminars and a strong theory component ensures awareness of cultural needs and responsible practice within existing socio-economic contexts.</p>
  <h3 align="justify">CERAMICS &amp; GLASS</h3>
<p align="justify">The Ceramics &amp; Glass programme focuses on studio ceramics and creative glass making. Students are given hands-on experience of the range of skills and processes, including wheel-throwing, slab and mold building, firing techniques, glazing, glass forming etc. Emphasis is placed upon experience and training in developing individually produced ceramic and glass works for the designer in individually workshop practice. Knowledge of the workings of ceramics and glass industry is made available for those intending to establish production workshops.</p>
  <h2 align="justify">Assessment</h2>
<p align="justify">Student assessment is based on practical assignments given throughout the term and examination held at the end of each semester. At the end of each semester there is a portfolio assessment. Students are counseled on their over all progress. Home assignments supplement classrooms projects.</p>
  <h3 align="justify">Grading</h3>
  <p align="justify">Passing percentage Is 50% in each course. The grades given to the students are expressed as a Numerical Grade (NG), an equivalent Alphabetical Grade (AG) and a Grade Point (GP). Grade Point Ratio (GPR) and a Cumulative Grade Point Ratio (CGPR) will be calculated.</p>
