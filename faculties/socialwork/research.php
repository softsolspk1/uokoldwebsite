  <p>&nbsp;</p>
  <p>&ldquo;Pakistan  Journal of Applied Social Sciences&rdquo; is launched under the patronage of Prof.  Dr. Mohammad Qaiser, Vice Chancellor-University of Karachi by the Department of  Social Work-University of Karachi on 8th March 2014. Its Special  Issue was published on 55th Anniversary of the Department on 8th  September 2016.</p>
  <p>    <strong><u>Aim:</u></strong> The Journal is focused on the development of the knowledge of Social sciences  by providing an intellectual platform for the  national and international scholars to showcase their research work. It  includes analytical review of researches, case studies, theoretical articles  pertaining to social sciences research, evaluation studies and diverse research  studies that contribute to the discipline of social sciences.</p>
  <p><strong><u>Topics covered</u></strong> : The journal publishes research papers in the fields such as  anthropology, business studies, communication studies, criminology,  cross-cultural studies, development studies, economics, education, geography,  history, information science, international relations, law, linguistics,  library science, media studies, methodology, philosophy, political science,  population Studies, psychology, public administration, sociology, religious  studies, women studies and many more.</p>
  <p><strong><u>Publication  Frequency:</u></strong> It is biannually as well as  bilingual published journal. Paper is immediately published after getting  approval from reviewers. Author can see the current status (submission is under  process, under review, accepted etc.) of paper anytime on website.&nbsp;</p>
