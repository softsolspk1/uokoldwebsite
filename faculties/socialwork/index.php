  <p align="justify">The Department of Social Work was  established in 1961 and it has continuously responded to the societal and  corporate needs by developing trained professional social workers. The  department boasts of having very successful alumni.</p>
  <p align="justify">The Department strives to strike the right balance by  creating a strong base of theoretical inputs combined with a rigorous  Industrial / NGO exposure of nearly 12 credit hours, through the field work  training which is an important part of the curriculum. Through this training,  students are provided opportunities to integrate their theoretical knowledge  with the practical world and enquire hands on experience to deal with the  variety of complex societal problems as challenges. The students are placed in  government and non-government organizations for obtaining knowledge in the  fields of community development, school, social work, and medical social work.  The students of M.A final year are bound to carry out research projects to be  submitted at the end of the year.</p>
  <p>&nbsp;</p>
  <h3>Teaching  and Assessment</h3>
<p align="justify">Students  are involved in theoretical discussions, research activities, symposia,  lectures and dialogues with different NGO’s. Assessment is by means of  examinations (semester examination and midterm tests) assignments and other  written and oral presentation.</p>
