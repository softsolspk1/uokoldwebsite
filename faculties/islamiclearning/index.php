  <h2>Chairman:   Dr. Muhammad Arif Khan Saqi</h2>
  <p>Department of  Islamic Learning is one of the oldest departments of the University of Karachi  and was founded in 1954 to fulfill the need of scholars of Islamic studies in  various institutions of Islamic Republic of Pakistan. The department aims to  promote the study of Islamic thoughts and offers an opportunity to study Islam  on Graduate &amp; Post Graduate level. The M. S. and Ph.D. program in the  department of Islamic learning covers the general areas of Islamic Studies with  special focus on the modern and contemporary issues. The area of Islamic thought,  Islamic Economics, Comparative Religion, Islamic Sociology and Muslim Political  thought are also be pursued in the Ph.D. Program.</p>
  <p>The  department is situated in a beautiful building of Islamic Studies near  Masjid-i-Ibrahim. In this department students are learning Islamic sciences  like Tafseer, Hadith, Seerah, History, Islamic Jurisprudence, Principles of  Islamic Jurisprudence, Mysticism, Ethics, Philosophy and Arabic. The department  is producing scholars for educational, religious and social institutions for  the country and abroad. </p>
