  <h2>Director: Prof. Dr. Nasreen Aslam Shah</h2>
  <p align="justify">Shaheed Mohtarma Benazir Bhutto (SMBB) Chair  is a non-profit research initiative that was established on 12th  November 2008 at University of Karachi, Sindh, Pakistan. Culture &amp; Tourism department Govt. of  Sindh initiated a proposal to establish chairs in her name in various universities  of Sindh such as University of Karachi, SMBB Chair for research  initiatives on the vision and mission of Mohtarma Benazir Bhutto. The Chair was  established to conduct research, develop a rich Resource Center cum Library, to  promote her democratic pursuits and link them with the national and global  research initiatives. It will ultimately support gender, especially women &amp;  youth. SMBBC would place a unique example of research on democratic themes that  would ultimately help the chair to create and strengthen regional &amp; global  synergy with the think tanks working on promotion of peace, democracy and  coexistence of diversity all over the world. <br />
    SMBB Chair is documenting all the  important events in the life of Shaheed Mohtarma Benazir Bhutto and encourages  scholars, intellectuals and researchers to undertake research on different  aspects of her life. She was a leader of international repute and wanted to  contribute time, energies and ideas for peace and prosperity here and elsewhere  in the world.</p>
