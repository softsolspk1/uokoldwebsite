  <h2>Chairman:  Prof. Dr. Muhammad Ali.</h2>
  <p>&nbsp;</p>
  <p>Department  of Political Science was established in 1952. It has since then initiated  programs for the award of research degrees of M.Phil. and Ph.D. in Political  Science and its allied fields.</p>
  <p>The  Department of Political Science has been playing an important role in the  overall development of the University. It has been the mother of the  Departments of International Relations, Sociology and Public Administration. At  present the department is second in the Faculty of Arts, after Economics, in  terms of the number of students enrolled.</p>
  <p>The Department has, since its inception, very qualified and competent  persons in its faculty. Professor (Late) Ilyas Ahmed, Professor Dr. M. Aziz  Ahmed; Prof. Dr. Manzooruddin Ahmed, Professor Dr. Syed Adil Hussian, Professor  (late) C.A Salahuddin, Professor (Late) Waheedud-din Kadri, Professor (Late)  Syed Sadique Hussain, Prof. (Late) Dr. Syed Shahid Ali Rizvi, Prof. (Late) Dr.  S. Rizwan Ali Rizvi, Prof. Dr. Arshad S. Karim, Prof. Nihal Hasan Rizvi, Prof.  Dr. Tanveer Khalid and Dr. Hafiz M. Abdullah Qadri have served the Department  with distinction. </p>
  <p>&nbsp;</p>
  <h3>Teaching and Assessment</h3>
  <p>Besides  regular lectures delivered in both English and Urdu by the faculty the students  participate in Seminars/ workshops and group discussions. Special lectures by  visiting faculty are also attended by students compulsorily.</p>
  <p>&nbsp;</p>
<h3>Career  opportunities </h3>
<p>In  addition to teaching and research positions in academic settings, Political  Science degree holders are prepared for careers at all levels of government as  well as journalism, International business, International risk analysis and  Political campaign organization their skills of surveys and statistical  analysis is in high demand in the public and private sectors. Their knowledge  and scientific education on current affairs, both national and international,  caters to the needs of the job market especially competitive exams.</p>
