  <h3 align="center">Master in Public Policy <br />
    (Two Years Evening Program) </h3>
  <h3 align="center">&nbsp;</h3>
  <h4 align="justify">Introduction</h4>
  <p align="justify">The Department of Political Science is one of the oldest and largest departments of the University of Karachi. It was established in 1951 and has been offering Bachelors, Master, M.Phil, M.S and Ph.D. programs. Later, departments of International Relations and Public Administration shooted off from the Department of Political Science.  In view of the contemporary trends in governance and public policy matters, the Department of Political Science is offering a two year Master’s program in Public Policy (MPP). Development, management and periodic analysis of public policy is an urgent need of the developing countries .Producing competent and capable manpower for this purpose is the responsibility of the universities. The University of Karachi, as the largest highest seat of learning, has been a leader in the higher education. The Public Policy programm promises a high intellectual level and scholarship for its prospective students</p>
  <h4 align="justify">&nbsp;</h4>
  <h4 align="justify">Objectives</h4>
  <p align="justify">The main objective behind MPP program is to prepare professionals in the field of Public Policy to take up the challenges of globalization .It is also aimed to help students to understand the leadership and the managerial tasks that come up in real life situations. MPP graduates have dual advantage over other graduates as they will have an understanding of the administrative issues of public sector as well as the ways and means to tackle the administrative problems. The program aims at providing career opportunities for the students by:  </p>
  <ul>
    
    <li>Preparing students for administrative careers in public sector and private organizations with qualities of leadership.</li>
      <li>Imparting both the theoretical and practical knowledge of the related fields.</li>
      <li>Enhancing the decision making power of the students.</li>
      <li>Making the students comprehend environmental issues  and development strategies</li>
      <li>Equipping the students with the analytical ability to understand the current financial &amp; administrative issues.</li>
</ul>
<p>&nbsp;</p>
