  <h2>&nbsp;</h2>
<p align="justify">Scope of Biotechnology Integration of  biological sciences with other disciplines particularly chemistry and process  engineering has resulted in the emergence of novel concepts and technologies  with applications in and consequences for agriculture, medicine, health care,  industry, environmental pollution cleaning of oil spills in the seas,  development of safe and environment-friendly bioinsecticides, energy generation  and several other sectors of activity.</p>
<p align="justify">The common denominator which links these  areas together are cells and products derived from them.</p>
<p align="justify">The use of bio-cellular materials in  conjunction with chemical and process engineering have ushered in a new kind of  revolution wherein it is possible to create transgenic animals plants and  microbes which otherwise could not have come into being in the foreseeable  future.</p>
<p align="justify">For that matter without Biotechnology it  would not be possible to create bio-degradable plastics or try to replace  defective genes with good ones in patients afflicted with potentially or  certainly fatal hereditary diseases.</p>
<p align="justify">The pivotal role in the unfolding  biotechnological revolution is of the recombinant DNA technology popularly  known as Genetic Engineering. Major Problems facing Pakistan These are:</p>
<p align="justify">Providing adequate food, both from the  agricultural and animal husbandry sectors, for a fast-growing population.</p>
<ul>
  <li>Low productivity.</li>
  <li>Salinity.</li>
  <li>Water-logging.</li>
  <li>Water shortage.</li>
  <li>Use of pesticides,  which have injurious effect on plants, soil and ecology.</li>
  <li>Shortage of  energy, and unwise use of our limited gas resources as fuel.</li>
  <li>Pollution (air,  water and noise).</li>
</ul>
<p align="justify">Use of industrial processes which are  either capital-intensive or high-energy consuming or both, and in which our national  resources are already over-strained.</p>
<p align="justify">Biotechnology offers processes which are  less expensive, less injurious and yield speedier results. But the question of  use of appropriate technology demands not only proper study and selection of  the processes evolved by the developed countries but also their adaptation to  suit our needs.</p>
<p align="justify">In addition, we have to build up the  requisite infrastructure and develop our human resources to create a highly  trained cadre of scientists, research scholars and technicians.</p>
<p align="justify">While Pakistan has a couple of institutes  providing facilities for postgraduate research and training, there is no  department or institute which provides for organized teaching in biotechnology  at all levels i.e. undergraduate, graduate and post-graduate. The newly  established department will fill this gap.</p>
<p align="justify">The graduating students will be able to  play a significant role in the national development through their services  rendered to educational institutions, R&amp;D organizations and existing and  future industrial setups.</p>
<p align="justify">Alternatively, they will be able to  effectively compete for admission in foreign institutions for doctoral and  post-doctoral training or for jobs in biotechnology companies.</p>
