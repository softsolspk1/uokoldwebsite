  <h2> Chairperson: Dr. Raheela Rahmat Zohra (Assoc. Prof.)</h2>
  <p>&nbsp;</p>
  <p align="justify">The  Department was established in 1996 with an objective of imparting quality  education in the multidisciplinary field of Biotechnology at both undergraduate  and postgraduate levels.</p>
  <p align="justify">Biotechnology  is defined as the application of biological systems to basic and technical and  industrial processes. These processes are based on the use of some form of  biological catalyst in the conversion of a substrate to a desired product.  These biological catalysts are simple as enzymes or highly complex  microorganisms or eukaryotic cells.</p>
  <p>&nbsp;</p>
  <p align="justify">Biotechnology  can be viewed as a group of useful, enabling technologies with wide and diverse  applications. It has large, highly profitable, modern industrial outlets of  great value to society e.g., DNA recombinant technology, most revolutionary  branch of the modern science and have a profound impact on medicine,  contributing to the diagnostics and cure of hereditary defects and serious  disease and the development of new biopharmaceutical drugs and vaccines for  human and animal use. It also deals with the modification of microorganisms,  plants and farm animals for improved and tailored food production and to  increased opportunities for environmental remediation and protection. </p>
<p>New  technologies dealing with plant and animal breeding are much faster and have  lower costs. Genetically modified crops are growing exponentially. The field is  further exemplified with the industrial production of enzymes like proteases,  amylases, celluloses and lipases, industrial manufacturing plants for milk and  milk products,alcohols, organic acids, antibiotics, vitamins, growth promoting  factors and monoclonal antibodies.</p>
<p>&nbsp;</p>
<h3>Career Opportunities</h3>
<p>Graduates  of Biotechnology usually get employment in well-known Pharmaceutical and food  industries of Pakistan. Countless opportunities are available in clinical  Laboratories, research institutes and teaching Institutions. </p>
