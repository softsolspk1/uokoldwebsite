  <p>The department of Sociology was established in 1960. Later, to meet the  academic demands of society, programs in Criminology and Population Sciences  were initiated under the umbrella of department of Sociology. Graduates from  the department have adopted a wide range of careers. Most have excelled in  their profession and have joined public and private institutions. The study in  the department is well organized. The teaching faculty includes experienced  Professors, including those with degrees from foreign universities. Research  work is a hallmark of the department. Seminars and workshops are important  characteristics of the department which are organized frequently.</p>
  

