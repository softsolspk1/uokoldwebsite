<h3>Teaching Methods and  Assessment</h3>
<p>  Teaching  methods involves assimilation of lectures and group discussion, class  presentations, individual and group projects, case studies, workshops extended  lecture and field research with the use of audio visual assistant. Students’  assessment involves evaluation, oral presentation, individual and group  projects, written assignments’, test results and performance in semester final  examination and one of the assessment methods of this program is the compulsory  attendance of students in the departmental library.</p>
