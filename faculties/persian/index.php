  <p>The department of  Persian was established in 1955 with a view to provide facilities for advanced  studies and research in the fields of Persian language and literature with  particular emphasis on the literature produced in the Indo-Pak subcontinent  during the last nine centuries, and to familiarize the younger generation of  this country with the history, language and literature of Iran. Professor Dr.  Ghulam Sarwar was the founder Chairman of the department.</p>
