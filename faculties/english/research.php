  <h3><strong>Research and Social Activities</strong></h3>
  <p>The department holds regular research seminars and teacher development programs. A number of teachers are conducting research for their M.Phil and Ph.D. degrees in the department. Moreover, several social and co-curricular activities are organized under the supervision of students Advisor and the Chairman.</p>
<h3>&nbsp;</h3>
  <h3><strong>Special Interest Groups</strong></h3>
  <p>[a] The Sharafat Ali Cassette Library for Blind University Students:</p>
<p>This is a library for blind students of the university which is housed in the English Department. Volunteers are always needed to record course material for blind students on cassettes. The aim is to encourage the spirit of helping others.</p>
  <p>[b] Shakespeare Association of Pakistan.</p>
  <p>An academic society, the Shakespeare Association of Pakistan is run by various members of staff.</p>
  <p>[c] Creative Writing Group.</p>
  <p>The members meet fortnightly and read out and discuss self composed poetry or prose.</p>
  <p>[d] The Book Club.</p>
  <p>The main aim is to share and thus encourage out of course reading. Students share one book in a meeting.</p>
  <p>[e] The Dramatics Club.<br />
    Students with dramatic talent are encouraged to demonstrate their skills on occasions such as Welcome &amp; Farewell parties and Shakespeare’s birthday.</p>
  <p>    [f] The Public Speaking Group.<br />
    The members of this group are encouraged to participate in debates and other public speaking contests. All the students who are interested in these activities or wish to start a new group should contact the department student advisor. It should be remembered that these co-curricular activities are in addition to curricular activities and are not in place of them.</p>
