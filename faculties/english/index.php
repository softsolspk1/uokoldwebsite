  <h2>Chairman: Dr. Iftikhar Shafi (Assoc. Prof.)</h2>
  <p>The department  of English was established in 1955. Dr. Muhammad Ahsan Farooqui was the first  head of the department. The department was located in Shivjee Murarji building  in Nanakwara. Later in January 1960 when the university moved to its present  location, the department was housed on the first floor of the Old Block in the  faculty of Arts. Professor Dr. Ahsan Farooqui was the first head of the  department of English. Prof. Dr Ali Ashraf, Prof. Maya Jamil, Prof. Dr Muzaffar  Hussain and Prof. Dr Kalim-ur-Rahman were among notable chairpersons. The  department offers masters programme in both English literature and linguistics  in the Morning as well as Evening. Prof. Maki Kureshi is one of the  internationally reputed Pakistani English poets.</p>
