  <h2>Chairperson: Prof. Dr. Saima Akhter</h2>
  <p>Department  of Public Administration was established in 1995 as a full-fledged department  of University of Karachi. However in 1987, 2- year MPA program and 1-year PGDPA  were initiated in the Department of Political Science. Realizing the  significance of this study in the professional field, Department of Public  Administration (DPA) was instituted separately. DPA started with PGDPA in  evening sessions with specializing in Human Resource Management and Health  Management. However, MPA has initiated specialization in HRM, Marketing,  Finance, MIS and development strategies.</p>
  <p>Realizing  the value of Public Administration as a separate professional course, the University  of Karachi initiated a new 2 year degree program. Recently, department of  Public Administration played a significant role by representing University of  Karachi at the meeting of University Grants Commission when specialization was  approved for the MPA graduates. MPAs have double advantages over other  graduates as they are not only aware of the administrative issues of public  sector but they also know the ways and means to tackle the administrative  dilemmas that confront the private sector. </p>
<p>&nbsp;</p>
<h3>Teaching and Assessment </h3>
  <p>DPA has  a semester system with 4 months of teaching &amp; 1 month of examination. Assessment  includes hourly, mid-term, research projects, reports, presentations,  internships &amp; a final exam.</p>
<h3>&nbsp;</h3>
<h3>Career Opportunities</h3>
<p>Because  of dual significance of our program over other degrees, our graduates are  highly appreciated &amp; demanded by the practical market   offering    them   various   management positions in Public &amp; private  concerns, nationally &amp; internationally in all kind of field ranging from  public services to FMCGs, banking, education, telecommunication, etc. </p>
