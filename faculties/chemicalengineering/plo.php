<h1>Program Learning Outcomes (PLOs)</h1>  </div>
<p>&nbsp;</p>
<p>&nbsp;</p>
<p align="justify">Following is the list of Program Learning Outcomes (PLO) that graduates of the Chemical   Engineering Program will attain during their stay at the University of Karachi.</p>
<p>
<ul>
<ol>
  <li><strong>Engineering  Knowledge: </strong>An ability to apply knowledge of mathematics, science,   engineering fundamentals and an engineering specialization to the solution of complex   engineering problems.</li>
  <p>&nbsp;</p>
  <li><strong>Problem  Analysis: </strong>An ability to identify, formulate, research literature, and analyze   complex engineering problems reaching substantiated conclusions using principles of   mathematics, natural sciences and engineering sciences. </li>
  <p>&nbsp;</p>
  <li><strong>Design/Development  of Solutions: </strong> An ability to design solutions for complex   engineering problems and design systems, components or processes that meet specified   needs with appropriate consideration for public health and safety, cultural, societal, and   environmental considerations.</li>
  <p>&nbsp;</p>
  <li><strong>Investigation</strong>:   An ability to investigate complex engineering problems in a methodical   way including literature survey, design and conduct of experiments, analysis and   interpretation of experimental data, and synthesis of information to derive valid   conclusions.  </li>
  <p>&nbsp;</p>
  <li><strong>Modern Tool  Usage: </strong>An ability to create, select and apply appropriate techniques,   resources, and modern engineering and IT tools, including prediction and modeling, to   complex engineering activities, with an understanding of the limitations. </li>
  <p>&nbsp;</p>
  <li><strong>The Engineer and  Society: </strong>An ability to apply reasoning informed by contextual   knowledge to assess societal, health, safety, legal and cultural issues and the   responsibilities relevant to professional engineering practice and solution to complex   engineering problems.</li>
  <p>&nbsp;</p>
  <li><strong>Environment and  Sustainability: </strong>An ability to understand the impact of professional   engineering solutions in societal and environmental contexts and demonstrate   knowledge of and need for sustainable development.</li>
  <p>&nbsp;</p>
  <li><strong>Ethics: </strong>Apply ethical principles and commit to professional ethics and responsibilities   and norms of engineering practice.</li>
  <p>&nbsp;</p>
  <li><strong>Individual and  Teamwork: </strong>An ability to work effectively, as an individual or in a   team, on multifaceted and /or multidisciplinary settings.</li>
  <p>&nbsp;</p>
  <li><strong>Communication: </strong>An ability to communicate effectively, orally as well as in writing,   on complex engineering activities with the engineering community and with society at   large, such as being able to comprehend and write effective reports and design   documentation, make effective presentations, and give and receive clear instructions.</li>
  <p>&nbsp;</p>
  <li><strong>Project Management: </strong>An ability to demonstrate management skills and apply   engineering principles to one&rsquo;s own work, as a member and/or leader in a team, to   manage projects in a multidisciplinary environment. </li>
  <p>&nbsp;</p>
  <li><strong>Lifelong Learning: </strong>Ability to recognize importance of and pursue lifelong learning in   the broader context of innovation and technological developments.</li>
</ol>
</ul>
</p>
