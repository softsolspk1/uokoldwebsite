<div align="center"><h3>The Psychomotor</h3></div>
<ol>
  <li><strong>1. Origination :</strong>
    Creating new movement patterns to fit a  particular situation or specific problem. Learning outcomes emphasize  creativity based upon highly developed skills.</li>
    <p>&nbsp;</p>
  <li><strong>2. Adaptation : 
  </strong>Skills are well developed  and the individual can modify movement patterns to fit special requirements.</li>
  <p>&nbsp;</p>
  <li><strong>3. Complex overt response: 
  </strong>The  skillful performance of motor acts that involve complex movement patterns.  Proficiency is indicated by a quick, accurate, and highly coordinated  performance, requiring a minimum of energy. This category includes performing  without hesitation, and automatic performance. For example, players are often  utter sounds of satisfaction or expletives as soon as they hit a tennis ball or  throw a football, because they can tell by the feel of the act what the result  will produce.</li>
  <p>&nbsp;</p>
  <li><strong>4. Mechanism: 
  </strong>This is the intermediate  stage in learning a complex skill. Learned responses have become habitual and  the movements can be performed with some confidence and proficiency.</li>
  <p>&nbsp;</p>
  <li><strong>5. Guided response : 
  </strong>The early stages in  learning a complex skill that includes imitation and trial and error. Adequacy  of performance is achieved by practicing.</li>
  <p>&nbsp;</p>
  <li><strong>6. Set :
  </strong>Readiness to act. It  includes mental, physical, and emotional sets. These three sets are  dispositions that predetermine a person's response to different situations  (sometimes called mindsets).</li>
<p>&nbsp;</p>
<li><strong>7. Perception (awareness) :
</strong>The ability to use sensory cues to guide motor  activity.  This ranges from sensory  stimulation, through cue selection, to translation<strong>.</strong></li>
</ol>
