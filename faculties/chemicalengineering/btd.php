<div align="center"><h3>The Affective Domain</h3></div>
 <p align="justify"><strong>1. Receiving :</strong>
  This refers to the  learner&rsquo;s sensitivity to the existence of stimuli – awareness, willingness to  receive, or selected attention.</p>
<p align="justify"><strong>2. Responding :</strong>
  This refers to the  learners&rsquo; active attention to stimuli and his/her motivation to learn –  acquiescence, willing responses, or feelings of satisfaction.</p>
  
  <p align="justify"><strong>3. Valuing :</strong>
  This refers to the  learner&rsquo;s beliefs and attitudes of worth – acceptance, preference, or  commitment. An acceptance, preference, or commitment to a value.</p>

<p align="justify"><strong>4. Organization :</strong>
  This refers to the  learner&rsquo;s internalization of values and beliefs involving (1) the  conceptualization of values; and (2) the organization of a value system. &nbsp;  As values or beliefs become internalized, the leaner organizes them according  to priority.</p>
<p align="justify">  <strong>5. Characterization – the Internalization of values :</strong>
  This refers to the  learner&rsquo;s highest of internalization and relates to behavior that reflects (1)  a generalized set of values; and (2) a characterization or a philosophy about  life. At this level the learner is capable of practicing and acting on their  values or beliefs.</p>
<p>&nbsp;</p>
