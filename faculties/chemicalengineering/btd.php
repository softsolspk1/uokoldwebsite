<h1>Blooms Taxonomy (Domains)</h1>  
<p>&nbsp;</p>
<p>&nbsp;</p>
<h3>Cognitive Domain</h3></div>
<ol>
  <li><strong>1. Knowledge:</strong>&nbsp;Remembering or retrieving previously  learned material.<br />
    <strong>Sample Verbs</strong>: know, identify, relate, list, define, recall, memorize,  repeat, record, name, recognize, acquire etc.</li>
    <p>&nbsp;</p>    
  <li><strong>2. Comprehension:&nbsp;</strong>The ability to grasp or construct meaning  from material.<br />
    <strong>Sample Verbs</strong>:  restate ,locate,  report, recognize, explain, express,identify, discuss, describe, discuss,review  ,infer, illustrate, interpret, draw, represent, differentiate, conclude etc.</li>
    <p>&nbsp;</p>
  <li><strong>3. Application:</strong>&nbsp;The ability to use learned material,  or to implement material in new and concrete situations.<br />
    <strong>Sample Verbs: </strong>apply, relate, develop, translate, use,operate,organize,  employ, restructure, interpret, demonstrate, illustrate,practice, calculate,  show, exhibit etc.</li>
    <p>&nbsp;</p>
  <li><strong>4. Analysis:&nbsp;</strong>The ability to break down or distinguish  the parts of material into its components so that its organizational structure  may be better understood.<br />
    <strong>Sample Verbs</strong> analyze, compare, probe, inquire, examine, contrast,  categorize, differentiate, contrast, investigate, detect survey ,classify,  deduce, experiment etc.</li>
    <p>&nbsp;</p>
  <li><strong>5. Synthesis:&nbsp;</strong>The ability to put parts together to form  a coherent or unique new whole<br />
    <strong>Sample Verbs</strong> : compose, produce, design, assemble, create, prepare  ,predict, modify, tell, plan, invent formulate, collect set etc.</li>
    <p>&nbsp;</p>
  <li><strong>6. Evaluation:&nbsp;</strong>The ability to judge, check, and even  critique the value of material for a given purpose.<br />
    <strong>Sample Verbs</strong>  : judge, assess,  compare, evaluate, conclude, measure, deduce, argue, decide ,choose, rate  ,select, estimate, validate, consider, appraise, value, criticize, infer etc.</li>
</ol>
<p>&nbsp;</p>
