<p align="justify"><strong><em>Engr. Khizra Abdul Wadood</em></strong><br/>
My name is Khizra Abdul Wadood. In 2015, I  graduated with a B.E. in Chemical Engineering from the University of Karachi,  and then I got a master's degree in Engineering Management from NED University  of Engineering &amp; Technology (2017).<br />
I have a proven ability to manage and coordinate multiple projects in a  categorically agile and professional environment. I have concrete experience in  working for analytical laboratories and quality assurance for consumer  products.  Along with this, I have  successfully completed several process simulation and design projects as well.  Remarkably improved project quality, workflow, customer satisfaction and  bottom-line results during my job. In addition, I am a great enthusiast of data  science and machine learning applications in the process and production  industries.<br />
Currently, I am enrolled in an engineering doctorate from at the University of  Birmingham. My research project is in collaboration with a pharmaceutical  company. The project is about the simulation and modelling of powder dispersion  and dissolution processes using open-source applications.    <br />
The aim of the project is to develop a modelling approach for particle wetting  and dissolution processes that can be applied to de-risk design, scale-up and  technology transfer of mixing processes. Typical powders in question have  varying degrees of solubility, wettability, density, size distribution etc.  In many cases, the materials will be in  limited supply and/or extremely expensive with little known behaviour beyond  bench scale.  Furthermore, since the  &ldquo;product&rdquo; is a formulation there may be synergies (positive and negative) to  consider in the sequence and rates of addition.   Trial and error scale-up is potentially  wasteful hence the need to develop an expert predictive model that identifies  key parameters to measure and, from these measurements, the best guess of the  suitable processes and conditions. This will necessarily be a multiscale  approach which will couple fluid and impeller flow dynamics with particle-fluid  interactions at the particle scale.</p>
