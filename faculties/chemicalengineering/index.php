  <p>&nbsp;</p>
  <p>Chemical Engineering arose from the need to apply physical, chemical, and engineering principles to the processing of such varied products such as fuels, drugs, foods, plastics, metals ,microelectronics, and basic chemicals. Undergraduate preparation for this field is therefore especially broad and balanced, drawing on chemistry, mathematics, physics etc. The graduates of a chemical engineering program are well prepared not only for industrial practice but also for graduate work in such diverse fields as biochemical, biomedical,or nuclear engineering; chemistry; environmental or energy studies; materials science; semiconductors, medicine; business administration; and law. Indeed, we seek to educate the future leaders of our technological society. Many chemical Engineers serve in the traditional chemical process industries of petroleum, natural gas, chemicals, paper, and plastics. Some develop new products or through research, while others carry out the pilot studies and design work to bring innovations from the laboratory into manufacturing operations. Many are engaged in the operation and management of process plants. Others are in marketing, developing new applications for, or solving problems arising from, the use of these products. Often a chemical engineer moves from one of these functions to the next as an idea develops-into a full-scale production facility. Chemical engineers have long aided in energy and materials production from oil, gas, coal, and high-energy chemicals. They are involved in the research, development, and production of energy from alternative energy resources. A chemical engineer's career path is varied and rewarding, allowing individual talents to grow and be fully utilized.</p>
