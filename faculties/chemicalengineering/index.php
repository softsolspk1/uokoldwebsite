  <h3><strong>Teaching and Assessment</strong></h3>
  <p>The course consists of class  room lectures plus laboratory practical. The courses are divided into 3 credit  hours (without practical) and 4 credit hours (with practical). Four credit  hours courses consist of 100 marks for theory and 50 marks for practical.</p>
