  <h2><strong>Chairperson: Dr. Humera Aziz (Assoc. Prof.)</strong></h2>
  <p>The  department of Special Education was established in the University of Karachi in  1988. The University of Karachi offers a regular program of studies in Special  Education at the graduate as well as the post graduate level for students who  intend to serve the Special need Community. During course of studies students  are prepared to be Special Education and Rehabilitation experts. </p>
  <p>The  teaching faculty includes trained and experienced teachers with Ph.D. degrees in  the discipline. The teaching in the Department is focused on developing  independent and analytical thinking abilities in the student. The program is  designed to provide students with opportunities to actually teach children with  special needs during the course of studies, so that they can get practical  experience along with their academic learning. </p>
  <p><br />
  </p>
  <h3><strong>Teaching and Assessment</strong></h3>
  <p>Lecture method with  emphasis on classroom discussion and feedback including effective use of  audio-visual aids, provision of expertise through resource persons and a  regular program of extension lectures are part of formal teaching methodology.  Field visits for on the spot observation of special children, particularly, in  the classroom children are also arranged.</p>
  <p>&nbsp; </p>
  <h3>Career  Opportunities</h3>
  <p>Students  of the Department of Special Education continue to enter a variety of  educational, vocational and rehabilitation fields.  Many are speech pathologists, audiologists,  and teachers in different special education centers for mental retardation,  physical handicap, hearing impairment, visual impairment, and learning  disability. The graduates of the department get jobs in schools, hospitals,  institutes, rehabilitation centers, directly or indirectly serving special need  children. </p>
  <p>&nbsp;</p>
  <h3>Facilities</h3>
  <p>The  Department has lecture and seminar rooms. Audio Visual Room, as well as a well  stocked seminar library with most recent books. The department has equipment,  which provides practical work facilities to students as well as provide  exposure of practical teaching at Special Schools.</p>
