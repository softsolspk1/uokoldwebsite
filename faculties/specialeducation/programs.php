  <h3><strong>Teaching  Practice</strong>  </h3>
  <p>The Department of Special Education, University of Karachi was  established with a vision to develop human resources in the form of highly  skilled teachers for persons with special need. To achieve this vision we are  providing an effective course of study and training for intended teachers in  special education. The student teachers are placed for internship program in all  disabilities in different Special Education Schools of Karachi with the  following objectives:  </p>
  <ul>
    <li>To observe teaching at different levels i.e., Pre-primary, Primary and Secondary  level.</li>
    <li>To assess the students with special needs.</li>
    <li>To deliver lessons with the assistance of cooperative teachers in  respective schools.</li>
</ul>
  <p>&nbsp;</p>
  <h3><strong>Community Rehabilitation</strong></h3>
  <p>For  this purpose, we provide assessment program planning and referral services like  speech therapy, audiometery, home based programs etc in all disabilities.</p>
