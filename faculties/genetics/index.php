  <h2>Chairperson: Prof. Dr. Erum Shoaib</h2>
  <p>The  science of Genetics started out as a study of inheritance of traits from  parents to offspring in the early 20th century. Recently the  life-sciences in general have emerged as multidisciplinary subjects and  genetics has now been recognized as the single most fundamental science among  all of the life-sciences. Due to the exponential pace of advancement that  genetics has enjoyed in the past few decades, especially after the Human Genome  Project, it is now finding more and more applications in the health sciences.  During the course of its development genetics has a firm foothold in improving  the quality of all kinds of biological produce. Moreover, its new role as a  genetic-tool has allowed many allied sciences to reach new heights especially  in the industrial applications of living things collectively called  biotechnologies and also cloning, and gene therapy. <br />
                                                                                                                                   <br />
The  Department of Genetics was established in 1969 at the University of Karachi,  offers the degrees of M.Sc., M.S. and Ph.D. in Genetics. A bachelor’s program is  expected to start soon. All of these programs are conducted by a staff  consisting of highly qualified faculty that includes nine PhDs.</p>
The department takes great pride in maintaining an intellectual and  cognitive atmosphere in order to promote learning and to provide to its  students an experience they will remember fondly for the rest of their lives.
<p>&nbsp;</p>
<h3>Teaching and Assessment</h3>
<p>Graduate  students learn in a conducive and comfortable environment with modern teaching  aids in classrooms and labs as well as computer labs. Assessments are done as  university policies. </p>
<p>&nbsp;</p>
<h3>Career Opportunities</h3>
<p>Since  late, Genetics is being applied in many diverse fields of science and industry.  Main application of genetics include: medical diagnostics; enhancement of  agricultural, livestock, and poultry products; industrial microbiology and  biotechnology. There are many fields in the industry requiring manpower highly  skilled in genetics in general, genetic engineering and molecular biology in  particular.</p>
