  <h3>Teaching  and Assessment</h3>
<p>Teaching at the Bengali department is carried out mainly through lecture. Visiting speakers from other institutes are also invited from time to time. Students are required to give presentations on various topics as well as to submit assignments. The department hosts seminars at national and international level from time to time, in which distinguished speakers from Bangladesh read out their papers and speak on different aspects of Bengali literature The seminar organized by the department was on the prominent Bengali scholar QaziNazrul Islam’s contribution to Human Rights and Bengali Language, <strong>recently the department organized seminar on the "Qazi Nazrul - Islam and Allama Iqbal"</strong> contribution to Muslim Dignity in South Asia.</p>
