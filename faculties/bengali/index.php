<h3>Career  Opportunities</h3>
<p>Students who graduate from this department are  competent enough to enter the teaching profession for the subject of Bengali at  primary as well as higher education level. Furthermore, opportunities of  working in Bangladeshi banking sector,including <em>ArifHabibRupali Bank, </em>and in various government departments are  available to them. They may also opt for research or work as translators and  interpreters.</p>
