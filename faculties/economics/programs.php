  <p><strong>Programs</strong><br />
    The  department offers a variety of programs designed to cater to the diverse  interests and career aspirations of students. These programs are structured to  provide a strong foundation in economic and finance theory, along with  real-world applications.</p>
  <p><strong>Undergraduate  Programs</strong></p>
  <ul>
    <li>BS  Economics (Morning &amp; Evening): This program offers a comprehensive  understanding of economic principles, quantitative methods, and their  applications in real-world scenarios.</li>
  </ul>
  <ul>
    <li>BS  Economics &amp; Finance (BSEF) (Morning &amp; Evening): This interdisciplinary  program combines economics and finance, equipping students with the skills  needed to excel in the financial sector.</li>
  </ul>
 
  <p><strong>Postgraduate  Programs</strong></p>
  <ul>
    <li>M.Phil./M.S.  in Economics (Morning): This advanced program focuses on in-depth economic  analysis and research, preparing students for academic and professional  careers.</li>
  </ul>
  <ul>
    <li>Ph.D.  in Economics (Morning): A research-intensive program designed for those who  wish to contribute to the field of economics through original research.</li>
  </ul>
  
  <p><strong>Postgraduate  Diploma</strong></p>
  <ul>
    <li>Postgraduate  Diploma in Economics &amp; Finance (PGDEF) (Evening only): This diploma program  provides specialized knowledge in economics and finance, ideal for  professionals seeking to enhance their expertise. </li>
