  <h4>Master  of Philosophy (M.Phil.) and Master of Studies (M.S.)</h4>
  <p><strong>Eligibility Criteria:</strong><br />
    At least sixteen years of studies (Master&rsquo;s  degree, M.A., M.Sc., B.S. (4 years)) or equivalent qualification with at least  second division in the relevant field from an HEC recognized  university/institution. There is no requirement to submit Equivalence  certificate for the graduates of Public Sector Universities.<br />
    Note: 6 credit hours of research  work are mandatory for M.Phil. Those candidates who have done MS (with course  work) are not eligible for admission in Ph.D.<br />
    For further information on  eligibility criteria and the admission process, please refer to the<br />
    admission prospectus.</p>
  
  
  <h4>Doctor  of Philosophy (Ph.D.)</h4>
  <p><strong>Eligibility Criteria:</strong><br />
  <strong>a)</strong> M.Phil., M.S. (with research),  or equivalent qualification in the relevant field from HEC recognized  University/Institution. There is no requirement to submit Equivalence  certificate for the graduates of Public Sector Universities.</p>
  
  <p><strong>b) CGPA</strong></p>
  <p><strong>a)</strong> For admission in the Ph.D.  programs, a minimum CGPA of 3.0 (out of 4.0 in the semester system) in the  M.Phil. / equivalent degree being considered for admission, is required,  whether such degree was obtained from Pakistani of foreign universities.</p>
  <p><strong>b)</strong> If the CGPA/Percentage is not  mentioned on the transcript, the candidate must produce equivalent weightage  from the parent university,</p>
  <p><strong>c)</strong> The students having strong  demonstrated interest in obtaining Ph.D. degree, but their CGPA is below 3.00  (minimum 2.6 CGPA) (out of 4.0 in the semester system) in the most recent  degree obtained, may be admitted to a Ph.D. program after fulfilling the  following requirements;</p>
  <p><strong>i.</strong>   Shall study additional courses of 9-12 CH of level 7 taking a zero  semester at admission awarding<br />
    university/HEI/DAI and score  minimum 3.00 out of 4.00 GPA, and</p>
  <p><strong>ii.</strong> The admission committee is  satisfied that the applicant's knowledge of primary area (level 7) has<br />
    sufficiently prepared him or her to  undertake the course of studies of the doctoral program.</p>
  <p><strong>iii.</strong> These requirements shall be in  addition to any other requirements set in this policy for admission to a Ph.D.  program.</p>
  <p>&nbsp;</p>
  <p>For further information on  eligibility criteria and the admission process, please refer to the admission  prospectus.</p>

