  <h3>Department  Environment</h3>
    The  Department of Economics provides a conducive environment for learning and  research. It features large lecture halls and classrooms, a computer lab, a  research lab, and a seminar library. There is ample office space for faculty  members and secretarial staff.</p>
  <h3>Seminar  Library</h3>
   <p align="justify">The Department of Economics is an  ideal place for study and research, offering a range of facilities to support  academic and research activities. The department has its own seminar library,  which boasts a comprehensive collection of around 2000 books and periodicals  related to economics and related fields. For materials not found within the library,  students and faculty can utilize inter-library loan facilities and access other  major libraries, including the main library and the research library of AERC at  the University of Karachi. The department's library is well-equipped to provide  course materials as well as reference literature essential for students  throughout their studies.</p>
  <h3>Computer  Lab</h3>
   <p align="justify">The  department prioritizes student facilities, such as a computer lab with 30  computers dedicated to economic analysis, financial modeling, and statistical  applications. This lab plays a crucial role in improving students' technical  skills through practical learning experiences that reinforce theoretical  knowledge. The lab fosters collaborative projects, simulations, and data  analysis, which enhance critical thinking and problem-solving capabilities  crucial for navigating the modern economic environment successfully.</p>
  <h3>Research  Lab</h3>
    <p align="justify">The  department has expanded its facilities with a dedicated research lab for  M.Phil. and Ph.D. students, equipped with 20 advanced computers. This new  addition enhances the department's research capabilities, providing a  supportive environment for in-depth data analysis and interdisciplinary  collaboration. The lab underscores the department's commitment to fostering  academic excellence and innovative research in economics and related fields,  empowering graduate students to pursue rigorous scholarly inquiry and  contribute impactful insights to their disciplines.</p>
  <h3>Extracurricular  Activities</h3>
    <p align="justify">The  department emphasizes the importance of extracurricular activities for the  overall development of students. Various sports such as cricket, football, and  hockey are available, with inter-department tournaments held annually. The  department also organizes study tours and visits to financial institutions,  which supplement theoretical knowledge with practical exposure.<br />
    The  department fosters a close-knit community where students have great  accessibility to the administration and faculty. The interactions between  faculty and students help in personal and professional development, making  students more confident, mature, and dynamic.</p>
  <h3>Awards</h3>
    <p align="justify">Through  the generosity of philanthropists, the department awards Gold Medals to  students who secure top positions at different levels, recognizing and  encouraging academic excellence.</p>
  <h3>Achievements</h3>
   <p align="justify">The  department is renowned for its high academic standards, leading to the  establishment of the AERC. The AERC, supported by a grant from the Sindh  Government and later by the Ford Foundation, has become a leading institute for  social and economic research. This achievement underscores the department's  commitment to academic excellence and research.</p>
