  <h3 align="center"> BS ECONOMICS</h3>
  <h3 align="center">(4 YEARS PROGRAMME)</h3>
  <p><strong>Courses</strong><br />
The  Department of Economics offers a comprehensive and well-structured scheme of  studies for both BS Economics and BS Economics &amp; Finance programs. These  courses are designed to provide a strong theoretical foundation while  incorporating practical applications to ensure students are well-prepared for  their future careers.</p>
  <p><strong>BS  Economics</strong><br />
    Students  have two entry points into the program: firstly, directly after completing  Intermediate or equivalent in semester-I, spanning eight (8) semesters. Secondly,  in semester-V, students with ADE/B.A./B.Sc./B.Com. or equivalent qualifications  can join, which spans four (4) semesters. These students will need to take  specific courses to address any deficiencies they may have.</p>
  
