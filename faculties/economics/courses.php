<h3><strong><u>M.Phil. (Economics)</u></strong><br />
  <strong><u>(With Course and Research Thesis)</u></strong><br />
  <strong>Coursework Requirements</strong></h3></div>

<p align="justify"><strong>Coursework Composition:</strong>
  <ul><ul><li>MPhil       candidates are required to complete 24 credit hours of coursework, and 6       credit hours dedicated to research work/thesis. Alternatively, candidates       may opt to complete 30 credit hours of coursework; however, upon       completion of 30 credit hours, they will be awarded an MS (Master of       Science) degree instead of an MPhil degree.</li></ul></ul></p>

<p align="justify"><strong>Coursework Composition:</strong>
  <ul><ul><li>The coursework       must be relevant to the MPhil degree and should be offered through regular       on-campus classes taught by full-time faculty members.</li>
  <li>The coursework       should cover the foundational and advanced topics necessary for the field       of study.</li></ul></ul></p>

<p align="justify"><strong>Research Component:</strong>
<ul><ul><li>If the program       includes a research component (thesis), the university must establish a       policy for thesis defense and evaluation through its statutory bodies.</li></ul></ul></p>

<p align="justify"><strong>Degree Completion Timeline:</strong>
<ul><ul><li>The MPhil       degree should be completed within a minimum of <strong>1.5 years</strong> (three       regular semesters) and a maximum of <strong>4 years</strong> (eight regular       semesters). Extensions may be granted in cases of force majeure.</li></ul></ul></p>

<p align="justify"><strong>Additional Points:</strong>
<ul><ul><li>Universities are       allowed to transfer credits from other institutions following the HEC's       guidelines, provided the coursework aligns with the program's       requirements.</li></ul></ul></p>

<p align="justify"><strong>Eligibility Criteria:</strong>
<ul><ul><li>Students who       have completed their BS in the following fields are eligible to apply for       MPhil admission: Economics, Economics and Finance, Commerce, Business       Administration, Public Administration, Mathematics, Statistics, and Physics</li></ul></ul></p>
<p align="justify"><strong>Passing Criteria:</strong>
<ul><ul><li>A minimum CGPA       of 2.6 is required for successful completion.</li></ul></ul></p>
