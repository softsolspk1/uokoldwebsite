<ul>
  <li><strong>Completion Timeline:</strong></li>
    <ul>
    <li>The coursework, comprehensive exam, and defense of the synopsis/research        proposal must be completed within the first six semesters (3 years) of        enrollment in the PhD program. The maximum duration allowed for        completing the PhD, as per HEC policy, is 8 years.</li>
