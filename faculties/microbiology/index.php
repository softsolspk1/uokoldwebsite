  <h2>Chairman: Prof.  <strong> Dr.   Abdul Wahab</strong></h2>
  <p align="justify">Microbiology  is a broad discipline which has both basic and applied aspects. Therefore,  microbiologists must have good understanding about microbial taxonomy,  genetics, immunology and physiology in order to identify these agents, utilize  their metabolic potential on commercial levels and to manipulate these  organisms for the betterment of humanity.</p>
<p align="justify">The  Department of Microbiology at the University of   Karachi was established in 1957 with only 22 students and one full-time  teacher (late Prof. Dr. A. A. Anwar) and a part time teacher cum student (Late  Prof. Dr. Pirzada Misbahuddin Ahmed Siddiqui). Since this was the first and only  Department of Microbiology for many years, in this country, offering a degree,  Prof. Dr. Anwer could be truly regarded as the Father of Microbiology in  Pakistan.</p>
  <p align="justify">Because  of the importance of the subject and its applicability, this department is now  regarded as one of the best departments within the faculty of Science. As a  result this department has become popular and a large number of students opt to  study Microbiology as their major. Furthermore, this department caters the  needs of more than 500 students who opt to study Microbiology as one of their  minors each year.</p>
  <p align="justify">Besides  offering B.S. / Honors and Masters degrees, this department has a reputation of its  M.S. / Ph.D. and Ph.D. programs. At present, more than 150 scholars are enrolled  in MS and Ph.D programs.</p>
