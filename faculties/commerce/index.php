  <h2>Chairperson: Prof. Dr. Zaeema Asrar Mohiuddin</h2>
  <p>The  Department of Commerce University of Karachi has been instrumental in providing  candidates with thorough knowledge and understanding of the principles of  commerce and business. The BS (four years) and M.Com programs are structured on  team based learning, class presentations, case studies, field research reports  and other reference materials, to combine academic theory with practical  problems, seminars and workshops on current economic and business issues are  also organized in the Department. </p>
  <p>The Department of Commerce has been imparting quality and research oriented business education since 1974. No one can deny that an educational institution is known because of the academic activities of its teachers and other members.</p>
  <p>To keep pace with the dynamic world of business and business education, the department of commerce is accelerating in both ways, one, the department is expanding in its educational program by introducing B.S. four year program. The department had also started B.Com (Hons) in the year 2004 for the first time in its history, which is now replaced by B.S. four year program. Another development is bringing about a change in its curriculum, which is in compliance with the international education system. Now the department of commerce has all those courses which are well demanded in the business world, the students are capable of acquiring good jobs both at national and international level, they are well equipped with all those disciplines which are the need of the day. Degree Conferred personalities of the department in the discipline of Finance, Accounts, Management, Marketing and Banking are well received by corporate sector today and enjoy the privilege of being highest academic degree holder in the field of Commerce</p>
