  <p>Physical  Education is a way of education by means of physical movement. From Molecular  Biology to Material Sciences nothing of value can be expected from a society if  the teaching and research in Health and physical education is ignored or if it  is relegate to a secondary status.  Being  a natural phenomenon, movement is the essence of life and the entire mechanism  of human body is geared to it. Experts believe that exercise is also as  important as food. While food provides necessary energy for the body, exercise  tones up the human organism so that it can utilize this energy in a better way.  Since a healthy body is necessary for a healthy mind, physical education as a  discipline is more intimately concerned with human development than educational  disciplines. </p>
