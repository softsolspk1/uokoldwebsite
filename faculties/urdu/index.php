  <h2>Chairperson: Prof. Dr. Uzma Farman Farooqui</h2>
  <p align="justify">The Department of Urdu officially came into existence  in 1955 when the University of Karachi decided to organize postgraduate classes  in Urdu under its own management instead of through the colleges.<br />
At the time of its establishment, Moulvi  Abdul Haq, &lsquo;Baba-e-Urdu&rsquo;, was made honorary Professor and the Chairman of the  Department. Teaching responsibilities were carried out by the teachers of local  colleges. Later, Dr. Ghulam Mustafa Khan, a prominent scholar and Professor at Urdu  College Karachi, was appointed both as a cooperative teacher and as the  Chairman of the department. In the same year, Dr. Abul Lais Siddiqui was  appointed as a Reader and Chairman and Dr. Abdul Qayyum, Dr. Syed Shah Ali, and  Qudratullah Fatimi joined as lecturers.<br />
With the valuable efforts and abilities of  these teachers as well as the scholars and teachers who joined the department  later on, the department has kept making progress. The following famous  academics have been associated with the Urdu department: Dr. Syed Abul Khair Kashfi,  Dr. Farman Fatehpuri, Dr. Aslam Farrukhi, Prof. Jameel Akhtar Khan, Dr. Haneef Fauq,  Dr. Younus Hasni, Shamim Ahmed, Prof. Sahar Ansari, Dr. Vaqar Ahmed Rizvi, Dr. Siddiqa  Arman, Dr. Moinuddin Aqeel and Dr. Zafar Iqbal.<br />
The Department of Urdu has a prominent  position in the University of Karachi for research. Over 100 scholars have  completed their Ph.D. research program and more than forty projects are in  progress.<br />
In addition to regular teaching and lectures,  co-curricular, literary and academic activities and gatherings are also  organized frequently.</p>
