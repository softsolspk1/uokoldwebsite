  <h2>Chairman: Dr. Naeem Ahmed (Assoc. Prof.)</h2>
  <p>International Relations is the oldest Department in the  field of International Relations in Pakistan. It was established in 1958. Prior  to its formation, the Department was under General History Department and  Professor Dr. Mahmud Hussain was its founding Chairman. Dr. Muhammad Ahsen Chaudhry  succeeded Dr. Mahmud Hussain as the Chairman of the Department. </p>
  <p>Since its inception, the Department of  International Relations has been active in organizing seminars, conferences and  workshops. A number of books have also been published under the Department and  several Research Projects funded by foreign foundations are presently being run  by its faculty members. The syllabus of the Department was revised in 1998 and  new courses focusing on the conceptual and regional studies have been offered. </p>
<p>&nbsp;</p>
<h3>Teaching and Assessment </h3>
  <p>Teaching for all degree programs is offered on  semester basis.  Student assessment  during the semester consists of mid-term tests, assignments and a terminal exam  at the end of every semester. </p>
<h3>&nbsp;</h3>
<h3>Career Opportunities</h3>
<p>Students graduating from the Department can be found  in various sectors. Traditionally, students of the Department have been  recruited to the bureaucracy, both provincial and federal. A popular option  these days is recruitment in the electronic media where there is a huge demand  for IR graduates focusing on current events.<br />
</p>
