  <h2>&nbsp;</h2>
  <p align="justify">    The department of Botany has developed a large and productive research and teaching group in plant sciences. Members of the faculty are working in many specialized fields of plant sciences and are endeavoring to enhance our knowledge of the plant world.</p>
<p align="justify"> </p>
  <h3 align="justify"><strong>Applied Botany</strong></h3>
  <p align="justify">The main topics of research in this section are plant tissue culture, plant embryology, cell wall biochemistry and biological nitrogen fixation. Research interest is in the production of transformed plants of vegetables and fruits using somatic embryogenesis, anther culture and cell selection techniques to be grown under normal and controlled environmental conditions. Work in embryology includes experimental studies on the life cycle of ferns in order to explore the stage at which activation and inactivation of genes responsible for the distinctive features of alternating generations takes place. A reinvestigation of embryology of some members of the family Solanaceae is also underway. Work in the field of biological nitrogen fixation mainly emphasizes the mode of infection in nodule development, structure and nature of nodules and characterization of microsymbionts on the basis of biochemistry, flagellar characters and N2 fixing potential of tree legumes with particular reference to cell wall biochemistry. This involves the qualitative and quantitative estimation of cell wall polymers with particular reference to cellulose which forms raw material for paper industry.</p>
  <p align="justify"> </p>
  <h3 align="justify"><strong>Mycology and Plant Pathology</strong></h3>
  <p align="justify">    Researches of both basic and applied nature are being carried out. These include seed pathology of economically important crops, foliar and root diseases of betelvine, identification of yeast with industrial, medicinal, and agricultural use and detection of secondary metabolites from yeasts and Fusarium spp. Parasites and predators of plant parasitic nematodes and root infecting fungi have been isolated and identified and various biological agents have been used for the control of root infecting fungi and nematodes. Nematicidal activity from seaweeds, reduction in viability of fungal propagules by organic amendments and their elimination by polythene mulching of soils have opened a new vista of an integrated control of soil borne fungi and nematodes. Investigations on the development of disease suppressiveness are also in progress. There is a good collection of mycological specimens in the Mycological Herbarium of the department.</p>
  <p align="justify"> </p>
  <h3 align="justify"><strong>Phycology and Marine Botany</strong></h3>
  <p align="justify">    The seaweed flora in the coastal areas of Karachi has been studied taxonomically. Survey of phytoplankton and seasonal variation of the algal population in the North Arabian Sea has been studied from the nutritional and ecological viewpoints. The occurrence and toxicity of harmful algal bloom caused by Dinoflagellates and other phytoplanktons have also been assessed. Work on phycochemistry of marine benthic algae growing along the coast of Karachi has also been carried out and several saturated and unsaturated fatty acids, sterols, terpenes, glycosides, secondary metabolites and other natural products have been isolated and chemically elucidated. There is a vast collection of both marine and fresh water algae. Studies are also being conducted on the Mangrove Ecosystem of Pakistan with emphasis on heavy metal pollution.</p>
  <p align="justify"> </p>
  <h3 align="justify"><strong>Plant Ecology</strong></h3>
  <p align="justify">    Plant ecology is an important area of teaching and research at the Department of Botany. Many studies have been conducted which are associated with different problems of ecological nature. To study the relation of organisms to their environment, ecologists have to undertake experimental studies, which have one thing in common, that is the collection of data to test hypotheses. In this section, the methods and problems associated with sampling, ordination and classification of plant communities are investigated. Studies in relation to plant and soil are also in progress. Industrial and automobile activities are the prime cause of air, water and soil pollution. In this regard, some research has been done to elucidate the effects of these pollutants on vegetation distribution. Moreover, the effects of heavy metal toxicity on plant species have also been evaluated.<br />
    Researches are also being conducted on the ecological management of inter-tidal, coastal and inland saline ecosystems, screening and development of cash-crop halophytes. Laboratory and field experiments are also in progress to develop fodder plant with brackish water irrigation. Specific research interest includes differential effects of light, salinity and temperature on seed germination, role of dormancy relieving compounds on the release of salinity induced seed dormancy of halophytes, seed bank, primary dormancy and demography of halophytes and salinity effects on the growth and salt tolerance of halophytes under both laboratory and semi-controlled conditions.</p>
  <p align="justify"> </p>
  <h3 align="justify"><strong>Plant Physiology</strong></h3>
  <p align="justify">    Researches are in progress in the utilization of brackish water for irrigation and cultivation of plants along the sandy coastal belt. Effects of various aspects of environmental pollution have been studied on the quantity and quality of crops with respect to pesticides, auto-exhaust, simulated acid rain and toxic heavy metals with emphasis on lead pollution. As a part of solid waste management, nitrogenous biofertilizer has been prepared from bagasse and compost from Sabzimandi and kitchen waste. Agricultural soil and irrigation water of several agricultural villages located in the outskirts of Karachi have been analyzed both qualitatively and quantitatively for the presence of pollutants. Work on growth hormones, mechanical stress on plants and biochemical changes in healthy and diseased plants are also under investigation.</p>
  <p align="justify"> </p>
  <h3 align="justify"><strong>Systematic Botany</strong></h3>
  <p align="justify">    The Department of Botany has earned international recognition for the Flora of Pakistan edited by Professor Dr. S. I. Ali and Professor Dr. M. Qaiser. Taxonomic accounts of 214 plant families have been published which have now become a standard source of reference on the plant wealth of Pakistan. The Karachi University Herbarium has a collection of over 150,000 plant specimens collected form different regions of Pakistan for over 5 decades along with some historic collections belonging to the British era. The section has also built up a unique collection of scientific literature on plants which, coupled with the herbarium has now become one of the best institutions for the teaching of Systematic Botany in the country. Contributions in the fields of Cytology, Palynology, Chemotaxonomy, Phytogeography, Reproductive Biology etc., have also been very significant. Intensive studies on the plant biodiversity of Gilgit, Naltar, Hunza, Indus delta, Hub River vicinity and Kirthar Range are presently in progress; besides Biosystematic studies on various taxa and pollen storage techniques.</p>
  <p align="justify"> </p>
