  <p align="justify"><strong><u>Aims and Scope of the Program:</u></strong></p>
  <p align="justify">Pharmacy  Practice at Faculty of Pharmacy and Pharmaceutical Sciences, University of  Karachi is aimed to produce leaders for integrating education, research and  practice by virtue of innovative and collaborative ventures within a  diversified community and clinical health care systems across the country.</p>
  <p align="justify">Pharmacy  Practice is the demand of the current era in healthcare system. In hospitals,  pharmacist take care of the patients by clinical interventions and  rationalizing therapy, monitoring the outcomes and strategizing the clinical  input to reduce adverse effects and report those adverse effects. Furthermore,  via patient education and counseling, the pharmacist practitioner provides the  social and behavioral contingence to the patients and general public.</p>
  <p align="justify">The  scope of Pharmacy practice is extending from Healthcare system, through  Academia, and Regulatory Affairs of pharmacy practice to pharmaceutical research  in Pharmacovigilance and Pharmacoepidemiology. These healthcare services as  regarded as a pillar in healthcare system, hence, services to the society. In  every sphere of healthcare system, these pharmacists are employed, and their  services are procured.</p>


