  <h2>Chairperson: Dr. Rafat Parveen Siddiqui (Assoc. Prof)</h2>
  <p align="justify">The Department of Library Sciences, the first ever to offer  professional degree in Pakistan in this discipline, was established in 1956.  Masters in Library Science (M.L.S.) was offered from 1962. Since 1982 the  department is known as Department of Library and Information Science, and  information control / management became an integral part of the studies.  Computer lab for cataloguing was established in 1984. This was the first  computer laboratory in all Library and Information Science Schools across  Pakistan as well as the Faculty of Arts, University of Karachi.<br />
The founder chairman, Dr. Abdul Moid was the first Ph. D. holder  in Library Science from the USA (1964). The Presidents&rsquo; Award for the Pride of  Performance has been awarded to Professor Dr. Anis Khurshid, a renowned teacher  of the department, known as the father of modern librarianship in Pakistan.<br />
The Process of revising and updating the curriculum is a regular  feature and the department remains in touch with national and international  library schools to moderate the curriculum so that the demand of the modern  librarianship be met.</p>
<p>&nbsp;</p>
  <p align="justify"><strong>Teaching and Assessment:</strong><br/>
   Teaching at the department includes lectures, practical,  presentations, group discussions, study tours and extension lectures.&nbsp;  Assessment is based on evaluation of performance in the semester examinations  along with various projects, assignments, reports and oral presentations.</p>
<p>&nbsp;</p>
  <p align="justify"><strong>Career Opportunities:</strong><br/>
   The need of a trained person to control and to search relevant  information in the modern time has become a necessity. Opportunities for  outgoing students are open in public and private sector and packages offered  are better in comparison to other professions. In government offices, BLIS / BS  degree holders are offered 16 – 17 (BPS) and MLIS 17 (BPS) and above.</p>
