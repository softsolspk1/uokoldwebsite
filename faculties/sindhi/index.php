  <p align="justify">The Department of Sindhi was  established in 1972. It started with a master’s program only, but later on  Honors program, certificate and diploma were also introduced. The Department  also offers Sindhi as a compulsory subject in lieu of Urdu in B.A./B.Sc. and  B.Com. (Honors) IInd year. In 2007 like other Departments of University of  Karachi, Sindhi Department also started BS four years program and MS/Ph.D.  while the Balochi Language certificate Programme is also administrated by  Sindhi Department. The curriculum is regularly revised and updated by  introducing the latest literature being produced by authors so that students  can be kept well aware. Regular literary lectures are arranged to inspire the  students and to make them aware of practical criticism, and develop skills of  expressing their opinion. For the same purpose, scholars and critics are  invited regularly for extension lectures. Interaction with literary figures is  a regular feature of the department’s activities.<br />
