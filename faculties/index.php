  <h3><strong><a name="sc" id="sc"></a>Faculty 
    
    
    
    of Science</strong></h3>
  <table width="95%" border="0">
    <tr>
     <td width="86%" valign="top"><h4><strong>Dean: Prof. Dr. Bilquees Gul</strong> <a href="/faculties/docs/pdbg.pdf" target="_blank"><strong> (Profile)</strong></a></h4>
   <p align="justify">Welcome to the Faculty of Science at the University of Karachi one, of the largest and most comprehensive academic faculties of the University, with a long-standing tradition of excellence in teaching, research, and service. The Faculty plays a central role in advancing scientific education and knowledge in Pakistan.<br/>
The Faculty of Science comprises 21 academic departments spanning biological, physical, chemical, earth, environmental, mathematical, computational, agricultural, and health sciences. It offers a diverse range of undergraduate, graduate, and doctoral programs designed to provide students with strong theoretical foundations, rigorous practical training, and research-oriented learning. A centralized laboratory further supports interdisciplinary teaching and research through shared, state-of-the-art facilities.</p></td>
     <td>&nbsp;</td>
     <td width="14%" align="center"><img src="images/dbg.jpg" alt="dean-ass" width="127" height="128" align="right" /></td></tr></table>
    <table width="95%">
    <tr><td><p align="justify">Our  academic programs namely BS, MSc/MS, MPhil, and PhD, are delivered by a highly  qualified and dedicated faculty actively engaged in innovative research and  scholarly activities. Through structured coursework, laboratory work, seminars,  field training, and research projects, students are prepared to excel in  academia, industry, healthcare, environmental management, biotechnology, and  other scientific and technical fields.<br />
         In  addition to its academic departments, the Faculty includes several nationally  and internationally recognized institutes and centers of excellence, including  the International Center for Chemical &amp; Biological Sciences (ICCBS–H.E.J.  Research Institute of Chemistry), Dr. A.Q. Khan Institute of Biotechnology and  Genetic Engineering (KIBGE), Centre of Excellence in Marine Biology, Institute  of Environmental Studies, Institute of Space Science &amp; Technology,  Institute of Marine Sciences, and the Dr. Muhammad Ajmal Khan Institute of  Sustainable Halophyte Utilization (ISHU). These institutions significantly  enrich the faculties research culture of the Faculty and provide advanced  training opportunities for postgraduate students.<br />
         The  Faculty of Science takes pride in its distinguished alumni who have made  exceptional contributions to science and academia at national and international  levels. Their achievements reflect the quality of education, rigorous training,  and vibrant research environment fostered at the University of Karachi and  continue to inspire future generations of scientists.<br />
         Research  remains a cornerstone of the Faculty&rsquo;s mission. Faculty members conduct  cutting-edge, multidisciplinary research addressing contemporary scientific,  societal, and environmental challenges. Supported by advanced laboratories and  specialized research facilities, this work contributes meaningfully to national  development and global scientific progress.<br />
         The  Faculty also emphasizes industry engagement and community outreach through  collaborative projects, internships, applied research initiatives, and outreach  programs. These efforts promote innovation, knowledge transfer, and societal  impact, ensuring that scientific education and research contribute effectively  to economic growth and community well-being.<br />
         Committed  to academic excellence, interdisciplinary collaboration, ethical research  practices, and a student centered learning environment, the Faculty of Science  continues to develop the skilled scientists, researchers, and professionals  equipped to address current challenges and to contribute at national and international  levels.</p></td> 
