    <strong><a name="med" id="med"></a>Faculty 
      
      
      
      of Medicine </strong></h3>
  <table width="95%" border="0">
    <tr>
      <td><h4><strong>Dean: Professor. Dr. Fareeda Islam</strong></h4></td>
     <!-- <td width="15%" align="center"><img src="images/dmna.jpg" alt="dean-med" width="100" height="115" align="right" /></td> -->
