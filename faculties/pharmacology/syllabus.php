  <h3 align="center"><strong>First Professional First Semester</strong></h3>
  <p><strong>PHARMACOLOGY PHL – 307<br />
  </strong>Physiology &amp; Histology Cr. Hrs. 3</p>
  <p>1. Physiology of Nerve and Muscle<br />
    Chemical change in muscle on contraction. Action potential. Never action potential, skeletal, smooth, cardiac excitation contraction.</p>
  <p>2. Blood<br />
    Composition, functions and genesis of formed elements. R.B.C, WBC and platelet. Fate of R.B.C, jaundice, reaction of blood, blood groups. Rh factors, ESR, blood volume, function of spleen, blood coagulation, haemophilia,, classification of anemias.</p>
  <p>3. Circulatory System<br />
    Properties of cardiac muscles, origin and conduction of heart beat, cardiac cycle, ECG, heart sounds, cardiac output, stroke volume and heart rate. Nerve supply of heart. Coronary, pulmonary and skin circulation. Blood pressure, vasomotor center. Arterial pulse venous pulse, haemorrhage, circulatory changes in exercise, composition and circulation of lymph, shock.</p>
  <p>4. Skin<br />
    Structure, functions of skin, temperature regulation by skin.</p>
  <p>5. Digestive System<br />
    Mastication, deglutition, digestive juices saliva, gastric juice, pancreatic, bile and intestinal juices, their composition, function and mechanism of secretions. Movement of stomach and intestine, function of large intestine, defecation, functions of liver and gall bladder. <br />
  </p>
  <p><strong>PHARMACOLOGY PHL – 309<br />
  </strong>Pharmaceutical Biochemistry Cr. Hrs. 3</p>
  <p>1. General Introduction and Basic Biochemical Principles<br />
    Role of pharmaceutical biochemistry in the health profession, nature of biochemical reactions.</p>
  <p>2. Basic Chemistry of Biomolecules<br />
    a Carbohydrates<br />
    Chemistry, classification, reactions, optical activity biological and pharmaceutical importance of carbohydrates.</p>
  <p>b Lipids<br />
    Chemistry of fatty acids and lipids classifications, (saponifiable and non saponifiable lipids, simple, complex and derived). Reactions of fatty acids and other lipids. Essential fatty acids, biological and pharmaceutical importance of lipids.</p>
  <p>c Proteins and Aminoacids<br />
    Chemistry, classification, reactions of proteins and amino acids. Organizational level, macromolecular nature, biological and pharmaceutical importance of proteins and amino acids.</p>
  <p>3. Metabolic Fate of Biomolecules<br />
    <br />
    a Carbohydrates<br />
    Brief digestion and absorption, aerobic and anaerobic breakdown of glucose, glycolysis, pentose phosphate pathway, glycogenolysis, gluconeogenesis, citric acid cycle, energetics of various metabolic processes.</p>
  <p>b Lipids<br />
    Brief digestion and absorption, oxidation of fatty acids through beta oxidation. Biosynthesis of fatty acids, neutral lipids, and cholesterol.</p>
  <p>c Proteins and Amino-acids<br />
    Brief digestion and absorption, metabolism of essential and non essential amino acids. Biosynthesis and catabolism of Haemins and porphyrin compounds.</p>
  <p>4. Bioenergetics<br />
    Principles of bioenergetics, electron transport chain and oxidative phosphorylation.</p>
  <p>5. Enzymes<br />
    Chemistry, classification, mode of action, kinetics (Michaelis Menten Equation and some modifications). Inhibition, activation. specificity, alleosteric enzymes. Factors affecting the rate of an enzyme catalyzed reaction. Biological and pharmaceutical importance, mechanism of action of some important enzyme (Chymotrypsin, Ribonuclease).</p>
  <p><strong>PHARMACOLOGY PHL – 311<br />
  </strong>Pharmaceutical Biochemistry (Practical) Cr. Hrs. 3</p>
  <p>1. Qualitative Analysis<br />
    Carbohydrates, amino acids, peptides and proteins. Lipids and sterols (Cholesterol) bile salts and bilirubin. Blood analysis-sugar, uric acid, bilirubin, cholesterol and creatinine.</p>
  <p>2. Quantitative Analysis<br />
    Carbohydrates–Glucose (reducing sugar) and any other carbohydrate using Benedict and anthrone method. Amino acids. Peptides and proteins using Biuret and Ninhydrin (Spectrophotometric) method. Analysis of normal and abnormal components of urine–sugar. Uric acid, bilirubin, cholesterol and creatinine. <br />
  </p>
  <h3 align="center"><strong>First Professional Second Semester</strong></h3>
  <p><strong>PHARMACOLOGY PHL – 308 <br />
  </strong>Physiology and Histology Cr. Hrs. 3</p>
  <p>1. Respiratory System <br />
    Mechanics of respiration, intrathoracic, intrapulmonary pressure. Pulmonary ventilation. Lungs volume and capacities. Composition of inspired air, expired air and alveolar air, carriage of oxygen and CO2 by the blood. Regulation of breathing (Nervous and Chemical control).</p>
  <p>2. Urinary System<br />
    Urine formation-composition of urine, G.F.R. urea clearance. Formation of concentrated and diluted urine. Regulation of osmolarity, and pH (acidic and basic urine), process of nicturation (nervous control), renal failures.</p>
  <p>3. Nervous System<br />
    Spinal reflexes. Reflex regulation of movement and posture. Cerebral cortex functions. Voluntary movements. Descending tracts of spinal cord. Basal ganglia, cerebellum, thalamus C.S.F. <br />
    Autonomic nervous system.</p>
  <p>4. Special senses<br />
    Elementary knowledge of structure and function of the special senses.</p>
  <p>5. Endocrinology<br />
    Definition of hormone. Nature of different types of hormone. Mechanism of action of hormone including pituitary hormones with abnormalities, thyroid gland with pathologies para thyroid hormone, pancreatic hormone with diabetes mellitus, Adrenal glands with cushing syndrome, Addison disease. Male and female sex hormones.</p>
  <p>6. Histology<br />
    Underlying principles of histological techniques and staining specific tissues. Staining of paraffin and frozen sections.</p>
  <p><br />
    <strong>PHARMACOLOGY PHL – 310</strong><br />
    Pharmaceutical Biochemistry Cr. Hrs. 3</p>
  <p>1. Vitamins<br />
    Chemistry, classification (fat-soluble and water-soluble vitamins), biological and pharmaceutical importance of vitamins.</p>
  <p>2. Hormones<br />
    Chemistry, classification (proteinous and non-proteinous hormones, amino acid derivatives, steroids). Biological and pharmaceutical importance of hormones.</p>
  <p>3. Regulation of Metabolic Processes<br />
    Role of Vitamins<br />
    Physiological role of fat-soluble (A.D.E and K) water-soluble (members of b-complex family and ascorbic acid). Coenzymes and their role in the regulation of metabolic processes. Niacin, thiamine, riboflavin, pyridoxine, pantothinicail, biotin, folic acid and vitamin B12.<br />
    Receptor Mediated Regulation (Hormones)<br />
    Mechanism of action of hormones, physiological roles of various hormones, site of synthesis and target, sites of hormones.Action, regulation, signal transaction mechanism. Role of cAMP, calcium ions and phosphoinositides, tyrosin kinase, jakkinase in the regulation of metabolic processes.</p>
  <p>4. Gene Expression<br />
    Regulation of gene expression, chemistry, transcription and translation, introduction to biotechnology and genetic engineering. Basic principles of recombittant DNA technology, Pharmaceutical applications. Genetic switch, inducers, fusion, genes, regulatory genes, zinc finger Helix-turn helix motif, the leucine-zipper motif.</p>
  <p><strong>PHARMACOLOGY PHL – 314</strong><br />
    Anatomy Cr. Hrs. 2</p>
  <p>1. Introduction<br />
    Anatomical terminology, definition of cell, tissue, organ, structure of cell membrane, cytoplasm, organelles, nucleus, cell cycle.<br />
    2. Tissues of Body<br />
    Cartilage, bone structure and types of bones and joints. <br />
    3. Muscle<br />
    Structure of skeletal, smooth muscles, and cardiac muscles.<br />
    4. Integumentary System<br />
    Including skin, glands, hair and nail.<br />
    5. Cardio Vascular System<br />
    Structure of heart, location, blood supply to heart, types of blood vessels. <br />
    6. Elementary System<br />
    Name and structure of different parts of elementary system and their interrelationship.<br />
    7. Urinary System<br />
    Name and structure of organs of urinary system and their inter relationship. <br />
    8. Male and Female Reproductive Systems<br />
    Endocrine system including pituitary, thyroid and adrenal glands with their structures.</p>
  <p>1. Nervous System<br />
    Including neuron, organization of CNS, brain, cerebrum, cerebellum, brain stem, pons and medulla oblongata, thalamus, hypothalamus, cranial nerves. Internal structure of spinal cord CSF, sensory and motor pathways, spinal reflexes, peripheral spinal nerves.<br />
    2. Autonomic Nervous System<br />
    Sympathetic and parasympathetic nervous system.</p>
