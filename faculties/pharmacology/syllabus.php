  <p><strong>PHARMACOLOGY PHL – 409</strong><br />
    Pharmacology &amp; Therapeutics (I) Cr. Hrs. 3</p>
  <p>1. Introduction<br />
    History and scope of Pharmacology, classification of Pharmacology. Drugs and their sources<br />
    2. Definitions<br />
    Bioavailability, bioequivalence therapeutic index, potency, efficacy, risk benefit ratio, selective toxicity, plasma half-life, dose response curve, area under curve, volume of distribution.<br />
    3. Drugs Delivery System<br />
    Advantages and disadvantages of oral medication. Advantages and disadvantages non-oral medication.<br />
    4. Pharmacokinetics <br />
    Drug solubility and passage of drugs across body membranes, plasma concentration of drugs and various factors affecting it. Factors affecting absorption, distribution, biotransformation and excretion.<br />
    5. Pharmacodynamics<br />
    Drug receptors and theories, mechanism of drug action, specificity of drug action, and factors modifying the action. <br />
    6. Drugs Acting on Blood<br />
    Antianemic (Vit B12, folic acid, iron). Coagulants and anticoagulants</p>
  <p>7. Drugs Acting on G.I.T. System<br />
    Gastroesophageal reflux disease and its treatment. Emesis and antiemetics. Constipation and laxatives. Diarrhea and antidiarrheals. Peptic and duodenal ulcer, drugs used in their treatments. Drugs for inflammatory bowel disease, and for cholelithiasis. Prokinetics.<br />
