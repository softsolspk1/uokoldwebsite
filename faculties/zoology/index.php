  <h2>Chairman:   <strong>Prof. Dr. Muhammad Shoaib</strong></h2>
  <p>The  department of Zoology was established in 1951 and now it holds a pivotal  position in the faculty and can also be compared with any department of Zoology  elsewhere in and outside Pakistan.  The  Department right from its inception has been imparting instruction at B.Sc.,  BS, and M.Sc. levels, besides providing facilities for post-graduate research  leading to M.Phil, and Ph.D. degrees. More than two thousand (2000) research  papers have been published by the faculty members in National and International  research journals. Various monographs and thirty two books have been published  by the faculty members. About 300 students are enrolled each year at various  levels in the department including various specializations. Several are being  enrolled each year in M.Phil and Ph.D programs.</p>
