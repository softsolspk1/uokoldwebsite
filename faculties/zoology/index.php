<h3>Career Opportunities</h3>
<p>The  graduates of the department while catering the needs of the education  department, where they are readily absorbed as teachers of Zoology in schools,  colleges and University also have job opportunities in the department of  Agriculture, Plant protection, Fisheries, Zoological Survey, Zoological Gardens  Safari parks, Pakistan Council of Scientific and Industrial Research,  National Institute of Oceanography, Pakistan  Agricultural Research Council, Wild life conservation and management of WWF,  IUCN, Public and Private sectors pathological laboratories. </p>
