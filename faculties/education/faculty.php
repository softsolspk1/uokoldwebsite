  <p align="justify"><font size="+.5"><u><strong>Dr. Rizwana Muneer</strong></u></font><br />
    Dr.  Rizwana Muneer joined the department of Education in 1991. She completed M.A.  Education from University of Karachi and secured First class First Position in  Karachi, also earned B.Ed., in First division from University of Karachi in  1987. She completed her Ph.D., in Education January 2011 from University of  Karachi. Her PhD., topic is &ldquo;<strong>Comparative  study of the work motivation of Teachers in Government and Private Secondary  Schools of Karachi</strong>&rdquo;. She served as an Assistant Professor and Chairperson  in the Department of Education in Jinnah University for Women, Karachi, 1991to  1999, served as an Assistant Professor and Associate Professor in Department of  Education, University of Karachi, since 1999 – to date. Also served as a  student Advisor and member of student Advisory Committee of University of  Karachi. Now served duties as a Chairperson Morning and Evening shift of  Department of Education, University of Karachi. Worked as member of board of  studies department of Education, University of Karachi, Hamdard University, Benazir  Bhutto Shaheed University Lyari, Karachi. Supervised around 1000 above theses  of M.A. Education, also M.Phil., and Ph.D., completed degree under the  supervision of her. She arranges different national seminars and also deliver  Lectures in different universities. She presents different research papers in  International and National Conferences. She writes Thirty-Two (32) research  articles relevant to her field in different HEC approved Journals. Also  completed two research projects i.e. &ldquo;<strong>Role  of School Management committee in Government Girls Secondary Schools</strong>&rdquo; ; <strong>A case study of Jamshed Town Karachi, and  Second is Role of Education mothers and issues of health for special children:  A case study of center for mentally retorted Childern (QMRC), Gulistan-E-Jouhar,  Karachi. </strong>She served as a Center Superintendent, Factotum, Co-Examiner and  Deputy Head Examiner in B.A., B.Com., M.A., ADA, B.Ed., &amp; M.Ed.,  examinations. Appointed many times as a subject specialist in Federal Public  Service Commission. Also she conducts Educational workshops, Exhibition, study  trips, Symposium, Seminars, Blended learning classes. Completed many  departmental development projects i.e. Gardening, Paint, Medical Camp, Fixation  of Bulletin Boards/ Noticed Boards.</p>
<p><font size="+.5"><u><strong>Dr.  Azizunnisa</strong></u></font><br />
Ms. Azizunnisa completed her Master in  Education from University of Karachi in 1995.   She completed B.Ed. from Govt. College of Education, F.B. Area in  1999.  She joined the Department of  Education as a Lecturer in 2001 and completed M. Phil in 2007.  Her research field is guidance and  counseling, and issues in education. </p>    
<p><font size="+.5"><u><strong>Dr. Naila  Siddiqua</strong></u></font><br/>
  Dr. Naila  Siddiqua is currently working as an Assistant Professor in the Department of  Education, University of Karachi.&nbsp;Pursuing  the Doctorate Degree in Education from Hamdard University she had studied  trends in Professional Education in the middle class society of Karachi. She has earned M. Phil. Education degree from  Hamdard University studying moral development in school children. She is a  science graduate with Mathematics, Physics and Statistics and holds M.Sc. degree  in Applied Statistics from University of Karachi.<br />
    <br />
    Prior to  Joining University of Karachi she has served as Lecturer, Incharge B.Ed.  program and secretary internal audit committee at Hamdard Institute of  Education and Social Sciences, Hamdard University Karachi.&nbsp;She has worked as focal person for plagiarism  testing of M.Phil and Ph.D. theses at Hamdard Institute of Education and Social  Sciences. She is a registered External Evaluator of National Accreditation  Council for Teacher Education and has participated in pilot testing of Accreditation  tools in Teacher Education Institutes of Sindh and Punjab. She was also a  member of departmental research committee, Board of Faculty and Board of  Studies at Hamdard University.<br />
    <br />
    She has  been associated with various educational institutions holding different Administrative  and Academic positions. She has worked as Incharge Assessment and Evaluation  and academic auditor for a network of schools. She has rich experience in  designing and implementing professional development programs for pre-service  &amp; in-service teachers, head teachers and teacher educators.<br />
She  is a Certified Quality Professional  from Pakistan Institute of Quality Control and a member of Quality  and Productivity Society of Pakistan and attended many Workshops, Seminars and  Conferences of quality and Education.</p>

<p align="justify"><font size="+.5"><u><strong>Dr.  Maroof Bin Rauf</strong></u></font><br />
  </p>
<p>Dr.  Maroof Bin Rauf is an Assistant Professor in the Department of Education, at  the University of Karachi. He did his Masters from the same department. His  Ph.D. is from the same alma mater, the University of Karachi in 2014 on  &quot;The Role of Professional Universities in Development of Individual and  Society&quot;. <br />
  <br />
  He started his professional career in 2004 with Usman Public School System and  after two years joined Karachi University as a full-time Cooperative Lecturer  in the Department of Education for eight years. He was also a part-time  (visiting) lecturer in the Department of Teacher Education as the first  practicum coordinator of the B.Ed. (Hons) 4-year program. In this program, he  trained many government teachers with his team. In 2014, he was appointed as an  Assistant Professor - IPFP at the Federal Urdu University of Arts Science &amp;  Technology, Karachi, where his primary responsibility was to establish the  Teacher Education Department at the Gulshan Iqbal Campus as a focal person.  There he started 4 programs including M.Phil. and Ph.D. (Teacher Education).  Later in May 2015, he was selected as an Assistant Professor in the Department  of Education, University of Loralai, Balochistan through the Tenure Track  System (TTS). Here he served for two and a half years as the Chairperson of the  Department of&nbsp;Education. <br />
  <br />
  He also worked with outstanding USAID organizations such as Pre-STEP and the  Pakistan Reading Project (PRP). His achievements include designing four courses  for the B.Ed. (Hons) 4-year program. These include Educational Psychology,  Guidance and Counseling, Reading Difficulties and designing Reading Practicum.  He is a registered external evaluator of the National Accreditation Council for  Teacher Education (NACTE) Pakistan. He also served as Judge and Lead Education  for 2 years in the National Idea Bank (NIB) started by the President of  Pakistan Dr. Arif Alwi. Along with them, he has been associated with various  educational and training institutions where he held various administrative and  educational positions. He also has experience in international training for  teachers and youth. Teachers and students have benefited from his extensive  teaching and training experience. In addition, several scholars have completed  and pursued an M.Phil./Ph.D.&nbsp;under his supervision. He has presented many  papers at national and&nbsp;international conferences. <br />
  <br />
  He won 3 Higher Education Commission Pakistan (HEC) research projects as  Principal Investigator and assisted in two USAID projects as a team member. He  is also the Approved Research Supervisor of the Higher Education Commission  (HEC) Pakistan. He is also the editor of the Pakistan Journal of Educational  Research since 2018. His areas of interest and expertise are Leadership and  Educational Administration, Educational Psychology, Guidance and Counseling,  Entrepreneurship, Curriculum Design and Teacher Training. </p>
<p>Some  of the major milestones in Dr. Maroof Bin Rauf's career so far are that he has  taught 22 different skills to&nbsp;around&nbsp;70,000 people through his 1,200  students through&nbsp;<strong>&quot;Social Action Projects&quot;</strong>&nbsp;from 2017  to 2023. Similarly, for his&nbsp;<strong>&quot;Activity-Based&nbsp;Exams&quot;</strong>&nbsp;he  not only created sub-rubrics, but from 2019 to 2024, his students also designed  more than 100 plays, skits, anthems,&nbsp;poems,&nbsp;tableaus, talk shows and  musical activities. In the year 2023 alone,&nbsp;he&nbsp;trained more than 100  new teachers working in schools through basic&nbsp;teacher&nbsp;training  courses. Today&nbsp;<strong>&quot;Gamification of Education&quot;</strong>&nbsp;is an  important aspect of the educational world. In this regard,&nbsp;he has  developed more than 40 physical and board games with his students so far, which  can support students' learning at different levels. </p>
