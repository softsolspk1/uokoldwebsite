  <h3></h3>
  <h2>Chairperson:   <strong>Dr. Aziz Un Nisa (Officiating)</strong></h2>
  <p>&nbsp;</p>
  <p align="justify">The Department of  Education aims to develop high quality and skilled manpower in the field of  education. The department serves as a resource center for all government &amp;  non-government organizations at both national &amp; international level. The  management and faculty put great emphasis on providing guide lines for teaching  techniques, innovative approaches &amp; student counseling. Highlighting new  trends and key issues through co-curricular activities are the prominent  feature of department performance.</p>
   <p align="justify">Presently the department  is offering B.S. 1st, B.S. 3rd, M.Phil./M.S., Ph.D. in  Education. Students in Education of BS program should offer optional for  Economics, Psychology, Sociology, International Relation, Islamic Learning,  English, Social Work, Political Science, Mass communication or Languages as  minor subjects. The total no. of seats in the Department of Education is 106  and Student enrollment is 190 which are approximately double of the actual  seats.</p>
   <p align="justify">The Department of Education has a seminar library containing latest books on  almost all the disciplines of Education. Moreover, the library also contains  extensive resource material for research at all levels of higher  education.&nbsp; The department also offers hands on training on the latest  equipment used in presenting research findings to the large audience.</p>
   <p align="justify">The importance of  Co-curricular activities cannot be denied. The Department of Education conduct  orientation day for welcoming new students. Moreover, students-week, welcome  and farewell parties, students-teacher union luncheons, cake-day on 13th  August, Teachers&rsquo; day on 5th October and a picnic as per the provided schedule  of Students Advisory Council.</p>
   <p align="justify">Department of Education  was established in 1984. The main goal of the department is to prepare human  capital in the field of Education as teachers, educators, educational leaders  and researchers. Innovative methods of teaching and learning, emerging  techniques of research and material development in the field of Education have  made this department parallel with that of the International standards.</p>
  <p align="justify">Education as a subject always remains important in the Faculty of Arts and  every year about 100 students were admitted in Masters Classes whereas about  1000 students were selected as a subsidiary subject at Masters level and always  8 to 10 sections were formed. At the beginning the department of education  started masters course of duration of two years consisting of 8 courses  including research as a compulsory subject, moreover for developing research  skills and aptitude among student&rsquo;s research thesis, research report was also  compulsory for every student in B.S./ M.A.(Final) to enable student to compete  new challenges of market in the field of education.</p>
   <p align="justify">BS in Education 4years  program and M.Phil., M.S. / Ph.D. (regular program) were also started in this  department in the year of 2007 and 2009 respectively and both programs being  successfully along with a BS (Minor) in which a large number of students  enrolled where as a reasonable number of students are not able to get admission  in minor classes every year due to shortage of physical facilities as well as  human resources. 15 students are enrolled in M.Phil. / Ph.D. Program in this  department. Ph.D. degree in education has been awarded to many students under  the umbrella of this department, which is one of the great achievements of this  department indicate assuring the effective and efficiency of this department.</p>
  <p align="justify">Along with regular morning programs, this department also running B.S./ M.A.  (Education) program in evening session for those students who are unable to  attend regular morning classes due to their employment in morning.</p>
<h3></h3>
    <p align="justify"><strong>Teaching and  assessment:</strong><br/>
   Varieties  of teaching methods are used in the department for rendering different courses  effectively. Faculty members arrange both inside and outside classroom  activities in order to broaden the learning experiences of the students.  Lectures, seminars, classroom quizzes and field-works are planned and conducted  during the semesters. The department believes on both, the summative and  formative assessment. Moreover, students are also asked to arrange and attend  different seminars for their professional growth.</p>
<h3></h3>   
<p align="justify"><strong>Career opportunities:</strong><br/>
Education  is an important discipline in Social Sciences and Humanities. Therefore,  graduate students of Education have ample opportunities in the competitive job  market at both national and international levels. Research Industry, Media  Career Counseling, Schools, Teacher Training Institutes, Human Resource  Development Centers, Professional Institutes, UNICEF, UNESCO and NGO based  organizations can be the potential job market for the graduates of education department.</p>
