<h3 align="center"><strong>Third  Professional</strong><strong> </strong></h3>
 <p><strong>PHG-512<br /> Pharmacognosy  Lab-II   Cr. Hrs. 3</strong></p>
1.     <strong>Preliminary  Screening of Natural Products</strong><br />
Preliminary  chemical tests for the detection of carbohydrates, tannins, alkaloids,  glycosides, steroids, saponins, terpenes and flavonoids.</p>
<ul>
  <li>Alkaloids: Mayer's reagent test, Wagner's reagent test,  Dragendorff's reagent test.</li>
  <li>Glycosides: Kedde reagent test, Keller killiani test.</li>
  <li>Saponins:  Haemolysis  test, Froth test, Leibermann-Burchard test.</li>
  <li>Sterols:  Salkowski  test.</li>
  <li>Flavonoids:  Colour  test, Cyanidin test.</li>
  <li>Tannins:  Ferric  chlorides test, Lead acetate test.</li>
</ul>
<p>2.     <strong>Chromatography</strong></p>
<ul>
  <li>To show the presence of strychnine and brucine in <em>Strychnosnux-vomica</em> mixture (acid or  akaline) by thin layer chromatography (TLC).</li>
  <li>To examine tinctures or extracts of <em>Digitalis purpurea</em> leaf by paper chromatography.</li>
  <li>To separate different constituents of alkaloid mixture or  colouring substances by column chromatography.</li>
  <li>To determine ephedrine hydrochloride through ion exchange  chromatography.</li>
  <li>To separate alkaloids from an extract or tincture of <em>Atropa belladonna</em> through ion exchange  chromatography.</li>
</ul>
