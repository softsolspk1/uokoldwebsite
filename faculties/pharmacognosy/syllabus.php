<p>2.     <strong>Cosmeceuticals</strong><br />
  Introduction,  classification of cosmeceuticals as skin, eye, hair care and others products.  Biological studies, chemistry, uses and toxicology of botanicals and their  isolated products used in cosmeceuticals. Role of rosemary, lavender, arnica,  chamomile, licorice, pomegranate, calendula, cinnamon, aloe, tea, carrot,  jojoba, apricot, ginger, olives, coconut, turmeric, thyme, walnut, cucumber,  henna, onion, sage, oats, hibiscus, propolis, bromelin, balsam, gum, myrrh,  honey, kelp and Laminaria as cosmeceuticals.</p>
<p>3.     <strong>Allergens and Allergenic  Preparations</strong><br />
  Introduction,  classification of allergens, causes, history, skin test and treatment of  allergies. Types of allergens: inhalent, ingestant, injectant, contactant,  infectant and  infestant.</p>
<p>4.     <strong>Enzymes</strong><br />
  Introduction,  classification, chemistry and functions of plant, animal and microbial enzymes.  Study of malt extract, pepsin, streptokinase and asparaginase.</p>
<p>5.     <strong>Hormones</strong><br />
  Introduction,  historical background of uses, commercial production, extraction and isolation  of animal hormones: adrenal gland, thyroid, pituitary, parathyroid, and  pancreas; Plant hormones: auxins, gibberellin, cytokinins and abscisic acid.</p>
<p>6.     <strong>Anticancer  Agents</strong><br />
  Introduction  of anticancer agents of natural origin, as <em>Catharanthusroseus</em>, <em>Colchicum autumnale</em>, <em>Podophyllumpeltatum</em>, rifamycin  antibiotics, macrolide antibiotics, Anti-AIDS agents and  immunostimulants.</p>
