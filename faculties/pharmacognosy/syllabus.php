<h3 align="center"><strong> First  Professional</strong></h3>

<h6>&nbsp;</h6>
<p><strong>PHG-312<br /> General Pharmacognosy  Cr. Hrs. 3</strong></p>
  1.     Historical Development and Scope of  Pharmacognosy<br />
  General  introduction, history of Pharmacognosy with special reference to the  contribution of Muslim scientists to the profession of Pharmacy.Introduction to  herbal pharmacopoeias and modern concepts about Pharmacognosy.</p>
<p>2.     Crude Drugs<br />
  Crude  drugs, commerce, preparation, chemical and therapeutic classifications of crude  drugs; official and un-official drugs.</p>
<p>3.     Evaluation and Adulteration of Crude Drugs<br />
  Organoleptic  study, physical evaluation, microscopic evaluation, types of adulteration,  inferiority, spoilage, admixture, sophistication and substitution of crude  drugs.</p>
<p>4.     Drugs of Animal Origin<br />
  General  introduction and discussion about honey, gelatin, shellac, musk, civet,  ambergris, cod liver oil, cantharides and spermaceti. </p>
<p>5.     Biologics<br />
  Sources,  structure, preparation, description and uses of vaccines, toxins, antitoxins,  venoms, antivenins, antisera.</p>
<p>6.     Surgical Dressings<br />
  Classification  of fibers as vegetable, animals and synthetic fibers.Evaluation of fibers in  surgical dressings, BPC standards for dressings and sutures.Discussion on  cotton, wool, cellulose, rayon and catgut.</p>
<p>7.     Pesticides<br />
  Introduction,  methods and control of pests with special reference to pyrethrum, tobacco, and  other natural pesticides.<br />
  <p></p>
