<h3 align="center"><strong>Second Professional</strong></h3>
  <p><strong>PHG-412<br /> 
  Chemical  Pharmacognosy-I  Cr. Hrs. 3</strong></p>
<p>1.     Carbohydrates and Related Compounds<br />
  Introduction  and classification of carbohydrates, sugars as adjuvant in drugs, role of  impurities in sugar substances.</p>
<p>2.     Fixed Oils<br />
  Introduction,  classification, source, active constituents and pharmacological uses of castor  oil, cotton seed oil, olive oil, peanut oil, sesame oil, sunflower oil,  chaulmoogra oil, corn oil, coconut oil, almond oil, linseed oil, mustard oil,  palm oil and soya oil.</p>
<p>3.     Essential Oils<br />
  Introduction,  classification, sources, active constituents and pharmacological uses of clove  oil, fennel oil, coriander oil, orange oil, eucalyptus oil, peppermint oil,  anise oil, chenopodium oil, turpentine oil, lemon peel oil, citronella oil,  caraway oil and thyme oil</p>

 <p>4. Resins  and Oleoresins <br />
Introduction,  classification, active  constituents,  pharmacological uses of jalap, turpentine, asafoetida, benzoin, rosin,  cannabis, podophyllum, ipomea, myrrh, and balsam.</p>
<p>5.     Tannins <br />
  Introduction,  classification, biosynthesis, extraction, identification, occurrence in plants,  their role in plant life and chemical study of tannins in kino, myroblan,  catechu, nutgall, castanea, and krameria.</p>
<p>6.     Chromatography <br />
  Introduction,  types and application of chromatography for the separation, isolation,  purification and identification of drug substances from natural sources.</p>
