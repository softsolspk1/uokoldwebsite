  <li>Caffeine from <em>Thea  sinensis</em>.</li>
  <li>Jalap resin from <em>Ipomeapurga</em>.</li>
  <li>Starch from <em>Solanum  tuberosum</em>.</li>
  <li>Myristicin and trimyristicin from <em>Myristicafragrans</em>.</li>
  <li>Pectin from <em>Citrus  paradisi</em>.</li>
