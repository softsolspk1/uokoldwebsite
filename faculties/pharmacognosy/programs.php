    <h3>Program details (Degree, Eligibility Criteria)</h3>
    <p>The  Bachelor’s degree in Pharmacy is Doctor of Pharmacy (Pahrm. D) which is offered  by the faculty of Pharmacy on behalf of its four departments. Its eligibility  criteria is established at the faculty level, while department is responsible  for admissions in M.Phil. and Ph. D. programs.</p>
   <p>Every year departmental board of studies  devise a policy according to which the number of seats and admission criteria  is worked-out for both M.Phil. and Ph. D. programs.</p>
  <h3>Eligibility  Criteria (M.Phil.)</h3>
    <p>At  least sixteen years of studies-4 years’ B. Pharm or Pharm. D., with at least  second division. Entrance Test is conducted by the department which is  mandatory for all the candidates. The test comprises of the following sections:</p>
    <ul>
   <li>Section-I  English and Communication Skills 20%</li>
    <li>Section-II  Subject knowledge 80%</li>
    </ul>
    <p>Candidates  are required to score at least 40% marks in section-I and 50% marks in  section-II separately to be eligible for consideration for provisional  admission.</p>
  <p>All  the students who qualify the test will be required to appear for an interview before Departmental Research Committee (DRC). The admissions are granted on the basis  of the following </p>
  <ul>
    <li>The  marks obtained in the prerequisite degree examination is given 50% weightage. </li>
    <li>The  marks secured in the Entrance Test is given 30% weightage.</li>
    <li>The  marks obtained in the interview is  given  20% weightage</li>
  </ul>
  <p>All  selected candidates are required to complete 8 courses of 24 credit hours in  two semesters.  There are five courses of  3 credit hours each in Ist semester and three courses of 3 credit  hours each in the 2nd semester. Candidates are required to attend at  least 75% classes of each course. They must clear the course work with atlest CGPA of  3.0 . In case a student fails to get the desired CGPA, he/ she will be  allowed to improve the grade (only once).</p>
