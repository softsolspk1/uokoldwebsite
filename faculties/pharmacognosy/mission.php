  <h2>&nbsp;</h2>
  <h3>Vision and Mission</h3>
 <p align="justify">The  vision of the Department of Pharmacognosy is to prepare a study program that is  in line with the most recent developments in the field and produce graduates  who could meet the national and international needs in health care. Those  enrolled under various programs will study the  following topics:</p>
      <ul>
        <li><strong>Natural product chemistry</strong> deals with the study of natural  products, their extraction and isolation methods, structure elucidation</li>
        <li><strong>Pharmacology of natural product </strong>relates to the biological  activity of crude drugs, isolated compounds and their toxicities</li>
        <li><strong>Ethanopharmedicine/Ethnopharmacology</strong>is the subject that deals with  the traditional medicine practices by different ethnic groups and indigenous  people. It relates to traditional medicine, ethnobotany, ethnopharmacology,  anthropology.<strong></strong></li>
        <li><strong>Marine Pharmacognosy </strong></li>
      </ul>
      <p align="justify">Pakistan’s diverse  and plentiful marine resources are the most promising avenue for future drug  development. It deals with the study of unique chemical composition of marine  plants and animals and their biological activity and pharmaceutical value. </p>
      <ul>
        <li><strong>Biologics </strong>is the study of sources, structures, preparation,  description and uses of vaccines, toxins, antitoxins, venoms, antivenins,  antisera and etc.</li>
        <li><strong>Allergens an  Allergenic Preparations </strong>is the topic that describe various types of allergens and the  development and preparation of vaccines used for their treatment. </li>
        <li><strong>Biosynthesis </strong>describes the various mechanisms  through which plants prepare their primary and secondary metabolites,  chemotaxonomy and how these pathways can be used to develop synthetic and semisynthetic  analogues of natural products.<strong></strong></li>
        <li><strong>Quality Control/Quality Assurance </strong>Under this  subject physical, chemical, and biological methods of analysis are studied to  ensure the quality of crude drugs, plant extracts, nutraceuticals and  pharmaceuticals.</li>
        <li><strong>Standardization </strong>methods are developed to produce  standardized extracts of plants and other natural resources.<strong></strong></li>
        <li><strong>Biotechnology </strong>deals with methods for  sustainable production of medicinally important natural products to meet the  market requirement</li>
      </ul>
      The current trend and  advancements are incorporated from time to time in board of studies and are  made part of the syllabus</li>
  </ul>
