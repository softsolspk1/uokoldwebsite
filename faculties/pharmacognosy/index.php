  <h2>Chairman: Prof. Dr. Muhammad Mohtasheemul Hasan</h2>
  <p>&nbsp;</p>
  <p align="justify">The  Faculty of Pharmacy was established in 1973 and comprised of four departments.  Department of Pharmacognosy has been working since then as an integral part of  the faculty. Today it has grown into a well-established department that is the  backbone of pharmacy education in the Faculty of Pharmacy and Pharmaceutical  Sciences.<br/>
  Pharmacognosy  is the portmanteau of two Greek words,&nbsp;<em>pharmakon</em>&nbsp;meaning  drug, and&nbsp;<em>gnosis</em>&nbsp;meaning knowledge. It is the study of  natural bioactive substances obtained from terrestrial and marine plants,  animals, microbes and minerals for their physical, chemical, biochemical and  biological properties, their taxonomy and ethno-biology.<br/>
  It  is one of the major areas of Pharmaceutical sciences; today a highly  interdisciplinary science which include parts of botany, organic chemistry,  biochemistry, pharmacology, zoology, anthropology, geography, ethno medicine,  biotechnology etc.<br/>
  This  discipline covers wide range of topics such as sources of natural products,  their chemical composition, medicinal value, distribution,  ethno-pharmacological profile, biosynthetic pathways, isolation, evaluation,  quality control, standardization, nutraceuticals and cosmeceuticals.<br/>
  Pharmacognosy  research topics encompasses identification of plant drugs, phytochemistry, extraction  methods, separation, purification, identification and structure elucidation of  natural products, phytotherapy, biologics, allergens, nutraceuticals,  cosmeceutical and toxic manifestation of natural products. It also provides for  the discovery of lead compounds for drug development, new methods of analysis for  drugs, toxins and herbal preparations.<br />
    In  Pakistan there has always been an immense interest in medicinal plants and also  in traditional system of medicine–Unani and Homeopathic systems. The active  chemical constituents of these plants are also used in the modern system of  medicine–Allopathy. Traditionally, most of the population depends on natural  sources of medicine. A vast majority does not have excess to modern medicine  hence there is a huge scope to develop cheap drugs from locally available  recourses to meet the needs of the country.<br />
      The Department offers to assists the undergraduates to earn a Pharm.  D.&nbsp;degree and guide the young scientific investigators to earn either  M.Phil. / Ph. D. degree in the field of Pharmacognosy. We further project that  our undergraduates will be equipped to bring a better promise of tomorrow in  pharmaceutical industry (manufacturing/quality control, drug development),  hospital and clinical pharmacy, regulatory bodies, academics, research and  development.<br />
  
    To  fulfill the national requirement, Department of Pharmacognosy strives to  provide professionals who could work in any Pharmaceutical industry or can be  instrumental in modernizing herbal drug industry on scientific basis. Our  graduates have an array of opportunities to work.</p>
