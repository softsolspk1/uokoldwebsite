<h3 align="center">M.Phil. Applied Physics</h3 align="justify"><strong>Mission Statement:</strong><br />
  The program mission of  post-graduate studies at the Department of Applied Physics is to provide  research based education and learnings in the various field of applied physical  sciences through rigorous research work. The program&rsquo;s primary mission is to equip  MPhil scholars with advanced research skills, including literature review, data  collection and analysis, experimental design, and critical thinking. By the end  of the program, students should be proficient in conducting independent and  rigorous research in their respective fields.</p>&nbsp;</p align="justify"><strong>Program Objective:</strong>
<ul>
  <li>The program aims to cultivate intellectual  independence among MPhil students. This involves encouraging students to  explore their research interests, develop their own research questions, and  pursue innovative approaches to problem-solving. By fostering intellectual  independence, the program seeks to produce scholars who can make original  contributions to knowledge.</li>
  <li>A key objective of the MPhil program is to  deepen students' subject matter expertise. Through rigorous coursework,  seminars, and engagement with leading scholars in the field, students will  develop a comprehensive understanding of the theoretical frameworks,  methodologies, and key debates relevant to their research area. This objective  ensures that students become authorities in their chosen fields.</li>
  <li>The program emphasizes the development of strong  communication skills among MPhil students. This includes both written and oral  communication, as students are expected to present and defend their research  findings to academic audiences. Additionally, students will be encouraged to  disseminate their research through publications and conference presentations,  ensuring that their work reaches a wider scholarly community.</li>
  <li>The MPhil program places a strong emphasis on  ethical research practices. Students will be guided to adhere to ethical  principles and guidelines while conducting their research, including obtaining  informed consent, ensuring data privacy and confidentiality, and maintaining  integrity in reporting research findings. This objective ensures that students  become responsible researchers who contribute to the advancement of knowledge  while upholding ethical standards.</li>
</ul>
