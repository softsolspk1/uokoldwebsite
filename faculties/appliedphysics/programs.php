  <h3 align="center">B.S. Applied Physics</h3 align="justify"><strong>Mission Statement:</strong><br/>
    The mission of the Department of  Applied Physics at University of Karachi is to provide profound education in  applied physical sciences which can be utilized in various fields of science  and technology. The fundamental approach of the department is to develop  technical skills in the students and is dedicated to educate future generations  of research and development professionals, data specialists, technology  experts, innovators, and scientists, for industries, HEIs, R&amp;D  organizations and society.</p align="justify"><strong>Program Objective:</strong><br />
    The graduates of the department of Applied Physics,  University of Karachi will be able:</p>
  <ul>
    <li>To contribute to advanced technology projects,</li>
    <li>To utilize the technical skills with analytical  approach to conduct research.</li>
    <li>To pursue career in R&amp;D organization as  JSO/SO/PSO; in various industries as technical officers/HoD instrumentation  &amp; control; in system designing and maintenance industry as system analyst,  DM/Managers/GM; and in HEIs as Lecturer/Assistant Professor/Associate  Professor/Professor.</li>
