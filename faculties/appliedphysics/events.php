   <h4 align="center"><strong>Field Visit – Master Windfarm Jhimpir<br />January 21, 2026</strong></h4>
   
   <p align="justify">On January 21,  2026, a full-day study visit to the Master Wind Energy Ltd. was organized for  4th Year students of Morning &amp; Evening programs as part of experiential  &amp; outcome based learning and industry exposure as part of the Renewable  Energy course under the supervision of Dr. Zeeshan Alam Nayyar, In-Charge,  Department of Applied Physics.</p>
