  <h4 align="center"><strong>Prof. Dr. Azhar Ahmad Ansari Legacy Award for Academic  Excellence in Applied Physics<br />
    January 31, 2026</strong></h4>
  <p align="justify">The Department of Applied  Physics, University of Karachi proudly organized a special ceremony to mark the  launch of the Prof. Dr. Azhar Ahmad Ansari Legacy Award for Academic Excellence  in Applied Physics, aimed at recognizing outstanding academic performance among  BS Applied Physics students.</p>
  <p align="justify">The event was chaired by the KU&rsquo;s  Vice Chancellor Prof. Dr. Khalid Mahmood Iraqi and distinguished guests,  Faculty Members, Alumni and Students attended the event held at the  departmental auditorium today. The ceremony highlighted the department&rsquo;s  commitment to promoting academic excellence and honoring the legacy of eminent  educators.</p>
  <p align="justify">The departmental in-charge Dr.  Zeeshan Alam Nayyar informed the audience that Legacy Award has been instituted  to acknowledge students who secure top academic positions each year. This  includes an Award of Academic Excellence for all the position holders of BS  Applied Physics (Morning and Evening Programs) and a cash prize of Rs. 50,000,  which will be awarded to the First Position Holder of the BS Applied Physics  (Morning Program).</p>
  <p align="justify">&ldquo;This prestigious initiative has  been generously established by the Applied Physics Alumni of the 1978 and 1979  Cohorts. Their contribution reflects a deep sense of gratitude and commitment  to their alma mater.&rdquo;</p>
