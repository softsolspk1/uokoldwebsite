  <h3>&nbsp;</h3>
  <h3 align="center"><strong>Research</strong></h3>
  <p align="justify">The Department of Applied Physics  integrates fundamental science with applied research to address critical  challenges in energy, materials, optics, and other allied fields. Faculty  members are engaged in multidisciplinary projects that advance knowledge,  foster innovation, and contribute directly to Pakistan&rsquo;s technological and  industrial development.</p>
  <p align="justify">Research in  renewable energy through Renewable Energy research Lab (RERL) focuses on  technologies that support Pakistan&rsquo;s transition toward sustainability. Key  areas include, but not limited to, wind energy resource assessment, GIS-based energy  modeling, tidal energy, waste-to-energy, smart grid systems.</p>
  <p align="justify">Faculty  members are actively engaged in advanced materials research in Nanoscale Synthesis &amp; Research  Laboratory (NSRL), emphasizing next-generation applications like 2D materials,  topological materials, composite materials and thin films.</p>
  <p align="justify">Research in  optics and related systems supports technological advancement in communication,  sensing, and energy applications for electro-optical &amp; electro-mechanical systems  and thermal optics.</p>
  <p align="justify">Through these research domains,  the Department of Applied Physics contributes to advancing scientific  knowledge, developing indigenous technologies, and training skilled professionals  capable of addressing Pakistan&rsquo;s industrial, academic, and societal needs.</p>
  <p>&nbsp;</p>
  <h3 align="center"><strong>Research Labs</strong></h3>
    
    <p><strong>1. <u> Renewable  Energy Research Lab (RERL):</u></strong></p>
  
  <p align="justify">The Renewable Energy Research  Lab (RERL), formerly known as the Renewable Energy Research Group, was founded  in 2012. From the very beginning, RERL has been committed to addressing the  pressing global challenges of climate change, energy security, and  environmental sustainability.</p>
  <p align="justify">Our lab is a hub for innovation,  focusing on research areas like wind, solar, tidal, waste-to-energy and smart  grids. We're not just about theory—we're on a mission to develop practical,  cost-effective solutions that benefit the planet and make renewable energy  accessible to all.</p>
  <p align="justify">At RERL, we provide an inspiring  space for undergraduate and postgraduate students to explore and solve  real-world energy problems. Whether they're working with cutting-edge software  or experimenting with advanced hardware, students are deeply involved in  shaping the future of energy.</p>
  <p align="justify">Finally, RERL is backed with  high impacts research publications in prestigious journals and conference  participations covering different aspects of wind, solar, smart grid, and  related energy resources.</p>
  
  <p><strong>2. <u> Nanoscale  Synthesis &amp; Research Laboratory (NSRL):</u></strong><br/>
  
  This  lab consists of two sub sections:</p>
  <ul>
    <li><strong>KM Aleem Nanotech Laboratory</strong></li>
  
  <p align="justify">This laboratory is named after  KM Aleem (late), one of the alumni of this department. It was established with  the generous funding and efforts of the family and friends (Alumni 1982) of  late KM Aleem. This section caters the synthesis of nano materials in general  and 2D materials in particular. Synthesis of 2D materials is done using  Chemical Vapor Technique (CVT), Chemical Vapor Deposition (CVD) as well as  hydrothermal method. Moreover, facility is also available to synthesize  nanomaterials using wet chemical method. Synthesized materials can be used in  electronics, optoelectronics, sensors, energy applications etc.<br />
    We are actively working on the  synthesis of TMDs, Mxenes, and other 2D materials in this laboratory. </p>
  
    <li><strong>Ansari &amp; Zaidi Thin Film Laboratory</strong></li>
  
  <p align="justify">This lab is named after two of  pioneer professors of this department to pay homage for their services to the  department. This lab aims at growth of thin films for electronic,  optoelectronics, sensor, and photovoltaic applications. Thin film growth is  carried out by thermal evaporation method using a vacuum coating unit. The lab  is equipped with the facilities to study electrical transport and dielectric  properties of thin films. Moreover, we also use spin coater and ultrasonic bath  for the fabrication of thin films. We are planning to use these facilities to  synthesis composite materials as well.</p>
  <p align="justify">These labs are supported by  extensive publication track record in basic physics, applied physics and  material physics journals of high repute.</p>
  </ul>


