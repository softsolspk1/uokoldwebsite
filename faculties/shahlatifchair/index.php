  <h2>Director: Prof. Saleem Memon</h2>
  <p> The principal aim of the Chair was to initiate research on different aspects of Shah Abdul Latif Bhitai’s life and poetry, and publish books and periodicals regularly to facilitate the students and general public to understand his philosophy. In order to spread his message of peace, love and brotherhood among the people of Sindh, Pakistan and the world, it was decided that the Chair would organize extension lectures, seminars and conferences at local, national and international levels. </p>
