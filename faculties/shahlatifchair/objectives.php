  <p>Prof. Dr. Ayaz Hussain Qadri the then Chairman of the Department of Sindhi, was requested to prepare the PC-I for the proposed Chair, through letter No. S-6/86-522 dated 4-9-1986. The aims and objectives, as described in the PC-I were:  </p>
  <p>&nbsp;</p>
  <ul>
    <li>
      <p> To organize and promote research on the life, poetry, times and the works of Shah Abdul Latif Bhitai, and on the branches of learning which have relevance to the study and understanding of the vision of Shah Latif, i.e. History, Philosophy, Sociology, Comparative Religions, Tasawuf (Mysticism). Literature and Art.</p>
    </li>
    <li>
      <p>To establish a research library and a museum, acquire research material/documents etc, including manuscripts of Shah-Jo-Risalo and works relevant to the study of Shah Latif.</p>
    </li>
    <li>
      <p>To hold and sponsor lectures, talks, seminars, meetings, study groups and conferences on the subjects close to the poetry and philosophy of Shah Latif and to participate in similar activities organized by other organizations.</p>
    </li>
    <li>
      <p>To publish books, pamphlets and journals to achieve the objectives.</p>
    </li>
    <li>
      <p>To institute fellowship.</p>
    </li>
    <li>
      <p>To translate Shah-Jo-Risalo and works on Shah Abdul Latif Bhitai in English, Urdu and other languages.</p>
    </li>
    <li>
      <p>To translate into Sindhi and Urdu all such literature which may promote his thoughts.</p>
    </li>
    <li>
      <p>To compile, translate and publish articles and literature, which may promote brotherhood and unity among the people of Pakistan in order to achieve objectives of national integration and cohesion.</p>
    </li>
  </ul>
