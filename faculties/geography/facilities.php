  <p align="justify">The Department is housed in a two storied  building where lecture rooms, laboratories, seminar library and staff rooms are  provided. The seminar library caters for the immediate reading needs of the  students and is provided with 1000 books form donations. The Map Library of the  Department is well equipped&nbsp;with topographical maps of various areas on  various scales. Total number of such maps is about 2000, aerial photographs and  satellite imageries&nbsp;are available in the Department. </p>
    <p align="justify"><strong><u>GIS Lab.</u></strong><br />
    Computer laboratory of the Department of Geography was  established in March, 1988. Initially it consisted of three PCs and a printer.  Currently this laboratory has fifteen computers, Intel Core 2 duo. Department  has purchased MapInfo Professional Software, which is one of the state-of-art  packages for GIS and Remote Sensing application. Presently, it is being used  for the purpose of teaching and research, in the fields of computer aided  cartography, GIS and Remote Sensing.</p>
    <p align="justify"><strong><u>Prehistoric Museum</u></strong><br />
On  the ground floor of the Department there is a Museum containing relic of  prehistoric cultures of Pakistan. These have been collected from an area  extending to 120 miles around Karachi. The material ranges from early  Paleolithic age through Middle and upper Paleolithic, Mesolithic and Neolithic  to Harappan Age. The museum also displays vertebrate fossils of Miocene Age  derived from Sindh Kohistan and coastal area of Sindh.</p>
    <p align="justify"><strong><u>Seminar Library:</u></strong><br />
    The department contains a fully fledged seminar library  which offers books, Atlases, different types of Maps and topographic sheets to  students. A section donated by Dr. I. H. Zaidi and Dr. M. I. Siddiqui is also  available having their valuable collection of books on various fields of  Geography. Different precious research journals and published material are also  available.  </p>
  
  
