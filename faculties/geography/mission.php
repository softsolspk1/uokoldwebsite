<h3></h3>
 
  <p align="justify"><strong>Mission</strong><br />
    The Department of Geography at  the University of Karachi aims to make students highly professional in the  field of Geography, GIS technology, and Remote Sensing technology. They provide  field survey skills, professional knowledge, and training opportunities for  teachers. The program's objectives align with the university mission and are  measured through comprehensive assessments. Strategies include practical field  trainings, integrating advanced technologies, industry collaboration, and  regular program updates to achieve these objectives.</p>
    <h3></h3>
  <p align="justify"><strong>Vision</strong><br />
    The Department of Geography at  the University of Karachi, established in 1952, has a rich history of  leadership from renowned geographers. It offers comprehensive teaching and  research in various geographic fields, producing a large number of graduates  working globally. The department, which has the highest number of Ph.D. /  M.Phil. graduates in Pakistan, offers graduate and post-graduate programs and  has hosted several geography conferences. It emphasizes practical geographical  research skills and maintains strong international academic partnerships.</p>
 
