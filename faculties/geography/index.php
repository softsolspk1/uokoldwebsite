  <p align="justify">Department of Geography is one of the pioneer departments of University of Karachi. It was established in 1952 under the chairmanship of Professor Dr. Manick B. Pithawala. Professor Oscar Schmider was one of the leading German Geographers who served as Chairman in the department. Department has been providing teaching and research in various fields of Geography for the last sixty years. Department has been served by leading Pakistani Geographers who were educated in USA, UK, Germany, India etc. The Department has an excellent academic history. The Department of Geography is the only Department among Universities of Pakistan which hosted International Geography Union (IGU) Conference. More than twenty Professors have served the Department as Chairpersons. Presently Prof. Dr. Sheeba Afsar is Chairperson. The Department has qualified academic staff which includes Professors, Assistant Professors and Visiting Faculty.</p>
