  <p align="justify"> It is the matter of great satisfaction that with the consistent efforts, the University of Karachi has introduced B.Ed. (Hons) 4 year program. The alternative  paradigm of teacher education program consider structural changes in the system  of teacher education, while redefining the teacher’s roles within the framework  of the school education system.</p>
  <p align="justify">Teacher Education courses in different  countries extend for three or four years providing opportunity to improve upon  teaching skills and the perception of teaching. Teacher education in Pakistan  is for only one year, which does not expose to experiences necessary to enhance  teaching skills and develop a positive perception of profession</p>
  <p align="justify">Our goal is to equip the prospective  teacher with skills essential for a lifelong learning.  We believe that a broad-based, flexible  professional education provides the most appropriate formal preparation to:</p>
