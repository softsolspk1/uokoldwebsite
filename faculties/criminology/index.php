  <h2>Chairperson:  Prof. Dr. Naima Saeed.</h2>
  <p>&nbsp;</p>
  <p align="justify">Criminology is the scientific study of the non-legal  aspects of crime and delinquency, including its causes, consequences,  prevention and rehabilitation from the viewpoints of such diverse disciplines  as sociology, biology, mental and physical health, information technology,  economics and statistics.</p>
 <p align="justify">Criminology was started in 1995 as a Master degree  program under the umbrella of Department of Sociology. Department of  criminology university of Karachi was established by a resolution of Academic  Council since when has been separately working. The Department of Criminology  at the University of Karachi is a pioneering academic institution in Pakistan,  dedicated to the interdisciplinary study of crime, criminal behavior, and the  functioning of the criminal justice system. As one of the first departments in  the country to offer formal education in criminology, it plays a vital role in  addressing contemporary challenges related to crime prevention, legal systems,  social justice, and public safety.</p>
 <p align="justify">The Department  of Criminology is  committed to fostering academic excellence, critical inquiry, and applied  research. Its academic programs are designed to equip students with theoretical  knowledge, analytical skills, and practical competencies required in a range of  professional contexts, including law enforcement, policy development, legal  practice, corrections, and academia.</p>
    <p align="justify">The Department of Criminology at the University of  Karachi aims to be a leading centre of academic excellence in criminological  theory, research, and practical application. We are dedicated to fostering a  diverse community of scholars, practitioners, and policymakers who contribute  to the advancement of criminological knowledge while addressing real-world  challenges. Through collaboration with communities, we strive to promote  justice, equity, and sustainable social change.</p>
 <p align="justify">The Department of Criminology at the University of  Karachi is committed to advancing academic excellence and professional  competence in the field of criminology and criminal justice. Its mission is to  educate and train students through rigorous undergraduate (BS), postgraduate  (Master&rsquo;s), and doctoral (PhD) programs that integrate theoretical knowledge  with practical application.</p>
   <p align="justify">The Department of Criminology aims to cultivate  critical inquiry, interdisciplinary research, and ethical responsibility among  students, preparing them to address complex issues related to crime, law enforcement,  forensic investigation, corrections, and public policy. By fostering  collaboration with academic institutions, criminal justice agencies, and civil  society organizations, the department seeks to contribute meaningfully to the  development of informed public policy and the promotion of a just, safe, and  equitable society.</p>
  <p align="justify">Through its teaching, research, and community  engagement, the Department of Criminology aspires to produce scholars and  professionals equipped to lead in the fields of criminology, criminal justice,  and social development at both national and international levels.</p>
  <p align="justify"><strong>Curriculum </strong><br />
    The Department of Criminology at the University  of Karachi offers a dynamic and modern curriculum designed to meet the  challenges of today&rsquo;s rapidly changing world. The syllabus provides students  with strong foundations in criminological theory, criminal law, policing,  victimology, corrections, and forensic science, while also incorporating  specialized contemporary fields. Intelligence Studies equips students with  skills to analyze and utilize information for crime prevention,  counter-terrorism, and combating organized crime. Security Studies addresses  national, regional, and international security concerns, focusing on strategies  to protect societies against emerging threats. Environmental Criminology  examines how physical and social environments influence criminal behavior,  emphasizing urban planning and crime prevention through environmental design.  Cyber Criminology prepares students to understand and tackle digital crimes  such as hacking, fraud, and identity theft, along with relevant cyber laws and  preventive measures. The inclusion of Artificial Intelligence in Criminology  introduces students to cutting-edge applications such as predictive policing,  big data analysis, and AI-driven surveillance systems. This comprehensive  approach ensures that graduates are not only well-versed in traditional  criminology but are also prepared to address future challenges in security,  technology, and justice.<br />
