<h3 align="justify">Learning Outcomes</h3>
<p align="justify">The Statistics Department offers a degree program leading to the B.S. degree in Statistics in the College of Science and Mathematics.<br />
  The Statistics Department graduate will:</p>
<ul type="disc">
  <li>Have good working knowledge of the most commonly used statistical methods, including</li>
  <ul type="circle">
    <li>statistical modeling and the omnipresent role of variability</li>
    <li>efficient design of studies and construction of effective sampling plans</li>
    <li>exploratory data analysis</li>
    <li>formal inference process</li>
  </ul>
  <li>Have background in probability, statistical theory, and mathematics, including especially calculus, linear algebra and symbolic and abstract thinking</li>
  <li>Be able to synthesize and apply knowledge of common inferential methods, understanding the limitations of the procedures and the appropriate scope of conclusions</li>
  <li>Communicate effectively (written and oral) with skills in collaboration (within and between disciplines) and teamwork, and in organizing and managing projects</li>
  <li>Have good mastery of several standard statistical software packages and facility with data management strategies</li>
  <li>Have a focused concentration in an area of application outside the discipline of statistics</li>
</ul>
<p align="justify">&nbsp;</p>
<p align="justify">The Statistics Department graduate will have received:</p>
<ul type="disc">
  <li>Experience with real data and authentic applications</li>
  <li>Frequent opportunities to develop communication skills</li>
  <li>Capstone experiences for students</li>
  <li>Frequent interaction with faculty and their peers and timely advising</li>
  <li>Exposure to statisticians and statistical applications outside the KU community.</li>
</ul>
<h3>Service</h3>
<p>The service objectives are to contribute to the on-going and long-term activities of the Department, University, and the statistical community. They include the following:</p>
<ul type="disc">
  <li>To improve the research and educational environment of the department and the University by facilitating recruitment of faculty and students, serving on committees, and participating in long-term planning activities.</li>
  <li>To contribute to the statistics profession and to the larger scientific community by serving on editorial boards, review panels, and administrative and advisory committees.</li>
  <li>To promote statistical reasoning and the use of statistical principles at the University of Karachi and in society at large.    </li>
</ul>
