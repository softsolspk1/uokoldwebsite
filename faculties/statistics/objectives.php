  <h3 align="justify">Mission</h3>
  <p align="justify">The mission of the Department of Statistics is to contribute to the overall objectives of the University of Karachi and the Affiliated Colleges, Science, and the Arts through excellence in research and education in the Statistical Sciences and through service to the university community, statistical profession, and society at large.</p>
  <p align="justify">The proliferation of quantitative information in society demands that we help to develop the next generation of statistics professionals while increasing the statistical literacy of our students and the frequency of collaboration with our colleagues. To meet these objectives, the mission of the  Statistics Department is to:</p>
  <ul type="disc">
    <li>Deliver a high-quality statistics program for our majors and minors that prepares them for either the workplace or further study in graduate programs;</li>
    <li>Offer service courses for the university that meet the needs of the various majors and enhance the statistical literacy of the students;</li>
    <li>Support continued growth of Statistics faculty members as teacher-scholars. To contribute to the theoretical and applied development of the field through scholarly research in core areas of statistical theory and probability and publications in leading professional journals.</li>
    <li>To contribute to the development of new statistical methodology to address substantive problems and to promote the use of these methods through publications in both statistics and subject-matter journals.</li>
    <li>To contribute to the advancement of science and technology through interdisciplinary research, jointly with scientists at the University of Karachi and at other research institutions and develop a research culture in society in general.</li>
</ul>
  <p>&nbsp;</p>
  <p align="justify">The Department's goals are to effectively serve the diverse educational needs of the students in the College and the University through a variety of activities and programs. These activities / programs and their objectives are:</p>
  <ul type="disc">
    <li>Service Teaching: To educate the students in the Affiliated Colleges of Karachi University and the University of Karachi in basic principles of statistical reasoning and statistical methods for data collection, analysis, and visualization through a range of introductory and intermediate courses and Postgraduate Diploma.</li>
    <li>Undergraduate Majors and Minors: To provide specialized training for students interested in careers in Statistics or in pursuing graduate programs in Statistics or related fields; to develop a strong quantitative background in statistics and data analysis for students pursuing a degree in another field.</li>
    <li>M.S. / Ph.D. program: To prepare M.S. / Ph.D. students for careers in research and consulting by providing them with advanced education in theory and methodology and by training them to carry out independent research.</li>
</ul>
