  <h2>Chairperson: Dr. Sadia Mahmood (Assoc. Prof.)</h2>
  <p align="justify">Previously known as the Department of Journalism, the Department of Mass Communication was established in 1955 with a diploma course  designed for working  journalists. The primary  objective was to produce qualified journalists and media professionals  to meet the growing needs of the national press and the Mass Communication  industry. In 1962, the diploma program was replaced by a regular two-year M.A.  program in light of the recommendations of the Pakistan Press Commission, with  the aim of expanding and modernizing media education in the country.</p>
 <p align="justify">The Department of Mass Communication continues to offer high-quality education  in Journalism, Advertising, Public Relations and Electronic Media.  Faculty members bring extensive professional experience from Print,  Radio, Television, Advertising and Public Relations, ensuring students receive  both theoretical and practical exposure to the media industry.</p>
  <p align="justify">Keeping pace with the changing media landscape, the department has  introduced new program including the BS Four Years Digital Media Marketing degree,  which equips students  with cutting- edge skills in  content creation for social media platforms, SEO, analytics, and digital  marketing strategies. This addition reflects the department&rsquo;s commitment to  preparing graduates for the demands of the modern digital  economy and emerging  career opportunities in the global  media and marketing industries.</p>
<p>&nbsp;</p>
  <h3>Teaching and Assessment</h3>
  <p align="justify">Apart from class lectures, students are required to do tutorials and assignments. It is also mandatory for each student to complete 180 hours of internships at media institutes. A certificate on satisfactory completion of internship enables students to apply for a marks sheet and a degree.</p>
  <p>&nbsp;</p>
  <h3>Career  Opportunities</h3>
  <p align="justify">The Department  of Mass Communication prepares students for a wide range of career  opportunities in the rapidly evolving media and communication industry.  Graduates can pursue roles in journalism as reporters, editors, feature  writers, broadcast journalists, and documentary producers, or work in  electronic media as television producers, radio broadcasters, news anchors,  video editors, and camerapersons.</p>
  <p align="justify">Exciting  prospects also exist in advertising and public relations as creative directors,  copywriters, media planners, brand managers, PR officers, and corporate  communication specialists. In the digital space, students are equipped for  careers as digital strategists, social media managers, SEO and SEM specialists,  content creators, community  managers, analytics experts,  and e-commerce marketers. Many also choose to work as independent  consultants, freelancers, or entrepreneurs, launching their own media and  marketing ventures.</p>
