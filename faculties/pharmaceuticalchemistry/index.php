  <p align="justify"><strong>Specific Research Areas</strong>br/>
  The  department has a rich history of excellence in research. Experienced and  actively growing research groups are working in the disciplines of drug  designing and development, product and process development of drug, analytical  aspects of drug, nanotechnology, kinetic studies and drug stability.  Researchers are working with different.</p>
<p>&nbsp;</p>  
<p align="justify"><strong>Career Opportunities </strong><br/>
Graduate  program of the department is dedicated to educate and train the students to  produce active, skilled and responsible future pharmacist for academia,  industry, hospitals and government setups. They can go in production, quality  control, marketing and drugs regulatory department of different pharmaceutical  industries. They can also work as part of a healthcare team comprising doctors,  pharmacists and paramedical staff. They can play an effective role as drug  experts, able to select best treatments for managing patient care. Apart from  these, there is a number of opportunities available in administrative and  general management sites in government health department. Pharmacists with M. Phil.  and or Ph.D. degree can also join teaching and research organizations.</p>
