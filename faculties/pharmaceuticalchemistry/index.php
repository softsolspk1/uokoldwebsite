  <h2>Chairperson: <strong>Prof. Dr. Asia Naz</strong></h2>
  <p align="justify">Department  of Pharmaceutical Chemistry is one of the most important academic units of the  Faculty of Pharmacy and Pharmaceutical Sciences. Department is dedicated to  provide sound education in the field of Pharmaceutical Chemistry and deals with  the physical and chemical aspects of Pharmaceuticals. Courses offer by the  Department are based on organic chemistry, physical chemistry, analytical,  instrumental and medicinal chemistry, with a focus on drug discovery and  development. Currently, the department has four Professors, two Associate  Professors, and four Assistant Professors. All are Ph.D. holders and actively  engaged in teaching and research. The department aims to promote learning  environment and training of students in the advanced specialized areas of the  field.</p>
