    Pharmaceutical Statistics Cr. Hrs. 3</p>
  <p>1. Description of statistics: Descriptive statistics: What is statistics? Importance&rsquo;s of statistics. What is biostatistics? Application of statistics in biological and pharmaceutical sciences. How samples are selected.</p>
  <p>2. Organizing and displaying data: Variables, quantitative and qualitative variables, univariate data, bivariate data, random variables. Frequency table, diagrams, pictograms, simple bar charts, multiple bar charts, histograms.<br />
