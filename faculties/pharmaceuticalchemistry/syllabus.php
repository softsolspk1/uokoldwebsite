  <p><strong>PHARMACEUTICAL CHEMISTRY PHC-313 </strong><br />
    Pharmaceutical Mathematics Cr. Hrs. 3</p>
  <p>1. Algebra <br />
    Common and natural logarithm, solution of linear and quadratic equations. Equations reducible to Quadratic form, solution of simultaneous equations. Arithmetic. Geometric and harmonic progressions. Arithmetic, geometric and harmonic means, permutations and combinations. Binomial Theorem: Simple application.</p>
  <p>2. Trigonometry<br />
    Measurement of angels in radian and degrees. Definitions of circular functions. Derivation of circular function for simple cases ant trigonometry identities.</p>
  <p>3. Analytical Geometry<br />
    Coordinates of point in a plane. Distance between two points in a plane. Locus. Equations of straight parallel and perpendicular lines. Equation of parabola, circle and ellipse.</p>
  <p>4. Differential Calculus<br />
    Limit, concept of derivations. Rules of differentiation, examples on the evaluation of derivations. Derivatives of algebraic, trigonometric, exponential and logarithmic functions, partial derivations, higher order derivatives. Maxima and minima points of inflections.</p>
  <p>5. Integral Calculus<br />
    Concept of integration. Rules of integration&rsquo;s. Integration&rsquo;s of algebraic, exponential, logarithmic and trigonometric functions by using different techniques and numerical integration.</p>
  <p>Books Recommended</p>
  <p>1. Text Book of Algebra and Trigonometry for Class XI and XII (New edition).<br />
    2. Edvards, C.H. Jr. and David E. Penney. Calculus and Analytical Geometry (1995).</p>
