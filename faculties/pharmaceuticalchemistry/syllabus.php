  <h3 align="center">First Professional First Semester</h3>
  <p><strong>PHARMACEUTICAL CHEMISTRY PHC-303</strong><br />
    Organic Cr. Hrs. 3</p>
  <p>1. Introduction to pharmaceutical chemistry, classification and nomenclature of organic pharmaceutical compounds. hyperconjugation, steric effects inductive effect and mesomeric effect,.<br />
    2. Nucleophilic and electrophilic substitution reaction in aromatic system. Theory of resonance.<br />
    3. Orientation in electrophilic substitution reactions on benzene ring.<br />
    4. Organic reactions: Baeyer-Villiger oxidation; Diels Alder reaction; Grignard&rsquo;s reaction, metal hydride reduction and Wolf Krishner reduction, Friedel Craft&rsquo;s reaction, Perkin reaction, Cannizzaro reaction.<br />
    5. Carbonium ion rearrangements; Pinacol-pinacolone, Wagner-Merrwein, Wolf, Hofmann and Beckmann rearrangments.<br />
    6. Carbanions; condensation reaction (Aldol condensation; Favorskii rearrangment; Wittig reaction).<br />
    7. Stereoismerism, optical isomerism, geometrical isomerism, tautamerism of carbonyl compounds, resolution of reacemic mixture and conformational analysis. <br />
    8. Free radicals: Introduction, structure and stability. <br />
    9. General methods of preparations, properties, identification test and pharmaceutical applications of the following classes and their analogs:<br />
    alcohols, phenols, ethers, aldehydes, ketones, carboxylic acids, esters, amines and aniline.</p>
  <p>Books Recommended</p>
  <p>1. Andrew Streitwieser, Jr., Clayton H. Heathcock. Introduction to Organic Chemistry. Second edition. Macmillan Publishing Co., Inc., New York (1981).<br />
    2. Graham Solomons T.W. Organic Chemistry. Fifth edition, John Wiley &amp; Sons, Inc. (1992).<br />
    3. Marye Anne Fox and James K. Core Organic Chemistry. Whitesell, Jemes and Bartlett Publisher (1997).<br />
    4. by Peter Sykes. A Guide Book to Mechanisms in Organic Chemistry. Fourth edition, Longman Group Ltd. (1978).<br />
    5. Jayashree Gost, S. A Textbook of Pharmaceutical Chemistry by Chand and Company Ltd. (1997).</p>
