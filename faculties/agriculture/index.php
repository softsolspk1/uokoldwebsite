  <h2>Chairperson: Prof. Dr. Saboohi Raza</h2>
  <p align="justify">The department of Agriculture  launched its BS-Program in Agriculture in 2004 and acquired the status of the  department in 2006. It was renamed as the Department of Agriculture and  Agribusiness Management in 2008. The Department offers specializations in <strong>&ldquo;Agribusiness management&rdquo;, &ldquo;Plant  protection&rdquo; </strong>and &ldquo;<strong>Plant pathology</strong>&rdquo;.</p>
  <p align="justify">Agribusiness is an important and  ever expanding industry in Pakistan. It combines the study of agricultural  sciences with the management skills providing an understanding of economic and  business principles and their application to Agribusiness. The program aims to  develop a range of personal and transferrable skills along with the critical  appreciation of the techniques to assist effective execution of agribusiness  management function.</p>
  <p align="justify">It cannot be denied that the  implementation of proper pest and disease management strategies can be helpful  in increasing the crop yield and ultimately boost the economy of the country.  The courses offered for specialization in plant pathology or plant protection  enable the students to acquire an in-depth knowledge of pest and diseases  affecting crops, vegetables, fruits and ornamental plants in the country and  make them aware of the management strategies to overcome the problem in an  eco-friendly manner.</p><br/>
  <h3>Teaching and Assessment</h3>
  <p align="justify">During the first two years, courses  related to different fields of agriculture are taught to develop good  background knowledge of the subject. From the third year, students can choose  either <strong>Agribusiness Management, Plant  Protection or Plant Pathology</strong> as their field of specialization. Assessment  is done as per semester rules that include midterm, Make-up and terminal  examinations, and a lab examination or assignment. In the final semester,  internship in either a research or agribusiness related organization is  mandatory. </p><br/>
  <h3>Career Opportunities</h3>
  <p align="justify">Specialization in Agribusiness  management is helpful in getting jobs in farm business related to national and  multinational organizations as managers, consultants, supply chain coordinators  and accountants. It also provides an opportunity to enter self-employment  immediately after graduating, largely within the farming or food sectors. </p>
  <p align="justify">Students specializing in plant  protection or plant pathology have job opportunities in various research  organizations like Department of plant protection, PARC, PCSIR, NIAB, NIA, ARI  etc. They can also get jobs in plant and pesticide related national and  multinational organizations or can initiate their own business to provide pest  and disease management services to farmers. </p>
