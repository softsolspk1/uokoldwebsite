  <h2>Chairperson:   <strong>Prof. Dr.  Shamim A. Qureshi</strong></h2>
  <p>&nbsp;</p>
  <p>Biochemistry  at University of Karachi started as part of the Department of Chemistry in 1962  under the Chairmanship of&nbsp;Dr. Rafiq Ahmed.&nbsp;Dr. MA Wali, Dr.  Zain-ul-Abedin and Dr. Sabir Ali&nbsp;have served as Department Chairs. During  the tenure of the first three Chairs research within the Department was closely  associated with the interests of the Chairs and was mentor to many scientists  as they established their research careers here.&nbsp;Through its history since  then the department has flourished under the direction of eleven chairpersons  and currently have 27 faculty members and a MPhil/PhD program for which the degrees  have been granted in the department since 1975. </p>
  <p> Research  work at molecular level led to an era of explosive productivity within the department  and the training of a whole generation of young scientists, many of whom went  on to distinguished careers in Biochemistry. With the creation&nbsp;of&nbsp;an  independent&nbsp;department, the faculty expanded slowly to include three  professors by 1970; 12 professors by 2007 and now 27 faculty members in 2012.  Student enrollment and PhDs awarded also increased as  the&nbsp;department&nbsp;expanded with increase in the annual scientific  productivity.&nbsp;&nbsp;In recent years an average doctoral student had just  over 3 co-authored papers from dissertation research, and is first author on  two papers. </p>
  <p>The department sets out to meet a key goal of modern  biology – to arrive at a full understanding of the structure and dynamic  chemistry of the underlying molecular constituents of cells, the essential  feature is that biochemistry uses molecular methods to explain biological processes.  The focus of research has shifted towards molecular biochemistry, genomics and  proteomics, biotechnology, cellular biophysics and structural biology, clinical  biochemistry, biochemical neuropharmacology, bioinformatics, nutritional  biochemistry  with several independent  groups engaged in studies in molecular structure determination, molecular  mechanisms of membrane trafficking, protein folding, and signal  transduction.&nbsp;</p>
  <p>    The Department of Biochemistry now covers such a wide  range that it is difficult to draw a demarcation around biochemistry it provides  a multidisciplinary and collaborative setting that brings together cell  biologists, neurochemists , clinical biochemists, biophysicists,  nutritionists, enzymologist,  geneticists, systems/computational biologists  and structural biologists which provides the foundations of pathology,  pharmacology, physiology, genetics. The research programs of most of the  faculty within the Department revolved around these central themes. Major  projects within the Department involved the understanding of the mechanism and  regulation of enzymes, clinical chemistry, biotechnology ,behavioral neuropharmacology,  protein-protein interactions, characterization of proteins in disease  conditions using 2-DE and Mass Spectrometry, western blotting, HPLC and the  structure of proteins using biophysical methods such as ultracentrifugation and  electron microscopy.</p>
  <p> Subsidiary student teaching remains an important role  of department faculty. The Biochemistry faculty members are principally  involved in the first Basic Science course,&nbsp;Molecules, Genes, and Cells to  approximately 1200 students per year. Graduate students are the leaders of  tomorrow and play a critical role in keeping the department at the forefront of  international research. Many of whom went on to distinguished careers in  Biochemistry like faculty at the world renowned Universities like Harvard  University and  NIH USA .</p>
  <p>Over the years, faculty in the Department of  Biochemistry has received considerable recognition, including receipt of major  University awards, election to the National Academy of Sciences, International  Advisory committee members and International Scientific Society Council members.  We are proud of our history and current status, and we strive towards continued  excellence in research, training, and service in the field of biochemistry.</p>
