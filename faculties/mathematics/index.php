  <h2>Chairman: Prof. Dr. Najeeb Alam Khan.</h2>
  <p align="justify">The University of Karachi  holds a unique position in the country's educational system. Its prestigious  research and teaching institution meets the commitment to spreading knowledge  through its programs. The research activities comprise original investigations,  discussions, lectures, and teaching at various levels. We are deeply committed  to supreme research in mathematics, and the scientific excellence of our  faculty is well recognized.</p>
  <p align="justify">Department of Mathematics was  established in 1956, and Prof. Dr. Suleman Kerawala was the founder Chairman.  It is one of the largest departments of the Faculty of Science, having a  well-equipped auditorium, E-laboratory with free internet and E-Library.</p>
  <p align="justify">We offer academic challenges  and support to our students to help them succeed. We encourage them to develop  problem-solving abilities to excel in mathematics. We collaborate with local  community organizations, professional associations, other campus entities, and  individuals. We promote the belief that mathematics holds an essential place in  the history of humanity and it is valuable in the future of all disciplines.</p>
<p align="justify">We offer BS in pure, applied,  financial, and computational mathematics. The Bachelor programs lead to the  Master of Arts, Master of Science, Master and Doctor of Philosophy degrees with  a major in Mathematics. In these programs, we cover a variety of subjects  related to Mathematics, such as: Programming, business management, actuarial  sciences, data sciences, accounting, and engineering etc.</p>
  <p align="justify">The department is well-known  for its long history, strength, and rigorous scholarships. Since its  establishment, many outstanding mathematicians have served here. It has always  had a leading status at home. It has been well-known abroad for its academic  influences, especially in Non-Linear Mechanics, Dynamical Systems, Convex  Analysis, Numerical Integration, Differential equations, Mathematical  Inequalities, Mathematical and Statistical Modeling in Climate Dynamics, and  Scientific and Engineering Computing.</p>
