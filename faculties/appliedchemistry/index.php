  <h2>Chairman:  Prof. Dr.   Mohib Reza Kazmi</h2>
  <p><br />
The department of Applied Chemistry was established in 1971 and was shifted to its new building in 1987. The courses have been designed keeping in view the need of the chemical industries of Pakistan and with due consideration of courses of foreign and local Universities offering similar program. Special emphasis has been put on important chemical industries of Pakistan, for instance, fertilizers, refineries, cement, sugar, polymers, pharmaceutics, textiles, etc. Due consideration has been given to important aspects of chemical engineering like unit operations, unit processes, quality control &amp; instrumentation, thermodynamics reaction engineering, design engineering, materials engineering, maintenance and environmental engineering, etc. Hence it is hoped that the graduates of this department will meet the needs of the chemical industries of Pakistan. </p>
  <h3>Teaching and Assessment </h3>
