  <h2>Dean:  <strong>Prof. Dr.  M. Harris Shoaib. <a href="/faculties/pharmaceutics/dhs.pdf" target="_blank">(Profile)</a></strong></h2>
  <p>&nbsp;</p>
<p align="justify">The Faculty of Pharmacy &amp; Pharmaceutical Sciences at the University of Karachi owes its origin to the Department of Pharmacy, which was established in 1964. The Department of Pharmacy was founded in response to the need of better drug delivery system in hospitals and retail pharmacy, and also to cater the ever growing need of pharmaceutical industries because 90 percent of the drug based industry in Pakistan, both national and multi-national, is located at Karachi.<br/>
<p>The Department of Pharmacy was raised as the first full-fledged Faculty of Pharmacy in the country. The faculty comprises five teaching and research departments viz. Pharmaceutics, Pharmaceutical Chemistry, Pharmacognosy, Pharmacology and Pharmacy Practice. More than 2000 regular students are today pursuing their studies leading to the award of Pharm. D., M. Phil. and Ph.D degrees.<br/>
<p>Apart from these departments the faculty also has a Research Institute of Pharmaceutical Sciences in which research on different aspects of drugs is conducted.</p>
<p>&nbsp;</p>
<h3>Career Opportunities </h3>
<p align="justify">Pharmacy as a distinct profession forms the edifice of the health care system on which lies success of well-being of the community. With the rise of population worldwide during the last few decades, it has been realized that the conventional traditional medical and healthcare services are unable to pay any significant role in the overall improvement of health status. This realization has driven all health professionals to the common goal of disease prevention and health promotion. In developed countries the clinical direction of Pharmacy has laid emphasis on the manipulative product-oriented and distributive skills and focuses more on the public health awareness. Today the Pharmacy profession has become highly patient-oriented which this has created much more opportunities for the pharmacists in hospital and community especially in the USA, Canada, Australia and the Middle East, while in Pakistan still 75% opportunities are in the industrial sector.</p>
