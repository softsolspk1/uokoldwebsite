  <h3 align="center">Program Objectives and Learning  Outcomes</h3>
  <p>&nbsp;</p>
  <p align="justify">The Pharm.D. program at the Faculty  of Pharmacy and Pharmaceutical Sciences, University of Karachi, aims to provide  students with a well-rounded education in pharmaceutical sciences. The program  focuses on core areas, including Pharmaceutics, Pharmacology, Pharmaceutical Chemistry,  Pharmacognosy, and Pharmacy Practice, enabling students to develop a deep  understanding of the field. A key objective of the program is to foster ethical  and professional development among students, ensuring they adhere to high professional  standards in all aspects of pharmacy practice.</p>
   <p align="justify">The Pharm.D. program graduates will  possess the knowledge and skills necessary to deliver high-quality  pharmaceutical care, applying scientific principles in real-world healthcare  settings. They will also be well-prepared to collaborate within  interdisciplinary healthcare teams, demonstrating effective communication and  interpersonal skills. Moreover, the program emphasizes lifelong learning,  equipping students to keep up with advancements in pharmaceutical sciences and  continuously improve their professional competence. These objectives and  outcomes ensure that students are well-prepared for diverse roles in  healthcare, industry, academia, and research, meeting both national and  international standards of the pharmacy profession.</p>
