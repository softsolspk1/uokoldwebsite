  <p align="justify">Pharmacy is a distinct profession and on it lies the success of any health program. With the rise of population world wide during the last few decades, it has been realized that the traditional medical and health services now play a limited role in the overall improvement of health status. This fact has driven all health professionals to the common goal of disease prevention and health promotion. In developed countries the clinical direction of Pharmacy has deemphasized the manipulative product oriented and distributive skills and focused more, on the public health awareness. Today, the pharmacists’ attention is directed towards the patient, his environment, and his state of general well-being. Pharmacy has achieved many successes in the past few years, it has undergone a transformation whereby both practice and teaching of the subject has been placed on more quantitative, rational and scientific bases, so much so that the Drug Oriented Pharmacy has now attired itself to Patient Oriented Pharmacy in most of the Western World.</p>
  <p align="justify">In United States, the Pharmacy professional is highly patient oriented, they have much more opportunities in hospital and community environment. Same trend is being followed in Middle East market, whereas locally in Pakistan, 75% opportunities are in Industrial sector. Although in Pakistan, this sector is also now reaching a level of saturation, which will result in diversion to other branches like marketing, hospital and community. Accordingly we will have to prepare our graduates for the changing trends, especially if they aim to work globally. This has become possible by reviewing our Pharmacy syllabi and changing the same to meet the local and global needs and requirements.</p>
  <p align="justify">The Faculty of Pharmacy, University of Karachi after a long and thorough discussion as well as practical work, converted the curriculum proposed by PCP (based on annual examination system) into semester examination system. There are 200 credit hours spread over 5 years. The Faculty has also designed one year deficiency courses of 2 semester duration for those holding 4 years B.Pharm degree in order to upgrade to Pharm-D (5 years program) if they so desire. These courses have been approved by the Board of Studies of each department as well as by the Board of Faculty.</p>
