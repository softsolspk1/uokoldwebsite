  <p>Assessment of performance on the basis of marks out of 100 fixed for a course of 3 or 4 credit hours unit is NG.</p>
  <p>b. Alphabetical Grade (AG)</p>
  <p>Equivalent of numerical grades in terms of alphabets shall be termed as alphabetical grades. (Each letter carries a value in terms of numerical points).</p>
