  <h4>3.<a name="DAR" id="DAR">Requirement for the Award of Pharm-D. Degree</a></h4>
  <p>a. A student must have passed all prescribed courses.</p>
  <p>b. A student must have obtained a minimum CGPR 2.45</p>
  <h4>4.<a name="PRR" id="PRR">Rules Concerning the Promotion and Repetition of Course</a></h4>
  <p>A student would be promoted to next higher class upon clearing 80% of courses. In case of any misinterpretation and discrepancy Deans' Committee would be the final authority in deciding any representation.</p>
  <p>(Approved by the Academic Council on 17-3-1999, vide Resolution No.1).</p>
  <h4>5.<a name="ATT" id="ATT">Attendance</a></h4>
  <p>Attendance in each subject is compulsory for all students and no student shall be eligible to appear at any University examination unless he has attended 75 per cent attendance in the course.</p>
  <p>i. The attendance of students admitted in the Faculty will be counted from the 1st day of semester and not from the date of admission.</p>
  <p>ii. Students called for national duty such as participation in Olympics, National Games, Inter-varsities, and going to perform Haj would be given exemption in attendance for the actual period of national duty/Haj. These cases would be decided individually.</p>
  <p>iii. If a student is unable to attend classes continuously for 15 days or more without informing the Dean/Chairperson of the Department (in writing) his/her admission will also stand cancelled. In case of illness or other similar situation, application along with a medical certificate from a registered medical practitioner duly verified by the Senior Medical Officer of the University must be submitted within two days after the incident.</p>
  <p>iv. Original attendance register is to be submitted to the Dean/ Chairperson for record and future reference.</p>
  <h4>6.<a name="MD" id="MD">Maximum Duration for Completion of Degree</a></h4>
  <p>i. Degree enrollment of the Pharm-D. will remain valid for two more years after the expiry of the required duration for the completion of the Pharm-D. degree (i.e. 5 years).</p>
  <p>ii. However a student unable to complete his/her degree requirement within the validity of his/her enrollment, will have to re-validate/extend his/her enrollment for not more than 2 years by paying a prescribed fee with the permission of Dean.</p>
  <h4>7.<a name="CAR" id="CAR">Cancellation of Admission/Readmission</a></h4>
  <p>i. If a student admitted in Pharm-D. 1st year class for the first time fails to attend the class for the first 15 days his/her admission shall stand cancelled.</p>
  <p>ii. If a student absents himself/herself for 15 consecutive days during the semester without any information, his/her admission shall also be cancelled. Re-admission would be granted in the same semester by the Dean if he/she can complete his/her attendance requirement.</p>
  <p>iii. If a student is unable to continue his/her studies during his/her studies, his/her admission will be treated as cancelled. He/she may however be re-admitted after the payment of prescribed fee in the same semester where he/she had left. Permission would be granted by Dean.</p>
  <p>iv. He/she may be allowed 3 chances to pass/get promoted in the next higher class if he/she has completed the attendance requirements.</p>
  <h4>8.<a name="UNM" id="UNM">Unfair Means</a></h4>
  <p>All the cases of unfairmeans will be forwarded to the Committee appointed for the purpose and the matter will be dealt with in accordance with the rules and regulationsof the University.</p>
  <h4>9.<a name="ISR" id="ISR">Interpretation of Semester Rules</a></h4>
  <p>The decision of the Deans' Committee would be final for the interpretation of semester rules. In case of any appeal Deans' Committee would dispose it off on its merits.</p>
