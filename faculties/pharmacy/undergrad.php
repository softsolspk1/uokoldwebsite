  <h4>1.<a name="TE" id="TE">Terminal Examination</a></h4>
  <p>The examination held at the end of semester after the completion of a course shall be known as Terminal Examination. It will carry 100 marks. This examination is a passing head i.e., a student must for each course obtain a minimum of 50 marks in this examination.</p>
