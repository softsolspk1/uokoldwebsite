  <h3 align="center">Acceptance Requirements and Criteria</h3>
  
  <p align="justify">To be  eligible for admission into the 5 years Doctor of Pharmacy (Pharm.D.) program  at the University of Karachi, applicants must meet the following criteria:</p>
      <P align="justify"><strong>Academic Qualifications:</strong><br/>
       Completion of Higher Secondary Certificate (H.S.C.) in the Pre-Medical group or an equivalent       international qualification, with a minimum of 60% marks (Grade 'B').       Admissions are test-based, with a minimum of 50 % passing marks.</P>
       
    <P align="justify"><strong>Merit-Based Admission:</strong><br/>
     Admission is competitive, with       200 seats allocated on a merit basis for the morning Pharm.D. program and       100 seats in the evening Pharm. D program, including reserved seats for international       students.</P>
  
  <P align="justify"><strong>Degree Upgradation:</strong><br/>
   Individuals holding three- or four-year  pharmacy degrees can upgrade to the five-year Pharm.D. program by completing  the necessary deficiency courses.</P>



