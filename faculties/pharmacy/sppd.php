  <h3 align="center">Standard Programs upon which the  Program is Designed</h3>
    <p>&nbsp;</p>
  <p align="justify">The Pharm.D. program at the Faculty  of Pharmacy and Pharmaceutical Sciences, University of Karachi, is designed in  accordance with international and national standards, ensuring high-quality  education and training in pharmaceutical sciences. The key standards and  guidelines upon which the program is based include:</p>
  <ul>
    <li>1. <strong> Pharmacy Council of Pakistan       (PCP) Standards:</strong><br/>
    The program strictly follows the  requirements set by the Pharmacy Council of Pakistan, including curriculum  structure, minimum contact hours, and mandatory clinical training.</li>
  <p>&nbsp;</p>
    <li>2. <strong> Higher Education Commission       (HEC), Pakistan Guidelines:</strong><br/>
    The curriculum aligns with HEC&rsquo;s  national framework for professional degree programs in pharmacy, covering core  pharmaceutical sciences, clinical practice, and research.</li>
    <p>&nbsp;</p>
    <li>3. <strong> World Health Organization (WHO)       Recommendations:</strong><br/>
   WHO guidelines on good pharmacy  education practices are integrated into the curriculum, particularly in areas  of clinical pharmacy, community pharmacy, and pharmaceutical care.</li>
  <p>&nbsp;</p>
   <li>4. <strong> Competency Frameworks:</strong><br/>
   The program incorporates elements  from globally accepted competency frameworks for pharmacists, such as the <strong>International  Pharmaceutical Federation (FIP)</strong> framework, to ensure graduates are  well-prepared for diverse roles in healthcare, research, and industry.</li>
   </ul>
   
   <p align="justify">This  standards-based design ensures that program graduates meet the professional requirements  of both local and international pharmacy sectors.</p>
