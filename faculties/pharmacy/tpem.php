  <h3 align="center">Theoretical and Practical Evaluation  Mechanism</h3>
    <p>&nbsp;</p>
  <p align="justify">The Faculty of Pharmacy and  Pharmaceutical Sciences at the University of Karachi employs a comprehensive  evaluation mechanism to assess both theoretical knowledge and practical skills  of Pharm.D. students. This system ensures that graduates meet the academic and  professional standards required in the field of pharmacy.</p>
  <p></p>
  <p><strong>Theoretical Evaluation:</strong>
  <ul>
   <li><strong>Terminal Examinations:</strong><br/>At the conclusion of each semester,  students undertake terminal examinations for each course, each carrying 100  marks. A minimum score of 50 marks is required to pass these examinations.</li>
  <li><strong>Grading System:</strong><br/>Student performance is quantified  using a numerical grade (NG) out of 100, which is then converted into an  alphabetical grade (AG) with corresponding grade points. The grading scale  ranges from A+ (90 and above, 4.0 grade points) to D (50-52 marks, 1.0 grade  point), with any score below 50 considered a failing grade (0.0 grade points).<br /> 
    Grade Point Ratio (GPR) and  Cumulative Grade Point Ratio (CGPR): The GPR is calculated by multiplying the  grade points obtained in each course by the respective credit hours. The CGPR  is determined by dividing the total grade points accumulated over the study  period by the total number of credit hours. A minimum CGPR of 2.45 is required  for the award of the Pharm.D. degree.</li> </ul>
      <p></p>
      <p></p>
  <p><strong>Practical Evaluation:</strong></p>
  <ul>
   <li><strong>Laboratory Work and Assignments:</strong><br/>
   Practical skills are assessed through laboratory experiments,       assignments, and projects conducted throughout the semester. These       assessments evaluate students' proficiency in applying theoretical       knowledge to practical scenarios.</li>
    <li><strong>Hospital       Pharmacy Training:</strong><br/>
     In alignment with the Pharmacy Council of Pakistan's requirements,       students must complete at least 200 contact hours of hospital pharmacy training       in tertiary care general hospitals. This training encompasses various       aspects of pharmacy practice, including inpatient and outpatient services,       inventory management, compounding, sterile preparations, and clinical       pharmacy practices. Students maintain medication histories and patient       logbooks to document clinical scenarios, and their performance is       evaluated by mentors and preceptors from the respective hospitals.</li>
    <li><strong>Attendance       Requirement:</strong><br/>
     A       minimum attendance of 75% in each course is mandatory for eligibility to       appear in examinations. Failure to meet this requirement may result in       disqualification from the terminal examinations.</li>
  </ul>
