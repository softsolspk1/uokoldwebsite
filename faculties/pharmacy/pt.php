  <h3 align="center">Practical Training (Including the  Nature, Duration, and Location of the Training)</h3>
    <p>&nbsp;</p>
  <p align="justify">The Pharmacy Council of Pakistan  mandates that undergraduate students complete a minimum of 200 contact hours of  hospital pharmacy training in a tertiary care general hospital. To fulfill this  requirement, the Faculty of Pharmacy and Pharmaceutical Sciences has  established MoUs with several well-reputed hospitals in Karachi, including Dow  University Hospital, Dar ul Sehat Hospital, National Institute of Blood  Diseases, Children&rsquo;s Hospital Gulshan-Iqbal, Patel Hospital, and Alkhidmat  Hospitals. Additionally, students gain hands-on experience at other prominent  institutions such as Aga Khan University Hospital, Liaquat National Hospital,  Ziauddin Hospitals, South City Hospital, Civil Hospital, and the National  Institute of Cardiovascular Diseases.</p>
    <p align="justify">The training program covers a wide  range of clinical and hospital services, including inpatient and outpatient  pharmacy setups, inventory management, drug storage, inpatient and outpatient  medication dispensation, compounding, sterile preparations, IV admixtures (wherever  available), and oncology pharmacy services. Furthermore, students are exposed  to specialized areas such as pharmacovigilance, medication reconciliation, drug  utilization reviews, total parenteral nutrition (TPN) preparation, clinical  pharmacokinetics, and antimicrobial stewardship programs. They also participate  in clinical pharmacy rounds, therapeutic drug monitoring (TDM), and counseling  sessions for chronic disease management, such as diabetes, hypertension, and  asthma.</p>
   <p align="justify">During their training, students  maintain a detailed medication history and patient logbook to document and  review clinical cases. The training is conducted during their fourth and fifth  academic years, with mentors and preceptors from the respective hospitals  evaluating and marking their performance, contributing to their overall  academic assessment. This comprehensive exposure ensures that students develop  the necessary competencies for hospital and clinical pharmacy practice.</p>
