  <p>&nbsp;</p>
  <p>The  Faculty of Pharmacy has well equipped laboratories in all the four departments,  fully capable of catering the teaching and research needs of the various  programs offered. Moreover, there is a good library of the faculty. Furthermore  the Faculty has an Institute of Pharmaceutical Sciences under its auspices so  as to give more impetus to scientific and technological research and  development.</p>
<p>&nbsp;</p>
<h3>Foreign Students</h3>
  <p>Faculty of Pharmacy admits 20 foreign students to Pharm-D. degree course every year. These admissions are not given directly but only after being duly processed by the concerned Embassies and the Ministry of Economic Affairs in Islamabad.</p>
  <p>&nbsp;</p>
  <h3>Extra Curricular Activities<br />
  </h3>
  <h4><strong>Annual Tour</strong></h4>
  <p>    Students of B.Pharm./Pharm-D. final year tour the country as a part of their training to get acquainted with the various pharmaceutical industries as well as various Pharmacy Institutions (public sector) of the country, while the junior students visit the local industries. Expenses of both trips are borne by University of Karachi.</p>
  <h4>Student Activities </h4>
  <p>    Pharmacy students have been very active to organize functions which include promotion of academic and extra-curricular activities, the later include social and literary functions as well as assistance to students in their day-to-day problems. They also publish two or three magazines every year from their own resources, to which students contribute their writings and are supplemented by teachers.</p>
  <p> </p>
  <h3>Incentives and Assistance</h3>
  <h4>President's Award</h4>
  <p>    Ministry of Health, Government of Pakistan gives this medal to the student who tops in over all performance during the 5 years Pharm-D. courses.</p>
  <h4>Research fellowships</h4>
  <p>    University of Karachi, the Higher Education Commission and Pakistan Science Foundation grant fellowships for talented students enrolled for M.Phil and Ph.D. programs.</p>
  <h4>Fee Remissions</h4>
  <p>    Over a hundred deserving undergraduate and postgraduate students are given full-fee remissions.</p>
  <h4>Duty Loan</h4>
  <p>    These interest-free loans are granted by Banker's Equity of Pakistan to outstanding and deserving students. Moreover, Pakistan Fauji Foundation and other social and cultural organizations give financial assistance to needy students  </p>
  <h4>Gold Medals</h4>
  <ul>
    <li>Hakimsons Chemical Industries Gold Medal is awarded to a student, who performs best in the 4 year B.Pharm./5 years Pharm-D. degree courses.</li>
    <li>Al-Haj Ikram Siddiqui Gold Medal goes to the most outstanding M.Pharm. student of the faculty</li>
    <li>Prof. S.M.S. Zoha Gold Medal is awarded to a student who secured best CGPR in Pharmacy at the B.Pharm/Pharm-D examinations.      </li>
    <li>Fauzia Rashid Gold Medal is received by a student who stood First at the B.Pharm/Pharm-D examinations. </li>
    <li>Amna Feroz Gold Medal goes to a student who stood First at the B.Pharm/Pharm-D examinations.</li>
    </ul>
  <p>&nbsp;</p>
  <h3>Professional Activities<br />
  </h3>
  <p>Pakistan Pharmacy Council was established after the enactment of Pakistan Pharmacy Act in 1967. This Council, along with Pakistan Pharmaceutical Manufacturing Association, Pakistan Pharmacists Association and Pharamakarian (an alumni association of the Faculty of Pharmacy, University of Karachi), is playing a vital role in propagating and establishing professional traditions of pharmacy in the country.</p>
