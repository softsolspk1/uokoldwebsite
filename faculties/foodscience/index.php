  <h2>Chairperson:  Dr.  Muhammad Abdul Haq (Assoc. Prof.)</h2>
  <img src="fsmp.jpg" width="670" height="310" alt="fsd" />
  
  <p align="justify">The department of Food Science &amp;  Technology was establish in 1994 to cater the needs of the fast growing food  industries in the country and also to meet the ever growing demand for food  scientists and technologists in government, research and educational establishments.  Its mission is to provide high-quality education and training to students and  prepare them for careers in the food industry, academia, or government, to  conduct basic and applied research for the ultimate benefit of the food  industry and consumers and to provide assistance and services to the food  industry. Over the years, the department has developed strong links with the  industry. Recently the department has established an <em>Industrial Advisory Board</em> comprising members from reputed Food industries  to help us shape our curriculum from an industrial perspective to keep it  relevant and to ensure that our curriculum reflect current developments and  industry skills requirements. The department has always been actively engaged   in providing advisory services and  consultancy to food industries and also    organizing seminars, conferences and training courses in collaboration  with industries.   In addition to food  industries, the department also works in collaboration with government  organizations such as PSQCA, PCSIR, PARC, SFA and different NGOs. Realizing the  importance of human nutrition in daily life and emergencies like earthquake,  drought, famine and man-made disasters, department offered another Four year BS  Program entitled <em>Human Nutrition &amp; Dietetics</em> from 2023. The Curriculum for the program has been developed in view of local  as well as global health needs. </p>
  <p>Accreditation status <br />
    The BS program in Food Science &amp;  Technology has been accredited by National Agriculture Education Accreditation Council  (NAEAC) in 2021.</p>
