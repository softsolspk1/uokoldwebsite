  <li>To protect our environmental  condition from deterioration of food.</li>
  <li>To introduce novel,  nutrition’s economic value added food products for local consumption and  export.</li>
  <li>To incorporate the food  industry waste for new products development.</li>
  <li>To provide consultancy and  advisory services of food industries</li>
  <li>To provide diagnostic  analysis of food products.</li>
