  <h2>Chairman: Prof. Dr.  S.  M. Farid Hasan</h2>
  <p> In  1964 the department of pharmacy was part of faculty of sciences and then it has  gained the status of faculty in 1973 after which the pharmacy started  flourishing in its own. The faculty comprised on four major departments, of  which pharmaceutics is one. Presently, more than 1800 regular students are  today pursuing their studies leading to the award of Doctor of Pharmacy  (Pharm-D.), Master of Pharmacy (M.Pharm.), Master of Studies (M.S.), and Doctor  of Philosophy (Ph.D.) degrees. <strong></strong></p>
  <p>    Pharmaceutics is one of the major departments of  Faculty of Pharmacy University of Karachi, holding about one third of the total  pharmacy curricula, indicating the length of areas covered in the field of  pharmaceutics that&rsquo;s why in some countries pharmaceutics refers to as pharmacy  itself.    <strong></strong></p>
  <p>    The term pharmaceutics is about science that  involves &ldquo;converting a drug into a medicine&rdquo;. It starts right after the drug  discovery from the natural sources, passing through its physical and chemical  characterization, manufacturing, quality control and analysis, its marketing  aspects till its use by the patients. Today&rsquo;s society&rsquo;s needs has been shifted  to a much more prognostic and sophisticated health care services, of it,  pharmaceutical care has been of a prominent importance. As per a research, a  significant increase in hospital admissions used to be due to the lacking in  quality pharmaceutical care in health care institutes. The pharmacist being a  drug expert and a very acceptable health care professional becomes an eminent  individual to cater with the needs and demands of the modern age health care  system. <strong></strong></p>
  <p>Department of  Pharmaceutics, Faculty of Pharmacy, University of Karachi presently, comprises  of academic as well as non-academic staff. Most  of the teaching staff has doctoral qualification and the rest are pursuing. The department  covers 24 courses spread over five years of Pharm. D program in morning and  evening shifts. The department is actively involved in pharmaceutical research  that covers all aspects of pharmaceutical sciences offering M.Pharm. MS and PhD  programs. The department has produced over 69 M. Phil and 11 PhD Scholars  in different disciplines of pharmaceutics. The department is sufficiently  equipped with all the needs and nodes that are of pivotal importance; here we  have technology, pharmaceutical microbiology laboratories and computer  laboratory to cope with the educational needs of the academia.    </p>
